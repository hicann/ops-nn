static void AssignDataToEachCore(ForeachAddcdivScalarTilingDataHost& tilingDataHost, int64_t needCoreNum,
                                 int64_t dataTypeSize)
{
    int64_t elementsPerBlock = ALIGN_SIZE / dataTypeSize;
    int64_t totalDataCount = tilingDataHost.totalDataCount;
    int64_t blockCount = (totalDataCount + elementsPerBlock - 1) / elementsPerBlock;
    if (blockCount == 0) {
        blockCount = 1;
    }

    int64_t perCoreBlockCount = blockCount / needCoreNum;
    int64_t remainder = blockCount % needCoreNum;

    uint16_t coreIndex = 0;
    int64_t cursorPosition = 0;
    int64_t dataCount = 0;
    tilingDataHost.tensorStartList[coreIndex] = 0;
    tilingDataHost.tensorStartOffsetList[coreIndex] = 0;

    for (uint16_t i = 0; i < static_cast<uint16_t>(tilingDataHost.tensorCount); i++) {
        int64_t curCmpCount = perCoreBlockCount * elementsPerBlock;
        if (remainder > 0 && coreIndex < static_cast<uint16_t>(remainder)) {
            curCmpCount += elementsPerBlock;
        }
        int64_t tempCount = tilingDataHost.tensorDataCountList[i] - cursorPosition;

        if (dataCount + tempCount < curCmpCount) {
            dataCount += tempCount;
            cursorPosition = 0;
            continue;
        }

        tilingDataHost.tensorEndList[coreIndex] = i;
        cursorPosition = cursorPosition + curCmpCount - dataCount;
        tilingDataHost.tensorEndOffsetList[coreIndex] = cursorPosition - 1;
        dataCount = 0;
        coreIndex++;

        if (cursorPosition < tilingDataHost.tensorDataCountList[i]) {
            tilingDataHost.tensorStartList[coreIndex] = i;
            tilingDataHost.tensorStartOffsetList[coreIndex] = cursorPosition;
            --i;
        } else if (coreIndex != static_cast<uint16_t>(needCoreNum)) {
            tilingDataHost.tensorStartList[coreIndex] = i + 1;
            tilingDataHost.tensorStartOffsetList[coreIndex] = 0;
            cursorPosition = 0;
        }
    }

    if (dataCount > 0) {
        tilingDataHost.tensorEndList[coreIndex] = static_cast<uint16_t>(tilingDataHost.tensorCount - 1);
        tilingDataHost
            .tensorEndOffsetList[coreIndex] = tilingDataHost.tensorDataCountList[tilingDataHost.tensorCount - 1] - 1;
    }
}

