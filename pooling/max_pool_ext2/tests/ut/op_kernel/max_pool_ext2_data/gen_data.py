def parse_shape(shape_str):
    return tuple(int(x) for x in shape_str.strip("()").split(","))


def parse_list_int(list_str):
    return ast.literal_eval(list_str)


def get_type_min(np_dtype):
    if np.issubdtype(np_dtype, np.floating):
        return np.finfo(np_dtype).min
    elif np.issubdtype(np_dtype, np.unsignedinteger):
        return np.iinfo(np_dtype).min
    elif np.issubdtype(np_dtype, np.integer):
        return np.iinfo(np_dtype).min
    return 0


def compute_output_dim(in_dim, ksize, stride, padding):
    if padding == "VALID":
        effective = in_dim - ksize + 1
        if effective <= 0:
            return 0
        return (effective + stride - 1) // stride
    elif padding == "SAME":
        return (in_dim + stride - 1) // stride
    else:
        raise ValueError(f"Unsupported padding mode: {padding}")


def compute_padding(in_dim, ksize, stride, padding):
    if padding == "SAME":
        out_dim = compute_output_dim(in_dim, ksize, stride, padding)
        pad_total = max(0, (out_dim - 1) * stride + ksize - in_dim)
        return pad_total // 2
    return 0


def max_pool2d_numpy(x, kH, kW, sH, sW, padding, data_format):
    np_dtype = x.dtype
