def _compute_pool_params(Hi, Wi, kh, kw, sh, sw, padding_mode, pads, ceil_mode):
    """
    计算 padding 和输出尺寸，严格按 CANN _padding_mode 公式。

    参数:
        Hi, Wi: 输入高、宽
        kh, kw: 池化核高、宽
        sh, sw: 步长高、宽
        padding_mode: "VALID" / "SAME" / "CALCULATED"
        pads: [pad_top, pad_bottom, pad_left, pad_right]（仅 CALCULATED 模式使用）
        ceil_mode: 是否向上取整

    返回:
        (pt, pb, pl, pr, Ho, Wo)
    """
    if padding_mode == "VALID":
        Ho = int(np.ceil((Hi - kh + 1) / sh))
        Wo = int(np.ceil((Wi - kw + 1) / sw))
        pt = pb = pl = pr = 0
    elif padding_mode == "SAME":
        Ho = (Hi + sh - 1) // sh
        Wo = (Wi + sw - 1) // sw
        pad_h = max((Ho - 1) * sh + kh - Hi, 0)
        pt = pad_h // 2
        pb = pad_h - pt
        pad_w = max((Wo - 1) * sw + kw - Wi, 0)
        pl = pad_w // 2
        pr = pad_w - pl
    elif padding_mode == "CALCULATED":
        pt, pb, pl, pr = pads
        if ceil_mode:
            Ho = (Hi - kh + pt + pb + sh - 1) // sh + 1
            Wo = (Wi - kw + pl + pr + sw - 1) // sw + 1
            # ceil_mode 下 pb/pr 可能被重新计算（可能为负，表示窗口超出边界）
            pb = (Ho - 1) * sh + kh - Hi - pt
            pr = (Wo - 1) * sw + kw - Wi - pl
        else:
            Ho = (Hi - kh + pt + pb) // sh + 1
            Wo = (Wi - kw + pl + pr) // sw + 1
            pb = max((Ho - 1) * sh + kh - Hi - pt, 0)
            pr = max((Wo - 1) * sw + kw - Wi - pl, 0)
    else:
        raise ValueError(f"Unsupported padding_mode: {padding_mode}")
    return pt, pb, pl, pr, Ho, Wo


