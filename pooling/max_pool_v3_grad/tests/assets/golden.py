def golden_max_pool_v3_grad_direct(
    orig_input,
    orig_output,
    grad,
    ksize,
    strides,
    padding_mode="CALCULATED",
    pads=None,
    data_format="NCHW",
    global_pooling=False,
    ceil_mode=False,
):
    """
    MaxPoolV3Grad 的 CANN 直接实现 Golden（纯 numpy 实现，不依赖任何深度学习框架 autograd）。

    基于 CANN TBE 实现的数学公式（im2col -> mask -> vsel -> col2img 四步流水）：
      1. 对每个池化窗口，比较窗口内输入值与前向最大值（orig_output）
      2. 第一个相等的位置（最大值位置）接收该窗口的梯度（first-wins 策略）
      3. 多个窗口覆盖同一输入位置时，梯度累加

    first-wins 策略对应 TBE 的 mask_or/mask_not 逻辑：
      - matched 数组累积已标记的输出位置（对应 mask_or）
      - eq = (x == y) & (~matched) 确保同一输出位置只被首次匹配的核内偏移标记

    参数:
        orig_input: numpy array, 前向输入 (N, C, H, W) 或 (N, H, W, C)
        orig_output: numpy array, 前向输出 (N, C, Ho, Wo) 或 (N, Ho, Wo, C)
        grad: numpy array, 输出梯度 (N, C, Ho, Wo) 或 (N, Ho, Wo, C)
        ksize: list[int], 长度 4, 池化窗口大小（按 data_format 解析 H/W 维）
        strides: list[int], 长度 4, 池化步长（按 data_format 解析 H/W 维）
        padding_mode: str, "CALCULATED" / "SAME" / "VALID"
        pads: list[int], 长度 4, [pad_top, pad_bottom, pad_left, pad_right]
        data_format: str, "NCHW" / "NHWC"
        global_pooling: bool, 全局池化（不支持，必须为 False）
        ceil_mode: bool, 是否使用 ceil 计算输出尺寸

    返回:
        out_grad: numpy array, 输入梯度，shape 和 dtype 与 orig_input 一致
    """
    if pads is None:
        pads = [0, 0, 0, 0]

    # NHWC -> NCHW 统一处理
    if data_format == "NHWC":
        x = np.transpose(orig_input, (0, 3, 1, 2)).copy()
        y = np.transpose(orig_output, (0, 3, 1, 2)).copy()
        g = np.transpose(grad, (0, 3, 1, 2)).copy()
        kh, kw = ksize[1], ksize[2]
        sh, sw = strides[1], strides[2]
    else:
        x = orig_input
        y = orig_output
        g = grad
        kh, kw = ksize[2], ksize[3]
        sh, sw = strides[2], strides[3]

    N, C, Hi, Wi = x.shape
    pt, pb, pl, pr, Ho, Wo = _compute_pool_params(
        Hi, Wi, kh, kw, sh, sw, padding_mode, pads, ceil_mode
    )

    # 钳位 Ho, Wo >= 0（与 tiling.cpp 钳位逻辑一致）
    Ho = max(Ho, 0)
    Wo = max(Wo, 0)

    # 保存原始 dtype，中间计算提升到 float32 避免累加精度损失（尤其 float16）
    orig_dtype = x.dtype
    g = g.astype(np.float32)
    out_grad = np.zeros_like(x, dtype=np.float32)
    if Ho == 0 or Wo == 0:
        out_grad = out_grad.astype(orig_dtype)
        if data_format == "NHWC":
            out_grad = np.transpose(out_grad, (0, 2, 3, 1)).copy()
        return out_grad

    matched = np.zeros((N, C, Ho, Wo), dtype=bool)  # 对应 TBE 的 mask_or

    for ho in range(Ho):
        for wo in range(Wo):
            h_start = ho * sh - pt
            w_start = wo * sw - pl
            for ki in range(kh):
                for kj in range(kw):
                    hi = h_start + ki
                    wj = w_start + kj
                    if 0 <= hi < Hi and 0 <= wj < Wi:
                        # first-wins: 仅当当前位置相等且此前轮次尚未标记过
                        eq = (x[:, :, hi, wj] == y[:, :, ho, wo]) & (
                            ~matched[:, :, ho, wo]
                        )
                        out_grad[:, :, hi, wj] += np.where(
                            eq, g[:, :, ho, wo], 0
                        ).astype(np.float32)
                        matched[:, :, ho, wo] |= eq

    out_grad = out_grad.astype(orig_dtype)
    if data_format == "NHWC":
        out_grad = np.transpose(out_grad, (0, 2, 3, 1)).copy()
    return out_grad


