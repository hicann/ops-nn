    if global_pooling:
        raise ValueError("global_pooling must be false")

    x = orig_input
    y = orig_output
    g = grad

    if data_format == "NCHW":
        kh, kw = int(ksize[2]), int(ksize[3])
        sh, sw = int(strides[2]), int(strides[3])
    else:
        kh, kw = int(ksize[1]), int(ksize[2])
        sh, sw = int(strides[1]), int(strides[2])
    tf_ksize = [1, kh, kw, 1]
    tf_strides = [1, sh, sw, 1]

