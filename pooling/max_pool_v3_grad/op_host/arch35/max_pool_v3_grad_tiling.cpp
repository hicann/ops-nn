// ComputePoolParams: 计算 padding 和输出尺寸 (与 Golden _compute_pool_params 严格对齐)。
// Ho/Wo 钳位 max(Ho,0)/max(Wo,0)。
static void ComputePoolParams(int64_t H, int64_t W, int64_t kh, int64_t kw, int64_t sh, int64_t sw,
                              const char* paddingMode, const int64_t* pads, bool ceilMode, int64_t& padTop,
                              int64_t& padLeft, int64_t& Ho, int64_t& Wo)
{
    std::string mode(paddingMode);
    if (mode == "VALID") {
        Ho = Ops::Base::CeilDiv(H - kh + 1, sh);
        Wo = Ops::Base::CeilDiv(W - kw + 1, sw);
        padTop = 0;
        padLeft = 0;
    } else if (mode == "SAME") {
        Ho = Ops::Base::CeilDiv(H, sh);
        Wo = Ops::Base::CeilDiv(W, sw);
        int64_t padH = std::max((Ho - 1) * sh + kh - H, static_cast<int64_t>(0));
        int64_t padW = std::max((Wo - 1) * sw + kw - W, static_cast<int64_t>(0));
        padTop = padH / 2;
        padLeft = padW / 2;
    } else {
        // CALCULATED
        padTop = pads[0];
        padLeft = pads[2];
        int64_t padBottom = pads[1];
        int64_t padRight = pads[3];
        if (ceilMode) {
            Ho = Ops::Base::CeilDiv(H - kh + padTop + padBottom, sh) + 1;
            Wo = Ops::Base::CeilDiv(W - kw + padLeft + padRight, sw) + 1;
        } else {
            Ho = FloorDiv(H - kh + padTop + padBottom, sh) + 1;
            Wo = FloorDiv(W - kw + padLeft + padRight, sw) + 1;
        }
    }
    // 钳位为 0 后 totalOutputPos=0，kernel 内循环不执行，返回全 0 out_grad。
    Ho = std::max(Ho, static_cast<int64_t>(0));
    Wo = std::max(Wo, static_cast<int64_t>(0));
}

