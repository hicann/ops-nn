    float startH = 0.0f;
    float roiW = 0.0f;
    float roiH = 0.0f;
    if (!LoadAndTransformRoi(batch, roi, batchSize, spatialScale, rois, divParams, batchId, startW, startH, roiW,
                             roiH)) {
        y[index] = FromFloat<YType>(0.0f);
        return;
    }
    IdxT hStart = 0;
    IdxT hEnd = 0;
    IdxT wStart = 0;
    IdxT wEnd = 0;
