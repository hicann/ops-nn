static constexpr int64_t IDX_0 = 0;
static constexpr int64_t IDX_1 = 1;

static ge::graphStatus InferDataTypeRoiPooling(gert::InferDataTypeContext* context)
{
    OP_LOGD(context->GetNodeName(), "Begin to do InferDataTypeRoiPooling");

    // 设置输出的dtype，与输入x的dtype一致
    ge::DataType xDtype = context->GetInputDataType(IDX_0);
    ge::DataType roisDtype = context->GetInputDataType(IDX_1);
    if (roisDtype != xDtype) {
        OP_LOGE_FOR_INVALID_DTYPES_WITH_REASON(context->GetNodeName(), "rois",
                                               std::to_string(static_cast<int32_t>(roisDtype)).c_str(),
                                               "rois dtype must match x dtype");
        return GRAPH_FAILED;
    }
    context->SetOutputDataType(IDX_0, xDtype);

    OP_LOGD(context->GetNodeName(), "End to do InferDataTypeRoiPooling");
    return GRAPH_SUCCESS;
}

