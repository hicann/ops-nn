def _calc_pads(
    padding_mode,
    pads,
    out_h,
    out_w,
    input_h,
    input_w,
    k_h,
    k_w,
    stride_h,
    stride_w,
    ceil_mode=False,
):
    if padding_mode == "VALID":
        if ceil_mode:
            pad_b = max((out_h - 1) * stride_h + k_h - input_h, 0)
            pad_r = max((out_w - 1) * stride_w + k_w - input_w, 0)
            return 0, pad_b, 0, pad_r
        return 0, 0, 0, 0
    if padding_mode == "SAME":
        total_pad_h = max((out_h - 1) * stride_h + k_h - input_h, 0)
        total_pad_w = max((out_w - 1) * stride_w + k_w - input_w, 0)
        pad_t = total_pad_h // 2
        pad_b = total_pad_h - pad_t
        pad_l = total_pad_w // 2
        pad_r = total_pad_w - pad_l
        return pad_t, pad_b, pad_l, pad_r
    # CALCULATED: pad_top/pad_left 取用户值，pad_bottom/pad_right 由输出尺寸公式
    # 反推并钳到非负，与 TBE calculate_pads（util_avgpool_update_dynamic.py 第92-97行）对齐。
    # TBE 语义：输出尺寸为真值，trailing pad 必须满足
    #   (out-1)*stride + k = input + pad_leading + pad_trailing
    # 故 pad_trailing = max((out-1)*stride + k - input - pad_leading, 0)，
    # 用户传入的 pad_bottom/pad_right 被丢弃。
    pad_t = int(pads[0])
    pad_l = int(pads[2])
    pad_b = max((out_h - 1) * stride_h + k_h - input_h - pad_t, 0)
    pad_r = max((out_w - 1) * stride_w + k_w - input_w - pad_l, 0)
    return pad_t, pad_b, pad_l, pad_r


def _mean_matrix_by_arange(
    out_h,
    out_w,
    input_h,
    input_w,
    k_h,
    k_w,
    stride_h,
    stride_w,
    pad_t,
    pad_b,
    pad_l,
    pad_r,
):
    h_idx = torch.arange(out_h, dtype=torch.float64)
    w_idx = torch.arange(out_w, dtype=torch.float64)
    val1_h = h_idx * stride_h - pad_t + k_h
    val2_h = (out_h - 1 - h_idx) * stride_h - pad_b + k_h
    mean_h = torch.minimum(
        torch.minimum(val1_h, val2_h),
        torch.tensor(min(k_h, input_h), dtype=torch.float64),
    )
    mean_h = torch.clamp(mean_h, min=1)
    val1_w = w_idx * stride_w - pad_l + k_w
    val2_w = (out_w - 1 - w_idx) * stride_w - pad_r + k_w
    mean_w = torch.minimum(
        torch.minimum(val1_w, val2_w),
        torch.tensor(min(k_w, input_w), dtype=torch.float64),
    )
    mean_w = torch.clamp(mean_w, min=1)
    mean_matrix = mean_h.unsqueeze(1) * mean_w.unsqueeze(0)
    return mean_matrix


