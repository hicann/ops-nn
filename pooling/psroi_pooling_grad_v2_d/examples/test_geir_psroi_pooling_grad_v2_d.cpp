int64_t RoundNearestEven(float value)
{
    // Smoke ROI coordinates are non-negative. Do not use nearbyint/rint, which follow the host rounding mode.
    const auto lower = static_cast<int64_t>(std::floor(value));
    const float fraction = value - static_cast<float>(lower);
    return lower + (fraction > 0.5f || (fraction == 0.5f && lower % 2 != 0) ? 1 : 0);
}

