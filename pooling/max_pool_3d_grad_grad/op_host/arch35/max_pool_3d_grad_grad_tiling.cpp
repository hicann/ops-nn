ge::graphStatus MaxPool3DGradGradTilingFunc(gert::TilingContext* context)
{
    OP_CHECK_NULL_WITH_CONTEXT(context, context);
    Spatial3D kernel, stride;
    bool same = false;
    if (ValidateInputs(context, kernel, stride, same) != ge::GRAPH_SUCCESS) {
        return ge::GRAPH_FAILED;
    }
    const auto& x = context->GetInputShape(ORIG_X_IDX)->GetStorageShape();
    PoolDim d, h, w;
    if (ComputePoolDim(context, x.GetDim(1), kernel.d, stride.d, same, d) != ge::GRAPH_SUCCESS ||
        ComputePoolDim(context, x.GetDim(2), kernel.h, stride.h, same, h) != ge::GRAPH_SUCCESS ||
        ComputePoolDim(context, x.GetDim(3), kernel.w, stride.w, same, w) != ge::GRAPH_SUCCESS) {
        return ge::GRAPH_FAILED;
    }
    if (ValidateExpectedOutput(context, d, h, w) != ge::GRAPH_SUCCESS) {
        return ge::GRAPH_FAILED;
    }
    int64_t total = 0;
    if (ComputeTotal(context, d, h, w, total) != ge::GRAPH_SUCCESS) {
        return ge::GRAPH_FAILED;
    }
    auto t = context->GetTilingData<MaxPool3DGradGradTilingData>();
    OP_CHECK_NULL_WITH_CONTEXT(context, t);
    FillTilingData(context, t, kernel, stride, d, h, w, total);
    if (SetPlatformResources(context, total, t) != ge::GRAPH_SUCCESS) {
        return ge::GRAPH_FAILED;
    }
    DumpTilingData(context, t);
    const bool k1 = kernel.d == 1 && kernel.h == 1 && kernel.w == 1;
    context->SetTilingKey(SelectTilingKey(k1, same, total <= INT32_MAX));
    return ge::GRAPH_SUCCESS;
}

