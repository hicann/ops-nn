/*!
 * \file test_assert_async.cpp
 * \brief CPU-simulation UT for the AssertAsync kernel body (op_kernel/arch35/assert_async_kernel.h).
 *
 * Covers the bit-exact zero-check semantics of IsZeroValue through the real kernel class:
 *   - FLOAT kind    : sign-bit-masked zero (+0.0 / -0.0) traps; NaN / +Inf pass.
 *   - INT kind      : all-zero bytes trap (INT32 0); a non-zero byte passes (INT32 non-zero).
 *   - BOOL          : true (0x01) passes.
 *   - COMPLEX kind  : real == 0 && imag == 0 traps (COMPLEX64 (0, 0)); a non-zero imag passes.
 *
 * Assertion strategy (why not EXPECT_DEATH):
 *   Under ASCENDC_CPU_DEBUG, ASSERT_MSG(assertFail, ...) expands to fprintf(stderr) + abort()
 *   (basic_api/kernel_log.h). However, ICPU_RUN_KF (kern_fwk.h RunKernelFunctionOnCpu) runs the
 *   kernel in a FORKED CHILD PER BLOCK: the abort() only kills that grandchild (its SIGABRT
 *   handler prints a backtrace and exits with status 1), while the parent gtest process merely
 *   waitpid()s it and prints nothing -- a gtest death test only observes its own forked child,
 *   so EXPECT_DEATH cannot see the kernel abort at all.
 *   The observable protocol of the CPU launch is therefore used instead: a non-trapping kernel
 *   child exits 0 and the parent prints "[SUCCESS][CORE_0]"; a trapping kernel prints
 *   "[ASSERT] <file>:<line>: Assertion `assertFail' <msg>" to the inherited stderr, where <msg>
 *   is the assertMsg string filled into the tiling (printed verbatim, without any prefix).
 *   Both stdout and stderr are captured around ICPU_RUN_KF and asserted:
 *     - pass case : contains "[SUCCESS][CORE_0]" and no "[ASSERT]";
 *     - trap case : contains the ASSERT_MSG text (strong: expr + the tiling assertMsg body) and
 *       no "[SUCCESS]".
 *   The trap cases also act as an environment sentinel: the CPU-debug pem backend (pv_mem_write)
 *   is resolved from LD_LIBRARY_PATH, and only the soc-matching Ascend950PR_9599 simulator lib
 *   simulates the arch35 DataCopyPad; with a mismatched (e.g. Ascend910B1) simulator first in
 *   LD_LIBRARY_PATH the GM->UB move is not performed and the trap cases fail loudly.
 *   Device-side failure behavior is additionally covered by tests/st/testcases/.
 */

