    uint8_t* workspace = static_cast<uint8_t*>(AscendC::GmAlloc(16));
    uint8_t* tilingBuf = static_cast<uint8_t*>(AscendC::GmAlloc(sizeof(AssertAsyncTilingData)));
    EXPECT_NE(input, nullptr);
    EXPECT_NE(tilingBuf, nullptr);
    memcpy(input, inputBytes.data(), td.elemByteSize);
    memcpy(tilingBuf, &td, sizeof(AssertAsyncTilingData));

    FdCapture capture;
    EXPECT_TRUE(capture.valid_);
    ICPU_SET_TILING_KEY(0);
    AscendC::SetKernelMode(KernelMode::AIV_MODE);
    ICPU_RUN_KF(AssertAsyncKernelCase, 1, input, workspace, tilingBuf);
