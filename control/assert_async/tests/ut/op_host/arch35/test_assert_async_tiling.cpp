TilingResult RunTilingFull(ge::DataType dtype, gert::StorageShape* inputShape, const std::string& assertMsg)
{
    std::map<std::string, std::string> socInfos;
    std::map<std::string, std::string> aicoreSpec;
    std::map<std::string, std::string> intrinsics;
    std::string compileInfoStr = R"({"hardware_info":{"UB_SIZE":262144,"CORE_NUM":64}})";
    GetPlatFormInfos(compileInfoStr.c_str(), socInfos, aicoreSpec, intrinsics);

    fe::PlatFormInfos platformInfo;
    platformInfo.Init();

    struct AssertAsyncCompileInfo {
    } compileInfo;

    auto tilingData = gert::TilingData::CreateCap(4096);
    auto workspace = gert::ContinuousVector::Create<size_t>(4096);

    // NOTE: the AssertAsync operator has NO output tensor, but the UT TilingContextFaker
    // cannot build a compute node with zero outputs (CreateComputeNodeInfo rejects it).
    // A dummy output is therefore supplied to the faker; the tiling function never reads it
    // (it only inspects input_condition), so this does not affect the validation under test.
    gert::StorageShape dummyOut = {{1}, {1}};

    auto holder = gert::TilingContextFaker()
                      .SetOpType(kOpType)
                      .NodeIoNum(1, 1)
                      .IrInstanceNum(std::vector<uint32_t>{1}, std::vector<uint32_t>{1})
                      .InputShapes({inputShape})
                      .OutputShapes({&dummyOut})
                      .CompileInfo(&compileInfo)
                      .PlatformInfo(reinterpret_cast<char*>(&platformInfo))
                      .NodeInputTd(0, dtype, ge::FORMAT_ND, ge::FORMAT_ND)
                      .NodeOutputTd(0, dtype, ge::FORMAT_ND, ge::FORMAT_ND)
                      .NodeAttrs({{"assert_msg", Ops::NN::AnyValue::CreateFrom<std::string>(assertMsg)}})
                      .TilingData(tilingData.get())
                      .Workspace(reinterpret_cast<gert::ContinuousVector*>(workspace.get()))
                      .Build();

    TilingResult r;
    gert::TilingContext* context = holder.GetContext<gert::TilingContext>();
    if (context == nullptr || context->GetPlatformInfo() == nullptr) {
        r.status = ge::GRAPH_FAILED;
        return r;
    }
    context->GetPlatformInfo()->SetPlatformRes("SoCInfo", socInfos);
    context->GetPlatformInfo()->SetPlatformRes("AICoreSpec", aicoreSpec);
    context->GetPlatformInfo()->SetCoreNumByCoreType("AICore");
    context->GetPlatformInfo()->SetPlatformRes("AICoreintrinsicDtypeMap", intrinsics);
    std::map<std::string, std::string> socVersionInfos = {
        {"SoC_version", "Ascend950"}, {"Short_SoC_version", "Ascend950"}, {"NpuArch", "3510"}};
    context->GetPlatformInfo()->SetPlatformRes("version", socVersionInfos);

    auto opImpl = gert::OpImplRegistry::GetInstance().GetOpImpl(kOpType);
    if (opImpl == nullptr || opImpl->tiling == nullptr) {
        r.status = ge::GRAPH_FAILED;
        return r;
    }
    r.status = opImpl->tiling(context);
    if (r.status == ge::GRAPH_SUCCESS) {
        r.tilingKey = context->GetTilingKey();
        r.blockDim = context->GetBlockDim();
        r.data = *context->GetTilingData<AssertAsyncTilingData>();
    }
    return r;
}
