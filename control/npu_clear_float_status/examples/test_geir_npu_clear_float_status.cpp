// 原 GenOnesData 重命名为 FillTensorWithValue（原名误导，实际生成 value 填充而非 ones）
// 根据 dtype 选择正确的 vector 类型，避免 int32_t vector 构造 float32 数据的类型不安全
// Tensor(const TensorDesc&, const uint8_t*, size_t) 深拷贝数据
// （构造后 Tensor 内部 ptr != 传入 ptr，源数据释放后值仍保留）
// 因此 pData 离开作用域析构后 input_tensor 仍有效，无需调用者持有 pData
int32_t FillTensorWithValue(vector<int64_t> shapes, Tensor& input_tensor, TensorDesc& input_tensor_desc,
                            DataType data_type, int value)
{
    input_tensor_desc.SetRealDimCnt(shapes.size());
    size_t size = 1;
    for (uint32_t i = 0; i < shapes.size(); i++) {
        size *= shapes[i];
    }
    int dtypeSize = ge::GetSizeByDataType(data_type);
    if (dtypeSize <= 0) {
        printf("%s - ERROR - unsupported data type: %d\n", GetTime().c_str(), data_type);
        return kFailed;
    }
    uint32_t data_len = size * static_cast<uint32_t>(dtypeSize);
    // float32 dtype 用 vector<float> 构造，保证类型安全
    // 其他 dtype 仍用 vector<int32_t>（int 值填充，按字节 reinterpret）
    if (data_type == ge::DT_FLOAT) {
        auto pData = std::make_shared<std::vector<float>>(size, static_cast<float>(value));
        input_tensor = Tensor(input_tensor_desc, reinterpret_cast<uint8_t*>(pData->data()), data_len);
    } else {
        auto pData = std::make_shared<std::vector<int32_t>>(size, value);
        input_tensor = Tensor(input_tensor_desc, reinterpret_cast<uint8_t*>(pData->data()), data_len);
    }
    return kSuccess;
}

