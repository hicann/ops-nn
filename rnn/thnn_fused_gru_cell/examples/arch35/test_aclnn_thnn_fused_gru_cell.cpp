    // (B, H) = (4, 8)：gates (B, 3H)，hx/hy (B, H)，storage (B, 5H)
    constexpr int64_t B = 4;
    constexpr int64_t H = 8;
    const std::vector<int64_t> gateShape = {B, 3 * H};
