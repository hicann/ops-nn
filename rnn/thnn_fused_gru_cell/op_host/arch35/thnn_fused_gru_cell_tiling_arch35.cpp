        // 1) 平台信息 + shape 获取 + 校验链
        auto ret = ReadPlatform();
        if (ret != ge::GRAPH_SUCCESS) {
            return ret;
        }
        ret = ReadShapes();
        if (ret != ge::GRAPH_SUCCESS) {
            return ret;
        }
        ret = ValidateChain();
        if (ret != ge::GRAPH_SUCCESS) {
            return ret; // 报错返回，不进入路由
        }

        // 2) 空 Tensor 兜底：input_gates.numel==0（B==0 或 H==0）→
        //    totalTiles=0/numCores=0 + SetBlockDim(1)（严禁 SetBlockDim(0)）
