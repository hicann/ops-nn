static bool FindSplitAxis(const std::vector<int64_t>& maxBroShape, int64_t elemBytes, int64_t ubPerCore,
                          int64_t paddedHidden, int64_t coreNum, ge::DataType dtype, SplitResult& out)
{
    const int64_t perElemBytes = PerTileElemBytes(dtype);
    const int64_t perBufElems = ubPerCore / perElemBytes;
    if (perBufElems < 1) {
        OP_LOGE("FindSplitAxis", "perBufElems(%ld) must be >= 1 (ubSize=%ld, perElemBytes=%ld)", perBufElems, ubPerCore,
                perElemBytes);
        return false;
    }
    const int64_t batch = maxBroShape[2];  // batch 维
    const int64_t hidden = maxBroShape[3]; // hidden 维（原始 H）
    if (paddedHidden > perBufElems) {
        // 形态 A：padded H 超出 UB → 沿 H 切，单行 tile（axis=3）
        out.axis = 3;
        out.aI = (hidden < perBufElems) ? hidden : perBufElems; // aI = min(H, P)
        out.aO = (hidden + out.aI - 1) / out.aI;                // 外轴 tile 数
        const int64_t rem = hidden % out.aI;
        out.aITail = (rem == 0) ? out.aI : rem; // 尾块
    } else if (batch * paddedHidden > perBufElems) {
        // 形态 B：沿 B 切、多行 tile（axis=2）
        // aI 上限 1：UB 容量约束 floor(P/paddedHidden)
        // aI 上限 2：多核利用率约束 ceil(B/coreNum)，保证 totalTiles ≥ coreNum
        const int64_t aIUb = perBufElems / paddedHidden;             // floor(P/paddedHidden)
        const int64_t aIMultiCore = (batch + coreNum - 1) / coreNum; // ceil(B/coreNum)
        out.axis = 2;
        out.aI = (aIUb < aIMultiCore) ? aIUb : aIMultiCore; // min(UB约束, 多核约束)
        if (out.aI < 1) {
            out.aI = 1; // 防御：极小 batch 时 aI 至少 1
        }
        out.aO = (batch + out.aI - 1) / out.aI;
        const int64_t rem = batch % out.aI;
        out.aITail = (rem == 0) ? out.aI : rem;
    } else if (batch > 1 && batch * paddedHidden * FP32_BYTES >= LAUNCH_BOUND_BYTES) {
        // 形态 B 偏好：batch > 1 且全量 fit UB → 多核切分（axis=2）
        // 回退谓词：微量数据（< LAUNCH_BOUND_BYTES）时，多核 launch 开销 > 计算收益，
        // 下落到形态 C 单 tile 避免 launch-bound 退化；
        // ≥ 192B 的受益场景不受影响，≤ 128B 的微量场景（含 strided 回退目标）均走 Form C
        const int64_t aIUb = perBufElems / paddedHidden;
        const int64_t aIMultiCore = (batch + coreNum - 1) / coreNum;
        out.axis = 2;
        out.aI = (aIUb < aIMultiCore) ? aIUb : aIMultiCore;
        if (out.aI < 1) {
            out.aI = 1;
        }
        out.aO = (batch + out.aI - 1) / out.aI;
        const int64_t rem = batch % out.aI;
        out.aITail = (rem == 0) ? out.aI : rem;
    } else {
        // 形态 C：全量单 tile（axis=0 padding 轴），batch == 1 或微量数据回退
        out.axis = 0; // d=1 → totalTiles=1
        out.aI = 1;
        out.aO = 1;
        out.aITail = 1;
    }
    // 小 batch 多核饥饿 override（axis=3 H 维切分）：默认分支链产出后、返回前裁决。
    // 触发条件（全部满足才覆写，否则保持默认切分逐字节不变）：
    //   ① totalTiles = ∏_{j<axis} maxBroShape[j] × aO < coreNum（多核饥饿态）
    //   ② batch × hidden × elemBytes ≥ MIN_HSPLIT_DATA_BYTES（数据量门槛）
    //   ③ coreNum / batch ≥ 2（整除口径；保证每核至多 1 tile 的切分余量）
    int64_t totalTiles = 1;
    for (int64_t j = 0; j < out.axis; j++) {
        totalTiles *= maxBroShape[j];
    }
    totalTiles *= out.aO;
    if (totalTiles < coreNum && batch * hidden * elemBytes >= MIN_HSPLIT_DATA_BYTES && coreNum / batch >= 2) {
        // k 策略：k = min(coreNum/batch, hidden)，收缩至段宽 ≥ MIN_HSPLIT_TILE_BYTES；
        // k ≥ 2 才覆写（k=1 表示 H 无法既满足段宽又可切，保持默认）
        int64_t k = coreNum / batch;
        if (k > hidden) {
            k = hidden;
        }
        while (k > 1 && ((hidden + k - 1) / k) * elemBytes < MIN_HSPLIT_TILE_BYTES) {
            k -= 1;
        }
        if (k >= 2) {
            const int64_t aIH = (hidden + k - 1) / k;         // ceil(hidden/k)
            out.axis = 3;                                     // 单行 H 段 tile（kernel 既有通路）
            out.aI = (aIH < perBufElems) ? aIH : perBufElems; // 防御性 min（触发数学下恒不生效）
            out.aO = (hidden + out.aI - 1) / out.aI;
            out.aITail = hidden - (out.aO - 1) * out.aI;
            // MultiCoreSplit 后 totalTiles = batch × aO ≤ coreNum（每核 ≤ 1 tile）
        }
    }
    return true;
}

// 多核切分：以 UB 切分产出的 tile 为单元核间均衡分配（前 coresTail 个核各多处理
// 1 个 tile，任意两核 tile 数差 ≤ 1）；totalTiles = aO × ∏_{j<axis} d_j，
// numCores = min(totalTiles, coreNum) 保证 BlockDim ≤ 物理核数
static bool MultiCoreSplit(const std::vector<int64_t>& maxBroShape, const SplitResult& ubSplit, int64_t coreNum,
                           MultiCoreResult& out)
{
    if (coreNum < 1) {
        OP_LOGE("MultiCoreSplit", "coreNum(%ld) must be >= 1", coreNum);
        return false;
    }
    int64_t outerProd = 1;
    for (int64_t j = 0; j < ubSplit.axis; j++) { // UB 外轴全量循环连乘
        outerProd *= maxBroShape[j];
    }
    out.totalTiles = outerProd * ubSplit.aO; // tile 总数（axis=0 → 1）
    out.numCores = (out.totalTiles < coreNum) ? out.totalTiles : coreNum;
    out.tilesMain = out.totalTiles / out.numCores;
    out.coresTail = out.totalTiles % out.numCores; // 前 coresTail 个核各处理 tilesMain+1
    return true;
}

