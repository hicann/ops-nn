    b1_r, b1_z, b1_n = b1[:hidden], b1[hidden : 2 * hidden], b1[2 * hidden :]
    b2_r, b2_z, b2_n = b2[:hidden], b2[hidden : 2 * hidden], b2[2 * hidden :]

    rg = 1.0 / (1.0 + np.exp(-(((gi_r + gh_r) + b1_r) + b2_r)))
    zg = 1.0 / (1.0 + np.exp(-(((gi_z + gh_z) + b1_z) + b2_z)))
    hn = gh_n + b2_n
    ng = np.tanh((gi_n + b1_n) + rg * hn)
    hy = zg * (hx - ng) + ng
    storage = np.concatenate([rg, zg, ng, hx, hn], axis=1)  # (B, 5H)
    return hy, storage


