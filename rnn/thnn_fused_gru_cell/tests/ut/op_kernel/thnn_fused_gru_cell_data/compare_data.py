import sys
import os
import numpy as np

curr_dir = os.path.dirname(os.path.realpath(__file__))


def bf16_u16_to_fp32(arr_u16):
    u32 = arr_u16.astype(np.uint32) << 16
    return u32.view(np.float32)


def load(dtype, path):
    if dtype == "float32":
        return np.fromfile(path, np.float32).astype(np.float64)
    if dtype == "float16":
        return np.fromfile(path, np.float16).astype(np.float64)
    if dtype == "bfloat16":
        return bf16_u16_to_fp32(np.fromfile(path, np.uint16)).astype(np.float64)
    raise ValueError(f"unsupported dtype {dtype}")


def compare_one(name, golden_file, out_file, dtype):
    if not os.path.exists(golden_file) or not os.path.exists(out_file):
        print(f"COMPARE DATA FAILED! missing file: {golden_file} or {out_file}")
        return False

    if dtype == "float32":
        rtol, atol = 1e-4, 1e-5
    elif dtype == "float16":
        rtol, atol = 1e-2, 1e-3
    else:  # bfloat16
        rtol, atol = 1e-2, 2e-2

    g = load(dtype, golden_file)
    o = load(dtype, out_file)
    if g.shape != o.shape:
        print(
            f"COMPARE DATA FAILED! {name} shape mismatch golden={g.shape} out={o.shape}"
        )
        return False

    close = np.isclose(o, g, rtol=rtol, atol=atol, equal_nan=True)
    bad = np.where(~close)[0]
    if len(bad) == 0:
        print(
            f"COMPARE DATA PASSED! {name} all {g.size} elements match (rtol={rtol}, atol={atol})"
        )
        return True

    print(
        f"COMPARE DATA FAILED! {name} {len(bad)}/{g.size} mismatches (rtol={rtol}, atol={atol})"
    )
    for idx in bad[:8]:
        print(f"  index {idx}: out={o[idx]} golden={g[idx]}")
    return False


def compare(tag, dtype):
    hy_ok = compare_one(
        "hy",
        os.path.join(curr_dir, f"{tag}_golden_hy.bin"),
        os.path.join(curr_dir, f"{tag}_hy.bin"),
        dtype,
    )
    st_ok = compare_one(
        "storage",
        os.path.join(curr_dir, f"{tag}_golden_storage.bin"),
        os.path.join(curr_dir, f"{tag}_storage.bin"),
        dtype,
    )
    return hy_ok and st_ok


if __name__ == "__main__":
    if len(sys.argv) != 3:
        print("Usage: python3 compare_data.py <tag> <dtype>")
        sys.exit(1)
    ok = compare(sys.argv[1], sys.argv[2])
    sys.exit(0 if ok else 1)
