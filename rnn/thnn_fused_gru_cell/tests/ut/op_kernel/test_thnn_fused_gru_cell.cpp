constexpr int64_t kUbSize = 245760;        // Ascend950 AIV per-core UB
constexpr int64_t kPhysNodes = PHYS_NODES; // 3 个 fp32 工作缓冲
constexpr int64_t kUbAlignBytes = 32;
constexpr int64_t kFp32Bytes = 4;
constexpr int64_t kLaunchBoundBytes = 160;    // 微量数据回退阈值
constexpr int64_t kMinHsplitDataBytes = 4096; // H 切分数据量门槛
constexpr int64_t kMinHsplitTileBytes = 512;  // H 切分段宽门槛

using SplitResult = ThnnFusedGruCellOp::SplitResult;
using MultiCoreResult = ThnnFusedGruCellOp::MultiCoreResult;

static int64_t DtypeElemBytes(bool isFp32) { return isFp32 ? kFp32Bytes : 2; }

static int64_t PerTileElemBytes(bool isFp32)
{
    return isFp32 ? 12 : 14; // 3 fp32 TBufs (+1 T cast buf)
}

// FindSplitAxis —— 形态 A/B/C + 小 batch 多核饥饿 H 维切分 override
static bool FindSplitAxis(int64_t batch, int64_t hidden, int64_t elemBytes, int64_t ubPerCore, int64_t paddedHidden,
                          int64_t coreNum, bool isFp32, SplitResult& out)
{
    const int64_t perElemBytes = PerTileElemBytes(isFp32);
    const int64_t perBufElems = ubPerCore / perElemBytes;
    if (perBufElems < 1) {
        return false;
    }
    auto formB = [&]() {
        const int64_t aIUb = perBufElems / paddedHidden;
        const int64_t aIMultiCore = (batch + coreNum - 1) / coreNum;
        out.axis = 2;
        out.aI = (aIUb < aIMultiCore) ? aIUb : aIMultiCore;
        if (out.aI < 1) {
            out.aI = 1;
        }
        out.aO = (batch + out.aI - 1) / out.aI;
        const int64_t rem = batch % out.aI;
        out.aITail = (rem == 0) ? out.aI : rem;
    };
    if (paddedHidden > perBufElems) {
        // 形态 A：padded H 超出 UB → 单行 tile（axis=3）
        out.axis = 3;
        out.aI = (hidden < perBufElems) ? hidden : perBufElems;
        out.aO = (hidden + out.aI - 1) / out.aI;
        const int64_t rem = hidden % out.aI;
        out.aITail = (rem == 0) ? out.aI : rem;
    } else if (batch * paddedHidden > perBufElems) {
        formB(); // 形态 B：沿 B 切
    } else if (batch > 1 && batch * paddedHidden * kFp32Bytes >= kLaunchBoundBytes) {
        formB(); // 形态 B 偏好（batch > 1 且全量 fit UB 的多核切分）
    } else {
        out.axis = 0; // 形态 C：全量单 tile
        out.aI = 1;
        out.aO = 1;
        out.aITail = 1;
    }
    // 小 batch 多核饥饿 override（axis=3 H 维切分）
    const int64_t maxBroShape[4] = {1, 1, batch, hidden};
    int64_t totalTiles = 1;
    for (int64_t j = 0; j < out.axis; j++) {
        totalTiles *= maxBroShape[j];
    }
    totalTiles *= out.aO;
    if (totalTiles < coreNum && batch * hidden * elemBytes >= kMinHsplitDataBytes && coreNum / batch >= 2) {
        int64_t k = coreNum / batch;
        if (k > hidden) {
            k = hidden;
        }
        while (k > 1 && ((hidden + k - 1) / k) * elemBytes < kMinHsplitTileBytes) {
            k -= 1;
        }
        if (k >= 2) {
            const int64_t aIH = (hidden + k - 1) / k;
            out.axis = 3;
            out.aI = (aIH < perBufElems) ? aIH : perBufElems;
            out.aO = (hidden + out.aI - 1) / out.aI;
            out.aITail = hidden - (out.aO - 1) * out.aI;
        }
    }
    return true;
}

// MultiCoreSplit —— tile 核间均衡分配（前 coresTail 个核各多 1 tile）
static void MultiCoreSplit(int64_t batch, int64_t hidden, const SplitResult& ubSplit, int64_t coreNum,
                           MultiCoreResult& out)
{
    const int64_t maxBroShape[4] = {1, 1, batch, hidden};
    int64_t outerProd = 1;
    for (int64_t j = 0; j < ubSplit.axis; j++) {
        outerProd *= maxBroShape[j];
    }
    out.totalTiles = outerProd * ubSplit.aO;
    out.numCores = (out.totalTiles < coreNum) ? out.totalTiles : coreNum;
    out.tilesMain = out.totalTiles / out.numCores;
    out.coresTail = out.totalTiles % out.numCores;
}

// BuildTiling —— 构造与真实 host tiling 字节一致的 ThnnFusedGruCellTilingData<4>
static void BuildTiling(uint8_t* buf, int64_t batch, int64_t hidden, bool isFp32, bool hasB1, bool hasB2,
                        int64_t coreNum)
{
    using TD = ThnnFusedGruCellTilingData<THNN_FUSED_GRU_CELL_RANK_4>;
    auto* t = reinterpret_cast<TD*>(buf);
    *t = TD{}; // 全字段清零后逐项赋值（hmajor 字段恒零：tilingKey=0 原路径）

    const int64_t elemBytes = DtypeElemBytes(isFp32);
    const int64_t paddedHidden = ((hidden * elemBytes + kUbAlignBytes - 1) / kUbAlignBytes) * kUbAlignBytes / elemBytes;
    SplitResult split;
    MultiCoreResult multicore;
    FindSplitAxis(batch, hidden, elemBytes, kUbSize, paddedHidden, coreNum, isFp32, split);
    MultiCoreSplit(batch, hidden, split, coreNum, multicore);
    t->split = split;
    t->multicore = multicore;
    t->perBufBytes = (kUbSize / kPhysNodes) & ~(kUbAlignBytes - 1);
    t->tileElems = kUbSize / PerTileElemBytes(isFp32);
    t->paddedHidden = paddedHidden;
    t->rank = 2; // 实际有效 rank（(B,H) 左补 1 至 RANK=4）
    t->maxBroShape[0] = 1;
    t->maxBroShape[1] = 1;
    t->maxBroShape[2] = batch;
    t->maxBroShape[3] = hidden;
    t->biasFlags = (hasB1 ? INPUT_BIAS_FLAG : 0) | (hasB2 ? HIDDEN_BIAS_FLAG : 0);
    t->numInputs = REQUIRED_INPUT_COUNT + ((t->biasFlags & INPUT_BIAS_FLAG) ? 1 : 0) +
                   ((t->biasFlags & HIDDEN_BIAS_FLAG) ? 1 : 0);
    t->numOutputs = MAX_OUTPUT_SLOTS;

    // 输入槽：gates (1,1,B,3H)、hx (1,1,B,H)、bias (1,1,1,3H) 广播（batch 维 stride=0）
    auto setIn = [&](int64_t slot, int64_t b, int64_t cols, int64_t rowStride) {
        t->inputShapes[slot][0] = 1;
        t->inputShapes[slot][1] = 1;
        t->inputShapes[slot][2] = b;
        t->inputShapes[slot][3] = cols;
        t->inputStrides[slot][0] = 0;
        t->inputStrides[slot][1] = 0;
        t->inputStrides[slot][2] = rowStride;
        t->inputStrides[slot][3] = 1;
    };
    setIn(0, batch, 3 * hidden, 3 * hidden); // input_gates
    setIn(1, batch, 3 * hidden, 3 * hidden); // hidden_gates
    setIn(2, batch, hidden, hidden);         // hx
    setIn(3, 1, hasB1 ? 3 * hidden : 1, 0);  // input_bias（缺省槽 shape=(1,1,1,1)）
    setIn(4, 1, hasB2 ? 3 * hidden : 1, 0);  // hidden_bias

    // 输出槽：hy (1,1,B,H)、storage (1,1,B,5H)
    auto setOut = [&](int64_t slot, int64_t cols) {
        t->outputShapes[slot][0] = 1;
        t->outputShapes[slot][1] = 1;
        t->outputShapes[slot][2] = batch;
        t->outputShapes[slot][3] = cols;
        t->outputStrides[slot][0] = 0;
        t->outputStrides[slot][1] = 0;
        t->outputStrides[slot][2] = cols;
        t->outputStrides[slot][3] = 1;
    };
    setOut(0, hidden);     // hy
    setOut(1, 5 * hidden); // storage
}

