/*!
 * \file block_lstm_grad_tiling.h
 * \brief TilingData for unified BlockLSTMGrad (V1+V2) -- fp32, Ascend 950PR.
 */
#include <cstdint>

struct BlockLstmGradTilingData {
    uint32_t batch;      // B
    uint32_t inputSize;  // I (REAL, as the API contract states)
    uint32_t hiddenSize; // H (REAL)
    uint32_t padI;       // I rounded up to the dtype's C0 -- every on-chip extent's unit
    uint32_t padH;       // H rounded up to the dtype's C0
    uint32_t timeStep;   // T
    uint32_t seqLenMax;  // <= T

    uint32_t rowsPerBlock; // mBlk
    uint32_t blockDim;     // B / rowsPerBlock

    uint32_t tChunkX;
    uint32_t iChunk;
    uint32_t tChunkW;
    uint32_t jChunk;
    uint32_t reduceMode;

    uint32_t usePeephole; // 0 or 1
    uint32_t gateOrder;   // 0=IFCO (V2), 1=ICFO (V1)

    // Padded restage copies of the REAL-H/I user inputs (phase 0 writes these; see
    // block_lstm_grad.cpp). All extents padded; tails zero-filled. The kernels read
    // ONLY these, never the user tensors, so no load can cross a tensor end.
    uint64_t offPadX;     // [T, B, padI]
    uint64_t offPadW;     // [padI+padH, 4*padH]
    uint64_t offPadPeep;  // [3, padH] wci/wcf/wco
    uint64_t offPadGates; // [7, T, B, padH] i, f, o, ci, co, h, cs (internal order)
    uint64_t offPadCsG;   // [T, B, padH] cs_grad
    uint64_t offPadHG;    // [T, B, padH] h_grad
    uint64_t offPadCsP;   // [B, padH] cs_prev
    uint64_t offPadHp;    // [B, padH] h_prev

    uint64_t offDg;      // [T, B, 4*padH]
    uint64_t offXhT;     // [blockDim, padI+padH, T*rowsPerBlock]
    uint64_t offWPar;    // [blockDim, padI+padH, 4*padH] w_grad partials per cluster
    uint64_t offBPar;    // [blockDim, 4*padH] b_grad partials per cluster
    uint64_t offPeepPar; // [blockDim, 3*padH] peephole grad partials per cluster
    uint64_t offXG;      // [T, B, padI] x_grad padded staging (odd-shape scatter src)
    uint64_t offCspG;    // [B, padH] cs_prev_grad padded staging
    uint64_t offHpG;     // [B, padH] h_prev_grad padded staging
    uint64_t offWRed;    // [padI+padH, 4*padH] reduced w_grad padded staging

    /* wave tiling: decouples B/I/H from whole-tensor residency. */
    uint32_t tiledA;  // 1 = dX phase runs the wave path (M waves x K stream)
    uint32_t mWaveA;  // dX: batch rows per wave (one timestep per wave)
    uint32_t kTileA;  // dX: K block width (c0-mult; tail block exact-k)
    uint32_t nTileA;  // dX: N slab width (c0-mult; tail slab exact-n)
    uint32_t xDirect; // 1 = padI == I: restage skipped, user x read directly
    uint32_t wDirect; // 1 = padI == I && padH == H: padW skipped, user w read directly
    uint32_t bDirect; // reserved (grad has no bias-table seeding)

    /* PRECOMPUTED on-chip layout (the kernel used to re-run the ctor's ~370
     * lines of budget arithmetic per core). TilingFunc fills it via blg::MakeLayout;
     * the kernel reads it and overrides only seqMax with the runtime seq_len_max. */
    blg::Layout layout;
    uint32_t tiledB;    // 1 = reverse recurrence runs in row chunks (large B)
    uint32_t rowChunkB; // recurrence: batch rows per chunk
    uint32_t hSlabB;    // reserved (grad recurrence keeps full-width planes)
    uint32_t kTileB;    // reserved

    /* Zero-extent mode (TF parity -- a zero T/B/I/H is legal input, not an error):
     * 0 = normal compute; 1 = B==0 (every output empty, nothing to write);
     * 2 = H==0 (x_grad is the only non-empty output, all zeros);
     * 3 = T==0 (x_grad empty, the seven param grads are zeros);
     * 4 = I==0 (rides the padded normal path: padI=c0, the x blocks zero-filled). */
    uint32_t zeroMode;
};

