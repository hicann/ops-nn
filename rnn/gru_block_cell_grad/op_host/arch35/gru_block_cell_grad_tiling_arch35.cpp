static TileSplitResult GruBlockCellGradTileSplit(const int64_t batch, const int64_t inputSize, const int64_t cellSize,
                                                 const PlatformSummary& plat)
{
    // 容量折算为 fp32 元素数（字节 / 4；ascend950 参考值：16384/16384/65536/131072/63488）
    const int64_t l0aElems = static_cast<int64_t>(plat.l0aSize) / kElemBytes;
    const int64_t l0bElems = static_cast<int64_t>(plat.l0bSize) / kElemBytes;
    const int64_t l0cElems = static_cast<int64_t>(plat.l0cSize) / kElemBytes;
    const int64_t l1Elems = static_cast<int64_t>(plat.l1Size) / kElemBytes;
    const int64_t ubElems = static_cast<int64_t>(plat.ubSize) / kElemBytes;
    const int64_t ubReserveElems = kUbReserveBytes / kElemBytes;

    // Step 1: 输出瓦片面积预算（元素数）——UB 预算为瓶颈（7680 < L0C/dbL0C=32768）
    const int64_t tileAreaCap = std::min(l0cElems / kDbL0C, (ubElems - ubReserveElems) / kPv);

    // Step 2: M/N 候选——各自钳制到实际维长（AlignUp 保证单瓦片覆盖小 shape）与 TILE_CAP
    int64_t mCand = std::max(std::min(AlignUp(batch, kAlignM), kTileCap), kAlignM);
    int64_t nCand = std::max(std::min(AlignUp(inputSize + cellSize, kAlignN), kTileCap), kAlignN);

    // Step 3: 面积超预算 → 固定顺序收缩（大边先缩、M 粒度粗先试 M；纯确定性，无自适应）
    while (mCand * nCand > tileAreaCap) {
        if (mCand >= nCand && mCand > kAlignM) {
            mCand -= kAlignM;
        } else if (nCand > kAlignN) {
            nCand -= kAlignN;
        } else {
            break; // 最小瓦片 16×8=128 元素，任何预算可容纳
        }
    }

    // Step 4: K 分块——L0A/L0B/L1 残余预算反推滚动深度，钳到实际 K（C）对齐上限
    const int64_t kCap = std::min(std::min(l0aElems / mCand, l0bElems / nCand),
                                  l1Elems / (kRollDepth * (mCand + nCand)));
    const int64_t baseK = std::min(std::max(AlignDown(kCap, kAlignK), kAlignK), AlignUp(cellSize, kAlignK));

    return TileSplitResult{mCand, nCand, baseK};
}

