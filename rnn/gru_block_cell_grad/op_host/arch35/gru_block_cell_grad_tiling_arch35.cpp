// ---------------------------------------------------------------------------
// CheckGroupDim(group, d, tag, ref) — validate broadcast dimension compatibility
//
// Checks that for a given dimension d, all tensors in the group have
// either size 1 (broadcastable) or the same size as the reference.
// If ref is -1 (unset), the first non-1 dimension sets the reference.
//
// Parameters:
//   group — vector of tensor shape vectors (padded to same rank)
//   d     — dimension index to check
//   tag   — debug label ("input" or "output")
//   ref   — [in/out] reference dimension size (-1 if not yet set)
//
// Returns: bool — true if all dimensions are compatible for broadcasting
// ---------------------------------------------------------------------------
static bool CheckGroupDim(const std::vector<std::vector<int64_t>>& group, int64_t d, const char* tag, int64_t& ref)
{
    for (size_t i = 0; i < group.size(); i++) {
        int64_t v = group[i][d];
        if (v == 1)
            continue;  // Dimension of 1 is always broadcast-compatible
        if (ref == -1) {
            ref = v;    // Set reference size from first non-1 dimension
        } else if (v != ref) {
            // Conflict: two tensors have different sizes at dimension d, and neither is 1
            OP_LOGE("PadAndSqueeze", "dim %d broadcast incompatible: %s[%d] size %d != %d", (int)d, tag, (int)i, (int)v,
                    (int)ref);
            return false;
        }
    }
    return true;
}

// ---------------------------------------------------------------------------
// CheckBroadcastShape(padded_in, padded_out, max_rank) — validate all dimensions
//
// Iterates over all dimensions of the padded shapes and checks broadcast
// compatibility for both inputs and outputs.
//
// Returns: bool — true if broadcast is valid for all dimensions
// ---------------------------------------------------------------------------
static bool CheckBroadcastShape(const std::vector<std::vector<int64_t>>& padded_in,
                                 const std::vector<std::vector<int64_t>>& padded_out, int64_t max_rank)
{
    for (int64_t d = 0; d < max_rank; d++) {
        int64_t ref = -1;
        if (!CheckGroupDim(padded_in, d, "input", ref))
            return false;
        if (!CheckGroupDim(padded_out, d, "output", ref))
            return false;
    }
    return true;
}

// ---------------------------------------------------------------------------
// PadFront(shapes, max_rank) — pad shape vectors to have the same rank
//
// Prepends 1s to the front of shorter shape vectors so that all shapes
// have max_rank dimensions. This enables dimension-by-dimension comparison
// for broadcasting.
//
// Example: shapes [[3,5], [5]] with max_rank=2 → [[3,5], [1,5]]
// Returns: vector of padded shapes
// ---------------------------------------------------------------------------
static std::vector<std::vector<int64_t>> PadFront(const std::vector<std::vector<int64_t>>& shapes, int64_t max_rank)
{
    std::vector<std::vector<int64_t>> out(shapes.size());
    for (size_t i = 0; i < shapes.size(); i++) {
        // Prepend (max_rank - shapes[i].size()) copies of 1
        out[i].assign(max_rank - (int64_t)shapes[i].size(), 1);
        // Append the original shape dimensions
        out[i].insert(out[i].end(), shapes[i].begin(), shapes[i].end());
    }
    return out;
}

// ---------------------------------------------------------------------------
// SqueezeDim(padded_in, padded_out, d, max_bro_shape, normal_input_shapes, normal_output_shapes)
//
// Checks if dimension d has ALL tensors with size 1. If so, the dimension
// can be squeezed (removed) since it doesn't carry meaningful data.
// Otherwise, pushes the max dimension size to max_bro_shape and the
// individual tensor sizes to normal shapes.
//
// Returns: bool — true if dimension was NOT squeezed (it carries data)
// ---------------------------------------------------------------------------
static bool SqueezeDim(const std::vector<std::vector<int64_t>>& padded_in,
                        const std::vector<std::vector<int64_t>>& padded_out, int64_t d,
                        std::vector<int64_t>& maximum_bro_shape, std::vector<std::vector<int64_t>>& normal_input_shapes,
                        std::vector<std::vector<int64_t>>& normal_output_shapes)
{
    bool all_one = true;
    int64_t max_dim = 0;
    for (auto& s : padded_in) {
        if (s[d] != 1)
            all_one = false;
        max_dim = std::max(max_dim, s[d]);
    }
    for (auto& s : padded_out) {
        if (s[d] != 1)
            all_one = false;
        max_dim = std::max(max_dim, s[d]);
    }
    if (all_one)
        return false;  // All tensors have size 1 at this dimension — squeeze it
    // Keep this dimension
    maximum_bro_shape.push_back(max_dim);
    for (size_t i = 0; i < padded_in.size(); i++)
        normal_input_shapes[i].push_back(padded_in[i][d]);
    for (size_t i = 0; i < padded_out.size(); i++)
        normal_output_shapes[i].push_back(padded_out[i][d]);
    return true;
}

// ---------------------------------------------------------------------------
// PadAndSqueeze(input_shapes, output_shapes, max_bro_shape, normal_input_shapes, normal_output_shapes)
//
// The main shape normalization function for broadcast scenarios:
//   1. Compute max_rank = maximum number of dimensions across all tensors
//   2. PadFront: align all shapes to same rank
//   3. CheckBroadcastShape: validate broadcast compatibility
//   4. SqueezeDim: for each dimension, either keep it (if non-trivial) or drop it
//   5. If ALL dimensions are squeezed (scalar case), push a single [1] element
//
// This produces the "maximum broadcast shape" used for tiling calculations
// and the normalized per-tensor shapes for stride computation.
//
// Returns: bool — true on success, false on broadcast error
// ---------------------------------------------------------------------------
bool PadAndSqueeze(const std::vector<std::vector<int64_t>>& input_shapes,
                    const std::vector<std::vector<int64_t>>& output_shapes, std::vector<int64_t>& maximum_bro_shape,
                    std::vector<std::vector<int64_t>>& normal_input_shapes,
                    std::vector<std::vector<int64_t>>& normal_output_shapes)
{
    int64_t num_inputs = (int64_t)input_shapes.size();
    int64_t num_outputs = (int64_t)output_shapes.size();
    // Find the maximum rank across all input and output shapes
    int64_t max_rank = 0;
    for (auto& s : input_shapes)
        max_rank = std::max(max_rank, (int64_t)s.size());
    for (auto& s : output_shapes)
        max_rank = std::max(max_rank, (int64_t)s.size());
    auto padded_in = PadFront(input_shapes, max_rank);
    auto padded_out = PadFront(output_shapes, max_rank);
    if (!CheckBroadcastShape(padded_in, padded_out, max_rank))
        return false;
    maximum_bro_shape.clear();
    normal_input_shapes.assign(num_inputs, std::vector<int64_t>());
    normal_output_shapes.assign(num_outputs, std::vector<int64_t>());
    for (int64_t d = 0; d < max_rank; d++) {
        SqueezeDim(padded_in, padded_out, d, maximum_bro_shape, normal_input_shapes, normal_output_shapes);
    }
    // If all dimensions were squeezed, push a single [1] element (scalar case)
    if (maximum_bro_shape.empty()) {
        maximum_bro_shape.push_back(1);
        for (int64_t i = 0; i < num_inputs; i++)
            normal_input_shapes[i].push_back(1);
        for (int64_t i = 0; i < num_outputs; i++)
            normal_output_shapes[i].push_back(1);
    }
    return true;
}

// ---------------------------------------------------------------------------
// FindSplitAxis(max_bro_shape, dtype_size, ub_per_core, phys_nodes, out)
//
// Determines which axis to split and computes per-tile dimensions.
// Works backward from the innermost dimension, accumulating elements until
// the per-buffer capacity is exceeded. The axis where capacity is exceeded
// becomes the split axis.
//
// per_buf_elems is computed in FP32 (4 bytes per element) because the
// kernel always computes in float precision internally, regardless of
// input data type.
// ---------------------------------------------------------------------------
bool FindSplitAxis(const std::vector<int64_t>& max_bro_shape, int64_t /*dtype_size*/, int64_t ub_per_core,
                    int64_t phys_nodes, SplitResult& out)
{
    if (phys_nodes <= 0) {
        OP_LOGE("FindSplitAxis", "phys_nodes(%ld) must be > 0", phys_nodes);
        return false;
    }
    // per_buf_bytes: UB bytes per pipeline node, aligned to 32 bytes
    int64_t per_buf_bytes = (ub_per_core / phys_nodes) & ~31LL;
    // per_buf_elems: number of FP32 elements that fit in per_buf_bytes
    int64_t per_buf_elems = per_buf_bytes / 4;
    int64_t rank = (int64_t)max_bro_shape.size();
    int64_t inner = 1;
    // Walk from innermost dimension outward, accumulating inner elements
    for (int64_t k = rank - 1; k >= 0; k--) {
        if (max_bro_shape[k] * inner > per_buf_elems) {
            // This axis exceeds per-buffer capacity — split here
            out.a_i = per_buf_elems / inner;
            if (out.a_i < 1)
                out.a_i = 1;
            out.a_o = (max_bro_shape[k] + out.a_i - 1) / out.a_i;
            int64_t rem = max_bro_shape[k] % out.a_i;
            out.a_i_tail = (rem == 0) ? out.a_i : rem;
            out.axis = k;
            return true;
        }
        if (k == 0) {
            // All elements fit in one buffer — no splitting needed
            out.axis = 0;
            out.a_i = max_bro_shape[0];
            out.a_o = 1;
            out.a_i_tail = max_bro_shape[0];
            return true;
        }
        inner *= max_bro_shape[k];
    }
    return true;
}

// ---------------------------------------------------------------------------
// MultiCoreSplit(max_bro_shape, ub_split, max_cores, out)
//
// Distributes tiles across available cores. Each core processes either
// tiles_main or tiles_main+1 tiles, achieving load balance.
// ---------------------------------------------------------------------------
bool MultiCoreSplit(const std::vector<int64_t>& max_bro_shape, const SplitResult& ub_split, int64_t max_cores,
                     MultiCoreResult& out)
{
    int64_t k = ub_split.axis, outer_prod = 1;
    // Compute product of dimensions outside the split axis
    for (int64_t j = 0; j < k; j++)
        outer_prod *= max_bro_shape[j];
    // total_tiles = outer_dimensions_product * tiles_along_split_axis
    out.total_tiles = outer_prod * ub_split.a_o;
    out.num_cores = (out.total_tiles < max_cores) ? out.total_tiles : max_cores;
    out.tiles_main = out.total_tiles / out.num_cores;
    out.cores_tail = out.total_tiles % out.num_cores;
    return true;
}

// ---------------------------------------------------------------------------
// PrecomputeStrides(s, strides) — compute row-major strides for a shape
//
// Standard row-major (C-order) stride computation: stride[d] = product of
// all later dimensions. Dimensions with size 1 get stride 0 (broadcast).
// ---------------------------------------------------------------------------
bool PrecomputeStrides(const std::vector<int64_t>& s, std::vector<int64_t>& strides)
{
    int64_t rank = (int64_t)s.size();
    strides.assign(rank, 0);
    for (int64_t d = rank - 1; d >= 0; d--) {
        if (s[d] == 1) {
            strides[d] = 0;  // Size-1 dimension: stride 0 (broadcast, always the same element)
            continue;
        }
        int64_t prod = 1;
        for (int64_t j = d + 1; j < rank; j++)
            prod *= s[j];
        strides[d] = prod;
    }
    return true;
}

