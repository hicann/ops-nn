// ---------------------------------------------------------------------------
// Arr2String(arr, n) — helper to format an int64 array as "[a,b,c,...]"
//
// Used for debug logging of shape/stride arrays in the tiling log output.
// ---------------------------------------------------------------------------
static std::string Arr2String(const int64_t* arr, int64_t n)
{
    std::ostringstream oss;
    oss << "[";
    if (n > 0) {
        for (int64_t i = 0; i < n - 1; ++i) {
            oss << arr[i] << ",";
        }
        oss << arr[n - 1];
    }
    oss << "]";
    return oss.str();
}

// ===========================================================================
// class GRUBlockCellGradTiling — main tiling orchestrator (sample)
// ===========================================================================
class GRUBlockCellGradTiling {
public:
    explicit GRUBlockCellGradTiling(gert::TilingContext* ctx) : ctx_(ctx) {}

    ge::graphStatus RunTiling()
    {
        ge::graphStatus ret = GetShapeInfo();
        if (ret != ge::GRAPH_SUCCESS)
            return ret;

        // Compute total output elements
        int64_t total_out = 1;
        for (auto d : raw_output_shapes_[0])
            total_out *= d;
        // Empty tensor: no computation, launch with 1 block (no-op)
        if (total_out == 0) {
            ctx_->SetBlockDim(1);
            return ge::GRAPH_SUCCESS;
        }

        // Map rank to tiling key: 1-4 dims → key 4, 5-8 dims → key 8
        int64_t mapped = (rank_ <= 4) ? 4 : 8;
        if (mapped == 4) {
            ret = DoTilingAndSet<4>();
            ctx_->SetTilingKey(GET_TPL_TILING_KEY(GRU_BLOCK_CELL_GRAD_RANK_4));
        } else {
            ret = DoTilingAndSet<8>();
            ctx_->SetTilingKey(GET_TPL_TILING_KEY(GRU_BLOCK_CELL_GRAD_RANK_8));
        }
        return ret;
    }

private:
    ge::graphStatus ReadPlatform()
    {
        fe::PlatFormInfos* platformInfo = ctx_->GetPlatformInfo();
        OP_CHECK_NULL_WITH_CONTEXT(ctx_, platformInfo);
        auto ap = platform_ascendc::PlatformAscendC(platformInfo);
        coreNum_ = ap.GetCoreNumAiv();
        ap.GetCoreMemSize(platform_ascendc::CoreMemType::UB, ubSize_);
        return ge::GRAPH_SUCCESS;
    }

    ge::graphStatus ReadShapes()
    {
        auto readInto = [&](const gert::StorageShape* shape, std::vector<std::vector<int64_t>>& dst) {
            std::vector<int64_t> dims;
            gert::Shape s = shape->GetStorageShape();
            for (size_t d = 0; d < s.GetDimNum(); ++d)
                dims.push_back(s.GetDim(d));
            dst.push_back(dims);
        };
        // Input 0: x
        auto xShape = ctx_->GetInputShape(0);
        OP_CHECK_NULL_WITH_CONTEXT(ctx_, xShape);
        readInto(xShape, raw_input_shapes_);
        // Input 1: scale
        auto scShape = ctx_->GetInputShape(1);
        OP_CHECK_NULL_WITH_CONTEXT(ctx_, scShape);
        readInto(scShape, raw_input_shapes_);
        // Input 2: bias (optional)
        auto biasShape = ctx_->GetOptionalInputShape(2);
        has_bias_ = (biasShape != nullptr) ? 1 : 0;
        if (biasShape != nullptr)
            readInto(biasShape, raw_input_shapes_);
        // Outputs
        for (size_t i = 0; i < ctx_->GetComputeNodeInfo()->GetOutputsNum(); ++i) {
            auto shape = ctx_->GetOutputShape(i);
            OP_CHECK_NULL_WITH_CONTEXT(ctx_, shape);
            readInto(shape, raw_output_shapes_);
        }
        return ge::GRAPH_SUCCESS;
    }

    ge::graphStatus ReadDtypeSize()
    {
        auto inputDesc = ctx_->GetInputDesc(0);
        OP_CHECK_NULL_WITH_CONTEXT(ctx_, inputDesc);
        ge::DataType dtype = inputDesc->GetDataType();
        if (dtype == ge::DT_FLOAT16 || dtype == ge::DT_BF16)
            dtype_size_ = 2;
        else if (dtype == ge::DT_FLOAT)
            dtype_size_ = 4;
        else {
            OP_LOGE(ctx_->GetNodeName(), "Unsupported dtype");
            return ge::GRAPH_FAILED;
        }
        return ge::GRAPH_SUCCESS;
    }

    void ReadAttrs()
    {
        const auto* attrs = ctx_->GetAttrs();
        if (attrs == nullptr)
            return;
        const int64_t* axisPtr = attrs->GetInt(0);
        const int64_t* numAxesPtr = attrs->GetInt(1);
        const bool* sfbPtr = attrs->GetBool(2);
        axis_ = axisPtr ? *axisPtr : 1;
        num_axes_ = numAxesPtr ? *numAxesPtr : 1;
        scale_from_blob_ = sfbPtr ? *sfbPtr : true;
    }

    void PadVecToAxis(std::vector<int64_t>& vshape, int64_t xRank, int64_t newAxis) const
    {
        int64_t vrank = (int64_t)vshape.size();
        if (vrank == 0)
            return;
        if (!(vrank < xRank && newAxis >= 0 && newAxis < xRank))
            return;
        std::vector<int64_t> padded(xRank, 1);
        if (scale_from_blob_) {
            int64_t scaleLen = (num_axes_ == -1) ? (xRank - newAxis) : num_axes_;
            if (scaleLen != 0)
                for (int64_t i = 0; i < vrank && (newAxis + i) < xRank; i++)
                    padded[newAxis + i] = vshape[i];
        } else {
            for (int64_t i = 0; i < vrank && (newAxis + i) < xRank; i++)
                padded[newAxis + i] = vshape[i];
        }
        vshape = padded;
    }

    void PrePadScaleBias()
    {
        if (raw_input_shapes_.size() < 2)
            return;
        int64_t xRank = (int64_t)raw_input_shapes_[0].size();
        int64_t newAxis = axis_ >= 0 ? axis_ : xRank + axis_;
        PadVecToAxis(raw_input_shapes_[1], xRank, newAxis);
        if (raw_input_shapes_.size() >= 3)
            PadVecToAxis(raw_input_shapes_[2], xRank, newAxis);
    }

    ge::graphStatus GetShapeInfo()
    {
        if (ReadPlatform() != ge::GRAPH_SUCCESS)
            return ge::GRAPH_FAILED;
        if (ReadShapes() != ge::GRAPH_SUCCESS)
            return ge::GRAPH_FAILED;
        if (ReadDtypeSize() != ge::GRAPH_SUCCESS)
            return ge::GRAPH_FAILED;
        ReadAttrs();
        PrePadScaleBias();

        // Normalize shapes for broadcast (handles multi-input broadcasting)
        if (!gru_block_cell_grad::PadAndSqueeze(raw_input_shapes_, raw_output_shapes_, max_bro_shape_, normal_input_shapes_,
                                   normal_output_shapes_)) {
            OP_LOGE(ctx_->GetNodeName(), "scale/bias shape cannot broadcast to x");
            return ge::GRAPH_FAILED;
        }
        rank_ = (int64_t)max_bro_shape_.size();

        // GRUBlockCellGrad supports max rank 8 (hardware vector register limit)
        if (rank_ > 8) {
            OP_LOGE(ctx_->GetNodeName(), "rank(%ld) exceeds max supported dim 8", rank_);
            return ge::GRAPH_FAILED;
        }

        OP_LOGI(ctx_->GetNodeName(), "GetShapeInfo done rank %ld dtype %ld ub %lu core %lu has_bias %ld", rank_,
                dtype_size_, ubSize_, coreNum_, has_bias_);

        return ge::GRAPH_SUCCESS;
    }

    template <int64_t R, typename ShapeArr, typename StrideArr>
    static void FillSlots(ShapeArr shapes, StrideArr strides, const std::vector<std::vector<int64_t>>& norm,
                           const std::vector<std::vector<int64_t>>& norm_strides, int64_t num, int64_t max_slots,
                           int64_t delta)
    {
        int64_t rank = R - delta;
        // Fill used slots
        for (int64_t i = 0; i < num; i++) {
            // Leading delta dimensions get shape=1, stride=0 (broadcast)
            for (int64_t d = 0; d < delta; d++) {
                shapes[i][d] = 1;
                strides[i][d] = 0;
            }
            // Actual dimensions fill from normalized shapes
            for (int64_t d = 0; d < rank; d++) {
                shapes[i][d + delta] = norm[i][d];
                strides[i][d + delta] = norm_strides[i][d];
            }
        }
        // Clear unused slots
        for (int64_t i = num; i < max_slots; i++)
            for (int64_t d = 0; d < R; d++) {
                shapes[i][d] = 1;
                strides[i][d] = 0;
            }
    }

    template <int64_t R>
    ge::graphStatus DoTilingAndSet()
    {
        auto* tiling = ctx_->GetTilingData<GRUBlockCellGradTilingData<R>>();
        OP_CHECK_NULL_WITH_CONTEXT(ctx_, tiling);

        int64_t ub_per_core = (int64_t)ubSize_;
        int64_t per_buf_bytes = (ub_per_core / kPhysNodes) & ~31LL;

        gru_block_cell_grad::FindSplitAxis(max_bro_shape_, dtype_size_, ub_per_core, kPhysNodes, tiling->split);
        gru_block_cell_grad::MultiCoreSplit(max_bro_shape_, tiling->split, (int64_t)coreNum_, tiling->multicore);
        tiling->per_buf_bytes = per_buf_bytes;
        tiling->per_buf_elems = per_buf_bytes / 4;  // FP32 elements per buffer

        int64_t num_in = (int64_t)normal_input_shapes_.size();
        int64_t num_out = (int64_t)normal_output_shapes_.size();
        std::vector<std::vector<int64_t>> in_strides(num_in), out_strides(num_out);
        for (int64_t i = 0; i < num_in; i++)
            gru_block_cell_grad::PrecomputeStrides(normal_input_shapes_[i], in_strides[i]);
        for (int64_t i = 0; i < num_out; i++)
            gru_block_cell_grad::PrecomputeStrides(normal_output_shapes_[i], out_strides[i]);

        tiling->rank = rank_;
        tiling->has_bias = has_bias_;
        int64_t delta = R - rank_;  // Padding gap between template rank and actual rank

        for (int64_t d = 0; d < delta; d++)
            tiling->max_bro_shape[d] = 1;
        for (int64_t d = 0; d < rank_; d++)
            tiling->max_bro_shape[d + delta] = max_bro_shape_[d];

        tiling->split.axis += delta;

        tiling->num_inputs = num_in;
        tiling->num_outputs = num_out;

        FillSlots<R>(tiling->input_shapes, tiling->input_strides, normal_input_shapes_, in_strides, num_in,
                      kMaxInputSlots, delta);
        FillSlots<R>(tiling->output_shapes, tiling->output_strides, normal_output_shapes_, out_strides, num_out,
                      kMaxOutputSlots, delta);

        ctx_->SetBlockDim(tiling->multicore.num_cores);
        LogTilingData<R>(tiling, num_in, num_out);
        return ge::GRAPH_SUCCESS;
    }

    template <int64_t R>
    void LogTilingData(GRUBlockCellGradTilingData<R>* tiling, int64_t num_in, int64_t num_out)
    {
        OP_LOGI(ctx_->GetNodeName(),
                "TilingData: per_buf_bytes=%ld rank=%ld->R=%d "
                "max_bro_shape=%s "
                "split(axis=%ld a_i=%ld a_o=%ld a_i_tail=%ld) "
                "multi(cores=%ld tiles=%ld main=%ld core_tail=%ld) num_in=%ld num_out=%ld has_bias=%ld",
                tiling->per_buf_bytes, rank_, (int)R, Arr2String(tiling->max_bro_shape, R).c_str(), tiling->split.axis,
                tiling->split.a_i, tiling->split.a_o, tiling->split.a_i_tail, tiling->multicore.num_cores,
                tiling->multicore.total_tiles, tiling->multicore.tiles_main, tiling->multicore.cores_tail, num_in,
                num_out, has_bias_);
    }

    // --- Member variables (read from context during GetShapeInfo) ---
    gert::TilingContext* ctx_;                              // Tiling context (read/write tiling data)
    std::vector<std::vector<int64_t>> raw_input_shapes_;    // Original input shapes (before normalization)
    std::vector<std::vector<int64_t>> raw_output_shapes_;   // Original output shapes
    std::vector<int64_t> max_bro_shape_;                    // Maximum broadcast shape (after PadAndSqueeze)
    std::vector<std::vector<int64_t>> normal_input_shapes_; // Normalized (squeezed) input shapes
    std::vector<std::vector<int64_t>> normal_output_shapes_;// Normalized (squeezed) output shapes
    int64_t dtype_size_ = 0;     // Bytes per element (2 for FP16/BF16, 4 for FP32)
    int64_t rank_ = 0;           // Effective rank after PadAndSqueeze (1-8)
    int64_t has_bias_ = 0;       // 1 if bias tensor is present, 0 otherwise
    int64_t axis_ = 1;           // Broadcast axis (from operator attribute)
    int64_t num_axes_ = 1;       // Number of broadcast axes (from operator attribute)
    bool scale_from_blob_ = true;// Scale-from-blob flag (from operator attribute)
    uint64_t coreNum_ = 0;       // Number of AIV cores on the NPU
    uint64_t ubSize_ = 0;        // Unified Buffer size per core (bytes)
};

static ge::graphStatus TilingFuncGRUBlockCellGrad(gert::TilingContext* context)
{
    GRUBlockCellGradTiling scaleTiling(context);
    auto ret = scaleTiling.RunTiling();
    if (ret != ge::GRAPH_SUCCESS)
        return ret;
    size_t* workspaces = context->GetWorkspaceSizes(1);
    workspaces[0] = 0;
    return ge::GRAPH_SUCCESS;
}

ge::graphStatus TilingPrepareForGRUBlockCellGrad(gert::TilingParseContext* context)
{
    fe::PlatFormInfos* platformInfo = context->GetPlatformInfo();
    auto compileInfo = context->GetCompiledInfo<GRUBlockCellGradCompileInfo>();
    OP_CHECK_NULL_WITH_CONTEXT(context, platformInfo);
    OP_CHECK_NULL_WITH_CONTEXT(context, compileInfo);
    auto ap = platform_ascendc::PlatformAscendC(platformInfo);
    compileInfo->coreNum = ap.GetCoreNumAic();   // MIX_AIC_1_2 组数上限 = AIC 核数（原 GetCoreNumAiv 与 MIX 组模型不符）
    ap.GetCoreMemSize(platform_ascendc::CoreMemType::UB, compileInfo->ubSize);
    return ge::GRAPH_SUCCESS;
}

IMPL_OP_OPTILING(GRUBlockCellGrad).Tiling(TilingFuncGRUBlockCellGrad).TilingParse<GRUBlockCellGradCompileInfo>(TilingPrepareForGRUBlockCellGrad);

