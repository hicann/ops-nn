IMPL_OP_OPTILING(ThnnFusedGruCellGrad)
    .Tiling(ThnnFusedGruCellGradTilingFunc)
    .TilingParse<ThnnFusedGruCellGradCompileInfo>(TilingPrepareForThnnFusedGruCellGrad);

