bool RunAndVerifyCase(ge::Session* session, uint32_t graphId, const LstmCase& cs, const std::string& concreteJson,
                      const std::vector<int64_t>& xShapeOverride, bool printPassLine)
{
    LstmInputs in;
    BuildInputs(cs, in);
    LstmGolden golden;
    CpuLstmGolden(cs, in, golden);

    std::vector<std::vector<int64_t>> shapes = CaseShapes(cs);
    if (!xShapeOverride.empty()) {
        shapes[0] = xShapeOverride; // probe: feed x with a different (rank-flexible) view
    }
    const std::vector<float>* bufs[8] = {&in.x, &in.csPrev, &in.hPrev, &in.w, &in.wci, &in.wcf, &in.wco, &in.b};

    std::vector<ge::Tensor> feeds;
    for (int i = 0; i < 8; ++i) {
        feeds.push_back(MakeHostTensor(shapes[i], bufs[i]->data(), bufs[i]->size()));
    }

    std::vector<ge::Tensor> output;
    Status ret = session->RunGraph(graphId, feeds, output);
    if (ret != SUCCESS) {
        printf("RunGraph rejected, ret=%u\n", static_cast<uint32_t>(ret));
        return false;
    }
    if (output.size() != 7) {
        printf("unexpected output num=%zu\n", output.size());
        return false;
    }

    bool allPass = true;
    static const char* kNames[7] = {"i", "cs", "f", "o", "ci", "co", "h"};
    const std::vector<float>* want[7] = {&golden.i,  &golden.cs, &golden.f, &golden.o,
                                         &golden.ci, &golden.co, &golden.h};
    const int64_t n = cs.batch * cs.hiddenSize;
    for (int k = 0; k < 7; ++k) {
        const ge::Tensor& t = output[k];
        if (t.GetTensorDesc().GetDataType() != ge::DT_FLOAT) {
            printf("  [%s] dtype mismatch: %d != DT_FLOAT\n", kNames[k],
                   static_cast<int>(t.GetTensorDesc().GetDataType()));
            allPass = false;
            continue;
        }
        if (t.GetData() == nullptr || t.GetSize() < static_cast<size_t>(n) * sizeof(float)) {
            printf("  [%s] empty/short output buffer\n", kNames[k]);
            allPass = false;
            continue;
        }
        // Shape check: concrete [B,H], or unknown dims (dynamic desc) with exact byte size
        const auto& os = t.GetTensorDesc().GetShape().GetDims();
        const bool shapeOk = (os.size() == 2 && os[0] == cs.batch && os[1] == cs.hiddenSize) ||
                             (os.size() == 2 && (os[0] < 0 || os[1] < 0) &&
                              t.GetSize() == static_cast<size_t>(n) * sizeof(float));
        if (!shapeOk) {
            printf("  [%s] shape mismatch: expect [%ld,%ld], got rank %zu\n", kNames[k], static_cast<long>(cs.batch),
                   static_cast<long>(cs.hiddenSize), os.size());
            allPass = false;
            continue;
        }
        const float* got = reinterpret_cast<const float*>(t.GetData());
        allPass &= CompareOutput(got, want[k]->data(), n, kNames[k]);
    }
    if (allPass && printPassLine) {
        printf("Shape, dtype and values PASSED for %s\n", concreteJson.c_str());
    }
    return allPass;
}

// One dynamic scenario: AddGraph once, consecutive RunGraph per concrete case.
