/*!
 * \file proj_budget.h
 * \brief Full-shape tile search for the single-step LSTMBlockCell GEMM.
 *
 * Its own header so `TilingFunc` and the host-side TilingUT call THE SAME
 * function. A tiling that hands back a tile one element too large overflows
 * L0A/L0B/L0C/BT/L1/UB on chip with no error anywhere -- so "it looked right"
 * is not an acceptable level of assurance for this arithmetic.
 * Host-side unit tests check it against the capacities independently,
 * including the shapes that must be REFUSED.
 *
 * Plain C++ (fwd_layout.h -> onchip_budget.h, no AscendC), so it builds under
 * g++ with op_host.
 *
 * TF LSTMBlockCell is single-step: ONE GEMM `gates = [x, h_prev] @ w + b`,
 * M = mBlk (batch), K = I + H (two segments), N = nBlk (one gate column tile
 * at a time), no time loop, no persistence.
 *
 * SEARCH POLICY (documented because it is a policy, not an accident):
 *   1. mBlk starts at CeilDiv(B, maxBlocks) -- the SMALLEST batch split that
 *      still uses every block -- and grows until a (nBlk, kChunk) fits. Small
 *      mBlk maximizes cross-cluster parallelism and minimizes the per-AIV
 *      plane, which is what the UB budget is dominated by.
 *   2. For each mBlk, nBlk falls from NBLK_MAX to NBLK_MIN: large nBlk means
 *      few N-tiles, which means few A-tile reloads in the cube loop (the A
 *      tile is re-read once per nTile, the structural cost of N-tiling).
 *   3. kChunk is the largest C0<T>-multiple whose A and B tiles fit L0A/L0B
 *      and L1.
 *   4. slots is 4 when four L0C accumulators (one full nTile's four gates)
 *      fit, else 2, else 1.
 *   5. MULTI-ROUND FALLBACK (no-capacity-refusal design): when the
 *      whole batch cannot give every cluster a single-round tile (B so large
 *      that even CeilDiv(B, maxBlocks) rows overflow the per-AIV planes), the
 *      per-round burst shrinks to the LARGEST mBlk that fits on chip and each
 *      cluster digests its row span in CeilDiv(span, burst) rounds (the
 *      kernel-side round loop; a single-step cell has no cross-batch
 *      dependency, so rounds only need the ring flags closed, which every
 *      CubeProject round does). blockDim = min(maxBlocks, CeilDiv(B, burst))
 *      = maxBlocks -- every core. The fallback search CANNOT fail: at
 *      mBlk=16 one [8, nBlk] fp32 plane is a few KB.
 * The first (mBlk, nBlk) with a valid kChunk wins; refusing is the failure
 * mode, not clamping.
 */
