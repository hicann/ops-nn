    td->kChunk = tc.kChunk;
    td->slots = tc.slots;
    td->offBiasF32 = static_cast<uint32_t>(sysWs / sizeof(float)); // 跳过系统保留区的 fp32 元素偏移
    td->tilingKey = key;
    td->ksCores = 0;
    td->ksStrips = 0;
    td->ksSegWidth = 0;
    td->offPartials = 0;
    td->splitGemm = 0;
