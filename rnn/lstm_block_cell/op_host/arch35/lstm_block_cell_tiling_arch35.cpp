static ge::graphStatus TilingFuncLstmBlockCell(gert::TilingContext* context)
{
    OP_LOGI(context->GetNodeName(), "Enter LstmBlockCellTilingFunc");

    auto* td = context->GetTilingData<LstmBlockCellTilingData>();
    OP_CHECK_NULL_WITH_CONTEXT(context, td);

    // ===== 读取 shape（输入：0=x, 1=cs_prev, 2=h_prev, 3=w, 4..6=wci/wcf/wco, 7=b）=====
    const gert::StorageShape* xs = context->GetInputShape(0);   // x  [B, I]
    const gert::StorageShape* cs = context->GetInputShape(1);   // cs_prev [B, H]
    const gert::StorageShape* hs = context->GetInputShape(2);   // h_prev [B, H]
    const gert::StorageShape* ws = context->GetInputShape(3);   // w  [I+H, 4H]
    const gert::StorageShape* wciS = context->GetInputShape(4); // wci [H]
    const gert::StorageShape* wcfS = context->GetInputShape(5); // wcf [H]
    const gert::StorageShape* wcoS = context->GetInputShape(6); // wco [H]
    const gert::StorageShape* bs = context->GetInputShape(7);   // b  [4H]
    OP_CHECK_NULL_WITH_CONTEXT(context, xs);
    OP_CHECK_NULL_WITH_CONTEXT(context, cs);
    OP_CHECK_NULL_WITH_CONTEXT(context, hs);
    OP_CHECK_NULL_WITH_CONTEXT(context, ws);
    OP_CHECK_NULL_WITH_CONTEXT(context, wciS);
    OP_CHECK_NULL_WITH_CONTEXT(context, wcfS);
    OP_CHECK_NULL_WITH_CONTEXT(context, wcoS);
    OP_CHECK_NULL_WITH_CONTEXT(context, bs);

    // ===== Rank 校验 =====
    if (xs->GetStorageShape().GetDimNum() != 2 || cs->GetStorageShape().GetDimNum() != 2 ||
        hs->GetStorageShape().GetDimNum() != 2 || ws->GetStorageShape().GetDimNum() != 2 ||
        wciS->GetStorageShape().GetDimNum() != 1 || wcfS->GetStorageShape().GetDimNum() != 1 ||
        wcoS->GetStorageShape().GetDimNum() != 1 || bs->GetStorageShape().GetDimNum() != 1) {
        OP_LOGE(context->GetNodeName(),
                "rank mismatch: x/cs_prev/h_prev/w must be rank 2 (cur %zu/%zu/%zu/%zu), "
                "wci/wcf/wco/b must be rank 1 (cur %zu/%zu/%zu/%zu)",
                xs->GetStorageShape().GetDimNum(), cs->GetStorageShape().GetDimNum(), hs->GetStorageShape().GetDimNum(),
                ws->GetStorageShape().GetDimNum(), wciS->GetStorageShape().GetDimNum(),
                wcfS->GetStorageShape().GetDimNum(), wcoS->GetStorageShape().GetDimNum(),
                bs->GetStorageShape().GetDimNum());
        return ge::GRAPH_FAILED;
    }

    // ===== 提取维度（先校验后转换，防 uint32 窄化回绕）=====
    const int64_t dimB = xs->GetStorageShape().GetDim(0);
    const int64_t dimI = xs->GetStorageShape().GetDim(1);
    const int64_t dimH = cs->GetStorageShape().GetDim(1);
    if (dimB <= 0 || dimB > DIM_MAX || dimI <= 0 || dimI > DIM_MAX || dimH <= 0 || dimH > DIM_MAX) {
        OP_LOGE(context->GetNodeName(), "invalid dims: B/I/H must be in [1, 2^24], cur B=%ld I=%ld H=%ld", dimB, dimI,
                dimH);
        return ge::GRAPH_FAILED;
    }
    const uint32_t B = static_cast<uint32_t>(dimB);
    const uint32_t I = static_cast<uint32_t>(dimI);
    const uint32_t H = static_cast<uint32_t>(dimH);

    // ===== 跨输入一致性 =====
    if (hs->GetStorageShape().GetDim(0) != static_cast<int64_t>(B) ||
        hs->GetStorageShape().GetDim(1) != static_cast<int64_t>(H) ||
        cs->GetStorageShape().GetDim(0) != static_cast<int64_t>(B)) {
        OP_LOGE(context->GetNodeName(),
                "shape mismatch: cs_prev/h_prev must be [B, H] consistent with x, cur B=%u H=%u", B, H);
        return ge::GRAPH_FAILED;
    }
    constexpr uint32_t GATES = LSTM_BLOCK_CELL_GATES;
    if (ws->GetStorageShape().GetDim(0) != static_cast<int64_t>(I + H) ||
        ws->GetStorageShape().GetDim(1) != static_cast<int64_t>(GATES * H)) {
        OP_LOGE(context->GetNodeName(), "shape mismatch: w must be [I+H, 4H], cur [%ld, %ld], expected [%u, %u]",
                ws->GetStorageShape().GetDim(0), ws->GetStorageShape().GetDim(1), I + H, GATES * H);
        return ge::GRAPH_FAILED;
    }
    if (bs->GetStorageShape().GetDim(0) != static_cast<int64_t>(GATES * H)) {
        OP_LOGE(context->GetNodeName(), "shape mismatch: b must be [4H], cur %ld, expected %u",
                bs->GetStorageShape().GetDim(0), GATES * H);
        return ge::GRAPH_FAILED;
    }
    if (wciS->GetStorageShape().GetDim(0) != static_cast<int64_t>(H) ||
        wcfS->GetStorageShape().GetDim(0) != static_cast<int64_t>(H) ||
        wcoS->GetStorageShape().GetDim(0) != static_cast<int64_t>(H)) {
        OP_LOGE(context->GetNodeName(), "shape mismatch: wci/wcf/wco must be [H], cur %ld/%ld/%ld, expected %u",
                wciS->GetStorageShape().GetDim(0), wcfS->GetStorageShape().GetDim(0), wcoS->GetStorageShape().GetDim(0),
                H);
        return ge::GRAPH_FAILED;
    }

    // ===== 属性读取：forget_bias（默认 1.0）、cell_clip（默认 3.0）、use_peephole（默认 false）=====
    float forgetBiasVal = 1.0f;
    float cellClipVal = 3.0f;
    bool usePeepholeVal = false;
    auto* attrs = context->GetAttrs();
    OP_CHECK_NULL_WITH_CONTEXT(context, attrs);
    const float* fb = attrs->GetAttrPointer<float>(0); // forget_bias
    const float* cc = attrs->GetAttrPointer<float>(1); // cell_clip
    const bool* up = attrs->GetAttrPointer<bool>(2);   // use_peephole
    if (fb != nullptr) {
        forgetBiasVal = *fb;
    }
    if (cc != nullptr) {
        cellClipVal = *cc;
    }
    if (up != nullptr) {
        usePeepholeVal = *up;
    }

    // ===== def 驱动 dtype：x.dtype -> tilingKey + 操作数类型 =====
    const gert::CompileTimeTensorDesc* xDesc = context->GetInputDesc(0);
    OP_CHECK_NULL_WITH_CONTEXT(context, xDesc);
    const ge::DataType xDt = xDesc->GetDataType();
    uint32_t key = 0;
    if (xDt == ge::DT_FLOAT) {
        key = 0; // fp32
    } else if (xDt == ge::DT_FLOAT16) {
        key = 1; // fp16
    } else {
        OP_LOGE(context->GetNodeName(), "dtype not supported: x must be float32/float16, cur dtype=%d",
                static_cast<int32_t>(xDt));
        return ge::GRAPH_FAILED;
    }

    // ===== 多核切分预算：平台上报的 AIC 核数（平台信息缺失即拒绝，不猜默认值）=====
    OP_CHECK_NULL_WITH_CONTEXT(context, context->GetPlatformInfo());
    auto plat = platform_ascendc::PlatformAscendC(context->GetPlatformInfo());
    uint32_t maxBlocks = plat.GetCoreNumAic();
    if (maxBlocks == 0) {
        OP_LOGE(context->GetNodeName(), "platform reports zero AIC core count");
        return ge::GRAPH_FAILED;
    }

    // ===== GM 偏移上界守卫：kernel 侧全部 GM 直接偏移以 uint32 元素寻址，
    // 其上界即下面三条乘积（x 偏移 < B*I、输出偏移 < B*H、w 偏移 < (I+H)*4H）。
    // 每个张量的总元素数必须 < 2^32（uint32 紧边界），否则乘法回绕导致静默
    // 读错地址（无任何报错）。host 侧一次性拒绝。[2^31, 2^32) 区间经真机
    // 实证（uint32 寻址下精度 PASS）。
    constexpr uint64_t ELEM_MAX = 1ULL << 32;
    if (static_cast<uint64_t>(B) * I >= ELEM_MAX || static_cast<uint64_t>(B) * H >= ELEM_MAX ||
        static_cast<uint64_t>(I + H) * (GATES * H) >= ELEM_MAX) {
        OP_LOGE(context->GetNodeName(),
                "tensor too large: total elements must be < 2^32, cur B*I=%lu B*H=%lu (I+H)*4H=%lu",
                static_cast<unsigned long>(static_cast<uint64_t>(B) * I),
                static_cast<unsigned long>(static_cast<uint64_t>(B) * H),
                static_cast<unsigned long>(static_cast<uint64_t>(I + H) * (GATES * H)));
        return ge::GRAPH_FAILED;
    }

    // ===== Tile 搜索（操作数位宽感知）=====
    // fp16 以 uint16_t 作为位宽代理：PickTile 的算术只读 sizeof(TOp)（2 字节，
    // 与 half 相同）；bisheng 专属的 half 类型不能出现在本 g++ 编译单元。
    proj::TileChoice tc;
    if (key == 0) {
        tc = proj::PickTile<float>(B, I, H, maxBlocks);
    } else {
        tc = proj::PickTile<uint16_t>(B, I, H, maxBlocks);
    }
    if (!tc.ok) {
        OP_LOGE(context->GetNodeName(), "tile search refused: %s (B=%u I=%u H=%u blocks=%u)", tc.why, B, I, H,
                maxBlocks);
        return ge::GRAPH_FAILED;
    }

    // ===== 系统 workspace 大小：用户区之前的保留区 =====
    // kernel 可见的 `workspace` 基址横跨 [系统保留区][用户区]；DumpTensor /
    // ASCENDC_OOM 构建会写入保留区，所以用户数据必须从保留区之后开始。
    // 保留区大小必须取真实值：猜小了会把用户数据落进保留区被静默破坏，
    // 因此平台信息缺失时直接拒绝（上方已判空，此处不再兜底）。
    const size_t sysWs = static_cast<size_t>(plat.GetLibApiWorkSpaceSize());

    // ===== K-split 计划（默认策略，常量见文件头注释）=====
    uint32_t ksSk = 0;
    uint32_t ksW = 0;
    if (key == 0) { // fp32
        const uint32_t K = I + H;
        ksSk = maxBlocks / 2; // K 轴并行度 = 核数一半（strips 至少 2 才能用满全部核）
        ksW = (K > KS_W_THRESHOLD_LARGE) ? KS_W_DEFAULT : ((K > KS_W_THRESHOLD_MID) ? KS_W_MID : KS_W_DEFAULT);
    } else { // fp16
        ksSk = KS_SK_FP16;
        ksW = 0;
    }

    // ===== 填充 TilingData =====
    td->batch = B;
    td->inputSize = I;
    td->hiddenSize = H;
    td->forgetBias = forgetBiasVal;
    td->cellClip = cellClipVal;
    td->usePeephole = usePeepholeVal ? 1u : 0u;
    td->rowsPerBlock = tc.mBlk; // 单轮最大行数（mBlkBurst）
    td->blockDim = tc.blockDim;
    td->rowsPerClusterTotal = tc.rowsPerClusterTotal; // cluster 行段跨度；多轮模式大于 burst
    td->nBlk = tc.nBlk;
    td->kChunk = tc.kChunk;
    td->slots = tc.slots;
    td->offBiasF32 = static_cast<uint32_t>(sysWs / sizeof(float)); // 跳过系统保留区的 fp32 元素偏移
    td->tilingKey = key;
    td->ksCores = 0;
    td->ksStrips = 0;
    td->ksSegWidth = 0;
    td->offPartials = 0;
    context->SetTilingKey(key);

    // ===== Workspace 大小：sys + fp32 padded bias [4, CeilAlign(H, 16)]（+ K-split partial 平面）=====
    const uint32_t Hpad = ((H + 15u) / 16u) * 16u;
    size_t off = static_cast<size_t>(GATES) * Hpad;
    uint64_t ksPartElems = 0;
    {
        if (ksSk < 1) {
            ksSk = 1;
        }
        if (ksSk > maxBlocks) {
            ksSk = maxBlocks;
        }
        const uint32_t K = I + H;
        // W（段宽）是精度旋钮，只按 K 分档：常规档 160/64，小 K 域（ceil(K/12) < 档位值）
        // 按 KS_SMALL_K_SEGMENTS 段均分。W 与 SK（核数）解耦 —— 分段边界即数值，
        // 不随平台核数查询值漂移；反饥饿改为收缩协作核数而不是放宽 W。
        const uint32_t even = ch::CeilDiv(K, KS_SMALL_K_SEGMENTS);
        const uint32_t W = (ksW == 0) ? ch::CeilDiv(K, ksSk) : ((ksW < even) ? ksW : even);
        const uint32_t S = ch::CeilDiv(K, W);
        if (ksSk > S) {
            ksSk = S;
        } // 段数不足以喂满协作核时收缩 SK（每核至少 1 段），W 不动
        // M-strip 数：至多 ceil(AIC/SK) 使每个 strip 都有 SK 个协作核；不超过
        // PickTile 的 blockDim（tile 的片上平面按该 burst 计价，更宽的跨度只
        // 是多跑几轮）。空 strip 防护：每个 mIdx 必须拥有 >= 1 行，否则已启动
        // 的 block 会跳过全网格 SyncAll 而死锁。
        uint32_t strips = tc.blockDim;
        const uint32_t maxStrips = maxBlocks / ksSk;
        if (strips > maxStrips) {
            strips = maxStrips;
        }
        while (strips > 1 && (uint64_t)(strips - 1) * ch::CeilDiv(B, strips) >= (uint64_t)B) {
            --strips;
        }
        const uint32_t span = ch::CeilDiv(B, strips);
        const uint32_t rounds = ch::CeilDiv(span, tc.mBlk);
        const uint32_t pairs = ch::CeilDiv(H, tc.nBlk) * GATES;
        ksPartElems = fwd::KsPartialElems(strips, rounds, S, pairs, H, tc.nBlk, tc.mBlk);
        // KS 网格替换普通 M 切分（blockDim = strips*SK，每 strip 一个 span）；
        // kernel 侧从相同字段推导两者。
        td->blockDim = strips * ksSk;
        td->rowsPerClusterTotal = span;
        td->ksCores = ksSk;
        td->ksStrips = strips;
        td->ksSegWidth = W;
        td->offPartials = static_cast<uint32_t>(static_cast<uint64_t>(td->offBiasF32) +
                                                static_cast<uint64_t>(GATES) * Hpad);
        off += static_cast<size_t>(ksPartElems); // off 计数元素个数（字节数在下面统一换算）
    }
    context->SetBlockDim(td->blockDim);

    // ===== 调度模式（batch scheduling：AIC + 2 AIV 协同）=====
    (void)context->SetScheduleMode(1U);

    size_t* currentWorkspace = context->GetWorkspaceSizes(1);
    OP_CHECK_NULL_WITH_CONTEXT(context, currentWorkspace);
    currentWorkspace[0] = sysWs + off * sizeof(float);

    return ge::GRAPH_SUCCESS;
}

