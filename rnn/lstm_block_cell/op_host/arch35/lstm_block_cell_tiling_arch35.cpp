// ---------------------------------------------------------------------------
IMPL_OP_OPTILING(LstmBlockCell)
    .Tiling(TilingFuncLstmBlockCell)
    .TilingParse<LstmBlockCellCompileInfo>(TilingPrepareForLstmBlockCell);

