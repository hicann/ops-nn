static ge::graphStatus InferShapeForLstmBlockCell(gert::InferShapeContext* context)
{
    using namespace lstm_infershape;
    OP_CHECK_NULL_WITH_CONTEXT(context, context);
    const gert::Shape* x = context->GetInputShape(0);      // x [B, I]
    const gert::Shape* csPrev = context->GetInputShape(1); // cs_prev [B, H]
    OP_CHECK_NULL_WITH_CONTEXT(context, x);
    OP_CHECK_NULL_WITH_CONTEXT(context, csPrev);
    // 未知 rank：传播到全部输出，不在推导层拒绝（执行期由 TilingFunc 兜底校验）
    if (IsUnknownRank(x) || IsUnknownRank(csPrev)) {
        for (size_t k = 0; k < OUTPUT_NUM; ++k) {
            gert::Shape* out = context->GetOutputShape(k);
            OP_CHECK_NULL_WITH_CONTEXT(context, out);
            out->SetDimNum(1);
            out->SetDim(0, UNKNOWN_RANK_DIM);
        }
        return GRAPH_SUCCESS;
    }
    if (x->GetDimNum() != 2 || csPrev->GetDimNum() != 2) {
        OP_LOGE(context->GetNodeName(),
                "rank mismatch: x must be rank 2 [B, I] (cur rank %zu), "
                "cs_prev must be rank 2 [B, H] (cur rank %zu)",
                x->GetDimNum(), csPrev->GetDimNum());
        return GRAPH_FAILED;
    }
    for (size_t k = 0; k < OUTPUT_NUM; ++k) {
        gert::Shape* out = context->GetOutputShape(k);
        OP_CHECK_NULL_WITH_CONTEXT(context, out);
        out->SetDimNum(2);
        out->SetDim(0, x->GetDim(0));      // B
        out->SetDim(1, csPrev->GetDim(1)); // H
    }
    return GRAPH_SUCCESS;
}

