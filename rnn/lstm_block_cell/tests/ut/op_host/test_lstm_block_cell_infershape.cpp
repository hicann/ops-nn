gert::StorageShape MakeShape(const std::vector<int64_t>& dims)
{
    gert::StorageShape shape;
    for (const int64_t dim : dims) {
        shape.MutableOriginShape().AppendDim(dim);
        shape.MutableStorageShape().AppendDim(dim);
    }
    return shape;
}

ge::graphStatus RunInferShapeCase(const std::vector<std::vector<int64_t>>& inputDims, bool dropX = false,
                                  bool dropCs = false)
{
    std::vector<gert::StorageShape> inputShapes;
    for (const auto& dims : inputDims) {
        inputShapes.emplace_back(MakeShape(dims));
    }
    gert::StorageShape outShape = MakeShape({16, 173});
    std::vector<gert::StorageShape*> inputPtr;
    for (size_t i = 0; i < kNumInputs; ++i) {
        inputPtr.push_back((dropX && i == 0) || (dropCs && i == 1) ? nullptr : &inputShapes[i]);
    }
    std::vector<gert::StorageShape*> outputPtr(kNumOutputs, &outShape);

    auto holder = gert::InferShapeContextFaker()
                      .SetOpType("LstmBlockCell")
                      .NodeIoNum(kNumInputs, kNumOutputs)
                      .IrInstanceNum({1, 1, 1, 1, 1, 1, 1, 1})
                      .InputShapes(inputPtr)
                      .OutputShapes(outputPtr)
                      .Build();

    const auto* opImpl = gert::OpImplRegistry::GetInstance().GetOpImpl("LstmBlockCell");
    if (opImpl == nullptr || opImpl->infer_shape == nullptr) {
        ADD_FAILURE() << "LstmBlockCell InferShape was not registered";
        return ge::GRAPH_FAILED;
    }
    return opImpl->infer_shape(holder.GetContext<gert::InferShapeContext>());
}

