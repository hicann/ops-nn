/* fwd_layout.h -- the FULL-SHAPE single-step LSTMBlockCell on-chip layout.
 *
 * TF LSTMBlockCell is a single-step cell: ONE GEMM `gates = [x, h_prev] @ w + b`
 * (K = I+H, loaded as TWO segments so I and H need no alignment) followed by
 * ONE ICFO activation. The GEMM is tiled on every axis:
 *
 *   M: blockDim clusters, each owning a UNIFORM span of rowsPerClusterTotal
 *      rows (ceil-div, ragged tail is M-free). When the span exceeds mBlk
 *      (only possible for a batch too large for a single-round tile) the
 *      cluster iterates CeilDiv(span, mBlk) ROUNDS of mBlk rows -- every
 *      on-chip plane below is priced at ONE ROUND (mBlk), which is what the
 *      host's capacity arithmetic checks.
 *   N: nTiles x nBlk columns (nBlk % 16 == 0, ragged tail padded to
 *      nPad = CeilAlign(n, 16); pad lanes are garbage but COLUMN-ISOLATED and
 *      never stored -- the GM boundary uses DataCopyPad, byte-granular on the
 *      GM side on 3510)
 *   K: per segment (x: I, h: H) kChunk blocks (ragged tail is K-free)
 *
 * Split out of the kernel proper so a host compiled by **g++** (the operator's
 * `op_host`) can compute the same layout the kernel will use and REFUSE a
 * shape that does not fit, instead of launching a kernel that overflows a
 * buffer on chip. Only onchip_budget.h is needed -- no AscendC.
 *
 * ⚠ The `fits` decision must read THIS layout, never a re-derivation of it.
 * Two copies of a capacity formula drifting apart is a silent on-chip overflow,
 * the one failure mode with no error message anywhere.
 */
