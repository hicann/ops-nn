/* proj_impl.h -- full-shape single-step LSTMBlockCell cube projection (K-split).
 *
 *     gates = [x, h_prev] @ w + b     for the rows THIS cluster owns
 *
 * ONE GEMM, tiled on every axis (see fwd_layout.h):
 *   M  mThis rows of this cluster (ragged tail cluster included; M is free)
 *   N  nTiles x nBlk columns; the cube emits (nTile j, gate g) PAIRS, gate
 *      block g of w at columns [g*H + j*nBlk, +n). The LAST N-tile's ragged
 *      n loads with dValue = n (EXACT, no GM overread): the NZ image's last
 *      column block carries stale lanes, which land in OUTPUT pad columns --
 *      column-isolated garbage that the drain (padded to nPad) and the AIV
 *      (which stores only n real columns) never let reach GM.
 *   K  TWO segments: x over [0, I) and h_prev over [0, H). Loading each
 *      segment's A operand as its own tile removes the old "I % C0 == 0"
 *      constraint (no shared A-tile column blocks). Each segment blocks into
 *      kChunk pieces with a ragged tail (K is free: mp.k is honoured exactly).
 *
 * ⚠⚠ PARTITIONED ON BATCH ROWS. Each cluster projects exactly the rows it will
 * then activate, so the vector side never reads another cluster's bytes.
 *
 * ⚠ BIAS RIDES THE BIAS TABLE, NOT A VECTOR ADD. The BT broadcasts one row
 * over all M rows in hardware. The bias comes from the AIV's fp32 padded
 * workspace ([4, CeilAlign(H,16)], see the kernel entry): every (g, j) slice
 * [g*Hpad + j*nBlk, +nPad) is 32B-aligned by construction, so the AIC never
 * does a ragged GM read.
 *
 * A-tile traffic note: the A tile is re-read once per (group, k-block). With
 * slots == 4 a group is exactly one nTile's four gates, so A traffic is
 * mThis*K per nTile -- the structural cost of N-tiling, and it is small next
 * to the GEMM itself. slots drops to 2/1 only when L0C cannot hold four
 * accumulators, which the tile search avoids when it can.
 */
