/* ⚠ HOW ONE PIECE OF ARITHMETIC SERVES BOTH THE KERNEL AND THE HOST.
 *
 * bisheng compiles each .asc TWICE -- a device pass with __CCE_AICORE__ defined, then a host pass.
 * A plain function is implicitly __host__ and CANNOT be called from a __global__ __aicore__ body
 * ("call to __host__ function from __global__ __aicore__ function"), while an __aicore__ function
 * is harmless to merely define on the host pass. The asymmetry is one-directional, so this macro
 * gives each pass the decoration it needs from a SINGLE definition. The name
 * reads as "callable on both the host (g++ tiling) and the device (aicore
 * kernel)". */
