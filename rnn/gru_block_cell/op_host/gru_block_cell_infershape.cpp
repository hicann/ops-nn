// ---------------------------------------------------------------------------
// InferShape4GruBlockCell(context) — shape inference function
//
// ：r/u/c/h 恒为 [B, H] = [x.dim(0), hPrev.dim(1)]，4 输出同形；
// shape 已知时执行七条布局校验（与 TilingFunc [V5] 段同源），违规拒绝。
//
// Parameters:
// context — InferShapeContext providing access to input shapes and
// allowing setting of output shapes
//
// Returns: ge::graphStatus — ge::GRAPH_SUCCESS on success
// ---------------------------------------------------------------------------
static ge::graphStatus InferShape4GruBlockCell(gert::InferShapeContext* context)
{
    using gru_infershape::INPUT_NUM;
    using gru_infershape::OUTPUT_NUM;

    const gert::Shape* shapes[INPUT_NUM] = {nullptr};
    for (size_t i = 0; i < INPUT_NUM; ++i) {
        shapes[i] = context->GetInputShape(i);
        OP_CHECK_NULL_WITH_CONTEXT(context, shapes[i]);
    }

    // ---- [-2] 未知 rank 声明：整体放通，输出同样推成 [-2]（评审意见）----
    // 任一输入以 [-2] 进入推导时，B/I/H 均无从确定，输出 shape 也无法推导——
    // 此时**正常放通**并把 4 个输出同样下发为 [-2]（未知 rank），把全部具体
    // shape/rank/布局校验后移到执行期的 arch35 TilingFunc（[V3]-[V5] 以实际
    // StorageShape 兜底，违规 GRAPH_FAILED 干净拒绝、不下发设备）。
    // 推导层不在此拦截：既不放松契约（校验点只是后移），也避免把合法的动态
    // rank 构图误拒。
    for (size_t i = 0; i < INPUT_NUM; ++i) {
        if (!gru_infershape::IsUnknownRank(shapes[i])) {
            continue;
        }
        for (size_t k = 0; k < OUTPUT_NUM; ++k) {
            gert::Shape* outShape = context->GetOutputShape(k);
            OP_CHECK_NULL_WITH_CONTEXT(context, outShape);
            outShape->SetDimNum(1);
            outShape->SetDim(0, gru_infershape::UNKNOWN_RANK_DIM);
        }
        return ge::GRAPH_SUCCESS;
    }

    // ---- rank 校验（x/hPrev/wRu/wC rank=2，bRu/bC rank1 或 rank2 dim0==1）----
    // 动态 rank 联动（OpDef DynamicRankSupportFlag(true)）：声明 [-2] 的输入以
    // 未知 rank 进入推导（GE -2 语义），跳过其 rank/值校验；数学契约不变——
    // 执行期实际供数 shape 仍须满足 shape 契约（arch35 TilingFunc [V3]-[V5] 兜底）。
    // 具体非法 rank（如 x rank 1/9）仍在此拒绝，静态负向口径不退化。
    for (size_t i = 0; i < 4; ++i) { // x/hPrev/wRu/wC rank=2
        if (gru_infershape::IsUnknownRank(shapes[i])) {
            continue; // [-2] 未知 rank 声明：推导期跳过，执行期定形
        }
        if (shapes[i]->GetDimNum() != 2) {
            OP_LOGE_FOR_INVALID_SHAPEDIM(context->GetNodeName(), gru_infershape::INPUT_NAMES[i],
                                         (std::to_string(shapes[i]->GetDimNum()) + "D").c_str(), "2D");
            return ge::GRAPH_FAILED;
        }
    }
    for (size_t i = 4; i < INPUT_NUM; ++i) { // bRu/bC：rank1，或 rank2 且 dim0==1（size-1 广播视图）
        if (gru_infershape::IsUnknownRank(shapes[i])) {
            continue; // [-2] 未知 rank 声明：推导期跳过，执行期定形
        }
        const size_t rank = shapes[i]->GetDimNum();
        if (rank != 1 && rank != 2) {
            OP_LOGE_FOR_INVALID_SHAPEDIM_WITH_REASON(context->GetNodeName(), gru_infershape::INPUT_NAMES[i],
                                                     (std::to_string(rank) + "D").c_str(),
                                                     "must be 1D, or 2D with dim0 equal to 1 (size-1 broadcast view)");
            return ge::GRAPH_FAILED;
        }
        if (rank == 2) {
            const int64_t dim0 = shapes[i]->GetDim(0);
            if (gru_infershape::DimKnown(dim0) && dim0 != 1) {
                const std::string paramName = std::string(gru_infershape::INPUT_NAMES[i]) + ".dim0";
                OP_LOGE_FOR_INVALID_VALUE(context->GetNodeName(), paramName.c_str(), std::to_string(dim0).c_str(), "1");
                return ge::GRAPH_FAILED;
            }
        }
    }

    // B/I/H 提取（未知 rank 声明 / 越界索引 → -1 未知占位，后续校验按未知跳过）
    const int64_t batchSize = gru_infershape::DimAt(shapes[0], 0);  // x.dim(0)
    const int64_t inputSize = gru_infershape::DimAt(shapes[0], 1);  // x.dim(1)
    const int64_t hiddenSize = gru_infershape::DimAt(shapes[1], 1); // hPrev.dim(1)

    // ---- 空 tensor 拒绝（B/I/H ≥ 1， 边界）----
    if (gru_infershape::DimKnown(batchSize) && batchSize < 1) {
        OP_LOGE_FOR_INVALID_VALUE_WITH_REASON(context->GetNodeName(), "x.dim0 (batch size B)",
                                              std::to_string(batchSize).c_str(),
                                              "must be >= 1; empty tensor is not supported");
        return ge::GRAPH_FAILED;
    }
    if (gru_infershape::DimKnown(inputSize) && inputSize < 1) {
        OP_LOGE_FOR_INVALID_VALUE_WITH_REASON(context->GetNodeName(), "x.dim1 (input size I)",
                                              std::to_string(inputSize).c_str(),
                                              "must be >= 1; empty tensor is not supported");
        return ge::GRAPH_FAILED;
    }
    if (gru_infershape::DimKnown(hiddenSize) && hiddenSize < 1) {
        OP_LOGE_FOR_INVALID_VALUE_WITH_REASON(context->GetNodeName(), "hPrev.dim1 (hidden size H)",
                                              std::to_string(hiddenSize).c_str(),
                                              "must be >= 1; empty tensor is not supported");
        return ge::GRAPH_FAILED;
    }

    // ---- 七条布局校验（仅当涉 dims 已知时执行——动态 shape/[-2] 交 Tiling 兜底）----
    const int64_t dim0H = gru_infershape::DimAt(shapes[1], 0);
    if (gru_infershape::DimKnown(batchSize) && gru_infershape::DimKnown(dim0H) && dim0H != batchSize) {
        OP_LOGE_FOR_INVALID_VALUE_WITH_REASON(
            context->GetNodeName(), "hPrev.dim0", std::to_string(dim0H).c_str(),
            ("must be equal to x.dim0, which is " + std::to_string(batchSize)).c_str());
        return ge::GRAPH_FAILED;
    }
    if (gru_infershape::DimKnown(inputSize) && gru_infershape::DimKnown(hiddenSize)) {
        const int64_t kDim = inputSize + hiddenSize;
        // wRu == [I+H, 2H]（wRu/wC 为 [-2] 未知 rank 声明时跳过——GetDim(1) 对 rank1
        // 声明越界，且布局无法核实，执行期由 Tiling [V5] 以实际 shape 兜底）
        if (!gru_infershape::IsUnknownRank(shapes[2]) &&
            (gru_infershape::DimAt(shapes[2], 0) != kDim ||
             gru_infershape::DimAt(shapes[2], 1) != GRU_GATE_NUM * hiddenSize)) {
            const std::string want = "[" + std::to_string(kDim) + ", " + std::to_string(GRU_GATE_NUM * hiddenSize) +
                                     "]";
            OP_LOGE_FOR_INVALID_SHAPE(context->GetNodeName(), "wRu", Shape2String(*shapes[2]).c_str(), want.c_str());
            return ge::GRAPH_FAILED;
        }
        // wC == [I+H, H]（同上，[-2] 声明跳过）
        if (!gru_infershape::IsUnknownRank(shapes[3]) &&
            (gru_infershape::DimAt(shapes[3], 0) != kDim || gru_infershape::DimAt(shapes[3], 1) != hiddenSize)) {
            const std::string want = "[" + std::to_string(kDim) + ", " + std::to_string(hiddenSize) + "]";
            OP_LOGE_FOR_INVALID_SHAPE(context->GetNodeName(), "wC", Shape2String(*shapes[3]).c_str(), want.c_str());
            return ge::GRAPH_FAILED;
        }
    }
    if (gru_infershape::DimKnown(hiddenSize)) {
        // bRu 元素总数 == 2H、bC 元素总数 == H（rank1 (2H,)/(H,) 与 [1,2H]/[1,H]
        // size-1 广播视图按总量等价判定；任一维未知时跳过，交 Tiling 兜底）
        // bRu 承载 r|u 两门 ⇒ GRU_GATE_NUM*H；bC 单门 ⇒ H
        const int64_t biasElems[INPUT_NUM - 4] = {GRU_GATE_NUM * hiddenSize, hiddenSize};
        for (size_t i = 4; i < INPUT_NUM; ++i) {
            const int64_t total = gru_infershape::TotalElems(shapes[i]);
            if (total >= 0 && total != biasElems[i - 4]) {
                OP_LOGE_FOR_INVALID_SHAPESIZE(context->GetNodeName(), gru_infershape::INPUT_NAMES[i],
                                              std::to_string(total).c_str(), std::to_string(biasElems[i - 4]).c_str());
                return ge::GRAPH_FAILED;
            }
        }
    }

    // ---- 输出：4 × [B, H] 同形（dtype 由 InferDataType 承载）----
    // B/H 未知（动态声明 [-1]/[-2] 或执行期定形前）→ 输出按未知维 [-1,H]/[-1,-1] 下发；
    // 声明输出冲突判定已移除（见 gru_infershape 命名空间头注释），推导直接覆写。
    for (size_t k = 0; k < OUTPUT_NUM; ++k) {
        gert::Shape* outShape = context->GetOutputShape(k);
        OP_CHECK_NULL_WITH_CONTEXT(context, outShape);
        outShape->SetDimNum(2);
        outShape->SetDim(0, batchSize);
        outShape->SetDim(1, hiddenSize);
    }
    return ge::GRAPH_SUCCESS;
}

