// 维度已知（≥0：-1/-2 为未知/任意占位，动态场景跳过值校验）
inline bool DimKnown(int64_t d) { return d >= 0; }

// 输入是否为未知 rank 声明 [-2]（动态 rank，OpDef DynamicRankSupportFlag(true)）：
// 构图期以 [-2] 进入推导时，该输入的 rank/布局未知，跳过其静态校验。
// 数学契约不变——执行期实际供数 shape 仍须满足 6 输入 shape 契约
// （x/hPrev/wRu/wC rank=2 等），由 arch35 TilingFunc [V3]-[V5] 以实际
// StorageShape 兜底校验（推导期无法核实的约束全部后移，不放松）。
inline bool IsUnknownRank(const gert::Shape* s) { return s->GetDimNum() == 1 && s->GetDim(0) == UNKNOWN_RANK_DIM; }

// 按索引取维：未知 rank 声明或索引越界返回 -1（未知维占位，交 DimKnown 守卫跳过）。
// 防护 GetDim 越界读（如 [-2] 声明 rank 1 时 GetDim(1)）。
inline int64_t DimAt(const gert::Shape* s, size_t idx)
{
    if (IsUnknownRank(s) || s->GetDimNum() <= idx) {
        return -1;
    }
    return s->GetDim(idx);
}

// 偏置元素总数（bRu/bC 各维均已知时有效；任一维未知返回 -1，交 Tiling 兜底）
inline int64_t TotalElems(const gert::Shape* s)
{
    int64_t total = 1;
    for (size_t d = 0; d < s->GetDimNum(); ++d) {
        const int64_t dim = s->GetDim(d);
        if (!DimKnown(dim)) {
            return -1;
        }
        total *= dim;
    }
    return total;
}

