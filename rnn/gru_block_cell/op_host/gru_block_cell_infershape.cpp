constexpr size_t OUTPUT_NUM = 4;

// 未知 rank 声明值（GE -2 语义：整个 shape 恰为 [-2]，即 rank 1 且 dim0 == -2）
constexpr int64_t UNKNOWN_RANK_DIM = -2;

// 输入/输出名（与 op_host/gru_block_cell_def.cpp 注册序一致）——日志用名称而非
