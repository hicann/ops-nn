static int RunRankProbe(ge::Session* session)
{
    printf("Scenario supplementary_rank_probe, declared shape [[-2],[-1,-1],[-1,-1],[-1,-1],[-1],[-1]]\n");
    const std::vector<std::vector<int64_t>> declaredShapes = {{-2}, {-1, -1}, {-1, -1}, {-1, -1}, {-1}, {-1}};
    Graph graph("gru_block_cell_unknown_rank_probe_graph");
    std::vector<ge::Operator> inputs;
    std::vector<ge::Operator> outputs;
    CHECK_RET(BuildDynamicGraph(graph, "gru_block_cell_unknown_rank_probe", "_unknown_rank_probe", declaredShapes,
                                inputs, outputs) == SUCCESS,
              "BuildDynamicGraph failed");
    graph.SetInputs(inputs).SetOutputs(outputs);
    Status ret = session->AddGraph(9901, graph, std::map<AscendString, AscendString>{});
    if (ret != SUCCESS) {
        printf("probe AddGraph rejected, ret=%u\n", static_cast<uint32_t>(ret));
        return FAILED;
    }

    const GruCase cs = {4, 16, 8};
    int nonRank2Rejected = 0;
    const int nonRank2Total = 2;
    const std::vector<std::vector<int64_t>> probes = {{4, 16, 1}, {4, 16, 1, 1}};
    for (const auto& xShape : probes) {
        printf("Probe concrete shape %s (x rank %zu, flattened 2D semantics [4,16])\n", ShapeToJson(xShape).c_str(),
               xShape.size());
        if (!RunAndVerifyGroup(session, 9901, cs, ShapeToJson(xShape), xShape, false)) {
            ++nonRank2Rejected;
            printf("Probe outcome: rejected by execution-time shape inference (contract: x must be rank 2 [B,I])\n");
        } else {
            printf("Probe outcome: accepted (unexpected for non-rank2 x)\n");
        }
    }
    printf("Scenario supplementary_rank_probe summary: %d/%d non-rank2 x rejections confirmed "
           "(framework -2 semantics: actual feed must satisfy the 2D shape contract; "
           "legal ranks are {1,2} only — 3 distinct rank signatures not coverable within the math contract)\n",
           nonRank2Rejected, nonRank2Total);
    return (nonRank2Rejected == nonRank2Total) ? SUCCESS : FAILED;
}

