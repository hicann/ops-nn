// Independent CPU golden: reset_before GRU cell semantics in double precision.
//   ru_bar = [x, h_prev]·w_ru + b_ru; r = sigmoid(ru_bar[:, :H]); u = sigmoid(ru_bar[:, H:])
//   c = tanh([x, h_prev⊙r]·w_c + b_c); h = u⊙(h_prev − c) + c
// IEEE semantics (NaN / ±Inf) propagate identically through the double chain,
// which is exactly the README special-value contract being asserted.
// ---------------------------------------------------------------------------
struct GruGolden {
    std::vector<float> r, u, c, h; // [B, H]
};

void CpuGruGolden(const GruInputs& in, GruGolden& g)
{
    const int64_t batch = in.batch;
    const int64_t inputSize = in.inputSize;
    const int64_t hiddenSize = in.hiddenSize;
    const int64_t kDim = inputSize + hiddenSize;
    const int64_t n2 = 2 * hiddenSize;
    const size_t bh = static_cast<size_t>(batch * hiddenSize);
    std::vector<double> ruBar(static_cast<size_t>(batch * n2), 0.0);
    for (int64_t b = 0; b < batch; ++b) {
        double* ru = &ruBar[static_cast<size_t>(b * n2)];
        for (int64_t k = 0; k < kDim; ++k) {
            const double a = (k < inputSize) ?
                                 static_cast<double>(in.x[static_cast<size_t>(b * inputSize + k)]) :
                                 static_cast<double>(in.hPrev[static_cast<size_t>(b * hiddenSize + (k - inputSize))]);
            const float* wrow = &in.wRu[static_cast<size_t>(k * n2)];
            for (int64_t n = 0; n < n2; ++n) {
                ru[n] += a * static_cast<double>(wrow[n]);
            }
        }
        for (int64_t n = 0; n < n2; ++n) {
            ru[n] += static_cast<double>(in.bRu[static_cast<size_t>(n)]);
        }
    }
    std::vector<double> rD(bh, 0.0);
    std::vector<double> uD(bh, 0.0);
    for (int64_t b = 0; b < batch; ++b) {
        for (int64_t j = 0; j < hiddenSize; ++j) {
            const double rb = ruBar[static_cast<size_t>(b * n2 + j)];
            const double ub = ruBar[static_cast<size_t>(b * n2 + hiddenSize + j)];
            rD[static_cast<size_t>(b * hiddenSize + j)] = 1.0 / (1.0 + std::exp(-rb));
            uD[static_cast<size_t>(b * hiddenSize + j)] = 1.0 / (1.0 + std::exp(-ub));
        }
    }
    std::vector<double> cBar(bh, 0.0);
    for (int64_t b = 0; b < batch; ++b) {
        double* cb = &cBar[static_cast<size_t>(b * hiddenSize)];
        for (int64_t k = 0; k < kDim; ++k) {
            const double a = (k < inputSize) ?
                                 static_cast<double>(in.x[static_cast<size_t>(b * inputSize + k)]) :
                                 static_cast<double>(in.hPrev[static_cast<size_t>(b * hiddenSize + (k - inputSize))]) *
                                     rD[static_cast<size_t>(b * hiddenSize + (k - inputSize))];
            const float* wrow = &in.wC[static_cast<size_t>(k * hiddenSize)];
            for (int64_t j = 0; j < hiddenSize; ++j) {
                cb[j] += a * static_cast<double>(wrow[j]);
            }
        }
        for (int64_t j = 0; j < hiddenSize; ++j) {
            cb[j] += static_cast<double>(in.bC[static_cast<size_t>(j)]);
        }
    }
    g.r.assign(bh, 0.0f);
    g.u.assign(bh, 0.0f);
    g.c.assign(bh, 0.0f);
    g.h.assign(bh, 0.0f);
    for (int64_t b = 0; b < batch; ++b) {
        for (int64_t j = 0; j < hiddenSize; ++j) {
            const size_t idx = static_cast<size_t>(b * hiddenSize + j);
            const double hp = static_cast<double>(in.hPrev[idx]);
            const double cD = std::tanh(cBar[idx]);
            const double hD = uD[idx] * (hp - cD) + cD;
            g.r[idx] = static_cast<float>(rD[idx]);
            g.u[idx] = static_cast<float>(uD[idx]);
            g.c[idx] = static_cast<float>(cD);
            g.h[idx] = static_cast<float>(hD);
        }
    }
}

// Elementwise comparison with IEEE special-value contract:
//  - bitwise-equal fast path (covers exact 0/1/±Inf saturation results)
//  - both-NaN passes (NaN propagates elementwise per README)
//  - otherwise rtol/atol tolerance
bool CompareOutput(const float* actual, const float* golden, int64_t n, const char* name, double atol = ATOL)
{
    int64_t badCount = 0;
    for (int64_t i = 0; i < n; ++i) {
        const float a = actual[i];
        const float g = golden[i];
        if (a == g) {
            continue; // bitwise equal (incl. ±Inf with same sign, exact saturation)
        }
        if (std::isnan(a) && std::isnan(g)) {
            continue; // NaN propagation contract
        }
        const double diff = std::fabs(static_cast<double>(a) - static_cast<double>(g));
        const double tol = atol + RTOL * std::fabs(static_cast<double>(g));
        if (diff > tol) {
            if (badCount < 5) {
                printf("  [%s][%ld] golden=%.7f actual=%.7f diff=%.3e tol=%.3e\n", name, static_cast<long>(i), g, a,
                       diff, tol);
            }
            ++badCount;
        }
    }
    // GRU_DUMP_ARRAYS：逐位回归基线取证（见文件头「回归仪器」说明）
    if (getenv("GRU_DUMP_ARRAYS") != nullptr && n <= 8192) {
        printf("  [%s] FULL-DUMP n=%ld (actual/golden)\n", name, static_cast<long>(n));
        for (int64_t i = 0; i < n; ++i) {
            if (i % 8 == 0) {
                printf("  [%s] r%ld:", name, static_cast<long>(i / 8));
            }
            printf(" %.6f/%.6f", actual[i], golden[i]);
            if (i % 8 == 7) {
                printf("\n");
            }
        }
    }
    if (badCount > 0) {
        printf("  [%s] %ld/%ld elements exceed tolerance\n", name, static_cast<long>(badCount), static_cast<long>(n));
        return false;
    }
    return true;
}

