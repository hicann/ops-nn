// 6 Data inputs -> op::GruBlockCell -> 4 [B, H] outputs (r/u/c/h)
int CreateStaticGraph(std::vector<ge::Tensor>& feeds, std::vector<ge::Operator>& inputs,
                      std::vector<ge::Operator>& outputs, Graph& graph, const GruInputs& in)
{
    const int64_t batch = in.batch;
    const int64_t inputSize = in.inputSize;
    const int64_t hiddenSize = in.hiddenSize;
    const int64_t kDim = inputSize + hiddenSize;
    auto gruCellOp = op::GruBlockCell("gru_block_cell");

    // ⚠ 输入声明 -1（动态图语义）：精确形状声明的静态图会触发 GE 的 buffer 复用
    // 规划，输出缓冲（pass0 中途写出的 r/u）可能与 kernel 在 pass1 仍要重读的输入
    // 设备缓冲（x 按组重读 / hPrev blend 重读）混叠 → r/u 正确而 c/h 全错（实测，
    // 原始 kernel 即存在，与本算子 tiling 注释登记的 GEIR 在线图路投递缺陷同类）。
    // 精确 shape 由 feeds 携带，执行期定形路径已验证不触发混叠。
    const std::pair<const char*, std::vector<int64_t>> descs[6] = {
        {"x", {-1, -1}}, {"hPrev", {-1, -1}}, {"wRu", {-1, -1}}, {"wC", {-1, -1}}, {"bRu", {-1}}, {"bC", {-1}}};
    const std::vector<int64_t> feedShapes[6] = {{batch, inputSize}, {batch, hiddenSize}, {kDim, 2 * hiddenSize},
                                                {kDim, hiddenSize}, {2 * hiddenSize},    {hiddenSize}};
    const std::vector<float>* bufs[6] = {&in.x, &in.hPrev, &in.wRu, &in.wC, &in.bRu, &in.bC};

    for (int i = 0; i < 6; ++i) {
        ge::TensorDesc d(ge::Shape(descs[i].second), ge::FORMAT_ND, ge::DT_FLOAT);
        d.SetRealDimCnt(static_cast<int64_t>(descs[i].second.size()));
        auto dataOp = op::Data(descs[i].first).set_attr_index(i);
        dataOp.update_input_desc_x(d);
        dataOp.update_output_desc_y(d);
        graph.AddOp(dataOp);
        feeds.push_back(MakeHostTensor(feedShapes[i], bufs[i]->data(), bufs[i]->size()));
        inputs.push_back(dataOp);
    }

    gruCellOp.set_input_x(inputs[0]);
    gruCellOp.set_input_hPrev(inputs[1]);
    gruCellOp.set_input_wRu(inputs[2]);
    gruCellOp.set_input_wC(inputs[3]);
    gruCellOp.set_input_bRu(inputs[4]);
    gruCellOp.set_input_bC(inputs[5]);

    ge::TensorDesc outDesc(ge::Shape({batch, hiddenSize}), ge::FORMAT_ND, ge::DT_FLOAT);
    outDesc.SetRealDimCnt(2);
    gruCellOp.update_output_desc_r(outDesc);
    gruCellOp.update_output_desc_u(outDesc);
    gruCellOp.update_output_desc_c(outDesc);
    gruCellOp.update_output_desc_h(outDesc);

    outputs.push_back(gruCellOp);
    return SUCCESS;
}

