bool RunOneCase(const std::string& case_name, bool use_peephole)
{
    LOG_PRINT("\n----------------------------------------");
    LOG_PRINT("[%s] B=%lld N=%lld C=%lld use_peephole=%s", case_name.c_str(), static_cast<long long>(B),
              static_cast<long long>(N), static_cast<long long>(C), use_peephole ? "true" : "false");
    LOG_PRINT("----------------------------------------");

    GeirOutput out = RunGeir(use_peephole);
    if (!out.ok) {
        LOG_PRINT("[FAIL] GEIR failed: %s", out.err_msg.c_str());
        return false;
    }

    // 1. 输出个数与形状
    bool shape_ok = out.shapes[0].size() == 2 && out.shapes[0][0] == B && out.shapes[0][1] == C &&
                    out.shapes[1].size() == 2 && out.shapes[1][0] == B && out.shapes[1][1] == 4 * C &&
                    out.shapes[2].size() == 1 && out.shapes[2][0] == C && out.shapes[3].size() == 1 &&
                    out.shapes[3][0] == C && out.shapes[4].size() == 1 && out.shapes[4][0] == C;
    LOG_PRINT("[%s] shapes: %s", case_name.c_str(), shape_ok ? "OK" : "MISMATCH");

    // 2. 有限性
    bool finite_ok = CheckFinite(out.cs_prev_grad) && CheckFinite(out.dicfo) && CheckFinite(out.wci_grad) &&
                     CheckFinite(out.wcf_grad) && CheckFinite(out.wco_grad);
    LOG_PRINT("[%s] finite: %s (cs_prev_grad=%zu dicfo=%zu peep=%zu each)", case_name.c_str(),
              finite_ok ? "OK" : "NAN_INF", out.cs_prev_grad.size(), out.dicfo.size(), out.wci_grad.size());

    // 3. use_peephole=false 时窥孔梯度精确全 0（TF 原生行为不变量）
    bool zero_ok = true;
    if (!use_peephole) {
        for (const auto* v : {&out.wci_grad, &out.wcf_grad, &out.wco_grad}) {
            for (float x : *v) {
                if (x != 0.0f) {
                    zero_ok = false;
                }
            }
        }
        LOG_PRINT("[%s] peephole-grads all-zero: %s", case_name.c_str(), zero_ok ? "OK" : "VIOLATED");
    }

    return shape_ok && finite_ok && zero_ok;
}

