constexpr uint32_t MAX_CLUSTERS = 32;

/* Phase A: does the input projection ([x, h_prev] @ W) fit, and how to tile it?
 * The projection GEMM is [m, I+H] x [I+H, 4H], run tile-by-tile ([m, kChunk] x [kChunk, H]).
 * `m` grows with tChunk: one timestep adds one row per batch-in-cluster. Pick the largest tChunk
 * that fits and divides T, and the largest kChunk that fits and divides I.
 * Returns false when nothing fits -- the caller MUST refuse; clamping to an oversized chunk is a
 * silent on-chip overflow.
 */
inline bool PickProjTiling(uint32_t mBlk, uint32_t inSize, uint32_t hid, uint32_t steps, uint32_t* tChunk,
                           uint32_t* kChunk, uint32_t dtypeSize = 4)
{
    const uint32_t FSZ = dtypeSize;
    const uint32_t c0 = ch::C0_BYTES / dtypeSize;
    *tChunk = 0;
    *kChunk = 0;
    /* inSize == 0 (I == 0) is ALLOWED: the x-side projection is a zero-contribution whose
     * K loop the kernel skips wholesale (kBlocks = 0/kChunk = 0). Any divisor-free kChunk
     * works then; c0 keeps the invariant trivially true. The gate loops below still run to
     * size the h-side-independent tiles, so return through the normal path. */
    if (mBlk == 0 || hid == 0 || steps == 0) {
        return false;
    }
    /* Callers pass I/H ALREADY PADDED (padI = CeilAlign(I, c0), padH = CeilAlign(H, c0)), so the
     * budget arithmetic below is pad-correct and there is no `inSize % c0` refusal here.
     * INVARIANT: kChunk must DIVIDE padI exactly -- a ragged K tail would need a second addressing
     * path in the innermost loop. The last K block runs with a dirty tail, which is safe because
     * Mmad honours mp.k exactly and pad lanes do not contribute. */

    // Largest K block whose [kChunk, H] B tile fits L0B, subject to dividing padI exactly.
    uint32_t kb = 0;
    if (inSize == 0) {
        /* I == 0: kBlocks = 0/kChunk = 0 regardless, and the kernel never builds an A tile.
         * Any nonzero kChunk satisfies "divides padI" (0 % k == 0); c0 is the cheapest. */
        kb = c0;
    } else {
        for (uint32_t k = inSize; k >= c0; k -= c0) {
            if (inSize % k != 0) {
                continue;
            }
            const uint32_t bElems = ch::CeilDiv(hid, c0) * ch::CeilAlign(k, ch::CUBE_BLOCK) * c0;
            if (bElems * FSZ <= ch::CAP_L0B) {
                kb = k;
                break;
            }
        }
    }
    if (kb == 0) {
        return false;
    }
    const uint32_t bElems = ch::CeilDiv(hid, c0) * ch::CeilAlign(kb, ch::CUBE_BLOCK) * c0;
    const uint32_t bBytes = ch::CeilAlign(bElems * FSZ, ch::C0_BYTES);

    const uint32_t rows = fwd::SPLIT ? ch::CeilDiv(mBlk, 2) : mBlk; // rows one AIV drains

    /* tChunk must DIVIDE T exactly. The A tile lays row r's timesteps at NZ rows
     * [r*tChunk, r*tChunk + tc), so a short last chunk leaves GAPS between the batch rows -- the
     * M extent stops being tc*mBlk and the Fixpipe split stops matching. Restricting to divisors
     * removes the partial chunk instead of adding a second addressing path for it. */
    for (uint32_t tc = steps; tc >= 1; --tc) {
        if (steps % tc != 0) {
            continue;
        }
        const uint32_t m = tc * mBlk;
        // A: the whole [m, I] stays in L1 for the chunk; only [m, kChunk] goes to L0A per k block.
        const uint32_t a1Elems = ch::CeilDiv(inSize, c0) * ch::CeilAlign(m, ch::CUBE_BLOCK) * c0;
        const uint32_t a2Elems = ch::CeilDiv(kb, c0) * ch::CeilAlign(m, ch::CUBE_BLOCK) * c0;
        const uint32_t cElems = ch::CeilAlign(m, ch::CUBE_BLOCK) * ch::CeilAlign(hid, ch::CUBE_BLOCK);
        const uint32_t l1Bytes = ch::CeilAlign(a1Elems * FSZ, ch::C0_BYTES) + bBytes;
        const uint32_t ubBytes = ch::CeilAlign(tc * rows * hid * FSZ, ch::C0_BYTES)     // drained plane
                                 + ch::CeilAlign(fwd::GATES * hid * FSZ, ch::C0_BYTES); // the bias row
        if (a2Elems * FSZ <= ch::CAP_L0A && cElems * FSZ <= ch::CAP_L0C && l1Bytes <= ch::CAP_L1 &&
            ubBytes <= ch::CAP_UB) {
            *tChunk = tc;
            *kChunk = kb;
            return true;
        }
        if (tc == 1) {
            break;
        }
    }
    return false;
}

/* Phase B: does the persistent recurrence itself fit? Reads `fwd::Layout` -- the very object the
 * kernel builds -- rather than re-deriving its extents. */
inline bool RecurrenceFits(uint32_t B, uint32_t H, uint32_t T, uint32_t mBlk, uint32_t dtypeSize = 4)
{
    const uint32_t c0 = ch::C0_BYTES / dtypeSize;
    /* B need NOT be a multiple of mBlk: the split is ragged and the host pads the batch up to
     * blockDim*mBlk (pad-to-divisible), so every cluster still owns exactly mBlk rows. Nothing
     * below reads B anyway -- the on-chip extents are all built from m=mBlk. */
    if (H == 0 || mBlk == 0) {
        return false;
    }
    /* H is the PADDED extent here (caller passes padH). The Layout math itself is
     * CeilDiv-based and needs no gate. */
    const fwd::Layout L(B, H, T, mBlk, dtypeSize);
    return L.aElems * dtypeSize <= ch::CAP_L0A && L.bElems * dtypeSize <= ch::CAP_L0B &&
           L.cElems * dtypeSize <= ch::CAP_L0C && L.l1Bytes <= ch::CAP_L1 && L.ubBytes <= ch::CAP_UB;
}

/* ---- wave pickers: the B/I/H decoupling ------------------------------------------
 *
 * The resident pickers above demand whole-operand on-chip residency and that is where the
 * tested ceilings came from:
 *   PickProjTiling : the A tile [m, padI] whole-K resident in L1 (m >= B/32) -> B*I <= ~4M
 *   RecurrenceFits : all four gate B-tiles [H, H] resident in L1          -> 4*H^2*esz <= L1
 *                    fifteen full-width UB planes                         -> m*H <= ~8K
 * The wave pickers below cap every on-chip tile independently; the kernel loops that
 * consume them stream the operands in blocks. They only fail on non-padded/zero input. */

/* Phase A waves: M (batch rows per wave, ONE timestep per wave) x K (streamed blocks of
 * padI) x N (slabs of padH). Loop shape in the kernel: for t { for wave { for ns {
 * for kb { load A[m,kb]; SplitA once; for g { load B[g,ns,kb]; SplitB; MmadAccum } }
 * drain 4 gate slots } } } -- L0C holds all four gate slots [m, nTile] simultaneously so
 * the A block is loaded once per (ns, kb) and reused across the four gates. All extents
 * are the PADDED padI/padH; every block/slab tail is exact (Mmad honours k exactly,
 * drains take the real n). */
inline bool PickProjWave(uint32_t mBlk, uint32_t padI, uint32_t padH, uint32_t dtypeSize, uint32_t* mWave,
                         uint32_t* kTile, uint32_t* nTile)
{
    const uint32_t c0 = ch::C0_BYTES / dtypeSize;
    const uint32_t esz = dtypeSize;
    *mWave = *kTile = *nTile = 0;
    /* padI == 0 (I == 0) is ALLOWED: kt starts at min(padI, ktCap) = 0, the halving loop below
     * never runs, and the kernel's kBlocks = CeilDiv(0, kTile) = 0 skips the whole x-side.
     * kTile gets the c0 floor so no 0/0 division can reach the kernel. */
    if (mBlk == 0 || (padI != 0 && padI < c0) || padH < c0) {
        return false;
    }
    /* N slab from padH DOWN: the first (widest) slab that yields a feasible (m, k) wins --
     * fewest slabs means fewest drain rounds.
     * nt TOP AT 64: the wave path is clean iff
     * (r0 == 1, any nt <= 64, ns <= 2) or (r0 >= 2, nt <= 32, ns == 1). Traps:
     * r0>=2 x (ns>=2 or nt>32); m=256 x nt>32; nt=96 at m=128. The NS-INTERACTION
     * GUARD in block_lstm_tiling.cpp enforces the r0>=2 arm; this cap keeps the
     * picker inside the r0==1 arm. */
    uint32_t ntTop = padH;
    if (ntTop > 64) {
        ntTop = 64;
    }
    for (uint32_t nt = ntTop; nt >= c0; nt -= c0) {
        const uint32_t colBlocks = ch::CeilDiv(nt, c0);
        /* K bound from L0B: [kTile, nTile] NZ tile = colBlocks * CeilAlign(k,16) * c0 * esz.
         * HALF the physical L0B: at a full 64 KB tile (H=64/c0=8/kt=256 measures exactly
         * 64 KB) the wave path corrupts data on device -- the ZN image the SplitB writes
         * needs headroom the arithmetic does not show. Halving is the safe bound;
         * the resident pickers never hit this because their own gate rejects such kChunk. */
        uint32_t ktCap = (ch::CAP_L0B / 2 / esz) / (colBlocks * c0);
        ktCap = (ktCap / ch::CUBE_BLOCK) * ch::CUBE_BLOCK; // CeilAlign(k,16) bound
        if (ktCap < c0) {
            continue;
        }
        /* K block from its cap DOWN by halving, re-floored to the c0 multiple every step
         * (DataCopy lengths are 32B blocks: a non-c0-mult kNow silently truncates --
         * invariant #7). The first that lets the A tile fit L0A/L1 wins.
         * padI == 0 (I == 0): start at the c0 floor -- the loop must run at least once to
         * size m/n; the kernel's kBlocks = CeilDiv(0, kTile) = 0 discards the x-side anyway. */
        uint32_t kt = (padI == 0) ? c0 : (padI < ktCap ? padI : ktCap);
        kt = kt / c0 * c0;
        for (; kt >= c0; kt = kt / 2 / c0 * c0) {
            /* M bounds. L0C: four gate slots, all live: 4 * CeilAlign(m,16) *
             * CeilAlign(nt,16) * 4B (fp32 accum) <= CAP_L0C. L0A/L1: the [m, kt] A tile. */
            const uint32_t nAl = ch::CeilAlign(nt, ch::CUBE_BLOCK);
            uint32_t mCapC = (ch::CAP_L0C / 4) / (4 * nAl);
            mCapC = (mCapC / ch::CUBE_BLOCK) * ch::CUBE_BLOCK;
            uint32_t mCapA = (ch::CAP_L0A / esz) / (ch::CeilDiv(kt, c0) * c0);
            uint32_t m = mBlk < (mCapA < mCapC ? mCapA : mCapC) ? mBlk : (mCapA < mCapC ? mCapA : mCapC);
            /* mWave CAP AT 128 (restored): mWave=256 traps the AIC at B=8192
             * across every slab config tested (hs=64/ck=4 and hs=32/ck=2/ns=2 both
             * NO_OUTPUT with W(256,1,64)), while W(128,1,64)+S(2,1,64) passes
             * (iso2_B4k_H64). The old cap was right; subBlockId fixed only the
             * one-gate-shift face of the 256 problem. */
            if (m > 128) {
                m = 128;
            }
            if (m < 1) {
                continue;
            }
            const uint32_t aBytes = ch::CeilDiv(kt, c0) * ch::CeilAlign(m, ch::CUBE_BLOCK) * c0 * esz;
            const uint32_t bBytes = colBlocks * ch::CeilAlign(kt, ch::CUBE_BLOCK) * c0 * esz;
            const uint32_t biasBytes = ch::CeilAlign(4 * nt * esz, ch::C0_BYTES);
            /* UB: the drain plane rowsMax * nTile fp32 (+ slop) -- binding only at silly
             * (m, nTile) products, checked for completeness. */
            const uint32_t ubPlane = ch::CeilDiv(m, 2) * nt * 4;
            if (aBytes + bBytes + biasBytes <= ch::CAP_L1 && ubPlane <= ch::CAP_UB) {
                *mWave = m;
                *kTile = kt;
                *nTile = nt;
                return true;
            }
        }
    }
    return false;
}

/* Phase B slab mode: reads fwd::SlabLayout (the object the kernel builds). */
inline bool RecurrenceSlabFits(uint32_t mC, uint32_t padH, uint32_t hSlab, uint32_t kTile, uint32_t dtypeSize)
{
    const uint32_t c0 = ch::C0_BYTES / dtypeSize;
    if (mC == 0 || hSlab < c0 || kTile < c0 || padH < c0) {
        return false;
    }
    const fwd::SlabLayout L(mC, padH, 0, hSlab, kTile, dtypeSize);
    /* FOUR L0C slots live simultaneously (one per gate -- the kb loop accumulates into
     * all four before the single drain round of the (t, ns) step). L0A/L1 read the slab
     * object's own aElems -- the [m, kTile] A BLOCK -- not a full-K tile: the full-K A
     * tile of the resident layout is exactly the wall this mode exists to remove. */
    const uint32_t l0cBytes = 4 * ch::CeilAlign(mC, ch::CUBE_BLOCK) * ch::CeilAlign(hSlab, ch::CUBE_BLOCK) * 4;
    return L.aElems * dtypeSize <= ch::CAP_L0A && L.bElems * dtypeSize <= ch::CAP_L0B && l0cBytes <= ch::CAP_L0C &&
           L.l1Bytes <= ch::CAP_L1 && L.ubBytes <= ch::CAP_UB;
}

/* Phase B tiling: the largest per-chunk row count mC <= mBlk across BOTH loop bodies.
 * Preference order per mC: the resident loop (W_hh stays in L1 -- only
 * possible while 4*padH^2*esz fits L1), then the slab loop (B streamed, arbitrary H).
 * mC candidates are mBlk and the powers of two below it: a chunk count of CeilDiv(mBlk,mC)
 * is what matters, not the exact mC, so the sparse ladder keeps the search O(100). */
inline bool PickRecurWave(uint32_t mBlk, uint32_t padH, uint32_t dtypeSize, uint32_t* rowChunk, uint32_t* hSlab,
                          uint32_t* kTile)
{
    const uint32_t c0 = ch::C0_BYTES / dtypeSize;
    const uint32_t esz = dtypeSize;
    *rowChunk = *hSlab = *kTile = 0;
    if (mBlk == 0 || padH < c0) {
        return false;
    }
    /* Can the resident loop EVER run at this H? Its L1 gate-tile bill is fixed:
     * 4 * [padH, padH] NZ tiles. If that alone overflows L1 no mC will rescue it. */
    const bool residentPossible = 4 * ch::CeilDiv(padH, c0) * ch::CeilAlign(padH, ch::CUBE_BLOCK) * c0 * esz <=
                                  ch::CAP_L1;
    /* COST-DIRECTED SEARCH: the wall clock of the slab loop scales with
     * nChunks * nSlabs * kBlocks -- every extra handshake round and every extra
     * K-block pass is pure overhead. The old "first feasible" order returned
     * (hSlab=512, kTile=16) at H=16k: 1024 kb x 32 slabs = 32k Mmad rounds and a
     * 20+ minute kernel. Enumerate (hs, mC, kt) over the ladders and keep the
     * feasible triple with the MINIMUM round cost; ties prefer wider slabs. */
    {
        uint32_t bestCost = 0xFFFFFFFFu;
        bool found = false;
        uint32_t bRc = 0, bHs = 0, bKt = 0;
        /* hs TOP is capped at 128 -- SplitB's supported N list
         * is 16/32/48/64/128 and the old isolation runs put a boundary at n in
         * (176, 256] (padH=256 hung BOTH loops). Larger H rides more 128-wide slabs
         * (the grad kernel ran 1024 rounds/step cleanly). hs skips 96 only (the old
         * iso-trap width); 64 is a VERIFIED green width (bbh64) and stays legal.
         * kt skips the grad K-chunk blacklist {64, 96}. */
        const auto wedgedN = [](uint32_t w) { return w == 96; };
        uint32_t hsTop = (padH > 128) ? 128 : padH;
        for (; hsTop >= c0; hsTop = hsTop / 2 / c0 * c0) {
            if (wedgedN(hsTop) || wedgedN(padH - (padH / hsTop) * hsTop)) {
                continue; // skip blacklisted slab widths (and tails that land on them)
            }
            uint32_t hs = hsTop;
            uint32_t mC = mBlk;
            while (true) {
                if (residentPossible && hs == padH && RecurrenceFits(0, padH, 0, mC, esz)) {
                    /* the resident loop at full width is always the cheapest */
                    *rowChunk = mC;
                    *hSlab = padH;
                    *kTile = padH;
                    return true;
                }
                uint32_t ktCap = (ch::CAP_L0B / 2 / esz) / (ch::CeilDiv(hs, c0) * c0);
                ktCap = (ktCap / ch::CUBE_BLOCK) * ch::CUBE_BLOCK;
                if (ktCap > 128) {
                    ktCap = 128; // SplitB's verified kFrac tops at 8 (K=128)
                }
                if (ktCap > padH) {
                    ktCap = padH / c0 * c0;
                }
                for (uint32_t kt = ktCap; kt >= c0; kt = kt / 2 / c0 * c0) {
                    if (kt == 64 || kt == 96) {
                        continue; // the grad kernel's K-chunk blacklist
                    }
                    if (RecurrenceSlabFits(mC, padH, hs, kt, esz)) {
                        const uint32_t cost = ch::CeilDiv(mBlk, mC) * ch::CeilDiv(padH, hs) * ch::CeilDiv(padH, kt);
                        if (cost < bestCost) {
                            bestCost = cost;
                            found = true;
                            bRc = mC;
                            bHs = hs;
                            bKt = kt;
                        }
                        break; /* widest kt for this (hs, mC): bigger kt only helps */
                    }
                }
                if (mC == 1) {
                    break;
                }
                mC /= 2;
            }
            if (hs == c0) {
                break;
            }
        }
        if (found) {
            *rowChunk = bRc;
            *hSlab = bHs;
            *kTile = bKt;
            return true;
        }
        return false;
    }
}

