/*!
 * \file proj_budget.h
 * \brief Phase A (input projection) on-chip budget: the time chunk and the K block.
 *
 * Its own header so TilingFunc and a host-side test call THE SAME function; capacities come from
 * ch::CAP_* in block_lstm_tiling.h. Plain C++ (no AscendC), so it builds under g++ with op_host.
 * The fractal is always 512 BYTES (16x8 at fp32, 16x16 at fp16); dtypeSize (2 or 4) lets one
 * budget serve both data types.
 */
