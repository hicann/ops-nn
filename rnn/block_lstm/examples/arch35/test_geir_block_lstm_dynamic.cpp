ForwardGolden ComputeForwardGolden(int t, int b, int i, int h, const CaseData& d)
{
    ForwardGolden out;
    const size_t plane = static_cast<size_t>(b) * h;
    for (int k = 0; k < 7; ++k) {
        out.gates[k].assign(static_cast<size_t>(t) * plane, 0.0);
    }
    std::vector<double> hh(d.hPrev.begin(), d.hPrev.end());
    std::vector<double> cc(d.csPrev.begin(), d.csPrev.end());
    /* h feedback uses a per-(t,b) snapshot of the previous h row (all gates
     * consume h_{t-1}); see the static example for the read-after-write
     * hazard note on the repository UT golden. */
    std::vector<double> hRow(h);
    std::vector<double> hNew(h);
    for (int tt = 0; tt < t; ++tt) {
        for (int bb = 0; bb < b; ++bb) {
            for (int j = 0; j < h; ++j) {
                hRow[static_cast<size_t>(j)] = hh[static_cast<size_t>(bb) * h + j];
            }
            for (int hhIdx = 0; hhIdx < h; ++hhIdx) {
                double ig = 0.0;
                double fg = 0.0;
                double cg = 0.0;
                double og = 0.0;
                for (int j = 0; j < i; ++j) {
                    const double xv = d.x[(static_cast<size_t>(tt) * b + bb) * i + j];
                    ig += xv * d.w[static_cast<size_t>(j) * 4 * h + hhIdx];
                    fg += xv * d.w[static_cast<size_t>(j) * 4 * h + h + hhIdx];
                    cg += xv * d.w[static_cast<size_t>(j) * 4 * h + 2 * h + hhIdx];
                    og += xv * d.w[static_cast<size_t>(j) * 4 * h + 3 * h + hhIdx];
                }
                for (int j = 0; j < h; ++j) {
                    const double hv = hRow[static_cast<size_t>(j)];
                    ig += hv * d.w[static_cast<size_t>(i + j) * 4 * h + hhIdx];
                    fg += hv * d.w[static_cast<size_t>(i + j) * 4 * h + h + hhIdx];
                    cg += hv * d.w[static_cast<size_t>(i + j) * 4 * h + 2 * h + hhIdx];
                    og += hv * d.w[static_cast<size_t>(i + j) * 4 * h + 3 * h + hhIdx];
                }
                ig += d.b[hhIdx];
                fg += d.b[h + hhIdx];
                cg += d.b[2 * h + hhIdx];
                og += d.b[3 * h + hhIdx];
                const double iv = 1.0 / (1.0 + std::exp(-ig));
                const double fv = 1.0 / (1.0 + std::exp(-fg));
                const double cv = std::tanh(cg);
                const double cn = fv * cc[static_cast<size_t>(bb) * h + hhIdx] + iv * cv;
                const double ov = 1.0 / (1.0 + std::exp(-og));
                const double cov = std::tanh(cn);
                const double hv2 = ov * cov;
                const size_t off = (static_cast<size_t>(tt) * b + bb) * h + hhIdx;
                out.gates[0][off] = iv;
                out.gates[1][off] = cn;
                out.gates[2][off] = fv;
                out.gates[3][off] = ov;
                out.gates[4][off] = cv;
                out.gates[5][off] = cov;
                out.gates[6][off] = hv2;
                cc[static_cast<size_t>(bb) * h + hhIdx] = cn;
                hNew[static_cast<size_t>(hhIdx)] = hv2;
            }
            for (int j = 0; j < h; ++j) {
                hh[static_cast<size_t>(bb) * h + j] = hNew[static_cast<size_t>(j)];
            }
        }
    }
    return out;
}

