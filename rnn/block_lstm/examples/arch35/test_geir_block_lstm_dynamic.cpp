bool CheckTensor(const ge::Tensor& tensor, const ShapeVector& shape, const std::vector<double>& golden,
                 const char* name)
{
    const ge::TensorDesc& desc = tensor.GetTensorDesc();
    const ge::Shape& actual = desc.GetShape();
    if (actual.GetDimNum() != shape.size()) {
        std::cout << name << " rank mismatch: " << actual.GetDimNum() << " vs " << shape.size() << std::endl;
        return false;
    }
    for (size_t index = 0; index < shape.size(); ++index) {
        if (actual.GetDim(index) != shape[index]) {
            std::cout << name << " dim[" << index << "] mismatch: " << actual.GetDim(index) << " vs " << shape[index]
                      << std::endl;
            return false;
        }
    }
    if (desc.GetDataType() != ge::DT_FLOAT) {
        std::cout << name << " dtype mismatch: " << desc.GetDataType() << std::endl;
        return false;
    }
    if (tensor.GetSize() != golden.size() * sizeof(float)) {
        std::cout << name << " byte size mismatch" << std::endl;
        return false;
    }
    const float* values = reinterpret_cast<const float*>(tensor.GetData());
    for (size_t index = 0; index < golden.size(); ++index) {
        const float error = std::fabs(values[index] - static_cast<float>(golden[index]));
        const float tolerance = kAtol + kRtol * static_cast<float>(std::fabs(golden[index]));
        if (!std::isfinite(values[index]) || error > tolerance) {
            std::cout << name << " value mismatch at " << index << ": " << values[index] << " vs " << golden[index]
                      << " (tol " << tolerance << ")" << std::endl;
            return false;
        }
    }
    return true;
}

