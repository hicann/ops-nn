struct BlockLstmTilingData {
    uint32_t batch;      // B
    uint32_t inputSize;  // I (REAL, as the API contract states)
    uint32_t hiddenSize; // H (REAL)
    uint32_t padI;       // I rounded up to C0F -- the extent every on-chip NZ tile uses
    uint32_t padH;       // H rounded up to C0F -- ditto
    uint32_t timeStep;   // T
    uint32_t seqLenMax;  // <= T

    uint32_t rowsPerBlock; // batch rows owned by one cluster (mBlk)
    uint32_t blockDim;     // ceil(B / rowsPerBlock)

    uint32_t tChunk;
    uint32_t kChunk;

    // V1+V2 unified attributes
    float forgetBias;     // V1 default 1.0, V2 default 0.0
    float cellClip;       // V1 default 3.0, V2 default 0.0 (0 = no clip)
    uint32_t usePeephole; // 0 or 1
    uint32_t gateOrder;   // 0=IFCO (V2), 1=ICFO (V1)

    // Workspace offsets in BYTES from the start of the user area.
    // igates/store strides are in units of padH (4*padH per row), NOT 4*H: the
    // strided UB copies that read/write these planes express their pitch in
    // 32-byte blocks, so the workspace adopts the padded extent. The seven GM
    // outputs keep the REAL H -- the scatter tail-blocks them down on the way out.
    // offIgates is ALWAYS an fp32 region for BOTH operand dtypes (no fp16
    // round-trip of the x-side pre-activations; see TilingFunc).
    // u64 -- a u32 field caps any single op's scratch at 4.29GB and makes
    // shapes the competitor serves trivially (B*H large enough that the B- or
    // H-strided planes pass 2^32 bytes) refuse with a workspace error. Both sides
    // of the launch compile from this header, so the widening is ABI-consistent;
    // every consumer adds the field to a byte pointer (no u32 truncation). */
    uint64_t offPadX;   // [T, B, padI]      x restaged with zero-filled pad columns
    uint64_t offPadW;   // [padI+padH, 4*padH] w restaged, rows AND columns padded
    uint64_t offPadB;   // [4*padH]          b restaged, each gate row padded
    uint64_t offIgates; // [T, B, 4*padH]    fp32 for both dtypes
    uint64_t offHAll;   // [T+1, B, padH]   slot 0 = h_prev
    uint64_t offCAll;   // [T+1, B, padH]   slot 0 = cs_prev
    uint64_t offStore;  // [T, B, 4*padH]   i, f, ci(g), o post-activation
    uint64_t offCo;     // [T+1, B, padH]   co post-activation (slot t+1, odd-shape
                        //                   scatter source; T+1 matches hAll/cAll)

    // ---- wave tiling: decouples B/I/H from whole-operand on-chip residency ----
    // The resident pickers demand the A tile whole-K resident in L1, all four gate B-tiles
    // resident, and 15 full-width UB planes -- the source of the B<=256 / I<=2048 /
    // H<=128|176 ceilings. The wave fields below cap every on-chip tile independently;
    // the kernel loops that consume them are proj::CubeProjectWaves/VectorProjectWaves
    // and fwd::CubeLoopSlab/VectorLoopSlab (impl.h). A field set of 0/identity means
    // "resident fast path" and the entry dispatches to the original loops.
    uint32_t tiledA;    // 1 = Phase A runs the wave path (M waves x K stream x N slabs)
    uint32_t mWaveA;    // Phase A: batch rows per wave (one timestep per wave)
    uint32_t kTileA;    // Phase A: K block width  (c0-mult; tail block exact-k, free)
    uint32_t nTileA;    // Phase A: N slab width   (c0-mult; tail slab exact-n)
    uint32_t xDirect;   // 1 = padI == I: waves read x from GM directly (no padX restage)
    uint32_t wDirect;   // 1 = padI == I && padH == H: padW skipped, w read directly
    uint32_t bDirect;   // 1 = padH == H: padB skipped, b read directly
    uint32_t tiledB;    // 1 = Phase B runs chunked (and slabbed, when hSlabB < padH)
    uint32_t rowChunkB; // Phase B: batch rows per chunk (chunks tile the cluster stripe)
    uint32_t hSlabB;    // Phase B: hidden slab width (< padH -> slabbed recurrence)
    uint32_t kTileB;    // Phase B: K block for the W_hh B-tiles (< padH -> streamed)
};

