/*!
 * \file block_lstm.cpp
 * \brief Kernel entry for unified TF BlockLSTM (V1+V2) -- forward, one launch.
 *
 *   phase 0   pad restage: x/w/b -> zero-padded workspace copies (any I/H)
 *   phase A   igates = x @ w[0:I] + b            (input projection)
 *   phase B   the whole T-step recurrence        (forward loop)
 *   phase C   scatter into the seven TF planes
 *
 * V1+V2 unified via the gate_order attribute: "icfo" (V1) / "ifco" (V2).
 * Supports peephole, forget_bias, cell_clip.
 *
 * INVARIANT: one .o per dtype, compile-time dispatch -- the entry instantiates
 * block_lstm_impl<DTYPE_X> from the macro the binary pipeline injects per variant. There is no
 * runtime dtype field and no tiling key (a dtype-dependent key would stamp the wrong symbols).
 * INVARIANT: workspace offsets are BYTES, and the igates region is ALWAYS fp32.
 * INVARIANT: every MTE burst's GM start and every VECTOR operand base must be 32B-aligned. Odd
 * I/H break that for naive per-row access, so phase 0 reads via aligned chunks + scalar slides
 * (odda::ReadRowUnaligned) and phase C writes via a global 32B-segment scatter (odda /
 * ScatterPlanes). Aligned shapes take the fast paths.
 */
