constexpr uint32_t K_CUBE_BLOCK = 16;
constexpr uint32_t K_C0_BYTES = 32;
constexpr uint32_t K_CAP_L1 = 512 * 1024;
constexpr uint32_t K_CAP_L0A = 64 * 1024;
constexpr uint32_t K_CAP_L0B = 64 * 1024;
constexpr uint32_t K_CAP_L0C = 256 * 1024;
constexpr uint32_t K_CAP_UB = 248 * 1024;
constexpr uint32_t K_GATES = 4;
constexpr uint32_t K_MAX_CLUSTERS = 32;

inline uint32_t CeilDivU(uint32_t a, uint32_t b) { return (a + b - 1) / b; }
inline uint32_t CeilAlignU(uint32_t a, uint32_t b) { return CeilDivU(a, b) * b; }

inline uint32_t PickRowsPerBlockReplica(uint32_t b)
{
    if (b < 2) {
        return b;
    }
    const uint32_t hi = (b / 2 < K_MAX_CLUSTERS) ? (b / 2) : K_MAX_CLUSTERS;
    for (uint32_t nb = hi; nb >= 1; --nb) {
        if (b % nb == 0) {
            return b / nb;
        }
    }
    return b;
}

inline bool PickProjTilingReplica(uint32_t mBlk, uint32_t inSize, uint32_t hid, uint32_t steps, uint32_t* tChunk,
                                  uint32_t* kChunk, uint32_t dtypeSize)
{
    const uint32_t c0 = K_C0_BYTES / dtypeSize;
    *tChunk = 0;
    *kChunk = 0;
    if (mBlk == 0 || inSize == 0 || hid == 0 || steps == 0) {
        return false;
    }
    uint32_t kb = 0;
    for (uint32_t k = inSize; k >= c0; k -= c0) {
        if (inSize % k != 0) {
            continue;
        }
        const uint32_t bElems = CeilDivU(hid, c0) * CeilAlignU(k, K_CUBE_BLOCK) * c0;
        if (bElems * dtypeSize <= K_CAP_L0B) {
            kb = k;
            break;
        }
    }
    if (kb == 0) {
        return false;
    }
    const uint32_t bElems = CeilDivU(hid, c0) * CeilAlignU(kb, K_CUBE_BLOCK) * c0;
    const uint32_t bBytes = CeilAlignU(bElems * dtypeSize, K_C0_BYTES);
    const uint32_t rows = CeilDivU(mBlk, 2);
    for (uint32_t tc = steps; tc >= 1; --tc) {
        if (steps % tc != 0) {
            continue;
        }
        const uint32_t m = tc * mBlk;
        const uint32_t a1Elems = CeilDivU(inSize, c0) * CeilAlignU(m, K_CUBE_BLOCK) * c0;
        const uint32_t a2Elems = CeilDivU(kb, c0) * CeilAlignU(m, K_CUBE_BLOCK) * c0;
        const uint32_t cElems = CeilAlignU(m, K_CUBE_BLOCK) * CeilAlignU(hid, K_CUBE_BLOCK);
        const uint32_t l1Bytes = CeilAlignU(a1Elems * dtypeSize, K_C0_BYTES) + bBytes;
        const uint32_t ubBytes = CeilAlignU(tc * rows * hid * dtypeSize, K_C0_BYTES) +
                                 CeilAlignU(K_GATES * hid * dtypeSize, K_C0_BYTES);
        if (a2Elems * dtypeSize <= K_CAP_L0A && cElems * dtypeSize <= K_CAP_L0C && l1Bytes <= K_CAP_L1 &&
            ubBytes <= K_CAP_UB) {
            *tChunk = tc;
            *kChunk = kb;
            return true;
        }
        if (tc == 1) {
            break;
        }
    }
    return false;
}

bool FillTiling(int T, int B, int I, int H, bool isFp16, bool usePeephole, bool isIcfo, float forgetBias,
                float cellClip, BlockLstmTilingData* td)
{
    const uint32_t dtypeSize = isFp16 ? 2 : 4;
    const uint32_t c0 = K_C0_BYTES / dtypeSize;
    const uint32_t padI = CeilAlignU(I, c0);
    const uint32_t padH = CeilAlignU(H, c0);
    const uint32_t mBlk = PickRowsPerBlockReplica(B);
    if (B % mBlk != 0) {
        return false;
    }
    uint32_t tChunk = 0, kChunk = 0;
    if (!PickProjTilingReplica(mBlk, padI, padH, T, &tChunk, &kChunk, dtypeSize)) {
        return false;
    }
    td->batch = B;
    td->inputSize = I;
    td->hiddenSize = H;
    td->padI = padI;
    td->padH = padH;
    td->timeStep = T;
    td->seqLenMax = T;
    td->rowsPerBlock = mBlk;
    td->blockDim = B / mBlk;
    td->tChunk = tChunk;
    td->kChunk = kChunk;
    td->forgetBias = forgetBias;
    td->cellClip = cellClip;
    td->usePeephole = usePeephole ? 1 : 0;
    td->gateOrder = isIcfo ? 1 : 0;
    uint32_t off = 0;
    td->offPadX = off;
    off += static_cast<size_t>(T * B * padI * dtypeSize);
    td->offPadW = off;
    off += static_cast<size_t>(padI + padH) * K_GATES * padH * dtypeSize;
    td->offPadB = off;
    off += static_cast<size_t>(K_GATES * padH * dtypeSize);
    td->offIgates = off;
    off += static_cast<size_t>(T * B * K_GATES * padH * 4);
    td->offHAll = off;
    off += static_cast<size_t>(T + 1) * B * padH * dtypeSize;
    td->offCAll = off;
    off += static_cast<size_t>(T + 1) * B * padH * dtypeSize;
    td->offStore = off;
    off += static_cast<size_t>(T * B * K_GATES * padH * dtypeSize);
    td->offCo = off;
    off += static_cast<size_t>(T + 1) * B * padH * dtypeSize;
    return true;
}

void BlockLstmGolden(int T, int B, int I, int H, const float* x, const float* csPrev, const float* hPrev,
                     const float* w, const float* wci, const float* wcf, const float* wco, const float* b,
                     float forgetBias, float cellClip, bool usePeephole, bool isIcfo, vector<vector<float>>& g)
{
    const size_t plane = static_cast<size_t>(B * H);
    vector<float> h(hPrev, hPrev + plane), c(csPrev, csPrev + plane);
    g.assign(7, vector<float>(static_cast<size_t>(T * plane), 0.0f));
    /* h feedback uses a per-(t,b) SNAPSHOT of the previous h row: all four
     * gates must consume h_{t-1} only. Writing h in place mid-row lets gate
     * hh see already-updated h at columns < hh (read-after-write hazard; the
     * kernel and the TTK golden use the clean snapshot semantics -- verified
     * against the on-device run 2026-09-15). */
    vector<float> hRow(H), hNewRow(H);
    for (int t = 0; t < T; ++t) {
        for (int bb = 0; bb < B; ++bb) {
            for (int j = 0; j < H; ++j) {
                hRow[j] = h[static_cast<size_t>(bb * H + j)];
            }
            for (int hh = 0; hh < H; ++hh) {
                float ig = 0.f, fg = 0.f, cg = 0.f, og = 0.f;
                for (int j = 0; j < I; ++j) {
                    const float xv = x[static_cast<size_t>(t * B + bb) * I + j];
                    ig += xv * w[static_cast<size_t>(j * 4 * H + hh)];
                    fg += xv * w[static_cast<size_t>(j * 4 * H + H + hh)];
                    cg += xv * w[static_cast<size_t>(j * 4 * H + 2 * H + hh)];
                    og += xv * w[static_cast<size_t>(j * 4 * H + 3 * H + hh)];
                }
                for (int j = 0; j < H; ++j) {
                    const float hv = hRow[j];
                    ig += hv * w[static_cast<size_t>(I + j) * 4 * H + hh];
                    fg += hv * w[static_cast<size_t>(I + j) * 4 * H + H + hh];
                    cg += hv * w[static_cast<size_t>(I + j) * 4 * H + 2 * H + hh];
                    og += hv * w[static_cast<size_t>(I + j) * 4 * H + 3 * H + hh];
                }
                if (isIcfo) {
                    std::swap(fg, cg);
                }
                ig += b[hh];
                fg += b[H + hh] + forgetBias;
                cg += b[2 * H + hh];
                og += b[3 * H + hh];
                if (usePeephole) {
                    ig += wci[hh] * c[static_cast<size_t>(bb * H + hh)];
                    fg += wcf[hh] * c[static_cast<size_t>(bb * H + hh)];
                }
                const float iv = 1.0f / (1.0f + std::exp(-ig));
                const float fv = 1.0f / (1.0f + std::exp(-fg));
                const float cv = std::tanh(cg);
                float cn = fv * c[static_cast<size_t>(bb * H + hh)] + iv * cv;
                if (cellClip > 0.0f) {
                    cn = std::min(std::max(cn, -cellClip), cellClip);
                }
                float go = og;
                if (usePeephole) {
                    go += wco[hh] * cn;
                }
                const float ov = 1.0f / (1.0f + std::exp(-go));
                const float cov = std::tanh(cn);
                const float hv2 = ov * cov;
                const size_t off = static_cast<size_t>(t * B + bb) * H + hh;
                g[0][off] = iv;
                g[1][off] = cn;
                g[2][off] = fv;
                g[3][off] = ov;
                g[4][off] = cv;
                g[5][off] = cov;
                g[6][off] = hv2;
                c[static_cast<size_t>(bb * H + hh)] = cn;
                hNewRow[hh] = hv2;
            }
            for (int j = 0; j < H; ++j) {
                h[static_cast<size_t>(bb * H + j)] = hNewRow[j];
            }
        }
    }
}

