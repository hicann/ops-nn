    const size_t planeTBH = static_cast<size_t>(T * B * H);
    vector<float> inF(nIn);
    unsigned int seed = 42u;
    auto rnd = [&seed]() {
        seed = seed * 1664525u + 1013904223u;
        return (seed >> 8) / 16777216.0f - 0.5f;
    };
    for (auto& v : inF) {
        v = rnd();
    }

    const float* xF = inF.data();
    const float* csF = xF + static_cast<size_t>(T * B * I);
    const float* hF = csF + static_cast<size_t>(B * H);
    const float* wF = hF + static_cast<size_t>(B * H);
    const float* wciF = wF + static_cast<size_t>(I + H) * 4 * H;
    const float* wcfF = wciF + H;
    const float* wcoF = wcfF + H;
    const float* bF = wcoF + H;
    vector<vector<float>> gold;
    BlockLstmGolden(T, B, I, H, xF, csF, hF, wF, wciF, wcfF, wcoF, bF, forgetBias, cellClip, usePeephole, isIcfo, gold);

    auto alloc = [dtypeSize](size_t n) { return (uint8_t*)AscendC::GmAlloc(n * dtypeSize); };
    uint8_t* slmGM = (uint8_t*)AscendC::GmAlloc(sizeof(int64_t));
    uint8_t* xGM = alloc(static_cast<size_t>(T * B * I));
    uint8_t* csGM = alloc(static_cast<size_t>(B * H));
    uint8_t* hGM = alloc(static_cast<size_t>(B * H));
    uint8_t* wGM = alloc(static_cast<size_t>(I + H) * 4 * H);
    uint8_t* wciGM = alloc(H);
    uint8_t* wcfGM = alloc(H);
    uint8_t* wcoGM = alloc(H);
    uint8_t* bGM = alloc(4 * H);
    vector<uint8_t*> outs(7);
    for (auto& o : outs) {
        o = alloc(planeTBH);
    }
    uint8_t* wsGM = (uint8_t*)AscendC::GmAlloc(wsTotal);
    uint8_t* tilingGM = (uint8_t*)AscendC::GmAlloc(sizeof(td));
