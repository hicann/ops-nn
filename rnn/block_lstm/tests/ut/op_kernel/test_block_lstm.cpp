    const uint32_t dtypeSize = isFp16 ? 2 : 4;
    uint64_t wsUser = static_cast<uint64_t>(T * B * td.padI * dtypeSize);
    wsUser += static_cast<uint64_t>(td.padI + td.padH) * K_GATES * td.padH * dtypeSize;
    wsUser += static_cast<uint64_t>(K_GATES * td.padH * dtypeSize);
    wsUser += static_cast<uint64_t>(T * B * K_GATES * td.padH * 4);
    wsUser += static_cast<uint64_t>(T + 1) * B * td.padH * dtypeSize * 3;
    wsUser += static_cast<uint64_t>(T * B * K_GATES * td.padH * dtypeSize);
    const uint64_t wsTotal = wsUser + 64ull * 1024 * 1024;

