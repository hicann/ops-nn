// GM -> L1: ND [rows, cols] (GM row stride srcRowStride, in ELEMENTS) -> NZ
// tile in L1, laid out with the PARENT tile's aligned row count. Parameter
// units are ELEMENTS (never × sizeof(T) — NDDMA contract).
