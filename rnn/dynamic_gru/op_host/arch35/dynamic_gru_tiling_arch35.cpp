// FindHiddenChunk(H, ubBudget) — hidden 维 UB 反解（单时间步 gate 工作集）
//
//   cap    = ubBudget / (BUF_CNT*sizeof(float) + MASK_ROW_BYTES)   // 单行也要放得下
//   hChunk = min(FloorAlign(cap, 16), CeilAlign(H, 16))            // H 整块放得下时不放大 buffer
//   return max(hChunk, 16)                                          // 下限 16（对齐基）
// ---------------------------------------------------------------------------
inline int64_t FindHiddenChunk(int64_t H, int64_t ubBudget)
{
    const int64_t cap = ubBudget / (BUF_CNT * FP32_BYTES + MASK_ROW_BYTES);
    const int64_t hChunk = std::min(Ops::Base::FloorAlign(cap, HIDDEN_ALIGN), Ops::Base::CeilAlign(H, HIDDEN_ALIGN));
    return std::max(hChunk, HIDDEN_ALIGN);
}

