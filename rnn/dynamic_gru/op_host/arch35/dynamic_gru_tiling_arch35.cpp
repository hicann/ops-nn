// ValidateDtypeAndFormat — 异常值校验 1) dtype / 2) format（任一失败
// return GRAPH_FAILED，不占 tilingKey）。
// ---------------------------------------------------------------------------
ge::graphStatus ValidateDtypeAndFormat(gert::TilingContext* context, const TilingIo& io)
{
    // 1) dtype：x/w/cw ∈ {fp16}；b/cb ∈ {fp16, fp32} 且同 dtype；seq_length=int32
    //    （传入时）；init_h 与 b/cb 同 dtype（传入时）；输出 dtype 跟随 b（组合一致性）
    const ge::DataType dtX = io.xDesc->GetDataType();
    const ge::DataType dtW = io.wDesc->GetDataType();
    const ge::DataType dtB = io.bDesc->GetDataType();
    const ge::DataType dtCw = io.cwDesc->GetDataType();
    const ge::DataType dtCb = io.cbDesc->GetDataType();
    const auto isFp16 = [](ge::DataType d) { return d == ge::DT_FLOAT16; };
    const auto isFp16OrFp32 = [](ge::DataType d) { return d == ge::DT_FLOAT16 || d == ge::DT_FLOAT; };
    if (!isFp16(dtX) || !isFp16(dtW) || !isFp16(dtCw)) {
        OP_LOGE(context, "dtype_not_supported: x/w/cw must be float16 (got x=%d w=%d cw=%d)", static_cast<int>(dtX),
                static_cast<int>(dtW), static_cast<int>(dtCw));
        return ge::GRAPH_FAILED;
    }
    if (!isFp16OrFp32(dtB) || !isFp16OrFp32(dtCb) || dtB != dtCb) {
        OP_LOGE(context, "dtype_not_supported: b/cb must share one dtype in {float16, float32} (got b=%d cb=%d)",
                static_cast<int>(dtB), static_cast<int>(dtCb));
        return ge::GRAPH_FAILED;
    }
    if (io.hasSeqLength && (io.seqDesc == nullptr || io.seqDesc->GetDataType() != ge::DT_INT32)) {
        OP_LOGE(context, "dtype_not_supported: seq_length must be int32");
        return ge::GRAPH_FAILED;
    }
    if (io.hasInitH && (io.initHDesc == nullptr || io.initHDesc->GetDataType() != dtB)) {
        OP_LOGE(context, "dtype_not_supported: init_h dtype must follow b/cb");
        return ge::GRAPH_FAILED;
    }
    for (size_t i = 0; i < NUM_OUTPUTS; i++) {
        const gert::CompileTimeTensorDesc* outDesc = context->GetOutputDesc(i);
        OP_CHECK_NULL_WITH_CONTEXT(context, outDesc);
        if (outDesc->GetDataType() != dtB) {
            OP_LOGE(context, "dtype_not_supported: output[%zu] dtype must follow b", i);
            return ge::GRAPH_FAILED;
        }
    }

    // 2) format：全部输入 / 输出 ∈ {ND}（运行时 GetStorageFormat() 口径）
    if (io.xDesc->GetStorageFormat() != ge::FORMAT_ND || io.wDesc->GetStorageFormat() != ge::FORMAT_ND ||
        io.bDesc->GetStorageFormat() != ge::FORMAT_ND || io.cwDesc->GetStorageFormat() != ge::FORMAT_ND ||
        io.cbDesc->GetStorageFormat() != ge::FORMAT_ND) {
        OP_LOGE(context, "format_mismatch: x/w/b/cw/cb must be ND");
        return ge::GRAPH_FAILED;
    }
    if (io.hasSeqLength && io.seqDesc->GetStorageFormat() != ge::FORMAT_ND) {
        OP_LOGE(context, "format_mismatch: seq_length must be ND");
        return ge::GRAPH_FAILED;
    }
    if (io.hasInitH && io.initHDesc->GetStorageFormat() != ge::FORMAT_ND) {
        OP_LOGE(context, "format_mismatch: init_h must be ND");
        return ge::GRAPH_FAILED;
    }
    for (size_t i = 0; i < NUM_OUTPUTS; i++) {
        if (context->GetOutputDesc(i)->GetStorageFormat() != ge::FORMAT_ND) {
            OP_LOGE(context, "format_mismatch: output[%zu] must be ND", i);
            return ge::GRAPH_FAILED;
        }
    }
    return ge::GRAPH_SUCCESS;
}

