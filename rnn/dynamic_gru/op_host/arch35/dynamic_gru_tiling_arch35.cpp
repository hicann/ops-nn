// QueryPlatformCaps — 平台容量动态查询（先于一切 shape 工作；禁止硬编码）。
// ---------------------------------------------------------------------------
ge::graphStatus QueryPlatformCaps(gert::TilingContext* context, PlatformCaps& caps)
{
    fe::PlatFormInfos* platformInfo = context->GetPlatformInfo();
    OP_CHECK_NULL_WITH_CONTEXT(context, platformInfo);
    const auto plat = platform_ascendc::PlatformAscendC(platformInfo);
    caps.coreNumAic = static_cast<int64_t>(plat.GetCoreNumAic());
    uint64_t ubTotalU = 0;
    uint64_t l1TotalU = 0;
    uint64_t l0aTotalU = 0;
    uint64_t l0cTotalU = 0;
    plat.GetCoreMemSize(platform_ascendc::CoreMemType::UB, ubTotalU);
    plat.GetCoreMemSize(platform_ascendc::CoreMemType::L1, l1TotalU);
    // L0A/L0C 容量动态查询（禁写死硬件参数）。
    plat.GetCoreMemSize(platform_ascendc::CoreMemType::L0_A, l0aTotalU);
    plat.GetCoreMemSize(platform_ascendc::CoreMemType::L0_C, l0cTotalU);
    caps.ubTotal = static_cast<int64_t>(ubTotalU);
    caps.l1Total = static_cast<int64_t>(l1TotalU);
    caps.l0aAvail = static_cast<int64_t>(l0aTotalU) - PLATFORM_RESERVE;
    caps.l0cAvail = static_cast<int64_t>(l0cTotalU) - PLATFORM_RESERVE;
    return ge::GRAPH_SUCCESS;
}

