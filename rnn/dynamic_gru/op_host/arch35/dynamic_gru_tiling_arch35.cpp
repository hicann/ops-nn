// IMPL_OP_OPTILING(DynamicGRU) — register tiling functions with CANN
//
// .Tiling(TilingFuncDynamicGRU):
//   Registers the runtime tiling function for DynamicGRU (public pipeline,
//   see above). No TilingInputsDataDependency: host tiling never reads
//   tensor VALUES — seq_length presence only.
//
// .TilingParse<DynamicGRUCompileInfo>(TilingPrepareForDynamicGRU):
//   Registers the compile-time preparation function with the compile info type.
//   DynamicGRUCompileInfo carries platform info from compile time to runtime.
// ---------------------------------------------------------------------------
IMPL_OP_OPTILING(DynamicGRU)
    .Tiling(TilingFuncDynamicGRU)
    .TilingParse<DynamicGRUCompileInfo>(TilingPrepareForDynamicGRU);

