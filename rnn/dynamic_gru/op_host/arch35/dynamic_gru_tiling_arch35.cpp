// ValidateRankAndAttr — 异常值校验 3) 维度 rank / 4) attr 值域。
// ---------------------------------------------------------------------------
ge::graphStatus ValidateRankAndAttr(gert::TilingContext* context, const TilingIo& io)
{
    // 3) 维度：rank 精确匹配（x=3D、w/cw=2D、b/cb/seq_length=1D、init_h=2D、输出=3D）
    if (ShapeRank(io.xShape) != 3 || ShapeRank(io.wShape) != 2 || ShapeRank(io.bShape) != 1 ||
        ShapeRank(io.cwShape) != 2 || ShapeRank(io.cbShape) != 1) {
        OP_LOGE(context,
                "shape_mismatch: input rank must be x=3D w=2D b=1D cw=2D cb=1D (got x=%zu w=%zu b=%zu cw=%zu"
                " cb=%zu)",
                ShapeRank(io.xShape), ShapeRank(io.wShape), ShapeRank(io.bShape), ShapeRank(io.cwShape),
                ShapeRank(io.cbShape));
        return ge::GRAPH_FAILED;
    }
    if (io.hasSeqLength && (io.seqShape == nullptr || ShapeRank(io.seqShape) != 1)) {
        OP_LOGE(context, "shape_mismatch: seq_length must be 1D");
        return ge::GRAPH_FAILED;
    }
    if (io.hasInitH && (io.initHShape == nullptr || ShapeRank(io.initHShape) != 2)) {
        OP_LOGE(context, "shape_mismatch: init_h must be 2D");
        return ge::GRAPH_FAILED;
    }
    for (size_t i = 0; i < NUM_OUTPUTS; i++) {
        const gert::StorageShape* outShape = context->GetOutputShape(i);
        OP_CHECK_NULL_WITH_CONTEXT(context, outShape);
        if (ShapeRank(outShape) != 3) {
            OP_LOGE(context, "shape_mismatch: output[%zu] must be 3D", i);
            return ge::GRAPH_FAILED;
        }
    }

    // 4) attr 值域：仅默认值合法（is_training 为 bool 占位，前向语义不区分，不校验值）
    const auto* attrs = context->GetAttrs();
    if (attrs != nullptr) {
        const char* direction = attrs->GetStr(0);
        const int64_t* cellDepth = attrs->GetInt(1);
        const float* keepProb = attrs->GetFloat(2);
        const float* cellClip = attrs->GetFloat(3);
        const int64_t* numProj = attrs->GetInt(4);
        const bool* timeMajor = attrs->GetBool(5);
        const char* activation = attrs->GetStr(6);
        if (direction != nullptr && std::strcmp(direction, "UNIDIRECTIONAL") != 0) {
            OP_LOGE(context, "attribute_value_out_of_range: direction must be UNIDIRECTIONAL (got %s)", direction);
            return ge::GRAPH_FAILED;
        }
        if (cellDepth != nullptr && *cellDepth != 1) {
            OP_LOGE(context, "attribute_value_out_of_range: cell_depth must be 1 (got %ld)", *cellDepth);
            return ge::GRAPH_FAILED;
        }
        if (keepProb != nullptr && *keepProb != 1.0f) {
            OP_LOGE(context, "attribute_value_out_of_range: keep_prob must be 1.0 (got %f)", *keepProb);
            return ge::GRAPH_FAILED;
        }
        if (cellClip != nullptr && *cellClip != -1.0f) {
            OP_LOGE(context, "attribute_value_out_of_range: cell_clip must be -1.0 (got %f)", *cellClip);
            return ge::GRAPH_FAILED;
        }
        if (numProj != nullptr && *numProj != 0) {
            OP_LOGE(context, "attribute_value_out_of_range: num_proj must be 0 (got %ld)", *numProj);
            return ge::GRAPH_FAILED;
        }
        if (timeMajor != nullptr && !(*timeMajor)) {
            OP_LOGE(context, "attribute_value_out_of_range: time_major must be true");
            return ge::GRAPH_FAILED;
        }
        if (activation != nullptr && std::strcmp(activation, "tanh") != 0) {
            OP_LOGE(context, "attribute_value_out_of_range: activation must be tanh (got %s)", activation);
            return ge::GRAPH_FAILED;
        }
    }
    return ge::GRAPH_SUCCESS;
}

// ---------------------------------------------------------------------------
// ExtractDims — 逻辑维度提取（按名字；H 由 w/cw 推导，禁止按下标取）。
// ---------------------------------------------------------------------------
void ExtractDims(const TilingIo& io, TilingDims& dims)
{
    dims.L = ShapeDim(io.xShape, 0);
    dims.N = ShapeDim(io.xShape, 1);
    dims.I = ShapeDim(io.xShape, 2);
    dims.H = ShapeDim(io.cwShape, 1); // == w.shape[1]/2
    dims.K = ShapeDim(io.wShape, 0);  // 经 == I+H 校验后写入 TilingData
}

// ---------------------------------------------------------------------------
// ValidateShapeConstraints — 异常值校验 5) shape 硬约束绑定
// （CheckShapeConsistency 语义逐条）。
// b/cb length: 长度 ≈ 2*H/H，16 对齐；有效值为前 2H/H 个（padding 截断
// 语义 — kernel 只读前 2H/H 个元素, VecStageBias DataCopyPad）。值域为
// [2H, align16(2H)] / [H, align16(H)] 及更大的对齐形态；唯一硬下界是
// 2H/H（精确长度形态亦合法）。
// ---------------------------------------------------------------------------
ge::graphStatus ValidateShapeConstraints(gert::TilingContext* context, const TilingIo& io, const TilingDims& dims)
{
    if (ShapeDim(io.wShape, 0) != dims.I + dims.H) {
        OP_LOGE(context, "shape_mismatch: w.shape[0](%ld) != I+H(%ld)", ShapeDim(io.wShape, 0), dims.I + dims.H);
        return ge::GRAPH_FAILED;
    }
    if (ShapeDim(io.wShape, 1) != 2 * dims.H) {
        OP_LOGE(context, "shape_mismatch: w.shape[1](%ld) != 2*H(%ld)", ShapeDim(io.wShape, 1), 2 * dims.H);
        return ge::GRAPH_FAILED;
    }
    if (ShapeDim(io.cwShape, 0) != dims.K || ShapeDim(io.cwShape, 1) != dims.H) {
        OP_LOGE(context, "shape_mismatch: cw.shape(%ld,%ld) != (K,H)(%ld,%ld)", ShapeDim(io.cwShape, 0),
                ShapeDim(io.cwShape, 1), dims.K, dims.H);
        return ge::GRAPH_FAILED;
    }
    const int64_t bLen = ShapeDim(io.bShape, 0);
    const int64_t cbLen = ShapeDim(io.cbShape, 0);
    if (bLen < 2 * dims.H) {
        OP_LOGE(context, "shape_mismatch: b.shape[0](%ld) must be >= 2*H(%ld) (16-align padding, first 2H valid)", bLen,
                2 * dims.H);
        return ge::GRAPH_FAILED;
    }
    if (cbLen < dims.H) {
        OP_LOGE(context, "shape_mismatch: cb.shape[0](%ld) must be >= H(%ld) (16-align padding, first H valid)", cbLen,
                dims.H);
        return ge::GRAPH_FAILED;
    }
    if (io.hasSeqLength && ShapeDim(io.seqShape, 0) != dims.N) {
        OP_LOGE(context, "shape_mismatch: seq_length.shape[0](%ld) != N(%ld)", ShapeDim(io.seqShape, 0), dims.N);
        return ge::GRAPH_FAILED;
    }
    if (io.hasInitH && (ShapeDim(io.initHShape, 0) != dims.H || ShapeDim(io.initHShape, 1) != dims.N)) {
        OP_LOGE(context, "shape_mismatch: init_h.shape(%ld,%ld) != (H,N)(%ld,%ld)", ShapeDim(io.initHShape, 0),
                ShapeDim(io.initHShape, 1), dims.H, dims.N);
        return ge::GRAPH_FAILED;
    }
    return ge::GRAPH_SUCCESS;
}

