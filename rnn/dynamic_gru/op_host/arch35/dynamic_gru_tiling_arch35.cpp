// ---------------------------------------------------------------------------
// ResolveCommonSplit — 公共切分反解（NORMAL/MASK 共用；MASK 最坏情况口径）:
// UB 切分 → 多核切分 → L1 形态判定（恒流载）+ 流载再反解 → 段 1 切分 tChunk。
//
// L1 形态 — 恒流载形态：常驻形态的 B 条带依赖 AIV→L1 直写暂存，该通路在
//   本平台不可用（见 kernel 侧文件头 L1 形态说明），故 host 固定流载
//   （GM fp32 镜像为 w/cw hidden 段唯一供给形态）；hChunk/B_tile 仍按流载
//   逐级保底反解（确定性公式）。
//   hChunk 上限 64（MAX_H_CHUNK）：AIV V 管单指令掩码尾段在 count∈(64,128)
//   非 64 整数倍时不落盘（kernel 侧平面 elems=count·sj 触发）；钳 64 后
//   sj ≤ 64，逐行 V 管操作单重复掩码安全。
// ---------------------------------------------------------------------------
void ResolveCommonSplit(const PlatformCaps& caps, const TilingDims& dims, CommonSplit& s)
{
    const int64_t N = dims.N;
    const int64_t I = dims.I;
    const int64_t H = dims.H;
    const int64_t l1Avail = caps.l1Total - PLATFORM_RESERVE;

    // —— UB 切分：跨 base-N 档先行；单 base-N tile（2*hChunk ≤ baseN）放宽 176KB 重解一次 ——
    int64_t ubBudget = std::min(caps.ubTotal - PLATFORM_RESERVE, UB_BUDGET_CROSS);
    int64_t hChunk = FindHiddenChunk(H, ubBudget);
    if (2 * hChunk <= BASE_N) {
        ubBudget = std::min(caps.ubTotal - PLATFORM_RESERVE, UB_BUDGET_SINGLE);
        hChunk = FindHiddenChunk(H, ubBudget); // 单调放大，无迭代
    }
    int64_t hCnt = Ops::Base::CeilDiv(H, hChunk);
    int64_t hTail = H - (hCnt - 1) * hChunk;

    // —— 多核切分（batch 维 host 手算 + UB 反解上限；不委托 matmul tiling API）——
    const int64_t bTileUb = ubBudget / (BUF_CNT * hChunk * FP32_BYTES + MASK_ROW_BYTES);
    int64_t usedCoreNum = std::max(std::min(caps.coreNumAic, N), static_cast<int64_t>(1));
    int64_t singleCoreB = std::min(Ops::Base::CeilDiv(N, usedCoreNum), bTileUb);
    int64_t c5MinB = Ops::Base::CeilDiv(MIN_BUF_BYTES, hChunk * FP32_BYTES);
    if (singleCoreB < c5MinB) {
        singleCoreB = c5MinB; // C5 不满足先抬 singleCoreB
    }
    int64_t bCnt = Ops::Base::CeilDiv(N, singleCoreB);
    int64_t bTail = N - (bCnt - 1) * singleCoreB;

    // —— 流载形态 L1 再反解：hChunk → B_tile 逐级保底，下限 16 / 1；
    //    hChunk_ub / B_tile_ub 取 UB 反解结果（口径 (c)），仅计数重算。
    //    capL1 预留按 B=1 计，但 C5 下限可把 B 抬到 2/4（hChunk<64 时），
    //    抬高后的 8·B·H + 4·tChunk·B·I 可能使可行域硬校验失败。按「其余项
    //    取最小可行」的设计本意，硬校验失败且 hChunk > 16 时 hChunk 降 16
    //    重解（至多 3 次，确定性）；hChunk=16 仍不可行则拒绝
    //    （超大 shape 由 tiling 拒绝）。
    int64_t hChunkUb = hChunk;
    int64_t hChunkTry = hChunk;
    while (true) {
        const int64_t capL1 = (l1Avail - L1_AMIRROR_BYTES_PER_ELEM * H - L1_ATILE_BYTES_PER_ELEM * I) /
                              (L1_BSEG_BYTES_PER_ELEM * H);
        hChunkTry = std::max(Ops::Base::FloorAlign(std::min(hChunkUb, capL1), HIDDEN_ALIGN), HIDDEN_ALIGN);
        hChunkTry = std::min(hChunkTry, MAX_H_CHUNK);
        hCnt = Ops::Base::CeilDiv(H, hChunkTry);
        hTail = H - (hCnt - 1) * hChunkTry;
        const int64_t bCapL1 = (l1Avail - L1_BSEG_BYTES_PER_ELEM * H * hChunkTry) /
                               (L1_AMIRROR_BYTES_PER_ELEM * H + L1_ATILE_BYTES_PER_ELEM * I);
        int64_t bTile = std::min(std::min(bTileUb, Ops::Base::CeilDiv(N, usedCoreNum)), bCapL1);
        bTile = std::max(bTile, static_cast<int64_t>(1));
        c5MinB = Ops::Base::CeilDiv(MIN_BUF_BYTES, hChunkTry * FP32_BYTES);
        if (bTile < c5MinB) {
            bTile = c5MinB; // 可行域硬校验含 C5：抬升而非拒绝
        }
        const int64_t fixedL1Try = L1_BSEG_BYTES_PER_ELEM * H * hChunkTry;
        const int64_t aMirrorTry = L1_AMIRROR_BYTES_PER_ELEM * bTile * H;
        // 内层 tChunk 反解除法与外层（下方 aTileBytesPerStep 处）口径
        // 对齐：分母下限 1 防 I=0 整型除零（非空路径 I>0 已在上方显式
        // 拒绝，此处为纵深防护）。
        const int64_t aTileBytesPerStepTry = std::max(L1_ATILE_BYTES_PER_ELEM * bTile * I, static_cast<int64_t>(1));
        const int64_t tChunkTry = std::max((l1Avail - fixedL1Try - aMirrorTry) / aTileBytesPerStepTry,
                                           static_cast<int64_t>(1));
        if (fixedL1Try + aMirrorTry + L1_ATILE_BYTES_PER_ELEM * tChunkTry * bTile * I <= l1Avail ||
            hChunkTry <= HIDDEN_ALIGN) {
            hChunk = hChunkTry;
            singleCoreB = bTile;
            bCnt = Ops::Base::CeilDiv(N, singleCoreB);
            bTail = N - (bCnt - 1) * singleCoreB;
            break;
        }
        hChunkUb = hChunkTry - HIDDEN_ALIGN; // 降档重解（capL1 同步收紧）
    }

    // —— 段 1 切分 tChunk（L1 预算允许的最大值，禁止限制为 L 的因子；
    //    A tile 双缓冲开销 4*B*I 字节/步）——
    s.hChunk = hChunk;
    s.hCnt = hCnt;
    s.hTail = hTail;
    s.usedCoreNum = usedCoreNum;
    s.singleCoreB = singleCoreB;
    s.bCnt = bCnt;
    s.bTail = bTail;
    s.fixedL1 = L1_BSEG_BYTES_PER_ELEM * H * hChunk; // 恒流载形态的 B 列段包络
    s.aMirror = L1_AMIRROR_BYTES_PER_ELEM * singleCoreB * H;
    const int64_t aTileBytesPerStep = std::max(L1_ATILE_BYTES_PER_ELEM * singleCoreB * I,
                                               static_cast<int64_t>(1)); // I=0 防除零
    s.tChunk = std::max((l1Avail - s.fixedL1 - s.aMirror) / aTileBytesPerStep, static_cast<int64_t>(1));
}

// ---------------------------------------------------------------------------
// CapTChunkByKernelLayout — kernel 实际片上布局可行性：L1 反解的
//   (B, hChunk, tChunk) 须同时装进 kernel per-AIV UB 布局与 L0A/L0C mMax 槽。
//   UB 工作集模型（bTileUb）未覆盖 kernel 实际布局的段 1 drain 平面（随
//   mMax = min(tChunk,L)·B 增长、L1 反解无 UB 侧上界）、8 个平面区的 hCnt
//   倍增与固定暂存（tmpT/bias/stage/scratch/trans）——合法 shape 可被接受但
//   per-AIV UB 超物理容量数倍 → 设备侧越界写（raw LocalTensor 偏移寻址无
//   分配器检查）。补齐三式（逐项镜像 dynamic_gru_normal.h Init，32B 对齐
//   逐 Take）：
//     (UB)  drain1 + (8·hCnt+4)·⌈B/2⌉·hChunk·4 + 固定暂存 ≤ ubAvail
//     (L0A) CeilAlign(mMax,16)·kSeg1(=64)·2 ≤ l0aAvail
//     (L0C) CeilAlign(mMax,16)·CeilAlign(nBlk,16)·4 ≤ l0cAvail
//   其中 drain1 = ⌈mMax/2⌉·nBlk·4（段 1 drain 平面，唯一随 mMax 增长的
//   UB 项）→ 三式对 mMax 单调，先反解 mMax 上界；L·B 超界则降 tChunk 重解
//   （tChunk ≥ 1 下界；B 已由 bTileUb ≤ 232 < L0A mMax 上界约束，无需降 B）。
//   mMax 上界（L0A 式 ≤ FloorAlign(l0aAvail/128,16) = 512 ≪ 65535）同时闭合
//   normal.h DrainToUB fp.mSize uint16 截断域。
// ---------------------------------------------------------------------------
void CapTChunkByKernelLayout(gert::TilingContext* context, const PlatformCaps& caps, const TilingIo& io,
                             const TilingDims& dims, CommonSplit& s, LayoutNeeds& needs)
{
    const int64_t B = s.singleCoreB;
    const int64_t rowsMax = Ops::Base::CeilDiv(B, static_cast<int64_t>(2)); // normal.h rowsMax_
    const int64_t planeElems = rowsMax * s.hChunk;                          // normal.h planeElems_
    const int64_t nBlk = std::min(Ops::Base::CeilAlign(std::min(2 * dims.H, NBLK_STRUCT_MAX), KERNEL_CUBE_BLOCK),
                                  static_cast<int64_t>(64)); // normal.h nBlk_（V 管掩码尾段上限 64）
    const int64_t tBytes = (io.bDesc->GetDataType() == ge::DT_FLOAT) ? 4 :
                                                                       2; // T = b/cb dtype（tmpT/biasT/transT 视图）
    const int64_t biasCbOff = Ops::Base::CeilAlign(2 * dims.H * tBytes, KERNEL_C0_BYTES) /
                              tBytes; // normal.h biasCbOff_
    const int64_t rowBatch = std::max(
        std::min(dims.H, Ops::Base::FloorAlign(KERNEL_STAGE_F16_BYTES / std::max(s.hChunk * 2, static_cast<int64_t>(2)),
                                               KERNEL_CUBE_BLOCK / 2)),
        static_cast<int64_t>(1));                                                       // normal.h rowBatch_
    const int64_t transPitchE = Ops::Base::CeilAlign(rowsMax * 2, KERNEL_C0_BYTES) / 2; // normal.h transPitchE_
    // 平面区 + 固定暂存（不随 mMax 变化的 UB 项，逐 Take 32B 对齐）：
    // hCnt 倍增平面区 + 单平面区（个数/区名见 KERNEL_PLANE_REGIONS_* 常量注，
    // normal.h Init 逐 Take 镜像）
    int64_t fixedUb = 0;
    for (int64_t k = 0; k < KERNEL_PLANE_REGIONS_HCNT; ++k) {
        fixedUb += Ops::Base::CeilAlign(s.hCnt * planeElems * FP32_BYTES, KERNEL_MIN_ALIGN);
    }
    for (int64_t k = 0; k < KERNEL_PLANE_REGIONS_FIXED; ++k) {
        fixedUb += Ops::Base::CeilAlign(planeElems * FP32_BYTES, KERNEL_MIN_ALIGN);
    }
    fixedUb += Ops::Base::CeilAlign(planeElems * tBytes, KERNEL_MIN_ALIGN);                    // offTmpT_
    fixedUb += Ops::Base::CeilAlign((biasCbOff + dims.H) * tBytes, KERNEL_MIN_ALIGN);          // offBiasT_
    fixedUb += Ops::Base::CeilAlign((biasCbOff + dims.H) * FP32_BYTES, KERNEL_MIN_ALIGN) + 64; // offBiasF32_
    fixedUb += Ops::Base::CeilAlign(rowBatch * s.hChunk * 2, KERNEL_MIN_ALIGN);                // offStageF16_
    fixedUb += Ops::Base::CeilAlign(rowBatch * s.hChunk * FP32_BYTES, KERNEL_MIN_ALIGN);       // offStageF32_
    fixedUb += Ops::Base::CeilAlign(KERNEL_SCRATCH_BYTES, KERNEL_MIN_ALIGN);                   // offScratchU8_
    fixedUb += Ops::Base::CeilAlign(s.hChunk * transPitchE * tBytes, KERNEL_MIN_ALIGN);        // offTransT_
    fixedUb += Ops::Base::CeilAlign(s.hChunk * transPitchE * FP32_BYTES, KERNEL_MIN_ALIGN);    // offTransF_
    if (io.hasSeqLength) { // [MASK] 行向量（offSeqRow_ + offMaskRow_）
        fixedUb += 2 * Ops::Base::CeilAlign(rowsMax * 4, KERNEL_MIN_ALIGN);
    }
    // mMax 上界三式反解（drain1 = ⌈m/2⌉·nBlk·4 单调；L0A/L0C 以
    // CeilAlign(m,16) 计，上界对齐到 16 后 m 可取满该 16 倍数）。
    const int64_t ubAvail = caps.ubTotal - PLATFORM_RESERVE;
    const int64_t drainBytesPerRow = nBlk * FP32_BYTES;
    int64_t mMaxUb = 0;
    if (ubAvail - fixedUb >= drainBytesPerRow) {
        mMaxUb = 2 * ((ubAvail - fixedUb) / drainBytesPerRow); // (UB) 式
    }
    mMaxUb = std::min(mMaxUb,
                      Ops::Base::FloorAlign(caps.l0aAvail / L0A_BYTES_PER_M_ROW, KERNEL_CUBE_BLOCK)); // (L0A) 式
    mMaxUb = std::min(
        mMaxUb, Ops::Base::FloorAlign(caps.l0cAvail / (Ops::Base::CeilAlign(nBlk, KERNEL_CUBE_BLOCK) * FP32_BYTES),
                                      KERNEL_CUBE_BLOCK)); // (L0C) 式
    if (dims.L * B > mMaxUb) {
        const int64_t tChunkCapped = std::max(mMaxUb / B, static_cast<int64_t>(1));
        if (tChunkCapped < s.tChunk) {
            OP_LOGI(context, "kernel layout cap: mMaxUb=%ld (ubLeft=%ld l0a=%ld l0c=%ld) tChunk %ld -> %ld", mMaxUb,
                    ubAvail - fixedUb, caps.l0aAvail, caps.l0cAvail, s.tChunk, tChunkCapped);
            s.tChunk = tChunkCapped;
        }
    }
    // 终值复核：三式在最终 (B, hChunk, hCnt, tChunk) 下的取值（供可行域硬校验）
    const int64_t mMax = std::min(s.tChunk, dims.L) * B;
    needs.layoutUbBytes = fixedUb +
                          Ops::Base::CeilAlign(Ops::Base::CeilDiv(mMax, static_cast<int64_t>(2)) * drainBytesPerRow,
                                               KERNEL_MIN_ALIGN);
    needs.l0aNeed = Ops::Base::CeilAlign(mMax, KERNEL_CUBE_BLOCK) * L0A_BYTES_PER_M_ROW;
    needs.l0cNeed = Ops::Base::CeilAlign(mMax, KERNEL_CUBE_BLOCK) * Ops::Base::CeilAlign(nBlk, KERNEL_CUBE_BLOCK) *
                    FP32_BYTES;
}

// ---------------------------------------------------------------------------
// PlanWorkspace — workspace 规划：igates / cgates / fb 槽 / whid 镜像，32B
//   对齐。fb 槽 = 段 2 A 操作数 GM 中继（每核 [B, CeilAlign(H,8)] fp32 单槽，
//   h/rh 逐轮复用 — kernel 侧按同公式自 wsCgatesOffset 反解基址，故无独立
//   TilingData 字段）；whid 镜像 = 段 2 B 源 fp32 流载镜像（恒流载形态）。
// ---------------------------------------------------------------------------
void PlanWorkspace(const TilingDims& dims, const CommonSplit& s, WsLayout& ws)
{
    const int64_t wsCgatesOffset = Ops::Base::CeilAlign(dims.L * dims.N * 2 * dims.H * FP32_BYTES, WS_ALIGN);
    const int64_t cgatesLen = Ops::Base::CeilAlign(dims.L * dims.N * dims.H * FP32_BYTES, WS_ALIGN);
    const int64_t fbLen = Ops::Base::CeilAlign(
        s.usedCoreNum * s.singleCoreB * Ops::Base::CeilAlign(dims.H, H_ALIGNED_GRAN) * FP32_BYTES, WS_ALIGN);
    ws.wsIgatesOffset = 0;
    ws.wsCgatesOffset = wsCgatesOffset;
    ws.wsWhidOffset = wsCgatesOffset + cgatesLen + fbLen;
    ws.wsTotalSize = ws.wsWhidOffset + Ops::Base::CeilAlign(3 * s.hCnt * dims.H * s.hChunk * FP32_BYTES, WS_ALIGN);
}

// ---------------------------------------------------------------------------
// WriteTilingResult — 填 TilingData（字段与 TilingData 结构体逐字段一致）
//   + SetBlockDim + workspace[0] + 结果日志。
// ---------------------------------------------------------------------------
void WriteTilingResult(gert::TilingContext* context, DynamicGRUTilingData* tilingData, size_t* currentWorkspace,
                       const TilingDims& dims, const TilingIo& io, const CommonSplit& s, const WsLayout& ws)
{
    tilingData->numStep = dims.L;
    tilingData->batchSize = dims.N;
    tilingData->inputSize = dims.I;
    tilingData->hiddenSize = dims.H;
    tilingData->kSize = dims.K;
    tilingData->isInitH = io.hasInitH ? 1 : 0;
    tilingData->batchSplit.usedCoreNum = s.usedCoreNum;
    tilingData->batchSplit.singleCoreB = s.singleCoreB;
    tilingData->batchSplit.bCnt = s.bCnt;
    tilingData->batchSplit.bTail = s.bTail;
    tilingData->hiddenSplit.hChunk = s.hChunk;
    tilingData->hiddenSplit.hCnt = s.hCnt;
    tilingData->hiddenSplit.hTail = s.hTail;
    tilingData->tChunk = s.tChunk;
    tilingData->wsIgatesOffset = ws.wsIgatesOffset;
    tilingData->wsCgatesOffset = ws.wsCgatesOffset;
    tilingData->wsWhidOffset = ws.wsWhidOffset;
    tilingData->wsTotalSize = ws.wsTotalSize;

    context->SetBlockDim(static_cast<uint32_t>(s.usedCoreNum)); // AIC 核对数；AIV = 2×（MIX_AIC_1_2）
    currentWorkspace[0] = static_cast<size_t>(ws.wsTotalSize);

    OP_LOGI(context, "shape: L=%ld N=%ld I=%ld H=%ld K=%ld isInitH=%d", dims.L, dims.N, dims.I, dims.H, dims.K,
            static_cast<int>(tilingData->isInitH));
    OP_LOGI(context, "batch: cores=%ld B_tile=%ld bCnt=%ld bTail=%ld", s.usedCoreNum, s.singleCoreB, s.bCnt, s.bTail);
    OP_LOGI(context, "hidden: hChunk=%ld hCnt=%ld hTail=%ld tChunk=%ld", s.hChunk, s.hCnt, s.hTail, s.tChunk);
    OP_LOGI(context, "ws: igates@%ld cgates@%ld whid@%ld total=%ld", ws.wsIgatesOffset, ws.wsCgatesOffset,
            ws.wsWhidOffset, ws.wsTotalSize);
}

