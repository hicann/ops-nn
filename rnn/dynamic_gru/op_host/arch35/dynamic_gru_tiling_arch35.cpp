// ---------------------------------------------------------------------------
// TilingFuncDynamicGRU(context) — tiling entry point called by CANN runtime
//
// Pipeline (顺序固定):
//   平台查询 → Shape 提取（按名字）→ 异常值校验（dtype→format→维度→attr→shape）
//   → 分支判定（empty → mask/normal，随即 SetTilingKey）
//   → [EMPTY] FillEmptyDefaults + SetBlockDim(1) + 早返
//   → [NORMAL/MASK] UB 切分 → 多核切分 → L1 形态判定 →（流载再反解）→ 段 1 切分
//   → 可行域硬校验 → workspace 规划 → 填 TilingData + SetBlockDim + workspace
//
// Parameters:
//   context — TilingContext with input shapes/tensors, platform info, attrs
//
// Returns: ge::graphStatus（校验失败 / 资源不可行 → GRAPH_FAILED，不下发 kernel）
// ---------------------------------------------------------------------------
static ge::graphStatus TilingFuncDynamicGRU(gert::TilingContext* context)
{
    if (context == nullptr) {
        return ge::GRAPH_FAILED;
    }
    OP_LOGI(context, "Enter TilingFuncDynamicGRU");

    // ===== 平台查询（先于一切 shape 工作；动态查询，禁止硬编码）=====
    PlatformCaps caps;
    if (QueryPlatformCaps(context, caps) != ge::GRAPH_SUCCESS) {
        return ge::GRAPH_FAILED;
    }

    // ===== Shape / Tensor / Desc 获取（按名字；可选输入经 IR 下标实例感知接口）=====
    TilingIo io;
    if (FetchTilingIo(context, io) != ge::GRAPH_SUCCESS) {
        return ge::GRAPH_FAILED;
    }

    // ===== 异常值校验（顺序固定，任一失败 return GRAPH_FAILED，不占 tilingKey）=====
    if (ValidateDtypeAndFormat(context, io) != ge::GRAPH_SUCCESS) {
        return ge::GRAPH_FAILED;
    }
    if (ValidateRankAndAttr(context, io) != ge::GRAPH_SUCCESS) {
        return ge::GRAPH_FAILED;
    }
    TilingDims dims;
    ExtractDims(io, dims);
    if (ValidateShapeConstraints(context, io, dims) != ge::GRAPH_SUCCESS) {
        return ge::GRAPH_FAILED;
    }

    // ===== TilingData / workspace 载体获取 =====
    DynamicGRUTilingData* tilingData = context->GetTilingData<DynamicGRUTilingData>();
    OP_CHECK_NULL_WITH_CONTEXT(context, tilingData);
    // currentWorkspace[0]: the caller must allocate wsTotalSize bytes for the
    // operator-owned segments (igates / cgates / whid); the arch35 codegen
    // wrapper hands the kernel a pointer past the system reserve, and the
    // kernel re-bases to the operator-owned area（见 dynamic_gru_normal.h
    // 文件头 WORKSPACE 基址说明）.
    size_t* currentWorkspace = context->GetWorkspaceSizes(1);
    OP_CHECK_NULL_WITH_CONTEXT(context, currentWorkspace);

    // ===== 分支判定（empty 最先（empty∧mask 归一化），mask/normal 互斥）=====
    const bool isEmpty = (dims.L == 0) || (dims.N == 0) || (dims.H == 0);
    if (isEmpty) {
        FillEmptyDefaults(context, tilingData, currentWorkspace, dims);
        return ge::GRAPH_SUCCESS;
    }
    // ===== I 维值域校验 =====
    // I=0 仅在 H=0（K=0 空内积，已由上方 empty 分支承接，含 I=0∧H=0 形态）
    // 时可达：非空路径（H>0）下 I=0 的段 1 输入投影收缩维为空，kernel 段 1
    // A tile/Mmad/drain 链无 I=0 语义（kb 循环 0 次 → L0C 未种子即 drain，
    // 静默脏数据），且 tiling 段 1 切分以 4*B*I 为步长反解（除零点）。此处
    // 显式拒绝 I <= 0（OP_LOGE + GRAPH_FAILED），非法维不静默下传。
    if (dims.I <= 0) {
        OP_LOGE(context,
                "shape_mismatch: input_size I(%ld) must be > 0 on the non-empty path (L=%ld N=%ld H=%ld);"
                " I=0 is only legal as the K=0 empty inner product with H=0 (empty branch)",
                dims.I, dims.L, dims.N, dims.H);
        return ge::GRAPH_FAILED;
    }
    if (io.hasSeqLength) {
        context->SetTilingKey(GET_TPL_TILING_KEY(DYNAMIC_GRU_TPL_MODE_MASK)); // key = 1，掩码吸收路径
    } else {
        context->SetTilingKey(GET_TPL_TILING_KEY(DYNAMIC_GRU_TPL_MODE_NORMAL)); // key = 0，定长主路径（m ≡ 1）
    }

    // ===== 公共 tiling 量（NORMAL/MASK 共用；MASK 最坏情况口径）=====
    CommonSplit split;
    ResolveCommonSplit(caps, dims, split);

    // ===== kernel 实际片上布局可行性（mMax 三式钳 tChunk）=====
    LayoutNeeds needs;
    CapTChunkByKernelLayout(context, caps, io, dims, split, needs);

    // ===== 可行域硬校验（不过 → GRAPH_FAILED，超大 shape 由 tiling 拒绝）=====
    const int64_t l1Avail = caps.l1Total - PLATFORM_RESERVE;
    const bool feasible = (split.fixedL1 + split.aMirror +
                               L1_ATILE_BYTES_PER_ELEM * split.tChunk * split.singleCoreB * dims.I <=
                           l1Avail) &&
                          (split.singleCoreB * split.hChunk * FP32_BYTES >= MIN_BUF_BYTES) &&
                          (needs.layoutUbBytes <= caps.ubTotal - PLATFORM_RESERVE) &&
                          (needs.l0aNeed <= caps.l0aAvail) && (needs.l0cNeed <= caps.l0cAvail);
    if (!feasible) {
        // 资源不可行（超大 shape 由 tiling 拒绝），不下发 kernel
        OP_LOGE(context,
                "resource infeasible: L=%ld N=%ld I=%ld H=%ld hChunk=%ld B=%ld tChunk=%ld"
                " l1Avail=%ld layoutUb=%ld ubAvail=%ld l0aNeed=%ld l0aAvail=%ld l0cNeed=%ld l0cAvail=%ld",
                dims.L, dims.N, dims.I, dims.H, split.hChunk, split.singleCoreB, split.tChunk, l1Avail,
                needs.layoutUbBytes, caps.ubTotal - PLATFORM_RESERVE, needs.l0aNeed, caps.l0aAvail, needs.l0cNeed,
                caps.l0cAvail);
        return ge::GRAPH_FAILED;
    }

    // ===== workspace 规划 + 填 TilingData + 写 context =====
    WsLayout ws;
    PlanWorkspace(dims, split, ws);
    WriteTilingResult(context, tilingData, currentWorkspace, dims, io, split, ws);
    return ge::GRAPH_SUCCESS;
}

// ---------------------------------------------------------------------------
// TilingPrepareForDynamicGRU(context) — compile-time preparation
//
// This function is called during graph compilation (before runtime tiling).
// It populates the DynamicGRUCompileInfo struct with platform hardware info
// (core count, UB size) so downstream consumers can access it without
// re-querying. The TilingFunc above queries the platform directly per call
// (see file header note) and does not depend on this carrier.
//
// Parameters:
//   context — TilingParseContext used during graph compilation
//
// Returns: ge::graphStatus
// ---------------------------------------------------------------------------
ge::graphStatus TilingPrepareForDynamicGRU(gert::TilingParseContext* context)
{
    fe::PlatFormInfos* platformInfo = context->GetPlatformInfo();
    auto compileInfo = context->GetCompiledInfo<DynamicGRUCompileInfo>();
    OP_CHECK_NULL_WITH_CONTEXT(context, platformInfo);
    OP_CHECK_NULL_WITH_CONTEXT(context, compileInfo);
    auto ap = platform_ascendc::PlatformAscendC(platformInfo);
    compileInfo->coreNum = ap.GetCoreNumAiv();
    ap.GetCoreMemSize(platform_ascendc::CoreMemType::UB, compileInfo->ubSize);
    return ge::GRAPH_SUCCESS;
}

