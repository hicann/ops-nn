// ---------------------------------------------------------------------------
// InferShape4DynamicGRU(context) — shape inference function
//
// Parameters:
//   context — InferShapeContext providing access to input shapes and
//             allowing setting of output shapes
//
// Returns:
//   ge::graphStatus — ge::GRAPH_SUCCESS on success; GRAPH_FAILED with an
//   OP_LOGE diagnostic (shape_mismatch) on any C1–C9 or declared-output
//   violation.
// ---------------------------------------------------------------------------
static ge::graphStatus InferShape4DynamicGRU(gert::InferShapeContext* context)
{
    // ===== Shape 获取（按名字；可选输入经 IR 下标实例感知接口，nullptr = 未传入）=====
    const gert::Shape* xShape = context->GetInputShape(IDX_X);
    const gert::Shape* wShape = context->GetInputShape(IDX_W);
    const gert::Shape* bShape = context->GetInputShape(IDX_B);
    const gert::Shape* cwShape = context->GetInputShape(IDX_CW);
    const gert::Shape* cbShape = context->GetInputShape(IDX_CB);
    OP_CHECK_NULL_WITH_CONTEXT(context, xShape);
    OP_CHECK_NULL_WITH_CONTEXT(context, wShape);
    OP_CHECK_NULL_WITH_CONTEXT(context, bShape);
    OP_CHECK_NULL_WITH_CONTEXT(context, cwShape);
    OP_CHECK_NULL_WITH_CONTEXT(context, cbShape);
    const gert::Shape* seqShape = context->GetOptionalInputShape(IDX_SEQ_LENGTH);
    const gert::Shape* initHShape = context->GetOptionalInputShape(IDX_INIT_H);
    const bool hasSeqLength = (seqShape != nullptr);
    const bool hasInitH = (initHShape != nullptr);

    // ===== DynamicRankSupportFlag(true) 配套：[-2] 未知 Rank 声明早退 =====
    // GE 图编译期 [-2] 声明的 shape 为 rank-1 单元素 {-2}；此时不做 rank/维值
    // 校验（具体 shape 由运行时数据确定），全部输出同样声明为 {-2} 未知 Rank。
    if (Ops::Base::IsUnknownRank(*xShape)) {
        for (size_t k = 0; k < NUM_OUTPUTS; k++) {
            gert::Shape* outShape = context->GetOutputShape(k);
            OP_CHECK_NULL_WITH_CONTEXT(context, outShape);
            Ops::Base::SetUnknownRank(*outShape);
        }
        return ge::GRAPH_SUCCESS;
    }

    // ===== C1/C9：rank 精确匹配（rank 在动态编译期同样已知，不做未知跳过）=====
    if (xShape->GetDimNum() != 3 || wShape->GetDimNum() != 2 || bShape->GetDimNum() != 1 || cwShape->GetDimNum() != 2 ||
        cbShape->GetDimNum() != 1) {
        OP_LOGE(context,
                "shape_mismatch: input rank must be x=3D w=2D b=1D cw=2D cb=1D (got x=%zu w=%zu b=%zu cw=%zu cb=%zu)",
                xShape->GetDimNum(), wShape->GetDimNum(), bShape->GetDimNum(), cwShape->GetDimNum(),
                cbShape->GetDimNum());
        return ge::GRAPH_FAILED;
    }
    if (hasSeqLength && seqShape->GetDimNum() != 1) {
        OP_LOGE(context, "shape_mismatch: seq_length must be 1D (got %zuD)", seqShape->GetDimNum());
        return ge::GRAPH_FAILED;
    }
    if (hasInitH && initHShape->GetDimNum() != 2) {
        OP_LOGE(context, "shape_mismatch: init_h must be 2D (got %zuD)", initHShape->GetDimNum());
        return ge::GRAPH_FAILED;
    }

    // ===== 基础维取值（H 由 cw 推导；含未知维传播）=====
    const int64_t L = xShape->GetDim(0);
    const int64_t N = xShape->GetDim(1);
    const int64_t I = xShape->GetDim(2);
    const int64_t H = cwShape->GetDim(1);
    const int64_t wDim0 = wShape->GetDim(0);
    const int64_t wDim1 = wShape->GetDim(1);
    const int64_t cwDim0 = cwShape->GetDim(0);
    const int64_t bLen = bShape->GetDim(0);
    const int64_t cbLen = cbShape->GetDim(0);

    // ===== C2：w.shape[0] == I + H（K = I + H，含未知跳过）=====
    if (IsKnownDim(wDim0) && IsKnownDim(I) && IsKnownDim(H) && (wDim0 != I + H)) {
        OP_LOGE(context, "shape_mismatch: w.shape[0](%ld) != I+H(%ld+%ld=%ld)", wDim0, I, H, I + H);
        return ge::GRAPH_FAILED;
    }
    // ===== I 值域登记（C2 的 K=I+H 家族补充，含未知跳过）：I==0 仅在空
    //      tensor 路径（L==0 || N==0 || H==0，K=0 空内积由 empty 分支承接）
    //      合法；非空路径 I==0 的段 1 输入投影收缩维为空，kernel 段 1 链
    //      无 I=0 语义（L0C 未种子即 drain），原样下传会在 host tiling 段 1
    //      切分触发整型除零 —— 此处登记值域，非法维不静默下传（tiling 侧
    //      有同款兜底拒绝）。
    if (IsKnownDim(I) && I == 0 && IsKnownDim(H) && H > 0 && IsKnownDim(L) && L > 0 && IsKnownDim(N) && N > 0) {
        OP_LOGE(context,
                "shape_mismatch: input_size I(=0) is only legal on the empty path (L=%ld N=%ld H=%ld);"
                " non-empty inputs require I > 0",
                L, N, H);
        return ge::GRAPH_FAILED;
    }
    // ===== C3：w.shape[1] == 2*H（G = 2H，含未知跳过）=====
    if (IsKnownDim(wDim1) && IsKnownDim(H) && (wDim1 != 2 * H)) {
        OP_LOGE(context, "shape_mismatch: w.shape[1](%ld) != 2*H(%ld)", wDim1, 2 * H);
        return ge::GRAPH_FAILED;
    }
    // ===== C4：cw.shape[0] == w.shape[0]（含未知跳过）=====
    if (IsKnownDim(cwDim0) && IsKnownDim(wDim0) && (cwDim0 != wDim0)) {
        OP_LOGE(context, "shape_mismatch: cw.shape[0](%ld) != w.shape[0](%ld)", cwDim0, wDim0);
        return ge::GRAPH_FAILED;
    }
    // ===== C5：x.shape[1] == seq_length.shape[0]（可选传入时；含未知跳过）=====
    if (hasSeqLength) {
        const int64_t seqLen = seqShape->GetDim(0);
        if (IsKnownDim(seqLen) && IsKnownDim(N) && (seqLen != N)) {
            OP_LOGE(context, "shape_mismatch: seq_length.shape[0](%ld) != N(%ld)", seqLen, N);
            return ge::GRAPH_FAILED;
        }
    }
    // ===== C5/C6：init_h.shape == (H, N)（可选传入时；含未知跳过）=====
    if (hasInitH) {
        const int64_t ihDim0 = initHShape->GetDim(0);
        const int64_t ihDim1 = initHShape->GetDim(1);
        if (IsKnownDim(ihDim0) && IsKnownDim(H) && (ihDim0 != H)) {
            OP_LOGE(context, "shape_mismatch: init_h.shape[0](%ld) != H(%ld)", ihDim0, H);
            return ge::GRAPH_FAILED;
        }
        if (IsKnownDim(ihDim1) && IsKnownDim(N) && (ihDim1 != N)) {
            OP_LOGE(context, "shape_mismatch: init_h.shape[1](%ld) != N(%ld)", ihDim1, N);
            return ge::GRAPH_FAILED;
        }
    }
    // ===== C7：b.shape[0] >= 2H（16 对齐 padding，有效值为前 2H 个；含未知跳过）=====
    if (IsKnownDim(bLen) && IsKnownDim(H) && (bLen < 2 * H)) {
        OP_LOGE(context, "shape_mismatch: b.shape[0](%ld) must be >= 2*H(%ld) (16-align padding, first 2H valid)", bLen,
                2 * H);
        return ge::GRAPH_FAILED;
    }
    // ===== C8：cb.shape[0] >= H（16 对齐 padding，有效值为前 H 个；含未知跳过）=====
    if (IsKnownDim(cbLen) && IsKnownDim(H) && (cbLen < H)) {
        OP_LOGE(context, "shape_mismatch: cb.shape[0](%ld) must be >= H(%ld) (16-align padding, first H valid)", cbLen,
                H);
        return ge::GRAPH_FAILED;
    }

    // ===== 逐输出推导：5 输出全等 (L, H, N) =====
    // DynamicShapeSupportFlag(true) 下 GE 动态图复用同一 Session 多次 RunGraph 时，
    // 上一次执行的输出 shape 会残留在 context 中（"declared" 实为 stale 值，
    // 非用户声明）——若与本次输入推导值比对必假失败。故不做 declared 输出校验，
    // 直接以输入推导值覆盖（编译期的用户声明校验由 GE 框架在图构建阶段完成）。
    for (size_t k = 0; k < NUM_OUTPUTS; k++) {
        gert::Shape* outShape = context->GetOutputShape(k);
        OP_CHECK_NULL_WITH_CONTEXT(context, outShape);
        *outShape = {L, H, N};
    }
    return ge::GRAPH_SUCCESS;
}

