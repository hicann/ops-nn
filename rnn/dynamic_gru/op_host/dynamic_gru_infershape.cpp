constexpr size_t IDX_X = 0;          // x          (L, N, I) fp16
constexpr size_t IDX_W = 1;          // w          (I+H, 2H) fp16
constexpr size_t IDX_B = 2;          // b          (B2,) 16 对齐
constexpr size_t IDX_CW = 3;         // cw         (I+H, H) fp16
constexpr size_t IDX_CB = 4;         // cb         (B1,) 16 对齐
constexpr size_t IDX_SEQ_LENGTH = 5; // seq_length (N,) int32 OPTIONAL
constexpr size_t IDX_INIT_H = 6;     // init_h     (H, N) OPTIONAL
