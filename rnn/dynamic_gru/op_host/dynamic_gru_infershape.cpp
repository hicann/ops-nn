// 维值动态标记：ge/gert 以 -1 表示未知维；gert::Shape::kInvalidDimValue
// (INT64_MIN) 为非法占位，一并按未知处理。已知维恒 >= 0。
inline bool IsKnownDim(const int64_t dim) { return dim >= 0; }

// 判定输出 shape 是否为调用方真实声明：
//   rank 0（未初始化）或 rank 1 且首维 < 0（框架的 unknown 标记）视为未声明。
inline bool IsDeclaredShape(const gert::Shape& shape)
{
    const size_t dimNum = shape.GetDimNum();
    if (dimNum == 0U) {
        return false;
    }
    if (dimNum == 1U && shape.GetDim(0) < 0) {
        return false;
    }
    return true;
}

