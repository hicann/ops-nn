// ROLE: Shape inference for the DynamicGRU operator.
//   When the Graph Engine compiles a graph (static shapes) or executes it
//   (dynamic shapes, host-side runtime inference), it calls this infer-shape
//   function to determine the output shapes from the input shapes.
//
//   Rules implemented:
//     - H (hidden_size) is derived from w/cw BY NAME (cw.shape[1], equivalent
//       check w.shape[1] == 2*H) — never by input index (BIAS_INDEX=2 trap:
//       input index 2 is b, whose length is 16-aligned padded ≈2H, not H).
//     - All 5 outputs y / output_h / r / i / n share (L, H, N) =
//       (x.shape[0], cw.shape[1], x.shape[1]).
//     - Input validations C1–C9 (ND 布局):
//         C1 rank: x=3D, w/cw=2D, b/cb=1D, seq_length=1D, init_h=2D
//         C2 w.shape[0] == x.shape[2] + cw.shape[1]   (K = I + H)
//            + I 值域：I==0 仅空路径合法（非空路径 I>0，kernel 段 1 链
//              无 I=0 语义）
//         C3 w.shape[1] == 2 * cw.shape[1]            (G = 2H)
//         C4 cw.shape[0] == w.shape[0]
//         C5 x.shape[1] == seq_length.shape[0] == init_h.shape[1] (传入时)
//         C6 init_h.shape[0] == cw.shape[1]                       (传入时)
//         C7 b.shape[0] >= 2H   (16 对齐 padding, 有效值前 2H 个)
//         C8 cb.shape[0] >= H   (16 对齐 padding, 有效值前 H 个)
//         C9 seq_length 恒 1D（收紧为 (N,)）
//     - Dynamic dims (dim < 0, e.g. -1 from dynamic compile / INT64_MIN
//       invalid marker) propagate to the corresponding output dim; every
//       equality/inequality check involving an unknown dim is skipped at the
//       unknown stage and re-checked once shapes become concrete.
//     - Empty shapes (L=0 / N=0 / H=0) fall through naturally to empty
//       outputs instead of errors (k_zero_empty_inner_product 边界).
//
//   Attributes do not participate in shape inference (their value-domain
//   validation lives in the tiling entry).
//
