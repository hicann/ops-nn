    if (!feasible) {
        r.ok = false; // resource infeasible -> GRAPH_FAILED (no tilingKey, no kernel)
        return r;
    }

    // (S7) workspace 规划: igates / cgates / fb 槽 / whid 镜像.
    //      fb = 段 2 A 操作数 GM 中继 (每核 [B, AlignUp(H,8)] fp32 单槽;
