// Holds the built context alive so the output shapes stay readable.
struct InferShapeResult {
    uint32_t status = 0xFFFFFFFFU; // ge::GRAPH_FAILED until proven otherwise
    gert::KernelRunContextHolder holder;
};

InferShapeResult RunInferShape(const InferShapeCaseIn& c)
{
    InferShapeResult res;
    auto opImpl = gert::OpImplRegistry::GetInstance().GetOpImpl(kOpType);
    if (opImpl == nullptr || opImpl->infer_shape == nullptr) {
        return res;
    }

    gert::StorageShape xShape = MakeStorageShape(c.x);
    gert::StorageShape wShape = MakeStorageShape(c.w);
    gert::StorageShape bShape = MakeStorageShape(c.b);
    gert::StorageShape cwShape = MakeStorageShape(c.cw);
    gert::StorageShape cbShape = MakeStorageShape(c.cb);
    gert::StorageShape seqShape = MakeStorageShape(c.seq);
    gert::StorageShape initHShape = MakeStorageShape(c.initH);

    // OPTIONAL inputs via IR instance counts (packed present-only shapes).
    std::vector<gert::StorageShape*> inShapes = {&xShape, &wShape, &bShape, &cwShape, &cbShape};
    std::vector<uint32_t> inputInst = {1, 1, 1, 1, 1, 0, 0};
    if (c.hasSeqLength) {
        inShapes.push_back(&seqShape);
        inputInst[5] = 1;
    }
    if (c.hasInitH) {
        inShapes.push_back(&initHShape);
        inputInst[6] = 1;
    }

    // Output shapes are out-params of the InferShape function.
    gert::Shape outShape[NUM_OUTPUTS];
    std::vector<gert::Shape*> outShapes = {&outShape[0], &outShape[1], &outShape[2], &outShape[3], &outShape[4]};

    res.holder = gert::InferShapeContextFaker()
                     .SetOpType(kOpType)
                     .NodeIoNum(7, NUM_OUTPUTS)
                     .IrInstanceNum(inputInst, {1, 1, 1, 1, 1})
                     .InputShapes(inShapes)
                     .OutputShapes(outShapes)
                     .Build();

    auto context = res.holder.GetContext<gert::InferShapeContext>();
    if (context == nullptr) {
        return res;
    }
    res.status = opImpl->infer_shape(context);
    // status stays raw UINT32; compared against ge::GRAPH_SUCCESS/GRAPH_FAILED below
    return res;
}

// All NUM_OUTPUTS outputs must equal the expected dims.
void ExpectAllOutputs(InferShapeResult& res, const std::vector<int64_t>& expected)
{
    auto context = res.holder.GetContext<gert::InferShapeContext>();
    ASSERT_NE(context, nullptr);
    for (size_t k = 0; k < NUM_OUTPUTS; k++) {
        const gert::Shape* output = context->GetOutputShape(k);
        ASSERT_NE(output, nullptr) << "output " << k << " shape is null";
        ASSERT_EQ(output->GetDimNum(), expected.size()) << "output " << k << " rank mismatch";
        for (size_t d = 0; d < expected.size(); ++d) {
            EXPECT_EQ(output->GetDim(d), expected[d]) << "output " << k << " dim " << d << " mismatch";
        }
    }
}

