int32_t CreateOppInGraph(vector<Tensor>& input, vector<std::unique_ptr<uint8_t[]>>& inputHolder,
                         vector<Operator>& inputs, vector<Operator>& outputs, Graph& graph)
{
    auto gru = op::DynamicGRU("dynamic_gru_1");
    const vector<int64_t> xShape = {L, N, I};      // time_major：(L, N, I)
    const vector<int64_t> wShape = {I + H, 2 * H}; // (I+H, 2H)，列序 [r, i]
    const vector<int64_t> bShape = {2 * H};        // B2 = 2H，16 对齐
    const vector<int64_t> cwShape = {I + H, H};    // (I+H, H)
    const vector<int64_t> cbShape = {H};           // B1 = H，16 对齐
    const vector<int64_t> seqShape = {N};          // (N,) int32
    const vector<int64_t> initHShape = {H, N};     // (H, N)

    const HostFeeds feeds = MakeFeeds();

    auto addFp16Input = [&](const string& name, uint32_t index, const vector<int64_t>& shape,
                            const vector<uint16_t>& data) -> int32_t {
        const size_t dataSize = data.size() * sizeof(uint16_t);
        std::unique_ptr<uint8_t[]> buffer(new (std::nothrow) uint8_t[dataSize]);
        if (buffer == nullptr) {
            return RET_FAILED;
        }
        std::memcpy(buffer.get(), data.data(), dataSize);
        const ge::TensorDesc desc = MakeTensorDesc(shape, ge::DT_FLOAT16);
        Tensor tensor(desc, buffer.get(), dataSize);
        inputHolder.emplace_back(std::move(buffer));
        input.push_back(tensor);
        auto dataOp = op::Data(name.c_str()).set_attr_index(index);
        dataOp.update_input_desc_x(desc);
        dataOp.update_output_desc_y(desc);
        graph.AddOp(dataOp);
        inputs.push_back(dataOp);
        return RET_SUCCESS;
    };
    auto addFp32Input = [&](const string& name, uint32_t index, const vector<int64_t>& shape,
                            const vector<float>& data) -> int32_t {
        const size_t dataSize = data.size() * sizeof(float);
        std::unique_ptr<uint8_t[]> buffer(new (std::nothrow) uint8_t[dataSize]);
        if (buffer == nullptr) {
            return RET_FAILED;
        }
        std::memcpy(buffer.get(), data.data(), dataSize);
        const ge::TensorDesc desc = MakeTensorDesc(shape, ge::DT_FLOAT);
        Tensor tensor(desc, buffer.get(), dataSize);
        inputHolder.emplace_back(std::move(buffer));
        input.push_back(tensor);
        auto dataOp = op::Data(name.c_str()).set_attr_index(index);
        dataOp.update_input_desc_x(desc);
        dataOp.update_output_desc_y(desc);
        graph.AddOp(dataOp);
        inputs.push_back(dataOp);
        return RET_SUCCESS;
    };

    if (addFp16Input("data_x", 0U, xShape, feeds.x) != RET_SUCCESS ||
        addFp16Input("data_w", 1U, wShape, feeds.w) != RET_SUCCESS ||
        addFp32Input("data_b", 2U, bShape, feeds.b) != RET_SUCCESS ||
        addFp16Input("data_cw", 3U, cwShape, feeds.cw) != RET_SUCCESS ||
        addFp32Input("data_cb", 4U, cbShape, feeds.cb) != RET_SUCCESS) {
        return RET_FAILED;
    }
    {
        // seq_length：int32，(N,)
        const size_t dataSize = feeds.seqLength.size() * sizeof(int32_t);
        std::unique_ptr<uint8_t[]> buffer(new (std::nothrow) uint8_t[dataSize]);
        if (buffer == nullptr) {
            return RET_FAILED;
        }
        std::memcpy(buffer.get(), feeds.seqLength.data(), dataSize);
        const ge::TensorDesc desc = MakeTensorDesc(seqShape, ge::DT_INT32);
        Tensor tensor(desc, buffer.get(), dataSize);
        inputHolder.emplace_back(std::move(buffer));
        input.push_back(tensor);
        auto dataOp = op::Data("data_seq_length").set_attr_index(5U);
        dataOp.update_input_desc_x(desc);
        dataOp.update_output_desc_y(desc);
        graph.AddOp(dataOp);
        inputs.push_back(dataOp);
    }
    if (addFp32Input("data_init_h", 6U, initHShape, feeds.initH) != RET_SUCCESS) {
        return RET_FAILED;
    }

    gru.set_input_x(inputs[0]);
    gru.set_input_w(inputs[1]);
    gru.set_input_b(inputs[2]);
    gru.set_input_cw(inputs[3]);
    gru.set_input_cb(inputs[4]);
    gru.set_input_seq_length(inputs[5]);
    gru.set_input_init_h(inputs[6]);
    // 属性保持 proto 默认值（唯一支持取值）：direction=UNIDIRECTIONAL、
    // cell_depth=1、keep_prob=1.0、cell_clip=-1.0、num_proj=0、
    // time_major=true、activation=tanh、is_training=true。

    const vector<int64_t> outShape = {L, H, N};
    const TensorDesc yDesc = MakeTensorDesc(outShape, ge::DT_FLOAT);
    gru.update_output_desc_y(yDesc);
    gru.update_output_desc_output_h(yDesc);
    gru.update_output_desc_r(yDesc);
    gru.update_output_desc_i(yDesc);
    gru.update_output_desc_n(yDesc);
    outputs.push_back(gru);
    return RET_SUCCESS;
}

