GoldenOutputs ComputeGolden(const HostFeeds& feeds)
{
    const int64_t plane = H * N; // h 布局 (H, N)
    vector<float> x(feeds.x.size());
    vector<float> w(feeds.w.size());
    vector<float> cw(feeds.cw.size());
    vector<float> h(plane);
    for (size_t index = 0; index < x.size(); ++index) {
        x[index] = Fp16ToFloat(feeds.x[index]);
    }
    for (size_t index = 0; index < w.size(); ++index) {
        w[index] = Fp16ToFloat(feeds.w[index]);
    }
    for (size_t index = 0; index < cw.size(); ++index) {
        cw[index] = Fp16ToFloat(feeds.cw[index]);
    }
    for (size_t index = 0; index < h.size(); ++index) {
        h[index] = feeds.initH[index];
    }

    GoldenOutputs out;
    out.y.resize(static_cast<size_t>(plane * L));
    out.outputH.resize(static_cast<size_t>(plane * L));
    out.r.resize(static_cast<size_t>(plane * L));
    out.i.resize(static_cast<size_t>(plane * L));
    out.n.resize(static_cast<size_t>(plane * L));

    vector<float> reset(H);
    vector<float> update(H);
    vector<float> cand(H);
    const int32_t* seq = feeds.seqLength.data();
    const float* wBase = w.data();
    const float* cwBase = cw.data();
    for (int64_t t = 0; t < L; ++t) {
        float* yPlane = out.y.data() + t * plane; // (H, N) 时间片
        float* rPlane = out.r.data() + t * plane;
        float* iPlane = out.i.data() + t * plane;
        float* nPlane = out.n.data() + t * plane;
        for (int64_t bIdx = 0; bIdx < N; ++bIdx) {
            const float* xBatch = x.data() + (t * N + bIdx) * I;
            const float* hCol = h.data() + bIdx;
            // 双门 GEMM：gates = [x_t, h] @ w + b，列序 [r, i]
            for (int64_t hidden = 0; hidden < H; ++hidden) {
                float resetAcc = 0.0F;
                float updateAcc = 0.0F;
                for (int64_t j = 0; j < K; ++j) {
                    const float a = (j < I) ? xBatch[j] : hCol[(j - I) * N];
                    resetAcc += a * wBase[j * 2 * H + hidden];
                    updateAcc += a * wBase[j * 2 * H + H + hidden];
                }
                reset[static_cast<size_t>(hidden)] = Sigmoid(resetAcc + feeds.b[static_cast<size_t>(hidden)]);
                update[static_cast<size_t>(hidden)] = Sigmoid(updateAcc + feeds.b[static_cast<size_t>(H + hidden)]);
            }
            // 候选门 GEMM（reset 前置）：n = tanh([x_t, r*h] @ cw + cb)
            for (int64_t hidden = 0; hidden < H; ++hidden) {
                float candAcc = 0.0F;
                for (int64_t j = 0; j < K; ++j) {
                    const float a = (j < I) ? xBatch[j] : reset[static_cast<size_t>(j - I)] * hCol[(j - I) * N];
                    candAcc += a * cwBase[j * H + hidden];
                }
                cand[static_cast<size_t>(hidden)] = std::tanh(candAcc + feeds.cb[static_cast<size_t>(hidden)]);
            }
            // 源码口径更新 + 冻结式掩码：h_t = h_prev + (h~ - h_prev) * 1[t < s[b]]
            const float mask = (t < static_cast<int64_t>(seq[bIdx])) ? 1.0F : 0.0F;
            for (int64_t hidden = 0; hidden < H; ++hidden) {
                const int64_t hIdx = hidden * N + bIdx;
                const float hPrev = h[static_cast<size_t>(hIdx)];
                const float hRaw = (hPrev - cand[static_cast<size_t>(hidden)]) * update[static_cast<size_t>(hidden)] +
                                   cand[static_cast<size_t>(hidden)];
                h[static_cast<size_t>(hIdx)] = hPrev + (hRaw - hPrev) * mask;
                yPlane[hIdx] = h[static_cast<size_t>(hIdx)]; // r/i/n 不受掩码影响
                rPlane[hIdx] = reset[static_cast<size_t>(hidden)];
                iPlane[hIdx] = update[static_cast<size_t>(hidden)];
                nPlane[hIdx] = cand[static_cast<size_t>(hidden)];
            }
        }
    }
    out.outputH = out.y;
    return out;
}

