// IEEE 754 binary16 conversion with round-to-nearest-even. All pattern values
// below are small dyadic rationals (exactly representable in fp16), so the
// golden and the device kernel observe identical input bits.
uint16_t FloatToFp16(float value)
{
    uint32_t bits = 0;
    std::memcpy(&bits, &value, sizeof(bits));
    const uint16_t sign = static_cast<uint16_t>((bits >> 16U) & 0x8000U);
    const int32_t exponent = static_cast<int32_t>((bits >> 23U) & 0xFFU) - 127;
    const uint32_t mantissa = bits & 0x7FFFFFU;
    if (exponent > 15) {
        return static_cast<uint16_t>(sign | 0x7C00U); // overflow -> +/-Inf
    }
    if (exponent >= -14) { // fp16 normal range
        uint16_t half = static_cast<uint16_t>((static_cast<uint32_t>(exponent + 15) << 10U) | (mantissa >> 13U));
        const uint32_t remainder = mantissa & 0x1FFFU;
        if ((remainder > 0x1000U) || ((remainder == 0x1000U) && ((half & 1U) != 0U))) {
            half = static_cast<uint16_t>(half + 1U);
        }
        return static_cast<uint16_t>(sign | half);
    }
    if (exponent < -25) {
        return sign; // rounds to signed zero
    }
    const uint32_t fraction = mantissa | 0x800000U;
    const int32_t shift = -(exponent + 1);
    const uint32_t remainderMask = (1ULL << static_cast<uint32_t>(shift)) - 1U;
    const uint32_t halfway = (remainderMask + 1U) >> 1U;
    uint16_t half = static_cast<uint16_t>(fraction >> static_cast<uint32_t>(shift));
    const uint32_t remainder = fraction & remainderMask;
    if ((remainder > halfway) || ((remainder == halfway) && ((half & 1U) != 0U))) {
        half = static_cast<uint16_t>(half + 1U);
    }
    return static_cast<uint16_t>(sign | half);
}

float Fp16ToFloat(uint16_t value)
{
    const float sign = ((value & 0x8000U) != 0U) ? -1.0F : 1.0F;
    const uint32_t exponent = (static_cast<uint32_t>(value) >> 10U) & 0x1FU;
    const uint32_t mantissa = static_cast<uint32_t>(value) & 0x3FFU;
    if (exponent == 0x1FU) {
        return sign * std::numeric_limits<float>::infinity();
    }
    if (exponent == 0U) {
        return sign * std::ldexp(static_cast<float>(mantissa), -24);
    }
    return sign * std::ldexp(static_cast<float>(mantissa | 0x400U), static_cast<int>(exponent) - 25);
}

