                        ShapeToString(initHShape) + "]";
    printf("Shape, dtype and values PASSED for %s\n", shapeGroup.c_str());
    printf("%s - INFO - [XIR]: DynamicGRU static GEIR verification PASSED\n", GetTime().c_str());

    delete session;
    GEFinalize();
    return RET_SUCCESS;
