InputFeeds MakeFeeds(const GruDims& dims)
{
    // Small dyadic-rational patterns: exactly representable in fp16, bounded
    // pre-activations (|z| ~<= 2 keeps sigmoid/tanh unsaturated) and a hidden
    // state that stays a convex combination of h_prev and n (|h| <= 1).
    const std::vector<float> xPattern = {0.375F, -0.25F, 0.125F, -0.375F, 0.25F, -0.125F, 0.0625F, -0.0625F};
    const std::vector<float> wPattern = {0.25F, -0.1875F, 0.125F, -0.0625F, 0.3125F, -0.25F, 0.0625F, -0.125F};
    const std::vector<float> bPattern = {0.125F, -0.0625F, 0.1875F, -0.125F, 0.0625F, -0.1875F, 0.25F, -0.25F};
    const std::vector<float> cwPattern = {0.1875F, -0.3125F, 0.25F, -0.125F, 0.0625F, -0.25F, 0.3125F, -0.1875F};
    const std::vector<float> cbPattern = {0.0625F, -0.1875F, 0.125F, -0.0625F, 0.1875F, -0.125F, 0.25F, -0.25F};
    const std::vector<float> initHPattern = {0.125F, -0.0625F, 0.0625F, -0.125F, 0.1875F, -0.1875F};
    constexpr float kPadValue = -0.5F; // 16-align tail of b/cb, truncated by the contract

    const int64_t biasLen = AlignUp(2 * dims.h, 16);
    const int64_t candBiasLen = AlignUp(dims.h, 16);
    const int64_t kLen = dims.i + dims.h;

    InputFeeds feeds;
    FillFp16Pattern(feeds.x, dims.l * dims.n * dims.i, xPattern);
    FillFp16Pattern(feeds.w, kLen * 2 * dims.h, wPattern);
    FillFp16Pattern(feeds.b, biasLen, bPattern);
    FillFp16Pattern(feeds.cw, kLen * dims.h, cwPattern);
    FillFp16Pattern(feeds.cb, candBiasLen, cbPattern);
    FillFp16Pattern(feeds.initH, dims.h * dims.n, initHPattern);
    for (int64_t index = 2 * dims.h; index < biasLen; ++index) {
        feeds.b[static_cast<size_t>(index)] = FloatToFp16(kPadValue);
    }
    for (int64_t index = dims.h; index < candBiasLen; ++index) {
        feeds.cb[static_cast<size_t>(index)] = FloatToFp16(kPadValue);
    }
    // Real sequence length per batch spanning the full 0..L domain: s[b] = 0
    // keeps h frozen at init_h, s[b] = L is the full-length case.
    feeds.seqLength.resize(static_cast<size_t>(dims.n));
    const int64_t denom = std::max<int64_t>(dims.n - 1, 1);
    for (int64_t batch = 0; batch < dims.n; ++batch) {
        feeds.seqLength[static_cast<size_t>(batch)] = static_cast<int32_t>(batch * dims.l / denom);
    }

    const ge::TensorDesc xDesc = MakeTensorDesc({dims.l, dims.n, dims.i}, ge::DT_FLOAT16, true);
    const ge::TensorDesc wDesc = MakeTensorDesc({kLen, 2 * dims.h}, ge::DT_FLOAT16, true);
    const ge::TensorDesc bDesc = MakeTensorDesc({biasLen}, ge::DT_FLOAT16, true);
    const ge::TensorDesc cwDesc = MakeTensorDesc({kLen, dims.h}, ge::DT_FLOAT16, true);
    const ge::TensorDesc cbDesc = MakeTensorDesc({candBiasLen}, ge::DT_FLOAT16, true);
    const ge::TensorDesc seqDesc = MakeTensorDesc({dims.n}, ge::DT_INT32, true);
    const ge::TensorDesc initHDesc = MakeTensorDesc({dims.h, dims.n}, ge::DT_FLOAT16, true);

    feeds.tensors.reserve(7U);
    feeds.tensors.emplace_back(xDesc, reinterpret_cast<uint8_t*>(feeds.x.data()),
                               static_cast<uint32_t>(feeds.x.size() * sizeof(uint16_t)));
    feeds.tensors.emplace_back(wDesc, reinterpret_cast<uint8_t*>(feeds.w.data()),
                               static_cast<uint32_t>(feeds.w.size() * sizeof(uint16_t)));
    feeds.tensors.emplace_back(bDesc, reinterpret_cast<uint8_t*>(feeds.b.data()),
                               static_cast<uint32_t>(feeds.b.size() * sizeof(uint16_t)));
    feeds.tensors.emplace_back(cwDesc, reinterpret_cast<uint8_t*>(feeds.cw.data()),
                               static_cast<uint32_t>(feeds.cw.size() * sizeof(uint16_t)));
    feeds.tensors.emplace_back(cbDesc, reinterpret_cast<uint8_t*>(feeds.cb.data()),
                               static_cast<uint32_t>(feeds.cb.size() * sizeof(uint16_t)));
    feeds.tensors.emplace_back(seqDesc, reinterpret_cast<uint8_t*>(feeds.seqLength.data()),
                               static_cast<uint32_t>(feeds.seqLength.size() * sizeof(int32_t)));
    feeds.tensors.emplace_back(initHDesc, reinterpret_cast<uint8_t*>(feeds.initH.data()),
                               static_cast<uint32_t>(feeds.initH.size() * sizeof(uint16_t)));
    return feeds;
}

struct GoldenOutputs {
    std::vector<float> y;       // (L, H, N)
    std::vector<float> outputH; // (L, H, N), element-wise equal to y
    std::vector<float> r;       // (L, H, N), sigmoid, unmasked
    std::vector<float> i;       // (L, H, N), sigmoid, unmasked
    std::vector<float> n;       // (L, H, N), tanh, unmasked
};

GoldenOutputs ComputeGolden(const InputFeeds& feeds, const GruDims& dims)
{
    const int64_t steps = dims.l;
    const int64_t batch = dims.n;
    const int64_t inputSize = dims.i;
    const int64_t hiddenSize = dims.h;
    const int64_t kLen = inputSize + hiddenSize;
    const int64_t plane = hiddenSize * batch;

    // Widen the fp16 inputs to fp32 once (lossless); both GEMMs accumulate in
    // fp32 and sigmoid/tanh are evaluated in fp32, mirroring the kernel's
    // numeric contract. Only the valid 2H/H prefix of b/cb participates.
    std::vector<float> x(feeds.x.size());
    std::vector<float> w(feeds.w.size());
    std::vector<float> b(static_cast<size_t>(2 * hiddenSize));
    std::vector<float> cw(feeds.cw.size());
    std::vector<float> cb(static_cast<size_t>(hiddenSize));
    std::vector<float> h(plane); // h layout (H, N), seeded with init_h
    for (size_t index = 0; index < x.size(); ++index) {
        x[index] = Fp16ToFloat(feeds.x[index]);
    }
    for (size_t index = 0; index < w.size(); ++index) {
        w[index] = Fp16ToFloat(feeds.w[index]);
    }
    for (size_t index = 0; index < b.size(); ++index) {
        b[index] = Fp16ToFloat(feeds.b[index]);
    }
    for (size_t index = 0; index < cw.size(); ++index) {
        cw[index] = Fp16ToFloat(feeds.cw[index]);
    }
    for (size_t index = 0; index < cb.size(); ++index) {
        cb[index] = Fp16ToFloat(feeds.cb[index]);
    }
    for (size_t index = 0; index < h.size(); ++index) {
        h[index] = Fp16ToFloat(feeds.initH[index]);
    }

    GoldenOutputs out;
    out.y.resize(static_cast<size_t>(plane * steps));
    out.outputH.resize(static_cast<size_t>(plane * steps));
    out.r.resize(static_cast<size_t>(plane * steps));
    out.i.resize(static_cast<size_t>(plane * steps));
    out.n.resize(static_cast<size_t>(plane * steps));

    std::vector<float> reset(hiddenSize);  // r gate activations of one batch row
    std::vector<float> update(hiddenSize); // i gate activations of one batch row
    std::vector<float> cand(hiddenSize);   // n candidate activations of one batch row
    const int32_t* seq = feeds.seqLength.data();
    const float* wBase = w.data();
    const float* cwBase = cw.data();
    for (int64_t t = 0; t < steps; ++t) {
        float* yPlane = out.y.data() + t * plane; // (H, N) slice of step t
        float* rPlane = out.r.data() + t * plane;
        float* iPlane = out.i.data() + t * plane;
        float* nPlane = out.n.data() + t * plane;
        for (int64_t bIdx = 0; bIdx < batch; ++bIdx) {
            const float* xBatch = x.data() + (t * batch + bIdx) * inputSize;
            const float* hCol = h.data() + bIdx; // column bIdx, row stride batch
            // Joint gate GEMM: gates = [x_t, h] @ w + b, column order [r, i].
            for (int64_t hidden = 0; hidden < hiddenSize; ++hidden) {
                float resetAcc = 0.0F;
                float updateAcc = 0.0F;
                for (int64_t j = 0; j < kLen; ++j) {
                    const float a = (j < inputSize) ? xBatch[j] : hCol[(j - inputSize) * batch];
                    resetAcc += a * wBase[j * 2 * hiddenSize + hidden];
                    updateAcc += a * wBase[j * 2 * hiddenSize + hiddenSize + hidden];
                }
                reset[static_cast<size_t>(hidden)] = Sigmoid(resetAcc + b[static_cast<size_t>(hidden)]);
                update[static_cast<size_t>(hidden)] = Sigmoid(updateAcc + b[static_cast<size_t>(hiddenSize + hidden)]);
            }
            // Candidate GEMM with the reset applied to h before the matmul:
            // n = tanh([x_t, r * h] @ cw + cb).
            for (int64_t hidden = 0; hidden < hiddenSize; ++hidden) {
                float candAcc = 0.0F;
                for (int64_t j = 0; j < kLen; ++j) {
                    const float a = (j < inputSize) ?
                                        xBatch[j] :
                                        reset[static_cast<size_t>(j - inputSize)] * hCol[(j - inputSize) * batch];
                    candAcc += a * cwBase[j * hiddenSize + hidden];
                }
                cand[static_cast<size_t>(hidden)] = std::tanh(candAcc + cb[static_cast<size_t>(hidden)]);
            }
            // Source-form update h~ = (h - n) * i + n with the freeze-style
            // seq_length mask h_t = h_prev + (h~ - h_prev) * 1[t < s[bIdx]].
            const float mask = (t < static_cast<int64_t>(seq[bIdx])) ? 1.0F : 0.0F;
            for (int64_t hidden = 0; hidden < hiddenSize; ++hidden) {
                const int64_t hIdx = hidden * batch + bIdx;
                const float hPrev = h[static_cast<size_t>(hIdx)];
                const float hRaw = (hPrev - cand[static_cast<size_t>(hidden)]) * update[static_cast<size_t>(hidden)] +
                                   cand[static_cast<size_t>(hidden)];
                h[static_cast<size_t>(hIdx)] = hPrev + (hRaw - hPrev) * mask;
                yPlane[hIdx] = h[static_cast<size_t>(hIdx)]; // r/i/n outputs are unmasked
                rPlane[hIdx] = reset[static_cast<size_t>(hidden)];
                iPlane[hIdx] = update[static_cast<size_t>(hidden)];
                nPlane[hIdx] = cand[static_cast<size_t>(hidden)];
            }
        }
    }
    // output_h mirrors y element-wise (the last step carries the frozen state).
    out.outputH = out.y;
    return out;
}

bool HasExpectedShape(const ge::Shape& actual, const ShapeVector& expected)
{
    if (actual.GetDimNum() != expected.size()) {
        return false;
    }
    for (size_t index = 0; index < expected.size(); ++index) {
        if (actual.GetDim(index) != expected[index]) {
            return false;
        }
    }
    return true;
}

bool CompareFp16Output(const ge::Tensor& output, const std::vector<float>& golden, const ShapeVector& expectedShape,
                       const std::string& name)
{
    const ge::TensorDesc desc = output.GetTensorDesc();
    if (!HasExpectedShape(desc.GetShape(), expectedShape)) {
        std::cerr << name << " shape mismatch: expected " << ShapeToString(expectedShape) << std::endl;
        return false;
    }
    if (desc.GetDataType() != ge::DT_FLOAT16) {
        std::cerr << name << " dtype mismatch: expected DT_FLOAT16, got " << desc.GetDataType() << std::endl;
        return false;
    }
    const uint16_t* actual = reinterpret_cast<const uint16_t*>(output.GetData());
    const size_t expectedBytes = golden.size() * sizeof(uint16_t);
    if (actual == nullptr || output.GetSize() != expectedBytes) {
        std::cerr << name << " buffer mismatch: actual bytes=" << output.GetSize()
                  << ", expected bytes=" << expectedBytes << std::endl;
        return false;
    }
    for (size_t index = 0; index < golden.size(); ++index) {
        const float actualValue = Fp16ToFloat(actual[index]);
        const float error = std::fabs(actualValue - golden[index]);
        const float tolerance = kAtol + kRtol * std::fabs(golden[index]);
        if (!std::isfinite(actualValue) || error > tolerance) {
            std::cerr << name << " value mismatch at index " << index << ": actual=" << actualValue
                      << ", expected=" << golden[index] << ", tolerance=" << tolerance << std::endl;
            return false;
        }
    }
    return true;
}

bool VerifyOutput(const std::vector<ge::Tensor>& outputs, const GruDims& dims, const InputFeeds& feeds)
{
    if (outputs.size() != 5U) {
        std::cerr << "Expected exactly 5 outputs, got " << outputs.size() << std::endl;
        return false;
    }
    const GoldenOutputs golden = ComputeGolden(feeds, dims);
    const ShapeVector outShape = {dims.l, dims.h, dims.n};
    if (!CompareFp16Output(outputs[0], golden.y, outShape, "y")) {
        return false;
    }
    if (!CompareFp16Output(outputs[1], golden.outputH, outShape, "output_h")) {
        return false;
    }
    if (!CompareFp16Output(outputs[2], golden.r, outShape, "r")) {
        return false;
    }
    if (!CompareFp16Output(outputs[3], golden.i, outShape, "i")) {
        return false;
    }
    if (!CompareFp16Output(outputs[4], golden.n, outShape, "n")) {
        return false;
    }
    return true;
}

