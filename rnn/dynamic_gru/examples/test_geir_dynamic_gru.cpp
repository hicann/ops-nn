// IEEE 754 binary16 conversion with round-to-nearest-even; only used to fill
// host-side input buffers with small deterministic values (|v| < 8).
uint16_t FloatToFp16(float v)
{
    uint32_t bits = 0;
    std::memcpy(&bits, &v, sizeof(bits));
    const uint32_t sign = (bits >> 16U) & 0x8000U;
    const int32_t exp = static_cast<int32_t>((bits >> 23U) & 0xFFU) - 127 + 15;
    uint32_t mant = bits & 0x7FFFFFU;
    if (exp <= 0) {
        return static_cast<uint16_t>(sign);
    }
    if (exp >= 31) {
        return static_cast<uint16_t>(sign | 0x7C00U);
    }
    uint16_t half = static_cast<uint16_t>((static_cast<uint32_t>(exp) << 10U) | (mant >> 13U));
    const uint32_t rem = mant & 0x1FFFU;
    if ((rem > 0x1000U) || ((rem == 0x1000U) && ((half & 1U) != 0U))) {
        half = static_cast<uint16_t>(half + 1U);
    }
    return static_cast<uint16_t>(sign | half);
}

