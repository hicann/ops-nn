// InferDataTypeForDynamicGRU(context) — data type inference callback
//
// Parameters:
//   context — InferDataTypeContext that provides access to input dtypes
//             and allows setting output dtypes
//
// Returns:
//   ge::graphStatus — ge::GRAPH_SUCCESS on success; GRAPH_FAILED with an
//   OP_LOGE diagnostic (dtype_mismatch) on any dtype gate violation.
// ---------------------------------------------------------------------------
static ge::graphStatus InferDataTypeForDynamicGRU(gert::InferDataTypeContext* context)
{
    // ===== 输入 dtype 门槛（必选 5 输入，dtype 为编译期信息，静态/动态通路一致）=====
    const ge::DataType dtX = context->GetInputDataType(IDX_X);
    const ge::DataType dtW = context->GetInputDataType(IDX_W);
    const ge::DataType dtB = context->GetInputDataType(IDX_B);
    const ge::DataType dtCw = context->GetInputDataType(IDX_CW);
    const ge::DataType dtCb = context->GetInputDataType(IDX_CB);
    if (!IsFp16(dtX) || !IsFp16(dtW) || !IsFp16(dtCw)) {
        OP_LOGE(context, "dtype_mismatch: x/w/cw must be float16 (got x=%d w=%d cw=%d)", static_cast<int>(dtX),
                static_cast<int>(dtW), static_cast<int>(dtCw));
        return ge::GRAPH_FAILED;
    }
    if (!IsFp16OrFp32(dtB) || !IsFp16OrFp32(dtCb) || (dtB != dtCb)) {
        OP_LOGE(context, "dtype_mismatch: b/cb must share one dtype in {float16, float32} (got b=%d cb=%d)",
                static_cast<int>(dtB), static_cast<int>(dtCb));
        return ge::GRAPH_FAILED;
    }
    // ===== 可选输入 dtype 门槛（DT_UNDEFINED = 未传入，跳过）=====
    const ge::DataType dtSeq = context->GetOptionalInputDataType(IDX_SEQ_LENGTH);
    if ((dtSeq != ge::DT_UNDEFINED) && (dtSeq != ge::DT_INT32)) {
        OP_LOGE(context, "dtype_mismatch: seq_length must be int32 (got %d)", static_cast<int>(dtSeq));
        return ge::GRAPH_FAILED;
    }
    const ge::DataType dtInitH = context->GetOptionalInputDataType(IDX_INIT_H);
    if ((dtInitH != ge::DT_UNDEFINED) && (dtInitH != dtB)) {
        OP_LOGE(context, "dtype_mismatch: init_h dtype must follow b/cb (got init_h=%d b=%d)",
                static_cast<int>(dtInitH), static_cast<int>(dtB));
        return ge::GRAPH_FAILED;
    }

    // ===== 调用方声明输出 dtype 一致性（未声明 DT_UNDEFINED 跳过）=====
    for (size_t k = 0; k < NUM_OUTPUTS; k++) {
        const ge::DataType declared = context->GetOutputDataType(k);
        if ((declared != ge::DT_UNDEFINED) && (declared != dtB)) {
            OP_LOGE(context, "dtype_mismatch: declared output[%zu] dtype(%d) must follow b(%d)", k,
                    static_cast<int>(declared), static_cast<int>(dtB));
            return ge::GRAPH_FAILED;
        }
    }

    // ===== 推导：5 输出 dtype 全部 = b.dtype（≡ cb.dtype，无 promotion）=====
    for (size_t k = 0; k < NUM_OUTPUTS; k++) {
        if (context->SetOutputDataType(k, dtB) != ge::GRAPH_SUCCESS) {
            OP_LOGE(context, "dtype_mismatch: SetOutputDataType(%zu) failed", k);
            return ge::GRAPH_FAILED;
        }
    }
    return ge::GRAPH_SUCCESS;
}

