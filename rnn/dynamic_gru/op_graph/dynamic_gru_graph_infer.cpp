// ---------------------------------------------------------------------------
// ForceNd — ND-only format gate for one IO slot.
//   本算子全部输入/输出恒 ND：声明非 ND 的通路直接拒绝（format 不支持），
//   合法通路将 origin/storage format 统一固定为 ND。注册本回调后 GE 不再
//   对该节点执行 DefaultInferFormat（其按维数推导的默认格式会把 2D 权重
//   w/cw 改写成 HWCN，导致合法 ND 输入被拒）。
// ---------------------------------------------------------------------------
inline ge::graphStatus ForceNd(gert::StorageFormat* format, gert::InferFormatContext* context, const char* slotName)
{
    if (format == nullptr) {
        OP_LOGE(context, "format_mismatch: format holder of %s is null", slotName);
        return ge::GRAPH_FAILED;
    }
    if (format->GetOriginFormat() != ge::FORMAT_ND) {
        OP_LOGE(context, "format_mismatch: %s must be ND (got %d)", slotName,
                static_cast<int>(format->GetOriginFormat()));
        return ge::GRAPH_FAILED;
    }
    format->SetOriginFormat(ge::FORMAT_ND);
    format->SetStorageFormat(ge::FORMAT_ND);
    return ge::GRAPH_SUCCESS;
}

