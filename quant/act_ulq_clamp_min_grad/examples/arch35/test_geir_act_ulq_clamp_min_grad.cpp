uint32_t GetDataTypeSize(DataType dt)
{
    uint32_t dilation = 1;
    uint32_t oneByte = 1;
    uint32_t twoByte = 2;
    uint32_t fourByte = 4;
    uint32_t eightByte = 8;

    if (dt == ge::DT_FLOAT) {
        dilation = fourByte;
    } else if (dt == ge::DT_FLOAT16) {
        dilation = twoByte;
    } else if (dt == ge::DT_BF16) {
        dilation = twoByte;
    } else if (dt == ge::DT_INT16) {
        dilation = twoByte;
    } else if (dt == ge::DT_UINT16) {
        dilation = twoByte;
    } else if (dt == ge::DT_INT32) {
        dilation = fourByte;
    } else if (dt == ge::DT_UINT32) {
        dilation = fourByte;
    } else if (dt == ge::DT_INT64) {
        dilation = eightByte;
    } else if (dt == ge::DT_UINT64) {
        dilation = eightByte;
    } else if (dt == ge::DT_INT8) {
        dilation = oneByte;
    }
    return dilation;
}

int32_t GenOnesData(vector<int64_t> shapes, Tensor& input_tensor, TensorDesc& input_tensor_desc, DataType data_type,
                    int value)
{
    input_tensor_desc.SetRealDimCnt(shapes.size());
    size_t size = 1;
    for (uint32_t i = 0; i < shapes.size(); i++) {
        size *= shapes[i];
    }
    uint32_t data_len = size * GetDataTypeSize(data_type);
    uint8_t* pData = new (std::nothrow) uint8_t[data_len];
    if (pData == nullptr) {
        printf("ERROR: failed to allocate memory for input data\n");
        return FAILED;
    }
    if (data_type == ge::DT_FLOAT) {
        float* pFloat = reinterpret_cast<float*>(pData);
        for (uint32_t i = 0; i < size; ++i) {
            pFloat[i] = static_cast<float>(value);
        }
    } else if (data_type == ge::DT_FLOAT16) {
        float fval = static_cast<float>(value);
        uint32_t bits;
        memcpy(&bits, &fval, sizeof(float));
        uint16_t sign = static_cast<uint16_t>((bits >> 31) & 0x1);
        int32_t exp = static_cast<int32_t>((bits >> 23) & 0xFF) - 127 + 15;
        uint16_t mantissa = static_cast<uint16_t>((bits >> 13) & 0x3FF);
        uint16_t halfBits;
        if (exp <= 0) {
            halfBits = sign << 15;
        } else if (exp >= 31) {
            halfBits = static_cast<uint16_t>(sign << 15) | static_cast<uint16_t>(0x1F << 10);
        } else {
            halfBits = static_cast<uint16_t>(sign << 15) | static_cast<uint16_t>(exp << 10) | mantissa;
        }
        uint16_t* pHalf = reinterpret_cast<uint16_t*>(pData);
        for (uint32_t i = 0; i < size; ++i) {
            pHalf[i] = halfBits;
        }
    } else {
        for (uint32_t i = 0; i < data_len; ++i) {
            pData[i] = static_cast<uint8_t>(value);
        }
    }
    input_tensor = Tensor(input_tensor_desc, pData, data_len);
    delete[] pData;
    return SUCCESS;
}

int32_t WriteDataToFile(string bin_file, uint64_t data_size, uint8_t* inputData)
{
    FILE* fp = fopen(bin_file.c_str(), "wb");
    if (fp == nullptr) {
        printf("ERROR: failed to open file %s for writing\n", bin_file.c_str());
        return FAILED;
    }
    fwrite(inputData, sizeof(uint8_t), data_size, fp);
    fclose(fp);
    return SUCCESS;
}

