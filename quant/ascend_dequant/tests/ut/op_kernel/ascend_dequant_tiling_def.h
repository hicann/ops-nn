#ifndef ASCEND_DEQUANT_TILING_DEF_H_
#define ASCEND_DEQUANT_TILING_DEF_H_

#include <cstdint>
#include <cstring>

#include "kernel_tiling/kernel_tiling.h"

#define __CCE_UT_TEST__

#include "../../../op_kernel/arch35/ascend_dequant_tilingdata.h"

// CPU-side (tikicpulib) acquisition of the raw tiling buffer. The kernel entry
// uses GET_TILING_DATA_WITH_STRUCT for each RANK instantiation; on device this
// is generated by the tiling framework, here it is a plain byte copy.
template <typename T>
inline void InitTilingDataMock(uint8_t* tiling, T* dst)
{
    (void)memcpy(dst, tiling, sizeof(T));
}

#define GET_TILING_DATA_WITH_STRUCT(tiling_struct, tiling_data, tiling_arg) \
    tiling_struct tiling_data;                                              \
    InitTilingDataMock<tiling_struct>(tiling_arg, &tiling_data)

#ifndef DTYPE_X
#define DTYPE_X int32_t
#endif

#endif // ASCEND_DEQUANT_TILING_DEF_H_
