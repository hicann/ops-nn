        FillNdDmaLoopInfo<ND>(nddmaX_.loopInfo, td_->maxBroShape, td_->inputStrides[0]);
        FillNdDmaLoopInfo<ND>(nddmaSU64_.loopInfo, td_->maxBroShape, td_->inputStrides[1]);
        nddmaX_.constantValue = static_cast<T>(0);
        nddmaSU64_.constantValue = 0u;
