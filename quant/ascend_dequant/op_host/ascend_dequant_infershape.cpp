// deq_scale 是否可右对齐广播到 x：
//   秩不超过 x；右对齐后每一轴要么等于 x 的对应轴，要么为 1（numpy 广播语义）。
//   未知维（<0）参与比较时跳过，具体长度由 tiling 按实际 shape 校验。
inline bool ScaleBroadcastable(const std::vector<int64_t>& xShape, const std::vector<int64_t>& scaleShape)
{
    const int64_t xRank = static_cast<int64_t>(xShape.size());
    const int64_t scaleRank = static_cast<int64_t>(scaleShape.size());
    if (scaleRank > xRank) {
        return false;
    }
    const int64_t offset = xRank - scaleRank;
    for (int64_t d = 0; d < scaleRank; ++d) {
        const int64_t sLen = scaleShape[static_cast<size_t>(d)];
        const int64_t xLen = xShape[static_cast<size_t>(offset + d)];
        if (sLen < 0 || xLen < 0) {
            continue;
        }
        if (sLen != 1 && sLen != xLen) {
            return false;
        }
    }
    return true;
}

