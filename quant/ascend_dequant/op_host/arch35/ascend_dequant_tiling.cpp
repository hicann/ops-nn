ge::graphStatus TilingPrepareForAscendDequant(gert::TilingParseContext* context)
{
    if (context == nullptr) {
        OP_LOGE("AscendDequant", "null_input: tiling parse context is nullptr");
        return ge::GRAPH_FAILED;
    }
    OP_LOGD(context->GetNodeName(), "TilingPrepareForAscendDequant enter.");
    return ge::GRAPH_SUCCESS;
}

