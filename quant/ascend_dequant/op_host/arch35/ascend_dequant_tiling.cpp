// ---------------------------------------------------------------------------
// CheckBroadcastShape — 逐维校验：(1) 输入同维非 1 大小必须一致；(2) 输出必须稠密
// ---------------------------------------------------------------------------
static bool CheckGroupDim(const std::vector<std::vector<int64_t>>& group, int64_t d, const char* tag, int64_t& ref)
{
    for (size_t i = 0; i < group.size(); i++) {
        const int64_t v = group[i][static_cast<size_t>(d)];
        if (v == 1) {
            continue; // 广播维
        }
        if (ref == -1) {
            ref = v;
        } else if (v != ref) {
            OP_LOGE("CheckBroadcastShape", "dim %ld broadcast incompatible: %s[%zu] size %ld != %ld",
                    static_cast<long>(d), tag, i, static_cast<long>(v), static_cast<long>(ref));
            return false;
        }
    }
    return true;
}

static bool CheckBroadcastShape(const std::vector<std::vector<int64_t>>& normalIn,
                                const std::vector<std::vector<int64_t>>& normalOut, int64_t rank)
{
    for (int64_t d = 0; d < rank; d++) {
        int64_t ref = -1;
        if (!CheckGroupDim(normalIn, d, "input", ref)) {
            return false;
        }
        if (!CheckGroupDim(normalOut, d, "output", ref)) {
            return false;
        }
        // 输出稠密性：该维存在非 1 维值时，输出不允许为广播维（1）
        if (ref != -1) {
            for (size_t i = 0; i < normalOut.size(); i++) {
                if (normalOut[i][static_cast<size_t>(d)] == 1) {
                    OP_LOGE("CheckBroadcastShape",
                            "dim %ld broadcast output is not supported: output[%zu] size 1 vs max %ld",
                            static_cast<long>(d), i, static_cast<long>(ref));
                    return false;
                }
            }
        }
    }
    return true;
}

// ---------------------------------------------------------------------------
// MergeShapeByGroups — 按分组闭区间列表把 shape 每组收缩为一维（组内乘积）
// ---------------------------------------------------------------------------
static std::vector<int64_t> MergeShapeByGroups(const std::vector<int64_t>& s,
                                               const std::vector<std::vector<int64_t>>& groups)
{
    std::vector<int64_t> merged;
    merged.reserve(groups.size());
    for (const auto& g : groups) {
        int64_t prod = 1;
        for (int64_t k = g[0]; k <= g[1]; k++) {
            prod *= s[static_cast<size_t>(k)];
        }
        merged.push_back(prod);
    }
    return merged;
}

// ---------------------------------------------------------------------------
// BroadcastMergeAxis — 合轴（必须在 CheckBroadcastShape 通过之后、且仅在非空路径执行）
// ---------------------------------------------------------------------------
static void BroadcastMergeAxis(std::vector<int64_t>& maximumBroShape,
                               std::vector<std::vector<int64_t>>& normalInputShapes,
                               std::vector<std::vector<int64_t>>& normalOutputShapes)
{
    const int64_t numInputs = static_cast<int64_t>(normalInputShapes.size());
    const int64_t numOutputs = static_cast<int64_t>(normalOutputShapes.size());
    const int64_t oldRank = static_cast<int64_t>(maximumBroShape.size());
    if (oldRank <= 1) {
        return; // 单维无可合并
    }

    std::vector<std::vector<int64_t>> groups;
    int64_t groupLowDim = oldRank - 1;
    int64_t groupHighDim = oldRank - 1;
    for (int64_t d = oldRank - 2; d >= 0; d--) {
        int64_t maxProd = 1;
        for (int64_t k = d; k <= groupHighDim; k++) {
            maxProd *= maximumBroShape[static_cast<size_t>(k)];
        }
        bool mergeable = true;
        for (int64_t i = 0; i < numInputs && mergeable; i++) {
            int64_t prod = 1;
            for (int64_t k = d; k <= groupHighDim; k++) {
                prod *= normalInputShapes[static_cast<size_t>(i)][static_cast<size_t>(k)];
            }
            if (prod != 1 && prod != maxProd) {
                mergeable = false;
            }
        }
        for (int64_t i = 0; i < numOutputs && mergeable; i++) {
            int64_t prod = 1;
            for (int64_t k = d; k <= groupHighDim; k++) {
                prod *= normalOutputShapes[static_cast<size_t>(i)][static_cast<size_t>(k)];
            }
            if (prod != 1 && prod != maxProd) {
                mergeable = false;
            }
        }
        if (mergeable) {
            groupLowDim = d; // dim d 并入当前组
        } else {
            groups.push_back({groupLowDim, groupHighDim}); // 封闭当前组，从 dim d 开新组
            groupLowDim = d;
            groupHighDim = d;
        }
    }
    groups.push_back({groupLowDim, groupHighDim});
    std::reverse(groups.begin(), groups.end());

    maximumBroShape = MergeShapeByGroups(maximumBroShape, groups);
    for (int64_t i = 0; i < numInputs; i++) {
        normalInputShapes[static_cast<size_t>(i)] = MergeShapeByGroups(normalInputShapes[static_cast<size_t>(i)],
                                                                       groups);
    }
    for (int64_t i = 0; i < numOutputs; i++) {
        normalOutputShapes[static_cast<size_t>(i)] = MergeShapeByGroups(normalOutputShapes[static_cast<size_t>(i)],
                                                                        groups);
    }
}

// ---------------------------------------------------------------------------
// FindSplitAxis — 以 maximumBroShape 为坐标系选择单根切分轴（HostTiling.md §7）
//   perBufBytes = (ubPerCore / physNodes) & ~(ubBlockSize - 1)
//   perBufElems = perBufBytes / dtypeSize（本算子 fp32 = 4）
// ---------------------------------------------------------------------------
static void FindSplitAxis(const std::vector<int64_t>& maxBroShape, int64_t dtypeSize, int64_t ubPerCore,
                          int64_t physNodes, int64_t ubBlockSize, SplitResult& out)
{
    const int64_t perBufBytes = (ubPerCore / physNodes) & ~(ubBlockSize - 1);
    const int64_t perBufElems = perBufBytes / dtypeSize;
    const int64_t rank = static_cast<int64_t>(maxBroShape.size());
    int64_t inner = 1;
    for (int64_t k = rank - 1; k >= 0; k--) {
        if (maxBroShape[static_cast<size_t>(k)] * inner > perBufElems) {
            out.ubFactor = perBufElems / inner;
            out.ubOuter = CeilDiv(maxBroShape[static_cast<size_t>(k)], out.ubFactor);
            const int64_t rem = maxBroShape[static_cast<size_t>(k)] % out.ubFactor;
            out.ubTail = (rem == 0) ? out.ubFactor : rem;
            out.ubSplitIdx = k;
            return;
        }
        if (k == 0) { // 全量装得下
            out.ubSplitIdx = 0;
            out.ubFactor = maxBroShape[0];
            out.ubOuter = 1;
            out.ubTail = out.ubFactor;
            return;
        }
        inner *= maxBroShape[static_cast<size_t>(k)];
    }
}

// ---------------------------------------------------------------------------
// MultiCoreSplit — tile 均衡分配（HostTiling.md §8）
//   totalTiles = prod(dims before split axis) * ubOuter
//   usedCoreNum = min(totalTiles, maxCores)
//   mainTiles = CeilDiv(totalTiles, usedCoreNum)
//   mainCoreNum = totalTiles - (mainTiles - 1) * usedCoreNum
// ---------------------------------------------------------------------------
static void MultiCoreSplit(const std::vector<int64_t>& maxBroShape, const SplitResult& ubSplit, int64_t maxCores,
                           MultiCoreResult& out)
{
    const int64_t k = ubSplit.ubSplitIdx;
    int64_t outerProd = 1;
    for (int64_t j = 0; j < k; j++) {
        outerProd *= maxBroShape[static_cast<size_t>(j)];
    }
    out.totalTiles = outerProd * ubSplit.ubOuter;
    out.usedCoreNum = (out.totalTiles < maxCores) ? out.totalTiles : maxCores;
    out.mainTiles = CeilDiv(out.totalTiles, out.usedCoreNum);
    out.mainCoreNum = out.totalTiles - (out.mainTiles - 1) * out.usedCoreNum;
}

// ---------------------------------------------------------------------------
// CalcStrides — 稠密行主序步长；广播轴（该张量 dim==1 而坐标系 dim!=1）置 0。
//   scaleIsU64View = true 时按 uint32 低字视图计步长（×2）。
// ---------------------------------------------------------------------------
static void CalcStrides(const std::vector<std::vector<int64_t>>& normalShapes, const std::vector<int64_t>& maxBroShape,
                        int64_t rank, int64_t idx, bool scaleIsU64View, int64_t outStrides[RANK_8])
{
    int64_t stride = 1;
    for (int64_t d = rank - 1; d >= 0; d--) {
        const bool isBrc = (normalShapes[static_cast<size_t>(idx)][static_cast<size_t>(d)] == 1 &&
                            maxBroShape[static_cast<size_t>(d)] != 1);
        outStrides[d] = isBrc ? 0 : stride;
        if (!isBrc) {
            stride *= normalShapes[static_cast<size_t>(idx)][static_cast<size_t>(d)];
        }
    }
    if (scaleIsU64View) {
        for (int64_t d = 0; d < rank; d++) {
            outStrides[d] *= 2; // uint64 → 低 32 位字视图
        }
    }
}

