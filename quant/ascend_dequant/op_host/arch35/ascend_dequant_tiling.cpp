class AscendDequantTiling {
public:
    explicit AscendDequantTiling(gert::TilingContext* ctx) : ctx_(ctx) {}

    // -----------------------------------------------------------------------
    // RunTiling() — 唯一调用顺序，错误码优先级唯一（HostTiling.md §12）
    // -----------------------------------------------------------------------
    ge::graphStatus RunTiling()
    {
        ge::graphStatus ret = GetPlatformInfo();
        if (ret != ge::GRAPH_SUCCESS) {
            return ret;
        }
        ret = ReadAndValidate();
        if (ret != ge::GRAPH_SUCCESS) {
            return ret;
        }

        // PadAndSqueeze：第 2 项为 NormalizeScaleShape 之后的对齐形
        std::vector<std::vector<int64_t>> broIn = {xShape_, normalizedScaleShape_};
        std::vector<std::vector<int64_t>> broOut = {yShape_};
        ascend_dequant::PadAndSqueeze(broIn, broOut, maxBroShape_, normalInputShapes_, normalOutputShapes_);
        rank_ = static_cast<int64_t>(maxBroShape_.size()); // 空 tensor 路径的 rank_ 口径（不合轴）
        // 分支判据（BranchRoute.md §1/§2 第 3 步）：tilingKey 只由 PadAndSqueeze 后的
        // effective_shape 维度决定，必须在 BroadcastMergeAxis（合轴）之前取定；
        // 合轴只影响切分坐标系，不改变分支归属。
        const int64_t keyRank = static_cast<int64_t>(maxBroShape_.size());

        // ⑦ rank_ <= RANK_8（防模板数组负索引）
        if (keyRank > ascend_dequant::RANK_8) {
            OP_LOGE(ctx_->GetNodeName(), "shape_mismatch: rank after PadAndSqueeze (%ld) exceeds RANK_8 (%ld)",
                    static_cast<long>(keyRank), static_cast<long>(ascend_dequant::RANK_8));
            return ge::GRAPH_FAILED;
        }
        // ⑧ broadcast 兼容性
        if (!ascend_dequant::CheckBroadcastShape(normalInputShapes_, normalOutputShapes_, rank_)) {
            OP_LOGE(ctx_->GetNodeName(), "shape_mismatch: broadcast shapes are incompatible or y is not dense");
            return ge::GRAPH_FAILED;
        }

        // §10 perBufBytes：单个 buffer 字节数（两条路径都落盘）
        perBufBytes_ = (ubSize_ / kPhysNodes) & ~(ubBlockSize_ - 1);

        if (isEmpty_) {                 // ⑨ 空 tensor 短路：不合轴、不切分、无任何计算
            multicore_.usedCoreNum = 0; // 其余字段保持 NSDMI 初值
            rank_ = static_cast<int64_t>(maxBroShape_.size());
        } else {
            ascend_dequant::BroadcastMergeAxis(maxBroShape_, normalInputShapes_, normalOutputShapes_);
            rank_ = static_cast<int64_t>(maxBroShape_.size()); // 合轴后刷新
            ascend_dequant::FindSplitAxis(maxBroShape_, ascend_dequant::kFp32Bytes, ubSize_, kPhysNodes, ubBlockSize_,
                                          split_);
            ascend_dequant::MultiCoreSplit(maxBroShape_, split_, coreNum_, multicore_);
        }

        // 分支按合轴前的 PadAndSqueeze 维度选（BranchRoute.md §1）；切分字段仍基于合轴坐标系
        if (keyRank <= ascend_dequant::RANK_4) {
            return DoTilingAndSet<ascend_dequant::RANK_4>();
        }
        return DoTilingAndSet<ascend_dequant::RANK_8>();
    }

private:
    // -----------------------------------------------------------------------
    // GetPlatformInfo — coreNum / ubSize / ubBlockSize 全部动态取得（HostTiling.md §5）
    // -----------------------------------------------------------------------
    ge::graphStatus GetPlatformInfo()
    {
        fe::PlatFormInfos* platformInfo = ctx_->GetPlatformInfo();
        if (platformInfo == nullptr) {
            OP_LOGE(ctx_->GetNodeName(), "null platform info: GetPlatformInfo returned nullptr");
            return ge::GRAPH_FAILED;
        }
        auto ascendcPlatform = platform_ascendc::PlatformAscendC(platformInfo);
        coreNum_ = static_cast<int64_t>(ascendcPlatform.GetCoreNumAiv());
        if (coreNum_ == 0) {
            OP_LOGE(ctx_->GetNodeName(), "platform info invalid: GetCoreNumAiv returned 0");
            return ge::GRAPH_FAILED;
        }
        uint64_t ubSize = 0;
        ascendcPlatform.GetCoreMemSize(platform_ascendc::CoreMemType::UB, ubSize);
        ubSize_ = static_cast<int64_t>(ubSize);
        if (ubSize_ == 0) {
            OP_LOGE(ctx_->GetNodeName(), "platform info invalid: GetCoreMemSize(UB) returned 0");
            return ge::GRAPH_FAILED;
        }
        ubBlockSize_ = static_cast<int64_t>(Ops::Base::GetUbBlockSize(ctx_));
        if (ubBlockSize_ == 0) {
            OP_LOGE(ctx_->GetNodeName(), "platform info invalid: GetUbBlockSize returned 0");
            return ge::GRAPH_FAILED;
        }
        return ge::GRAPH_SUCCESS;
    }

    // -----------------------------------------------------------------------
    // ReadShapesAndAttrs — ⓪ 读取原始 shape / attr（null 检查）
    // -----------------------------------------------------------------------
    ge::graphStatus ReadShapesAndAttrs()
    {
        const gert::StorageShape* xStorage = ctx_->GetInputShape(ascend_dequant::X_IDX);
        const gert::StorageShape* sStorage = ctx_->GetInputShape(ascend_dequant::SCALE_IDX);
        const gert::StorageShape* yStorage = ctx_->GetOutputShape(ascend_dequant::Y_IDX);
        const gert::RuntimeAttrs* attrs = ctx_->GetAttrs();
        if (xStorage == nullptr || sStorage == nullptr || yStorage == nullptr || attrs == nullptr) {
            OP_LOGE(ctx_->GetNodeName(), "null_input: x / deq_scale / y shape or attrs pointer is nullptr");
            return ge::GRAPH_FAILED;
        }
        if (ctx_->GetInputDesc(ascend_dequant::X_IDX) == nullptr ||
            ctx_->GetInputDesc(ascend_dequant::SCALE_IDX) == nullptr ||
            ctx_->GetOutputDesc(ascend_dequant::Y_IDX) == nullptr) {
            OP_LOGE(ctx_->GetNodeName(), "null_input: input / output desc pointer is nullptr");
            return ge::GRAPH_FAILED;
        }

        xShape_ = ToVector(xStorage->GetOriginShape());
        deqScaleShape_ = ToVector(sStorage->GetOriginShape());
        yShape_ = ToVector(yStorage->GetOriginShape());

        const bool* sqrtModePtr = attrs->GetBool(ascend_dequant::ATTR_SQRT_MODE);
        const bool* reluFlagPtr = attrs->GetBool(ascend_dequant::ATTR_RELU_FLAG);
        const int64_t* dtypePtr = attrs->GetInt(ascend_dequant::ATTR_DTYPE);
        sqrtMode_ = (sqrtModePtr != nullptr && *sqrtModePtr) ? 1 : 0;
        reluFlag_ = (reluFlagPtr != nullptr && *reluFlagPtr) ? 1 : 0;
        dtypeAttr_ = (dtypePtr != nullptr) ? *dtypePtr : ascend_dequant::kDtypeAttrFloat32; // 缺省 0（float32）
        return ge::GRAPH_SUCCESS;
    }

    // -----------------------------------------------------------------------
    // ReadAndValidate — ①②③④⑤⑥ 按唯一顺序执行（HostTiling.md §6）
    // -----------------------------------------------------------------------
    ge::graphStatus ReadAndValidate()
    {
        ge::graphStatus ret = ReadShapesAndAttrs();
        if (ret != ge::GRAPH_SUCCESS) {
            return ret;
        }
        ret = CheckDtype();
        if (ret != ge::GRAPH_SUCCESS) {
            return ret;
        }
        ret = CheckXRank();
        if (ret != ge::GRAPH_SUCCESS) {
            return ret;
        }
        ret = CheckAttrValueRange();
        if (ret != ge::GRAPH_SUCCESS) {
            return ret;
        }

        // ④ 负维拦截（仅 dim < 0；dim == 0 是合法的空 tensor）
        if (ascend_dequant::HasNegativeDim({xShape_, deqScaleShape_}) || ascend_dequant::HasNegativeDim({yShape_})) {
            OP_LOGE(ctx_->GetNodeName(),
                    "shape_mismatch: dim size < 0 in x %s / deq_scale %s / y %s (all dim sizes must be >= 0, "
                    "empty tensor allowed)",
                    ascend_dequant::ShapeToStr(xShape_).c_str(), ascend_dequant::ShapeToStr(deqScaleShape_).c_str(),
                    ascend_dequant::ShapeToStr(yShape_).c_str());
            return ge::GRAPH_FAILED;
        }

        // ⑤ 空 tensor 标志：只看 x 自身维
        isEmpty_ = ascend_dequant::IsEmptyTensor(xShape_);

        // ⑥ 校验 deq_scale 可右对齐广播到 x，并归一化为与 x 同 rank 的对齐形
        if (!ascend_dequant::NormalizeScaleShape(xShape_, deqScaleShape_, normalizedScaleShape_)) {
            OP_LOGE(ctx_->GetNodeName(),
                    "shape_mismatch: deq_scale shape %s is not broadcastable to x %s (right-aligned axes must "
                    "equal x or be 1)",
                    ascend_dequant::ShapeToStr(deqScaleShape_).c_str(), ascend_dequant::ShapeToStr(xShape_).c_str());
            return ge::GRAPH_FAILED;
        }
        OP_LOGI(ctx_->GetNodeName(), "[AscendDequant] isEmpty=%ld, x shape=%s, deq_scale shape=%s",
                static_cast<long>(isEmpty_), ascend_dequant::ShapeToStr(xShape_).c_str(),
                ascend_dequant::ShapeToStr(deqScaleShape_).c_str());
        return ge::GRAPH_SUCCESS;
    }

    // ① dtype：x=int32、deq_scale=uint64，且 y 必须与 attr dtype 一致
    //   (x=int32, deq_scale=uint64) → y=float16 (dtype=1) / y=float32 (dtype=0)
    ge::graphStatus CheckDtype()
    {
        const ge::DataType xDtype = ctx_->GetInputDesc(ascend_dequant::X_IDX)->GetDataType();
        const ge::DataType scaleDtype = ctx_->GetInputDesc(ascend_dequant::SCALE_IDX)->GetDataType();
        const ge::DataType yDtype = ctx_->GetOutputDesc(ascend_dequant::Y_IDX)->GetDataType();
        const bool scaleOk = (scaleDtype == ge::DT_UINT64);
        const bool yOk = (yDtype == ge::DT_FLOAT16 || yDtype == ge::DT_FLOAT);
        // attr 越界（非 0/1）由 ③ 统一报错，这里只做能确定的一致性交叉校验
        const bool attrInRange = (dtypeAttr_ == ascend_dequant::kDtypeAttrFloat32 ||
                                  dtypeAttr_ == ascend_dequant::kDtypeAttrFloat16);
        const ge::DataType attrYDtype = (dtypeAttr_ == ascend_dequant::kDtypeAttrFloat32) ? ge::DT_FLOAT :
                                                                                            ge::DT_FLOAT16;
        if (xDtype != ge::DT_INT32 || !scaleOk || !yOk || (attrInRange && yDtype != attrYDtype)) {
            OP_LOGE(ctx_->GetNodeName(),
                    "dtype_not_supported: x dtype %d / deq_scale dtype %d / y dtype %d / attr dtype %ld, supported "
                    "combinations: x=int32(3) with deq_scale=uint64(23), y=float32(0) for attr dtype=0 or "
                    "y=float16(1) for attr dtype=1",
                    static_cast<int>(xDtype), static_cast<int>(scaleDtype), static_cast<int>(yDtype),
                    static_cast<long>(dtypeAttr_));
            return ge::GRAPH_FAILED;
        }
        outDtype_ = (yDtype == ge::DT_FLOAT) ? ascend_dequant::kDtypeAttrFloat32 : ascend_dequant::kDtypeAttrFloat16;
        return ge::GRAPH_SUCCESS;
    }

    // ② x rank ∈ [1, 8]
    ge::graphStatus CheckXRank()
    {
        const int64_t xRank = static_cast<int64_t>(xShape_.size());
        if (xRank < 1 || xRank > ascend_dequant::RANK_8) {
            OP_LOGE(ctx_->GetNodeName(), "shape_mismatch: x rank %ld is out of [1, %ld]", static_cast<long>(xRank),
                    static_cast<long>(ascend_dequant::RANK_8));
            return ge::GRAPH_FAILED;
        }
        return ge::GRAPH_SUCCESS;
    }

    // ③ attr dtype ∈ {0,1}：0 → float32 输出，1 → float16 输出
    ge::graphStatus CheckAttrValueRange()
    {
        if (dtypeAttr_ != ascend_dequant::kDtypeAttrFloat32 && dtypeAttr_ != ascend_dequant::kDtypeAttrFloat16) {
            OP_LOGE(ctx_->GetNodeName(),
                    "attribute_value_out_of_range: attribute dtype = %ld, must be 0 (float32) or 1 (float16)",
                    static_cast<long>(dtypeAttr_));
            return ge::GRAPH_FAILED;
        }
        return ge::GRAPH_SUCCESS;
    }

    static std::vector<int64_t> ToVector(const gert::Shape& shape)
    {
        std::vector<int64_t> v;
        v.reserve(shape.GetDimNum());
        for (size_t i = 0; i < shape.GetDimNum(); i++) {
            v.push_back(shape.GetDim(i));
        }
        return v;
    }

    // -----------------------------------------------------------------------
    // DoTilingAndSet<R> — 填 TilingData + SetBlockDim + SetTilingKey
    //   shape / stride 数组按 RANK 全量落盘（rank_ 不足 RANK 的尾部补 1 / stride 0）
    // -----------------------------------------------------------------------
    template <int64_t R>
    ge::graphStatus DoTilingAndSet()
    {
        auto* td = ctx_->GetTilingData<AscendDequantTilingData<R>>();
        if (td == nullptr) {
            OP_LOGE(ctx_->GetNodeName(), "GetTilingData returned nullptr");
            return ge::GRAPH_FAILED;
        }

        // ---- 切分结果 ----
        td->split = split_;
        td->multicore = multicore_;
        td->rank = rank_;
        td->perBufBytes = perBufBytes_;
        td->numInputs = kMaxInputSlots;
        td->numOutputs = kMaxOutputSlots;

        // ---- shape / stride：按 RANK 全量落盘，rank 之外的尾部补 1 / 0 ----
        for (int64_t d = 0; d < R; d++) {
            td->maxBroShape[d] = (d < rank_) ? maxBroShape_[static_cast<size_t>(d)] : 1;
        }
        int64_t tmpStrides[ascend_dequant::RANK_8] = {0};
        for (int64_t i = 0; i < kMaxInputSlots; i++) {
            // deq_scale 为 uint64，按低 32 位字视图计步长（×2）
            ascend_dequant::CalcStrides(normalInputShapes_, maxBroShape_, rank_, i, i == ascend_dequant::SCALE_IDX,
                                        tmpStrides);
            for (int64_t d = 0; d < R; d++) {
                td->inputShapes[i][d] = (d < rank_) ?
                                            normalInputShapes_[static_cast<size_t>(i)][static_cast<size_t>(d)] :
                                            1;
                td->inputStrides[i][d] = (d < rank_) ? tmpStrides[d] : 0;
            }
        }
        for (int64_t i = 0; i < kMaxOutputSlots; i++) {
            ascend_dequant::CalcStrides(normalOutputShapes_, maxBroShape_, rank_, i, false, tmpStrides);
            for (int64_t d = 0; d < R; d++) {
                td->outputShapes[i][d] = (d < rank_) ?
                                             normalOutputShapes_[static_cast<size_t>(i)][static_cast<size_t>(d)] :
                                             1;
                td->outputStrides[i][d] = (d < rank_) ? tmpStrides[d] : 0;
            }
        }

        // ---- attr 展开 + dtype 选择（运行时开关，不进 TilingKey）----
        td->sqrtMode = sqrtMode_;
        td->reluFlag = reluFlag_;
        td->outDtype = outDtype_; // 0 = float32 输出，1 = float16 输出

        LogTilingData<R>(td);

        // ---- SetBlockDim：严禁 0；空 tensor（usedCoreNum == 0）退化为 1 ----
        const uint32_t blockDim = static_cast<uint32_t>((td->multicore.usedCoreNum == 0) ? 1 :
                                                                                           td->multicore.usedCoreNum);
        ctx_->SetBlockDim(blockDim);

        // ---- SetTilingKey：只按 RANK 分档（TilingKey.md §1 位编码：RANK_4 → 0，RANK_8 → 1）----
        const uint64_t tilingKey = (R == ascend_dequant::RANK_4) ? ascend_dequant::TILING_KEY_RANK_4 :
                                                                   ascend_dequant::TILING_KEY_RANK_8;
        ctx_->SetTilingKey(tilingKey);
        OP_LOGI(ctx_->GetNodeName(), "[AscendDequant] tilingKey=%lu (RANK=%ld)", static_cast<unsigned long>(tilingKey),
                static_cast<long>(R));
        return ge::GRAPH_SUCCESS;
    }

    // -----------------------------------------------------------------------
    // LogTilingData<R> — 维测：外部参数 + TilingData 全量（INFO 级）
    // -----------------------------------------------------------------------
    template <int64_t R>
    void LogTilingData(const AscendDequantTilingData<R>* td)
    {
        OP_LOGI(ctx_->GetNodeName(), "[AscendDequant] split: ubSplitIdx=%ld, ubFactor=%ld, ubOuter=%ld, ubTail=%ld",
                static_cast<long>(td->split.ubSplitIdx), static_cast<long>(td->split.ubFactor),
                static_cast<long>(td->split.ubOuter), static_cast<long>(td->split.ubTail));
        OP_LOGI(ctx_->GetNodeName(),
                "[AscendDequant] multicore: usedCoreNum=%ld, totalTiles=%ld, mainTiles=%ld, mainCoreNum=%ld",
                static_cast<long>(td->multicore.usedCoreNum), static_cast<long>(td->multicore.totalTiles),
                static_cast<long>(td->multicore.mainTiles), static_cast<long>(td->multicore.mainCoreNum));
        OP_LOGI(ctx_->GetNodeName(),
                "[AscendDequant] rank=%ld, perBufBytes=%ld, attrs: sqrtMode=%ld, reluFlag=%ld, outDtype=%ld",
                static_cast<long>(td->rank), static_cast<long>(td->perBufBytes), static_cast<long>(td->sqrtMode),
                static_cast<long>(td->reluFlag), static_cast<long>(td->outDtype));
        OP_LOGI(ctx_->GetNodeName(), "[AscendDequant] maxBroShape = %s",
                ascend_dequant::ShapeToStr(td->maxBroShape, R).c_str());
        for (int64_t i = 0; i < td->numInputs; i++) {
            OP_LOGI(ctx_->GetNodeName(), "[AscendDequant] input[%ld]: shape=%s, stride=%s", static_cast<long>(i),
                    ascend_dequant::ShapeToStr(td->inputShapes[i], R).c_str(),
                    ascend_dequant::ShapeToStr(td->inputStrides[i], R).c_str());
        }
        for (int64_t i = 0; i < td->numOutputs; i++) {
            OP_LOGI(ctx_->GetNodeName(), "[AscendDequant] output[%ld]: shape=%s, stride=%s", static_cast<long>(i),
                    ascend_dequant::ShapeToStr(td->outputShapes[i], R).c_str(),
                    ascend_dequant::ShapeToStr(td->outputStrides[i], R).c_str());
        }
    }

    // --- context / platform ---
    gert::TilingContext* ctx_ = nullptr;
    int64_t coreNum_ = 0;     // AIV 核数（动态取）
    int64_t ubSize_ = 0;      // UB 字节数（动态取）
    int64_t ubBlockSize_ = 0; // UB 块字节数（Ops::Base::GetUbBlockSize，禁止硬编码）

    // --- 原始输入（未补 1）---
    std::vector<int64_t> xShape_;
    std::vector<int64_t> deqScaleShape_;
    std::vector<int64_t> yShape_;
    std::vector<int64_t> normalizedScaleShape_; // deq_scale 右对齐到 x 同 rank 后的形状

    // --- 归一化坐标系 ---
    std::vector<int64_t> maxBroShape_;                     // maximumBroShape（切分坐标系）
    std::vector<std::vector<int64_t>> normalInputShapes_;  // {x, deq_scale}
    std::vector<std::vector<int64_t>> normalOutputShapes_; // {y}

    // --- attr 展开 + dtype 选择 ---
    int64_t sqrtMode_ = 0;
    int64_t reluFlag_ = 0;
    int64_t dtypeAttr_ = ascend_dequant::kDtypeAttrFloat32; // proto 缺省 0（float32）
    int64_t outDtype_ = ascend_dequant::kDtypeAttrFloat32;  // 由 y 数据类型确定

    // --- 中间结果 ---
    int64_t rank_ = 0;            // effective rank（非空=合轴后，空 tensor=PadAndSqueeze 后）
    int64_t perBufBytes_ = 0;     // 单 buffer 字节数
    bool isEmpty_ = false;        // 空 tensor 标志（只看 x 自身维）
    SplitResult split_{};         // UB 切分结果（空 tensor 保持 NSDMI 初值）
    MultiCoreResult multicore_{}; // 多核切分结果（空 tensor 仅 usedCoreNum = 0）
};

// ---------------------------------------------------------------------------
// TilingFuncAscendDequant — tiling entry point called by CANN runtime
// ---------------------------------------------------------------------------
static ge::graphStatus TilingFuncAscendDequant(gert::TilingContext* context)
{
    if (context == nullptr) {
        OP_LOGE("AscendDequant", "null_input: tiling context is nullptr");
        return ge::GRAPH_FAILED;
    }
    AscendDequantTiling tiling(context);
    const ge::graphStatus ret = tiling.RunTiling();
    if (ret != ge::GRAPH_SUCCESS) {
        return ret;
    }
    // Workspace：Broadcast 不需要，但必须显式置 0
    size_t* workspaces = context->GetWorkspaceSizes(1);
    if (workspaces == nullptr) {
        OP_LOGE(context->GetNodeName(), "GetWorkspaceSizes(1) returned nullptr");
        return ge::GRAPH_FAILED;
    }
    workspaces[0] = 0;
    return ge::GRAPH_SUCCESS;
}

