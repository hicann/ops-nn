// 运行 tiling，成功时把 tilingData 视图返回；失败返回 false
static bool RunTiling(const gert::TilingContextPara& para, TilingInfo& info, const ActULQClampMaxGradTilingData*& td)
{
    bool ok = ExecuteTiling(para, info);
    if (!ok) {
        td = nullptr;
        return false;
    }
    EXPECT_GE(info.tilingDataSize, sizeof(ActULQClampMaxGradTilingData));
    td = reinterpret_cast<const ActULQClampMaxGradTilingData*>(info.tilingData.get());
    return true;
}

