// ─────────────────────────────────────────────────────────────────────────────
// [T-D] 4 组 dtype × bool/非bool mask 的 DTYPE_X 编译期分发：
//        同一模板（normal）下，4 组 dtype 组合产出【相同】 TilingKey → dtype 不进 key
// ─────────────────────────────────────────────────────────────────────────────
TEST_F(ActULQClampMaxGradTilingTest, dtype_dispatch_normal_same_key)
{
    // 4 组合法 dtype 组合（对齐 def.cpp supported_combinations）
    struct Combo {
        ge::DataType yGrad;
        ge::DataType mask;
        const char* name;
    };
    Combo combos[] = {
        {ge::DT_FLOAT16, ge::DT_FLOAT16, "fp16/fp16"},
        {ge::DT_FLOAT, ge::DT_FLOAT, "fp32/fp32"},
        {ge::DT_FLOAT16, ge::DT_BOOL, "fp16/bool"},
        {ge::DT_FLOAT, ge::DT_BOOL, "fp32/bool"},
    };

    int64_t baseKey = -999;
    const ActULQClampMaxGradTilingData* td = nullptr;
    for (auto& c : combos) {
        auto para = MakePara({8, 8}, c.yGrad, c.mask);
        TilingInfo info;
        ASSERT_TRUE(RunTiling(para, info, td)) << "tiling failed for combo " << c.name;
        EXPECT_EQ(td->axisNum, 2) << "combo " << c.name;
        EXPECT_EQ(td->usedCoreNum, 1) << "combo " << c.name; // normal 单核，与 dtype 无关
        if (baseKey == -999) {
            baseKey = info.tilingKey;
        } else {
            EXPECT_EQ(info.tilingKey, baseKey) << "combo " << c.name << " key diverged → dtype 误入 TilingKey";
        }
        std::cout << "[DTYPE] normal combo " << c.name << " key=" << info.tilingKey << std::endl;
    }
}

