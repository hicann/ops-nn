static ge::graphStatus InferShapeScatterNonAliasingAdd(gert::InferShapeContext* context)
{
    OP_LOGD(context->GetNodeName(), "Enter InferShapeScatterNonAliasingAdd");

    const gert::Shape* xShape = context->GetInputShape(X_INPUT_INDEX);
    OP_CHECK_NULL_WITH_CONTEXT(context, xShape);

    gert::Shape* yShape = context->GetOutputShape(Y_OUTPUT_INDEX);
    OP_CHECK_NULL_WITH_CONTEXT(context, yShape);

    if (Ops::Base::IsUnknownRank(*xShape)) {
        Ops::Base::SetUnknownRank(*yShape);
        OP_LOGD(context->GetNodeName(), "[InferShape] input rank is unknown, output shape is unknown rank");
        return GRAPH_SUCCESS;
    }

    // y.shape = x.shape; unknown dims (-1) are propagated unchanged.
    *yShape = *xShape;
    OP_LOGD(context->GetNodeName(), "[InferShape] output shape=%s", Ops::Base::ToString(*yShape).c_str());

    return GRAPH_SUCCESS;
}

