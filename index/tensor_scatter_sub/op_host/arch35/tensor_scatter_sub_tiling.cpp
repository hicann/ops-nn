static void ComputeScatterShapes(const gert::Shape& xShape, const gert::Shape& indicesShape, int64_t& numSlices,
                                 int64_t& sliceSize, int64_t& indicesLastDim, int64_t& xRank,
                                 int64_t xStrides[MAX_VAR_RANK])
{
    xRank = xShape.GetDimNum();
    int64_t indicesRank = indicesShape.GetDimNum();
    indicesLastDim = (indicesRank > 0) ? indicesShape.GetDim(indicesRank - 1) : 0;
    numSlices = 1;
    for (int64_t i = 0; i < indicesRank - 1; i++) {
        numSlices *= indicesShape.GetDim(i);
    }
    sliceSize = 1;
    for (int64_t i = indicesLastDim; i < xRank; i++) {
        sliceSize *= xShape.GetDim(i);
    }
    if (xRank > 0) {
        xStrides[xRank - 1] = 1;
        for (int64_t j = xRank - 2; j >= 0; j--) {
            xStrides[j] = xStrides[j + 1] * xShape.GetDim(j + 1);
        }
    }
}

static void ComputeScatterCoreNum(int64_t totalXElements, int64_t numSlices, int64_t coreNum,
                                  gert::TilingContext* context)
{
    if (totalXElements == 0 && numSlices == 0) {
        context->SetBlockDim(1);
        return;
    }
    int64_t perCoreX = Ops::Base::CeilDiv(totalXElements, coreNum);
    if (perCoreX < PER_CORE_MIN) {
        perCoreX = PER_CORE_MIN;
    }
    int64_t needCoreX = (totalXElements > 0) ? Ops::Base::CeilDiv(totalXElements, perCoreX) : 1;
    int64_t perCoreSlice = Ops::Base::CeilDiv(numSlices, coreNum);
    if (perCoreSlice < PER_CORE_MIN) {
        perCoreSlice = PER_CORE_MIN;
    }
    int64_t needCoreSlice = (numSlices > 0) ? Ops::Base::CeilDiv(numSlices, perCoreSlice) : 1;
    int64_t needCoreNum = std::min(std::max(needCoreX, needCoreSlice), coreNum);
    context->SetBlockDim(std::max(needCoreNum, static_cast<int64_t>(1)));
}

