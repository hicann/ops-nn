// Returns true on success; false if PadAndSqueeze/broadcast fails or effective
// rank > 4 (dispatch invariant violated). On success `out` is fully filled.
bool ComputeBranch4Tiling(const Branch4Inputs& in, TilingData4& out)
{
    // --- step 1: PadAndSqueeze (6 in / 1 out) + CheckBroadcastShape ---
    std::vector<int64_t> max_bro;
    std::vector<std::vector<int64_t>> normal_in, normal_out;
    if (!PadAndSqueeze(in.input_shapes, in.output_shapes, max_bro, normal_in, normal_out)) {
        return false;
    }
    int64_t eff_rank = (int64_t)max_bro.size();
    if (eff_rank > kRankThreshold4) {
        return false; // Branch-4 dispatch invariant: eff rank ≤ 4
    }
    if (!CheckBroadcastShape(normal_in, normal_out, eff_rank, nullptr)) {
        return false;
    }

    // --- step 2: UB split (FindSplitAxis) + multi-core split + per_buf ---
    SplitResult split{};
    if (!FindSplitAxis(max_bro, in.dtype_size, in.ub_per_core, kPhysNodes, split)) {
        return false;
    }
    MultiCoreResult mc{};
    if (!MultiCoreSplit(max_bro, split, in.max_cores, mc)) {
        return false;
    }
    int64_t per_buf_bytes = ComputePerBufBytes(in.ub_per_core, kPhysNodes);

    // --- step 3: pack TilingData4 ---
    FillTilingData4(out, split, mc, eff_rank, per_buf_bytes, max_bro, normal_in, normal_out, in.attrs);
    return true;
}

// Branch-8 integrated tiling (tilingKey=8, RANK=8).
// Runs the full Branch-8 pipeline reusing the public Host functions
// (PadAndSqueeze / CheckBroadcastShape / FindSplitAxis / MultiCoreSplit /
// ComputePerBufBytes) and packs the result into a TilingData8 via the local
// FillTilingData8 helper above. Split formulas are identical with Branch-4;
// RANK=8 array dims (max_bro_shape[8] /
// input_strides[6][8] / output_strides[1][8]) are the only TilingData
// difference. The RANK>5 NDDMA outer-loop path (CopyInBrc `else` branch,
// nddmaOuterIters) is a kernel-side concern computed in the kernel's Init from
// these TilingData8 fields — it is NOT reflected in TilingData8.
bool ComputeBranch8Tiling(const Branch8Inputs& in, TilingData8& out)
{
    // --- step 1: PadAndSqueeze (6 in / 1 out) + CheckBroadcastShape ---
    std::vector<int64_t> max_bro;
    std::vector<std::vector<int64_t>> normal_in, normal_out;
    if (!PadAndSqueeze(in.input_shapes, in.output_shapes, max_bro, normal_in, normal_out)) {
        return false;
    }
    int64_t eff_rank = (int64_t)max_bro.size();
    // Branch-8 dispatch invariant:
    // 4 < effective rank ≤ 8 (PadAndSqueeze result >4 enters Branch-8).
    if (eff_rank <= kRankThreshold4 || eff_rank > kRankThreshold8) {
        return false;
    }
    if (!CheckBroadcastShape(normal_in, normal_out, eff_rank, nullptr)) {
        return false;
    }

    // --- step 2: UB split (FindSplitAxis) + multi-core split + per_buf ---
    // dtype_size is signature-only (element count always /4,
    // FP32 basis, independent of dtype); identical formulas to Branch-4.
    SplitResult split{};
    if (!FindSplitAxis(max_bro, in.dtype_size, in.ub_per_core, kPhysNodes, split)) {
        return false;
    }
    MultiCoreResult mc{};
    if (!MultiCoreSplit(max_bro, split, in.max_cores, mc)) {
        return false;
    }
    int64_t per_buf_bytes = ComputePerBufBytes(in.ub_per_core, kPhysNodes);

    // --- step 3: pack TilingData8 ---
    FillTilingData8(out, split, mc, eff_rank, per_buf_bytes, max_bro, normal_in, normal_out, in.attrs);
    return true;
}

