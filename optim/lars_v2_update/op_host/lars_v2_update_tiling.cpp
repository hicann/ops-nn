// These pure-computation functions are shared by both RANK_4 / RANK_8 branches:
//   - PadAndSqueeze           (input preprocessing, 6 in / 1 out)
//   - CheckBroadcastShape     (validation, w.shape==g.shape)
//   - ComputePerBufBytes/Elems(P=3: (ub/P)&~31, /4)
//   - FindSplitAxis            (UB split)
