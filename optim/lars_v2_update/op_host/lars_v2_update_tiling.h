// Host-side public tiling logic for lars_v2_update.
// Pure-computation functions shared by both RANK_4 / RANK_8 branches; decoupled
// from gert::TilingContext so they can be unit-tested independently.

#ifndef LARS_V2_UPDATE_TILING_HOST_H
#define LARS_V2_UPDATE_TILING_HOST_H

#include <cstdint>
#include <vector>
#include "../op_kernel/arch35/lars_v2_update_tiling_data.h"

namespace optiling {

// Resolved LARS attrs. use_clip stored as int64_t
// 0/1 (bool->int64_t, does not drive dispatch).
struct LarsAttrs {
    float hyperpara;  // LARS eta, default 0.001
    float epsilon;    // anti-div-zero eps, default 1e-5
    int64_t use_clip; // 0/1
};

// PadAndSqueeze: 1-prepending pad + all-one dim squeeze.
// 6 inputs (w, g, w_square_sum, g_square_sum, weight_decay, learning_rate),
// 1 output (g_new). Fills the broadcast coordinate shape + per-input/output
// "normal" (de-squeezed) shapes.
bool PadAndSqueeze(const std::vector<std::vector<int64_t>>& input_shapes,
                   const std::vector<std::vector<int64_t>>& output_shapes, std::vector<int64_t>& max_bro_shape,
                   std::vector<std::vector<int64_t>>& normal_input_shapes,
                   std::vector<std::vector<int64_t>>& normal_output_shapes);

// CheckBroadcastShape: w.shape==g.shape / broadcast-compatible check.
// bad_dim (out, optional): -1 if compatible, else the first incompatible dim.
bool CheckBroadcastShape(const std::vector<std::vector<int64_t>>& padded_in,
                         const std::vector<std::vector<int64_t>>& padded_out, int64_t max_rank,
                         int64_t* bad_dim = nullptr);

// per_buf helpers (P = kPhysNodes = 3).
// per_buf_bytes = (ub_per_core / phys_nodes) & ~31  (32B align, TBuf hw requirement)
int64_t ComputePerBufBytes(int64_t ub_per_core, int64_t phys_nodes);
// per_buf_elems = per_buf_bytes / 4  (always /4, FP32 basis)
int64_t ComputePerBufElems(int64_t per_buf_bytes);

// FindSplitAxis: pick the UB split axis given per_buf_elems (P=3).
// dtype_size is kept for signature fidelity; the element count
// is always per_buf_bytes/4 (FP32 basis), independent of dtype.
bool FindSplitAxis(const std::vector<int64_t>& max_bro_shape, int64_t dtype_size, int64_t ub_per_core,
                   int64_t phys_nodes, SplitResult& out);

// MultiCoreSplit: total-tiles -> core mapping.
bool MultiCoreSplit(const std::vector<int64_t>& max_bro_shape, const SplitResult& ub_split, int64_t max_cores,
                    MultiCoreResult& out);

// TilingKey dispatch: effective rank (after PadAndSqueeze) -> key.
//   effective rank <= 4      -> 4  (LARS_V2_UPDATE_RANK_4)
//   4 < effective rank <= 8  -> 8  (LARS_V2_UPDATE_RANK_8)
//   > 8                      -> -1 (unsupported)
int64_t ChooseTilingKey(int64_t effective_rank);

// attrs acquisition: resolve nullable attr pointers with defaults.
//   hyperpara nullptr -> 0.001; epsilon nullptr -> 1e-5; use_clip nullptr/false -> 0.
void ResolveAttrs(const float* hyperpara, const float* epsilon, const bool* use_clip, LarsAttrs& out);

// === Branch-4 (tilingKey=4, RANK_4) integrated tiling ===
// Pre: caller dispatched via ChooseTilingKey(effective_rank) == 4 (effective
// rank ≤ 4 after PadAndSqueeze). Runs the full Branch-4 pipeline
// (PadAndSqueeze → CheckBroadcastShape → FindSplitAxis → MultiCoreSplit → fill
// TilingData4) and produces a complete TilingData4 ready for SetTilingData.
// Constants: P = kPhysNodes = 3,
// per_buf_bytes = (ub_per_core / 3) & ~31, per_buf_elems = per_buf_bytes / 4.
struct Branch4Inputs {
    std::vector<std::vector<int64_t>> input_shapes;  // 6 inputs (w,g,wss,gss,wd,lr)
    std::vector<std::vector<int64_t>> output_shapes; // 1 output (g_new)
    int64_t dtype_size;                              // 4 (fp32); signature fidelity (/4 basis)
    int64_t ub_per_core;                             // platform UB bytes per core (e.g. 196608 for 192 KiB)
    int64_t max_cores;                               // platform AIV core count
    LarsAttrs attrs;                                 // resolved LARS attrs
};

// Returns true on success; false if PadAndSqueeze/broadcast fails or effective
// rank > 4 (dispatch invariant violated). On success `out` is fully filled.
bool ComputeBranch4Tiling(const Branch4Inputs& in, TilingData4& out);

// === Branch-8 (tilingKey=8, RANK_8) integrated tiling ===
// Pre: caller dispatched via ChooseTilingKey(effective_rank) == 8 (4 < effective
// rank ≤ 8 after PadAndSqueeze). Runs the full Branch-8 pipeline
// (PadAndSqueeze → CheckBroadcastShape → FindSplitAxis → MultiCoreSplit → fill
// TilingData8) and produces a complete TilingData8 ready for SetTilingData.
// Constants: identical to Branch-4 — P =
// kPhysNodes = 3, per_buf_bytes = (ub_per_core / 3) & ~31, per_buf_elems =
// per_buf_bytes / 4. Split formulas are identical with Branch-4;
// the only differences are the RANK=8 array dims (max_bro_shape[8] /
// input_strides[6][8] / output_strides[1][8]) and the kernel-side NDDMA outer
// loop (RANK>5, CopyInBrc `else` branch) — the latter is a kernel concern
// not reflected in TilingData8 fields.
struct Branch8Inputs {
    std::vector<std::vector<int64_t>> input_shapes;  // 6 inputs (w,g,wss,gss,wd,lr)
    std::vector<std::vector<int64_t>> output_shapes; // 1 output (g_new)
    int64_t dtype_size;                              // 4 (fp32); signature fidelity (/4 basis)
    int64_t ub_per_core;                             // platform UB bytes per core (e.g. 196608 for 192 KiB)
    int64_t max_cores;                               // platform AIV core count
    LarsAttrs attrs;                                 // resolved LARS attrs
};

// Returns true on success; false if PadAndSqueeze/broadcast fails or effective
// rank ≤ 4 or > 8 (dispatch invariant violated). On success `out` is fully
// filled with the real Branch-8 pipeline.
bool ComputeBranch8Tiling(const Branch8Inputs& in, TilingData8& out);

} // namespace optiling

#endif // LARS_V2_UPDATE_TILING_HOST_H
