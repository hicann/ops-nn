/*!
 * \file lars_v2_update_infershape.cpp
 * \brief LarsV2Update 算子形状推导（g_new shape = w shape）
 */

#include "register/op_impl_registry.h"
#include "exe_graph/runtime/infer_shape_context.h"
#include "log/log.h"

using namespace ge;

namespace ops {

static constexpr int64_t IDX_0 = 0;

static ge::graphStatus InferShape4LarsV2Update(gert::InferShapeContext* context)
{
    OP_LOGD(context->GetNodeName(), "Begin to do InferShape4LarsV2Update");

    // g_new has the same shape as w (the first input).
    const gert::Shape* wShape = context->GetInputShape(IDX_0);
    gert::Shape* gNewShape = context->GetOutputShape(IDX_0);
    if (wShape == nullptr || gNewShape == nullptr) {
        return ge::GRAPH_FAILED;
    }
    *gNewShape = *wShape;

    OP_LOGD(context->GetNodeName(), "End to do InferShape4LarsV2Update");
    return ge::GRAPH_SUCCESS;
}

IMPL_OP_INFERSHAPE(LarsV2Update).InferShape(InferShape4LarsV2Update);

} // namespace ops
