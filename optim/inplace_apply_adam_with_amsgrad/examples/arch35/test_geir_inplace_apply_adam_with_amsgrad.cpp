// ---------------------------------------------------------------------------
// CPU golden: AMSGrad single-step update in fp32.
//   m'    = m + (grad - m) * (1 - beta1)
//   v'    = v + (grad^2 - v) * (1 - beta2)
//   vhat' = max(vhat, v')
//   var'  = var - alpha * m' / (sqrt(vhat') + epsilon)
//   alpha = lr * sqrt(1 - beta2_power) / (1 - beta1_power)
// ---------------------------------------------------------------------------
struct AdamParams {
    float beta1Power;
    float beta2Power;
    float lr;
    float beta1;
    float beta2;
    float epsilon;
};

static void CpuAmsgrad(const AdamParams& p, const float* var, const float* m, const float* v, const float* vhat,
                       const float* grad, float* varOut, float* mOut, float* vOut, float* vhatOut, int64_t n)
{
    const float alpha = p.lr * std::sqrt(1.0f - p.beta2Power) / (1.0f - p.beta1Power);
    const float oneMinusB1 = 1.0f - p.beta1;
    const float oneMinusB2 = 1.0f - p.beta2;
    for (int64_t i = 0; i < n; ++i) {
        const float mNew = m[i] + (grad[i] - m[i]) * oneMinusB1;
        const float vNew = v[i] + (grad[i] * grad[i] - v[i]) * oneMinusB2;
        const float vhatNew = (vhat[i] > vNew) ? vhat[i] : vNew;
        const float denom = std::sqrt(vhatNew) + p.epsilon;
        const float varNew = var[i] - alpha * mNew / denom;
        varOut[i] = varNew;
        mOut[i] = mNew;
        vOut[i] = vNew;
        vhatOut[i] = vhatNew;
    }
}

static bool CompareOutput(const float* actual, const float* golden, int64_t n, const char* name, float rtol, float atol)
{
    int64_t badCount = 0;
    for (int64_t i = 0; i < n; ++i) {
        const float diff = std::fabs((double)actual[i] - (double)golden[i]);
        const float tol = atol + rtol * std::fabs((double)golden[i]);
        if (diff > tol) {
            if (badCount < 5) {
                LOG_PRINT("  [%s][%ld] golden=%.6f actual=%.6f diff=%.6f tol=%.6f\n", name, i, golden[i], actual[i],
                          diff, tol);
            }
            badCount++;
        }
    }
    if (badCount > 0) {
        LOG_PRINT("  [%s] %ld/%ld elements exceed tolerance\n", name, badCount, n);
        return false;
    }
    return true;
}

