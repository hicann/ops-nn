// Convert NPU raw output bytes to fp32 for comparison.
static void OutputToFloat(const uint8_t* data, int64_t n, DataType dtype, std::vector<float>& out)
{
    out.resize(n);
    if (dtype == ge::DT_FLOAT) {
        memcpy(out.data(), data, n * 4);
    } else if (dtype == ge::DT_FLOAT16) {
        const uint16_t* h = (const uint16_t*)data;
        for (int64_t i = 0; i < n; ++i) {
            const uint16_t v = h[i];
            const uint16_t sign = (v >> 15) & 0x1;
            const int32_t exp = (int32_t)((v >> 10) & 0x1F) - 15 + 127;
            const uint32_t frac = v & 0x3FF;
            uint32_t bits = ((uint32_t)sign << 31) | ((uint32_t)exp << 23) | (frac << 13);
            if (((v >> 10) & 0x1F) == 0) {
                bits = ((uint32_t)sign << 31);
            }
            memcpy(&out[i], &bits, 4);
        }
    } else { // DT_BF16
        const uint16_t* b = (const uint16_t*)data;
        for (int64_t i = 0; i < n; ++i) {
            const uint32_t bits = (uint32_t)b[i] << 16;
            memcpy(&out[i], &bits, 4);
        }
    }
}

