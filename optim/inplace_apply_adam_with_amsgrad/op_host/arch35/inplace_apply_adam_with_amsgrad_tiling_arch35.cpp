// IMPL_OP_OPTILING(InplaceApplyAdamWithAmsgrad) — register the tiling function
// and the compile-time preparation callback (HostTiling.md §8).
//
// NOTE on TilingInputsDataDependency: REMOVED.  The framework's
// TilingInputsDataDependency mechanism stages scalar inputs to a
// framework-owned host buffer that is CACHED by (shape, dtype) — the first
// call stages the scalar value, and subsequent calls with the same shape/
// dtype REUSE the cached staging buffer without re-reading the device tensor.
// This breaks the div0 test case (beta1Power=1.0) which shares shape/dtype
// with the normal cases (beta1Power=0.9): the TilingFunc reads the CACHED
// 0.9 instead of the uploaded 1.0, computing a non-Inf alpha.
//
// Fix: the kernel reads beta1Power/beta2Power/lr DIRECTLY from their GM
// scalar tensors (via GlobalTensor::GetValue) and computes alpha locally
// (same fp32 formula as the host, per DESIGN-BRANCH-0.md §7).  The
// TilingData.alpha field is kept for documentation but the kernel ignores
// it; alpha is recomputed in the kernel from the un-staged GM scalars.
// This avoids the framework's staging cache and matches the oracle's
// alpha computation bit-for-bit (same fp32 formula).
//
//   .Tiling(InplaceApplyAdamWithAmsgradTilingFunc): runtime tiling callback.
//   .TilingParse<InplaceApplyAdamWithAmsgradCompileInfo>(TilingPrepareFor...):
//     compile-time platform info carrier.
// =============================================================================
IMPL_OP_OPTILING(InplaceApplyAdamWithAmsgrad)
    .Tiling(InplaceApplyAdamWithAmsgradTilingFunc)
    .TilingParse<InplaceApplyAdamWithAmsgradCompileInfo>(TilingPrepareForInplaceApplyAdamWithAmsgrad);

