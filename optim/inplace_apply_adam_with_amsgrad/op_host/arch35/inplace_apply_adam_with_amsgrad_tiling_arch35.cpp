// ComputeMultiCoreTiling — TilingFunc Step 7 (HostTiling.md §5): multi-core
// split.  Writes coreNum/blockFormer/blockNum into the TilingData buffer.
// ---------------------------------------------------------------------------
static void ComputeMultiCoreTiling(InplaceApplyAdamWithAmsgradTilingData* tiling, int64_t dim0, const DtypeParams& dp,
                                   uint32_t availableCoreNum)
{
    int64_t coreNum64 = CeilDiv(dim0 * dp.dtypeBits, kMinTilingBits);
    coreNum64 = std::min<int64_t>(coreNum64, static_cast<int64_t>(availableCoreNum));
    if (coreNum64 < 1) {
        coreNum64 = 1; // tiny-shape fallback
    }
    tiling->coreNum = static_cast<int32_t>(coreNum64);
    tiling->blockFormer = CeilDiv(CeilDiv(dim0, tiling->coreNum), kElemAlign) * kElemAlign;
    tiling->blockNum = CeilDiv(dim0, tiling->blockFormer);
}

// ---------------------------------------------------------------------------
// ComputeUbTiling — TilingFunc Steps 8-9 (HostTiling.md §4/§7): UB split.
//   bufferDivisor = bufferNum*dtypeBytes + K*sizeof(float)  (B/elem)
//     fp32:  5*4 + 4*4 = 36  | fp16/bf16: 5*2 + 13*4 = 62
//   maxElemNum  = (ubSize - extraSize) / bufferDivisor       (elements)
//   alignFactor = ALIGN_256 / dtypeBytes                      (fp32=64, fp16/bf16=128)
//   ubFormer    = AlignDown(maxElemNum, alignFactor); if <1 -> alignFactor
// Writes ubFormer plus the first/tail block UB loop/tail counts.
// ---------------------------------------------------------------------------
static void ComputeUbTiling(InplaceApplyAdamWithAmsgradTilingData* tiling, int64_t dim0, const DtypeParams& dp,
                            uint32_t ubSize)
{
    const int64_t bufferDivisor = kBufferNum * dp.dtypeBytes + dp.K * sizeof(float);
    const int64_t maxElemNum = (static_cast<int64_t>(ubSize) - kExtraSizeBytes) / bufferDivisor;
    const int64_t alignFactor = kAlign256 / dp.dtypeBytes;
    int64_t uf = AlignDown(maxElemNum, alignFactor);
    if (uf < 1) {
        uf = alignFactor;
    }
    tiling->ubFormer = uf;

    const int64_t blockTail = dim0 - (tiling->blockNum - 1) * tiling->blockFormer;
    tiling->ubLoopOfFormerBlock = CeilDiv(tiling->blockFormer, tiling->ubFormer);
    tiling->ubTailOfFormerBlock = tiling->blockFormer - (tiling->ubLoopOfFormerBlock - 1) * tiling->ubFormer;
    tiling->ubLoopOfTailBlock = CeilDiv(blockTail, tiling->ubFormer);
    tiling->ubTailOfTailBlock = blockTail - (tiling->ubLoopOfTailBlock - 1) * tiling->ubFormer;
}

