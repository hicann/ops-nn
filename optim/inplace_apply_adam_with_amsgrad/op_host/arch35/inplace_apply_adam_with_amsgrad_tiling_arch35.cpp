// TilingFunc — runtime tiling entry (HostTiling.md §9).
//
// Workflow:
//   1. Read platform info (coreNum, ubSize) via Ops::Base wrappers around
//      PlatformAscendC.  (Matches scale_custom_package's runtime query path;
