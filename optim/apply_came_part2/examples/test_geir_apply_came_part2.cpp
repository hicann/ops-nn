int CreateOppInGraph(DataType inDtype, std::vector<ge::Tensor>& input, std::vector<Operator>& inputs,
                     std::vector<Operator>& outputs, Graph& graph)
{
    auto came2 = op::ApplyCamePart2("apply_came_part2_1");

    std::vector<int64_t> gradShape = {4, 8}; // [n, m]
    std::vector<int64_t> rShape = {4};       // [n]
    std::vector<int64_t> cShape = {8};       // [m]
    std::vector<int64_t> scalarShape = {1};
    std::vector<int64_t> globalShapeDesc = {2};

    int idx = 0;
    // 9 inputs — order must match REG_OP(ApplyCamePart2) .INPUT order
    if (AddDataInput(
            idx++, [&](Operator& d) { came2.set_input_grad(d); }, inDtype, gradShape, 0.2f, graph, input, inputs) !=
        SUCCESS) {
        return FAILED;
    }
    if (AddDataInput(
            idx++, [&](Operator& d) { came2.set_input_sum_grad_r(d); }, ge::DT_FLOAT, rShape, 0.5f, graph, input,
            inputs) != SUCCESS) {
        return FAILED;
    }
    if (AddDataInput(
            idx++, [&](Operator& d) { came2.set_input_sum_grad_c(d); }, ge::DT_FLOAT, cShape, 0.3f, graph, input,
            inputs) != SUCCESS) {
        return FAILED;
    }
    if (AddDataInput(
            idx++, [&](Operator& d) { came2.set_input_sum_grad_rc(d); }, ge::DT_FLOAT, scalarShape, 1.0f, graph, input,
            inputs) != SUCCESS) {
        return FAILED;
    }
    if (AddDataInput(
            idx++, [&](Operator& d) { came2.set_input_r(d); }, inDtype, rShape, 0.4f, graph, input, inputs) !=
        SUCCESS) {
        return FAILED;
    }
    if (AddDataInput(
            idx++, [&](Operator& d) { came2.set_input_c(d); }, inDtype, cShape, 0.6f, graph, input, inputs) !=
        SUCCESS) {
        return FAILED;
    }
    if (AddDataInput(
            idx++, [&](Operator& d) { came2.set_input_beta2(d); }, ge::DT_FLOAT, scalarShape, 0.9f, graph, input,
            inputs) != SUCCESS) {
        return FAILED;
    }
    if (AddDataInput(
            idx++, [&](Operator& d) { came2.set_input_sum_r(d); }, ge::DT_FLOAT, scalarShape, 1.6f, graph, input,
            inputs) != SUCCESS) {
        return FAILED;
    }
    // global_shape: int64 tensor [n, m]
    {
        std::string name = "placeholder" + std::to_string(idx);
        auto data = op::Data(name.c_str()).set_attr_index(idx);
        TensorDesc desc = TensorDesc(ge::Shape(globalShapeDesc), FORMAT_ND, ge::DT_INT64);
        desc.SetPlacement(ge::kPlacementHost);
        desc.SetFormat(FORMAT_ND);
        Tensor tensor;
        Status ret = GenInt64Data(globalShapeDesc, tensor, desc, {4, 8});
        if (ret != SUCCESS) {
            return FAILED;
        }
        data.update_input_desc_x(desc);
        input.push_back(tensor);
        graph.AddOp(data);
        came2.set_input_global_shape(data);
        inputs.push_back(data);
    }

    // 4 outputs (r / c / u / sum_square_u); r & c are in-place alias with inputs
    TensorDesc rOutDesc = TensorDesc(ge::Shape(rShape), FORMAT_ND, inDtype);
    came2.update_output_desc_r(rOutDesc);
    TensorDesc cOutDesc = TensorDesc(ge::Shape(cShape), FORMAT_ND, inDtype);
    came2.update_output_desc_c(cOutDesc);
    TensorDesc uOutDesc = TensorDesc(ge::Shape(gradShape), FORMAT_ND, ge::DT_FLOAT);
    came2.update_output_desc_u(uOutDesc);
    TensorDesc sumSquareUOutDesc = TensorDesc(ge::Shape(scalarShape), FORMAT_ND, ge::DT_FLOAT);
    came2.update_output_desc_sum_square_u(sumSquareUOutDesc);

    outputs.push_back(came2);
    return SUCCESS;
}

