int RunScenario(ge::Session& session, uint32_t graphId, const std::string& scenarioName,
                const ShapeVector& gradDeclared, const ShapeVector& rDeclared, const ShapeVector& cDeclared,
                const ShapeCases& concreteShapes)
{
    std::cout << "Scenario " << scenarioName << ", declared grad " << ShapeToString(gradDeclared) << std::endl;
    const std::string graphName = "apply_came_part2_" + scenarioName + "_graph";
    ge::Graph graph(graphName.c_str());
    if (BuildGraph(scenarioName, gradDeclared, rDeclared, cDeclared, graph) != kSuccess) {
        std::cerr << "ERROR: BuildGraph failed for " << scenarioName << std::endl;
        return kFailed;
    }
    std::map<ge::AscendString, ge::AscendString> graphOptions;
    ge::Status status = session.AddGraph(graphId, graph, graphOptions);
    if (status != kSuccess) {
        std::cerr << "ERROR: AddGraph failed for " << scenarioName << ": " << ge::GEGetErrorMsgV2().GetString()
                  << std::endl;
        return kFailed;
    }

    size_t passed = 0U;
    for (const ShapeVector& shape : concreteShapes) {
        std::cout << "Run concrete grad shape " << ShapeToString(shape) << std::endl;
        InputFeeds feeds = MakeFeeds(shape);
        std::vector<ge::Tensor> outputs;
        status = session.RunGraph(graphId, feeds.tensors, outputs);
        if (status != kSuccess) {
            std::cerr << "ERROR: RunGraph failed for " << scenarioName << ": " << ge::GEGetErrorMsgV2().GetString()
                      << std::endl;
            continue;
        }
        if (!VerifyOutput(outputs, shape, feeds)) {
            std::cerr << "ERROR: verification failed for " << scenarioName << std::endl;
            continue;
        }
        ++passed;
        std::cout << "Shape, dtype and values PASSED for " << ShapeToString(shape) << std::endl;
    }

    std::cout << "Scenario " << scenarioName << " summary: " << passed << "/" << concreteShapes.size() << " passed"
              << std::endl;
    return passed == concreteShapes.size() ? kSuccess : kFailed;
}

