        AscendC::Muls(gradFp32, gradFp32, lrValue_, uK);
        // sgdBuf = grad*lr + accum_new*momentum*lr
        AscendC::Add(sgdBuf, sgdBuf, gradFp32, uK);
        // var -= sgd
        AscendC::Sub(varFp32, varFp32, sgdBuf, uK);
