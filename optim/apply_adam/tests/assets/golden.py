def _np_to_torch(x):
    """numpy ndarray -> torch tensor, bit-exact (bfloat16 via int16 bit view)."""
    import torch

    arr = np.asarray(x)
    if arr.dtype.name == "bfloat16":
        return torch.from_numpy(arr.view("int16")).view(torch.bfloat16)
    return torch.from_numpy(arr)


def _torch_to_np(t):
    """torch tensor -> numpy ndarray, bit-exact (bfloat16 via int16 bit view)."""
    import torch

    t = t.detach().cpu()
    if t.dtype == torch.bfloat16:
        import ml_dtypes

        return t.view(torch.int16).numpy().view(ml_dtypes.bfloat16)
    return t.numpy()


def _as_f32_np(x):
    """Any carrier (torch / numpy / python scalar) -> float32 numpy, for the
    TF benchmark. Pure semantics-preserving bridging: no arithmetic happens
    here, the reference math stays inside tf.raw_ops.ApplyAdam."""
    import torch

    if isinstance(x, torch.Tensor):
        t = x.detach().cpu()
        return (t if t.dtype == torch.float64 else t.to(torch.float32)).numpy()
    arr = np.asarray(x)
    return arr if arr.dtype == np.dtype(np.float64) else arr.astype(np.float32)


