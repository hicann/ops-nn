def _tf_scalar_f32(tf, x):
    """FP32 cast of a single-element coefficient, with its rank dropped to 0.

    TF counterpart of ``_torch_scalar``: keeps the tensor on its own device and
    stops a (1, 1) coefficient from broadcasting the result's rank.
    """
    t = _tf_native_f32(tf, x)
    if t.shape.rank == 0:
        return t
    num = t.shape.num_elements()
    if num is not None and num != 1:
        raise ValueError(
            f"ApplyAdam scalar input must hold one element, got shape {tuple(t.shape)}"
        )
    return tf.reshape(t, [])


