class _ApplyAdamE2ETorchCompose:
    """Torch E2E third-party provider (real ``.out`` schema).

    The schema has no var/m/v positional inputs: the in-place state triple is
    supplied through ``out``. Returns three updated states in op-def order.
    """

    def __call__(
        self,
        beta1_power,
        beta2_power,
        lr,
        beta1,
        beta2,
        epsilon,
        grad,
        use_locking: bool = False,
        use_nesterov: bool = False,
        out=None,
        **kwargs,
    ):
        import torch

        if out is None or len(out) < 3:
            raise ValueError(
                "npu_apply_adam third_party needs out=(var, m, v) from the .out schema"
            )
        var, m, v = out[0], out[1], out[2]

        def f32(x):
            t = x if isinstance(x, torch.Tensor) else _np_to_torch(np.asarray(x))
            return t.to(torch.float32)

        def s32(x):
            return _torch_scalar(f32(x))

        outs = _adam_formula(
            f32(var),
            f32(m),
            f32(v),
            s32(beta1_power),
            s32(beta2_power),
            s32(lr),
            s32(beta1),
            s32(beta2),
            s32(epsilon),
            f32(grad),
            bool(use_nesterov),
            torch.sqrt,
        )
        srcs = [
            x if isinstance(x, torch.Tensor) else _np_to_torch(np.asarray(x))
            for x in (var, m, v)
        ]
        return [res.to(src.dtype) for res, src in zip(outs, srcs)]


