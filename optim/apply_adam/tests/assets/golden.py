def _adam_formula(
    var, m, v, b1p, b2p, lr, b1, b2, eps, grad, nesterov, sqrt, where=None
):
    """Framework-agnostic ApplyAdam composition (beta-power protocol).

    ``sqrt`` is the framework's own sqrt, so the arithmetic executes entirely
    inside the provider framework and — for the GPU leg — entirely on device.
    The beta powers are multiplied inputs, never derived from a step counter:
    this is the ApplyAdam (non-D, non-V2) protocol.
    """
    m_new = b1 * m + (1.0 - b1) * grad
    v_new = b2 * v + (1.0 - b2) * grad * grad
    lr_hat = lr * sqrt(1.0 - b2p) / (1.0 - b1p)
    num = (b1 * m_new + (1.0 - b1) * grad) if nesterov else m_new
    return var - lr_hat * num / (eps + sqrt(v_new)), m_new, v_new


def _torch_scalar(t):
    """Single-element coefficient -> 0-d tensor (device and dtype untouched).

    ApplyAdamTiling::CheckIsScalar accepts any shape holding one element and the
    kernel reads a single value, so a (1, 1) coefficient must not broadcast the
    rank of the result; reshaping the result afterwards would only mask it.
    """
    if t.dim() == 0:
        return t
    if t.numel() != 1:
        raise ValueError(
            f"ApplyAdam scalar input must hold one element, got shape {tuple(t.shape)}"
        )
    return t.reshape(())


