static inline ge::DataType ResolveDtype(ge::DataType override, ge::DataType base)
{
    return override == ge::DT_UNDEFINED ? base : override;
}

static gert::KernelRunContextHolder BuildTilingContext(
    const InplaceApplyRMSPropTilingArgs& args, fe::PlatFormInfos& platformInfo, gert::StorageShape& varStorage,
    gert::StorageShape& msStorage, gert::StorageShape& momStorage, gert::StorageShape& lrStorage,
    gert::StorageShape& rhoStorage, gert::StorageShape& momentumStorage, gert::StorageShape& epsilonStorage,
    gert::StorageShape& gradStorage, InplaceApplyRMSPropUtCompileInfo& compileInfo, uint8_t* tilingData,
    gert::ContinuousVector* workspace)
{
    const ge::DataType msDt = ResolveDtype(args.msDtype, args.tensorDtype);
    const ge::DataType momDt = ResolveDtype(args.momDtype, args.tensorDtype);
    const ge::DataType lrDt = ResolveDtype(args.lrDtype, args.tensorDtype);
    const ge::DataType rhoDt = ResolveDtype(args.rhoDtype, args.tensorDtype);
    const ge::DataType momentumDt = ResolveDtype(args.momentumDtype, args.tensorDtype);
    const ge::DataType epsilonDt = ResolveDtype(args.epsilonDtype, args.tensorDtype);
    const ge::DataType gradDt = ResolveDtype(args.gradDtype, args.tensorDtype);
    return gert::TilingContextFaker()
        .SetOpType("InplaceApplyRMSProp")
        .NodeIoNum(8, 3)
        .IrInstanceNum({1, 1, 1, 1, 1, 1, 1, 1})
        .InputShapes({&varStorage, &msStorage, &momStorage, &lrStorage, &rhoStorage, &momentumStorage, &epsilonStorage,
                      &gradStorage})
        .OutputShapes({&varStorage, &msStorage, &momStorage})
        .CompileInfo(&compileInfo)
        .PlatformInfo(reinterpret_cast<char*>(&platformInfo))
        .NodeInputTd(0, args.tensorDtype, args.inputFormat, args.inputFormat)
        .NodeInputTd(1, msDt, args.inputFormat, args.inputFormat)
        .NodeInputTd(2, momDt, args.inputFormat, args.inputFormat)
        .NodeInputTd(3, lrDt, args.inputFormat, args.inputFormat)
        .NodeInputTd(4, rhoDt, args.inputFormat, args.inputFormat)
        .NodeInputTd(5, momentumDt, args.inputFormat, args.inputFormat)
        .NodeInputTd(6, epsilonDt, args.inputFormat, args.inputFormat)
        .NodeInputTd(7, gradDt, args.inputFormat, args.inputFormat)
        .NodeOutputTd(0, args.tensorDtype, args.inputFormat, args.inputFormat)
        .NodeOutputTd(1, msDt, args.inputFormat, args.inputFormat)
        .NodeOutputTd(2, momDt, args.inputFormat, args.inputFormat)
        .NodeAttrs({{"use_locking", Ops::NN::AnyValue::CreateFrom<bool>(args.useLocking)}})
        .TilingData(tilingData)
        .Workspace(workspace)
        .Build();
}

static void ReadTilingResult(gert::TilingContext* context, InplaceApplyRMSPropTilingResult& result)
{
    result.tilingKey = context->GetTilingKey();
    auto rawTilingData = context->GetRawTilingData();
    if (rawTilingData == nullptr || rawTilingData->GetDataSize() < sizeof(InplaceApplyRmsPropTilingData)) {
        return;
    }
    const auto* td = reinterpret_cast<const InplaceApplyRmsPropTilingData*>(rawTilingData->GetData());
    result.totalNum = td->totalNum;
    result.blockFactor = td->blockFactor;
    result.ubFactor = td->ubFactor;
}

static InplaceApplyRMSPropTilingResult DoInplaceApplyRMSPropTilingCase(const InplaceApplyRMSPropTilingArgs& args)
{
    InplaceApplyRMSPropTilingResult result{ge::GRAPH_FAILED, 0, 0, 0, 0};

    fe::PlatFormInfos platFormInfo;
    map<string, string> socInfos;
    map<string, string> aicoreSpec;
    map<string, string> intrinsics;
    map<string, string> socVersion = {{"Short_SoC_version", "ASCEND950"}};
    InitPlatForm(platFormInfo, socInfos, aicoreSpec, intrinsics, socVersion);

    std::string opType("InplaceApplyRMSProp");
    EXPECT_NE(gert::OpImplRegistry::GetInstance().GetOpImpl(opType.c_str()), nullptr);
    if (gert::OpImplRegistry::GetInstance().GetOpImpl(opType.c_str()) == nullptr) {
        return result;
    }

    auto tiling_func = gert::OpImplRegistry::GetInstance().GetOpImpl(opType.c_str())->tiling;

    auto param = gert::TilingData::CreateCap(4096);
    auto workspace_size_holer = gert::ContinuousVector::Create<size_t>(4096);
    auto ws_size = reinterpret_cast<gert::ContinuousVector*>(workspace_size_holer.get());
    EXPECT_NE(param, nullptr);
    if (param == nullptr) {
        return result;
    }

    gert::StorageShape varStorage = {args.varShape, args.varShape};
    gert::StorageShape msStorage = {args.msShape, args.msShape};
    gert::StorageShape momStorage = {args.momShape, args.momShape};
    gert::StorageShape lrStorage = {args.lrShape, args.lrShape};
    gert::StorageShape rhoStorage = {args.rhoShape, args.rhoShape};
    gert::StorageShape momentumStorage = {args.momentumShape, args.momentumShape};
    gert::StorageShape epsilonStorage = {args.epsilonShape, args.epsilonShape};
    gert::StorageShape gradStorage = {args.gradShape, args.gradShape};

    InplaceApplyRMSPropUtCompileInfo compileInfo;
    auto holder = BuildTilingContext(args, platFormInfo, varStorage, msStorage, momStorage, lrStorage, rhoStorage,
                                     momentumStorage, epsilonStorage, gradStorage, compileInfo, param.get(), ws_size);

    gert::TilingContext* tiling_context = holder.GetContext<gert::TilingContext>();
    EXPECT_NE(tiling_context->GetPlatformInfo(), nullptr);
    holder.GetContext<gert::TilingContext>()->GetPlatformInfo()->SetPlatformRes("SoCInfo", socInfos);
    holder.GetContext<gert::TilingContext>()->GetPlatformInfo()->SetPlatformRes("AICoreSpec", aicoreSpec);
    holder.GetContext<gert::TilingContext>()->GetPlatformInfo()->SetCoreNumByCoreType("AICore");
    holder.GetContext<gert::TilingContext>()->GetPlatformInfo()->SetPlatformRes("AICoreintrinsicDtypeMap", intrinsics);
    tiling_context->GetPlatformInfo()->SetPlatformRes("version", socVersion);

    result.status = tiling_func(tiling_context);
    if (result.status == ge::GRAPH_SUCCESS) {
        ReadTilingResult(tiling_context, result);
    }
    return result;
}

