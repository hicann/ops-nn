template <typename T, int BUFFER_MODE>
static void LaunchInplaceApplyRmsPropOnce(size_t totalNum, float lrVal, float rhoVal, float momentumVal,
                                          float epsilonVal, float varVal, float msVal, float momVal, float gradVal,
                                          std::vector<uint8_t>& outVar, std::vector<uint8_t>& outMs,
                                          std::vector<uint8_t>& outMom)
{
    constexpr size_t kElemSize = sizeof(T);
    const size_t mainBytes = totalNum * kElemSize;
    const size_t scalarBytes = 1 * kElemSize;

    uint8_t* var = (uint8_t*)AscendC::GmAlloc(mainBytes);
    uint8_t* ms = (uint8_t*)AscendC::GmAlloc(mainBytes);
    uint8_t* mom = (uint8_t*)AscendC::GmAlloc(mainBytes);
    uint8_t* lr = (uint8_t*)AscendC::GmAlloc(scalarBytes);
    uint8_t* rho = (uint8_t*)AscendC::GmAlloc(scalarBytes);
    uint8_t* momentum = (uint8_t*)AscendC::GmAlloc(scalarBytes);
    uint8_t* epsilon = (uint8_t*)AscendC::GmAlloc(scalarBytes);
    uint8_t* grad = (uint8_t*)AscendC::GmAlloc(mainBytes);
    uint8_t* var_out = (uint8_t*)AscendC::GmAlloc(mainBytes);
    uint8_t* ms_out = (uint8_t*)AscendC::GmAlloc(mainBytes);
    uint8_t* mom_out = (uint8_t*)AscendC::GmAlloc(mainBytes);

    uint8_t* workspace = (uint8_t*)AscendC::GmAlloc(16 * 1024 * 1024);
    uint8_t* tiling = (uint8_t*)AscendC::GmAlloc(sizeof(InplaceApplyRmsPropTilingData));

    FillArray<T>(var, totalNum, varVal);
    FillArray<T>(ms, totalNum, msVal);
    FillArray<T>(mom, totalNum, momVal);
    FillArray<T>(grad, totalNum, gradVal);
    FillArray<T>(var_out, totalNum, 0.0f);
    FillArray<T>(ms_out, totalNum, 0.0f);
    FillArray<T>(mom_out, totalNum, 0.0f);
    FillScalar<T>(lr, lrVal);
    FillScalar<T>(rho, rhoVal);
    FillScalar<T>(momentum, momentumVal);
    FillScalar<T>(epsilon, epsilonVal);

    auto* tilingData = reinterpret_cast<InplaceApplyRmsPropTilingData*>(tiling);
    tilingData->totalNum = static_cast<int64_t>(totalNum);
    tilingData->blockFactor = static_cast<int64_t>(totalNum > 0 ? totalNum : 1);
    tilingData->ubFactor = static_cast<int64_t>(totalNum >= 256 ? 256 : (totalNum > 0 ? totalNum : 1));

    AscendC::SetKernelMode(KernelMode::AIV_MODE);
    ICPU_SET_TILING_KEY(static_cast<uint64_t>(BUFFER_MODE) * 256);

    uint32_t blockDim = 1;
    auto KernelInplaceApplyRmsProp = [](GM_ADDR a, GM_ADDR b, GM_ADDR c, GM_ADDR d, GM_ADDR e, GM_ADDR f, GM_ADDR g,
                                        GM_ADDR h, GM_ADDR i, GM_ADDR j, GM_ADDR k, GM_ADDR l, GM_ADDR m) {
        ::inplace_apply_rms_prop<T, BUFFER_MODE>(a, b, c, d, e, f, g, h, i, j, k, l, m);
    };
    ICPU_RUN_KF(KernelInplaceApplyRmsProp, blockDim, var, ms, mom, lr, rho, momentum, epsilon, grad, var_out, ms_out,
                mom_out, workspace, tiling);

    outVar.assign(var_out, var_out + mainBytes);
    outMs.assign(ms_out, ms_out + mainBytes);
    outMom.assign(mom_out, mom_out + mainBytes);

    AscendC::GmFree(var);
    AscendC::GmFree(ms);
    AscendC::GmFree(mom);
    AscendC::GmFree(lr);
    AscendC::GmFree(rho);
    AscendC::GmFree(momentum);
    AscendC::GmFree(epsilon);
    AscendC::GmFree(grad);
    AscendC::GmFree(var_out);
    AscendC::GmFree(ms_out);
    AscendC::GmFree(mom_out);
    AscendC::GmFree(workspace);
    AscendC::GmFree(tiling);
}

