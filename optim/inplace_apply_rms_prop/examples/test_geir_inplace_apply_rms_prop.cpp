size_t GetDataTypeSize(DataType dt)
{
    size_t dilation = 1;
    constexpr size_t oneByte = 1;
    constexpr size_t twoByte = 2;
    constexpr size_t fourByte = 4;
    constexpr size_t eightByte = 8;

    if (dt == ge::DT_FLOAT) {
        dilation = fourByte;
    } else if (dt == ge::DT_FLOAT16) {
        dilation = twoByte;
    } else if (dt == ge::DT_BF16) {
        dilation = twoByte;
    } else if (dt == ge::DT_INT16) {
        dilation = twoByte;
    } else if (dt == ge::DT_UINT16) {
        dilation = twoByte;
    } else if (dt == ge::DT_INT32) {
        dilation = fourByte;
    } else if (dt == ge::DT_UINT32) {
        dilation = fourByte;
    } else if (dt == ge::DT_INT64) {
        dilation = eightByte;
    } else if (dt == ge::DT_UINT64) {
        dilation = eightByte;
    } else if (dt == ge::DT_INT8) {
        dilation = oneByte;
    }
    return dilation;
}

int32_t GenFloatData(const vector<int64_t>& shapes, Tensor& inputTensor, TensorDesc& inputTensorDesc, DataType dataType,
                     float value)
{
    if (dataType != ge::DT_FLOAT) {
        printf("GenFloatData: this example only generates float input data\n");
        return FAILED;
    }
    inputTensorDesc.SetRealDimCnt(shapes.size());
    size_t size = 1;
    for (int64_t dim : shapes) {
        size *= static_cast<size_t>(dim);
    }
    gInputBuffers.emplace_back(size, value);
    auto& data = gInputBuffers.back();
    inputTensor = Tensor(inputTensorDesc, reinterpret_cast<uint8_t*>(data.data()), data.size() * sizeof(float));
    return SUCCESS;
}

int32_t WriteDataToFile(const string& binFile, uint64_t dataSize, const uint8_t* inputData)
{
    FILE* fp = fopen(binFile.c_str(), "wb");
    if (fp == nullptr) {
        printf("WriteDataToFile: fopen failed for %s\n", binFile.c_str());
        return FAILED;
    }
    size_t written = fwrite(inputData, sizeof(uint8_t), dataSize, fp);
    fclose(fp);
    if (written != dataSize) {
        printf("WriteDataToFile: short write %zu/%lu\n", written, dataSize);
        return FAILED;
    }
    return SUCCESS;
}

template <typename SetterFn>
int32_t AddDataInput(int placeholderIndex, SetterFn portSetter, DataType dtype, const vector<int64_t>& shape,
                     float fillValue, Graph& graph, std::vector<ge::Tensor>& input, std::vector<Operator>& inputs)
{
    std::string name = "placeholder" + std::to_string(placeholderIndex);
    auto data = op::Data(name.c_str()).set_attr_index(placeholderIndex);
    TensorDesc desc = TensorDesc(ge::Shape(shape), FORMAT_ND, dtype);
    desc.SetFormat(FORMAT_ND);
    desc.SetOriginFormat(FORMAT_ND);
    desc.SetOriginShape(ge::Shape(shape));
    Tensor tensor;
    Status ret = GenFloatData(shape, tensor, desc, dtype, fillValue);
    if (ret != SUCCESS) {
        printf("%s - ERROR - [XIR]: Generate input data failed for %s\n", GetTime().c_str(), name.c_str());
        return FAILED;
    }
    data.update_input_desc_x(desc);
    data.update_output_desc_y(desc);
    input.push_back(tensor);
    graph.AddOp(data);
    portSetter(data);
    inputs.push_back(data);
    return SUCCESS;
}

int CreateOppInGraph(DataType inDtype, std::vector<ge::Tensor>& input, std::vector<Operator>& inputs,
                     std::vector<Operator>& outputs, Graph& graph)
{
    auto rmsprop = op::InplaceApplyRMSProp("inplace_apply_rms_prop1");

    std::vector<int64_t> tensorShape = {2, 4, 4, 4};
    std::vector<int64_t> scalarShape = {1};

    int idx = 0;
    if (AddDataInput(
            idx++, [&](Operator& d) { rmsprop.set_input_var(d); }, inDtype, tensorShape, 1.0f, graph, input, inputs) !=
        SUCCESS) {
        return FAILED;
    }
    if (AddDataInput(
            idx++, [&](Operator& d) { rmsprop.set_input_ms(d); }, inDtype, tensorShape, 0.1f, graph, input, inputs) !=
        SUCCESS) {
        return FAILED;
    }
    if (AddDataInput(
            idx++, [&](Operator& d) { rmsprop.set_input_mom(d); }, inDtype, tensorShape, 0.0f, graph, input, inputs) !=
        SUCCESS) {
        return FAILED;
    }
    if (AddDataInput(
            idx++, [&](Operator& d) { rmsprop.set_input_lr(d); }, inDtype, scalarShape, 0.01f, graph, input, inputs) !=
        SUCCESS) {
        return FAILED;
    }
    if (AddDataInput(
            idx++, [&](Operator& d) { rmsprop.set_input_rho(d); }, inDtype, scalarShape, 0.9f, graph, input, inputs) !=
        SUCCESS) {
        return FAILED;
    }
    if (AddDataInput(
            idx++, [&](Operator& d) { rmsprop.set_input_momentum(d); }, inDtype, scalarShape, 0.0f, graph, input,
            inputs) != SUCCESS) {
        return FAILED;
    }
    if (AddDataInput(
            idx++, [&](Operator& d) { rmsprop.set_input_epsilon(d); }, inDtype, scalarShape, 1e-7f, graph, input,
            inputs) != SUCCESS) {
        return FAILED;
    }
    if (AddDataInput(
            idx++, [&](Operator& d) { rmsprop.set_input_grad(d); }, inDtype, tensorShape, 0.2f, graph, input, inputs) !=
        SUCCESS) {
        return FAILED;
    }

    rmsprop.set_attr_use_locking(false);

    TensorDesc varOutDesc = TensorDesc(ge::Shape(tensorShape), FORMAT_ND, inDtype);
    TensorDesc msOutDesc = TensorDesc(ge::Shape(tensorShape), FORMAT_ND, inDtype);
    TensorDesc momOutDesc = TensorDesc(ge::Shape(tensorShape), FORMAT_ND, inDtype);
    rmsprop.update_output_desc_var(varOutDesc);
    rmsprop.update_output_desc_ms(msOutDesc);
    rmsprop.update_output_desc_mom(momOutDesc);

    outputs.push_back(rmsprop);
    return SUCCESS;
}

int main(int argc, char* argv[])
{
    const char* graph_name = "tc_inplace_apply_rms_prop_ge_irrun_test";
    Graph graph(graph_name);
    std::vector<ge::Tensor> input;

    printf("%s - INFO - [XIR]: Start to initialize ge using ge global options\n", GetTime().c_str());
    std::map<AscendString, AscendString> global_options = {{"ge.exec.deviceId", "0"}, {"ge.graphRunMode", "1"}};
    Status ret = ge::GEInitialize(global_options);
    if (ret != SUCCESS) {
        printf("%s - INFO - [XIR]: Initialize ge using ge global options failed\n", GetTime().c_str());
        return FAILED;
    }
    printf("%s - INFO - [XIR]: Initialize ge using ge global options success\n", GetTime().c_str());

    std::vector<Operator> inputs{};
    std::vector<Operator> outputs{};

    if (argc > 1) {
        std::cout << "device id arg: " << argv[1] << std::endl;
    }

    DataType inDtype = DT_FLOAT;
    std::cout << "input dtype: " << inDtype << std::endl;

    ret = CreateOppInGraph(inDtype, input, inputs, outputs, graph);
    if (ret != SUCCESS) {
        printf("%s - ERROR - [XIR]: Create ir session using build options failed\n", GetTime().c_str());
        GEFinalize();
        return FAILED;
    }

    if (!inputs.empty() && !outputs.empty()) {
        graph.SetInputs(inputs).SetOutputs(outputs);
    }

    std::map<AscendString, AscendString> build_options = {};
    printf("%s - INFO - [XIR]: Start to create ir session using build options\n", GetTime().c_str());
    std::unique_ptr<ge::Session> session(new (std::nothrow) Session(build_options));

    if (session == nullptr) {
        printf("%s - ERROR - [XIR]: Create ir session using build options failed\n", GetTime().c_str());
        GEFinalize();
        return FAILED;
    }
    printf("%s - INFO - [XIR]: Create ir session using build options success\n", GetTime().c_str());
    printf("%s - INFO - [XIR]: Start to add compute graph to ir session\n", GetTime().c_str());

    std::map<AscendString, AscendString> graph_options = {};
    uint32_t graph_id = 0;
    ret = session->AddGraph(graph_id, graph, graph_options);
    if (ret != SUCCESS) {
        printf("%s - ERROR - [XIR]: Add graph failed\n", GetTime().c_str());
        session.reset();
        GEFinalize();
        return FAILED;
    }

    printf("%s - INFO - [XIR]: Session add ir compute graph to ir session success\n", GetTime().c_str());
    printf("%s - INFO - [XIR]: dump graph to txt\n", GetTime().c_str());
    std::string file_path = "./dump";
    aclgrphDumpGraph(graph, file_path.c_str(), file_path.length());
    printf("%s - INFO - [XIR]: Start to run ir compute graph\n", GetTime().c_str());
    std::vector<ge::Tensor> output;
    ret = session->RunGraph(graph_id, input, output);
    if (ret != SUCCESS) {
        printf("%s - INFO - [XIR]: Run graph failed\n", GetTime().c_str());
        session.reset();
        GEFinalize();
        return FAILED;
    }
    printf("%s - INFO - [XIR]: Session run ir compute graph success\n", GetTime().c_str());

    const size_t input_num = input.size();
    for (size_t i = 0; i < input_num; ++i) {
        std::cout << "input " << i << " dtype :  " << input[i].GetTensorDesc().GetDataType() << std::endl;
        string input_file = "./tc_inplace_apply_rms_prop_ge_irrun_test_npu_input_" + std::to_string(i) + ".bin";
        uint8_t* input_data_i = input[i].GetData();
        int64_t input_shape = input[i].GetTensorDesc().GetShape().GetShapeSize();
        std::cout << "this is " << i << "th input, input shape size =" << input_shape << std::endl;
        if (input_shape < 0) {
            printf("%s - ERROR - [XIR]: Input %zu has an invalid shape size\n", GetTime().c_str(), i);
            session.reset();
            GEFinalize();
            return FAILED;
        }
        const uint64_t data_size = static_cast<uint64_t>(input_shape) *
                                   GetDataTypeSize(input[i].GetTensorDesc().GetDataType());
        if (WriteDataToFile(input_file, data_size, input_data_i) != SUCCESS) {
            session.reset();
            GEFinalize();
            return FAILED;
        }
    }

    const size_t output_num = output.size();
    if (output_num != 3) {
        printf("%s - ERROR - [XIR]: Expected 3 outputs, got %zu\n", GetTime().c_str(), output_num);
        session.reset();
        GEFinalize();
        return FAILED;
    }
    for (size_t i = 0; i < output_num; ++i) {
        std::cout << "output " << i << " dtype :  " << output[i].GetTensorDesc().GetDataType() << std::endl;
        string output_file = "./tc_inplace_apply_rms_prop_ge_irrun_test_npu_output_" + std::to_string(i) + ".bin";
        uint8_t* output_data_i = output[i].GetData();
        int64_t output_shape = output[i].GetTensorDesc().GetShape().GetShapeSize();
        std::cout << "this is " << i << "th output, output shape size =" << output_shape << std::endl;
        if (output_shape < 0) {
            printf("%s - ERROR - [XIR]: Output %zu has an invalid shape size\n", GetTime().c_str(), i);
            session.reset();
            GEFinalize();
            return FAILED;
        }
        const uint64_t data_size = static_cast<uint64_t>(output_shape) *
                                   GetDataTypeSize(output[i].GetTensorDesc().GetDataType());
        if (WriteDataToFile(output_file, data_size, output_data_i) != SUCCESS) {
            session.reset();
            GEFinalize();
            return FAILED;
        }
    }

    ge::AscendString error_msg = ge::GEGetErrorMsgV2();
    std::string error_str(error_msg.GetString());
    std::cout << "Error message: " << error_str << std::endl;
    ge::AscendString warning_msg = ge::GEGetWarningMsgV2();
    std::string warning_str(warning_msg.GetString());
    std::cout << "Warning message: " << warning_str << std::endl;
    printf("%s - INFO - [XIR]: Generated all graph outputs\n", GetTime().c_str());
    printf("%s - INFO - [XIR]: Start to finalize ir graph session\n", GetTime().c_str());
    session.reset();
    ret = ge::GEFinalize();
    if (ret != SUCCESS) {
        printf("%s - INFO - [XIR]: Finalize ir graph session failed\n", GetTime().c_str());
        return FAILED;
    }
    printf("%s - INFO - [XIR]: Finalize ir graph session success\n", GetTime().c_str());
    return SUCCESS;
}
