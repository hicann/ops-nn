template <typename T>
static void FillScalar(uint8_t* address, float value)
{
    const T convertedValue(value);
    std::memcpy(address, &convertedValue, sizeof(convertedValue));
}

template <typename T>
static void FillTensor(uint8_t* address, size_t elementCount, float value)
{
    for (size_t i = 0; i < elementCount; ++i) {
        FillScalar<T>(address + i * sizeof(T), value);
    }
}

struct KernelOutputs {
    std::vector<uint8_t> var;
    std::vector<uint8_t> accum;
    std::vector<uint8_t> accumUpdate;
};

template <typename T>
static void ExpectOutputSizes(const KernelOutputs& outputs, size_t totalNum)
{
    EXPECT_EQ(outputs.var.size(), totalNum * sizeof(T));
    EXPECT_EQ(outputs.accum.size(), totalNum * sizeof(T));
    EXPECT_EQ(outputs.accumUpdate.size(), totalNum * sizeof(T));
}

template <typename T, int BUFFER_MODE>
static KernelOutputs RunKernel(size_t totalNum)
{
    const size_t backingElements = totalNum == 0 ? 1 : totalNum;
    const size_t mainBytes = backingElements * sizeof(T);
    const size_t scalarBytes = sizeof(T);

    uint8_t* var = static_cast<uint8_t*>(AscendC::GmAlloc(mainBytes));
    uint8_t* accum = static_cast<uint8_t*>(AscendC::GmAlloc(mainBytes));
    uint8_t* accumUpdate = static_cast<uint8_t*>(AscendC::GmAlloc(mainBytes));
    uint8_t* lr = static_cast<uint8_t*>(AscendC::GmAlloc(scalarBytes));
    uint8_t* rho = static_cast<uint8_t*>(AscendC::GmAlloc(scalarBytes));
    uint8_t* epsilon = static_cast<uint8_t*>(AscendC::GmAlloc(scalarBytes));
    uint8_t* grad = static_cast<uint8_t*>(AscendC::GmAlloc(mainBytes));
    uint8_t* varOut = var;
    uint8_t* accumOut = accum;
    uint8_t* accumUpdateOut = accumUpdate;
    uint8_t* workspace = static_cast<uint8_t*>(AscendC::GmAlloc(16 * 1024 * 1024));
    uint8_t* tiling = static_cast<uint8_t*>(AscendC::GmAlloc(sizeof(InplaceApplyAdadeltaTilingData)));

    FillTensor<T>(var, backingElements, totalNum == 0 ? 7.0f : 1.0f);
    FillTensor<T>(accum, backingElements, totalNum == 0 ? 11.0f : 0.1f);
    FillTensor<T>(accumUpdate, backingElements, totalNum == 0 ? 13.0f : 0.05f);
    FillTensor<T>(grad, backingElements, 0.2f);
    FillScalar<T>(lr, 0.01f);
    FillScalar<T>(rho, 0.9f);
    FillScalar<T>(epsilon, 1e-4f);

    auto* tilingData = reinterpret_cast<InplaceApplyAdadeltaTilingData*>(tiling);
    tilingData->totalNum = static_cast<int64_t>(totalNum);
    tilingData->blockFactor = static_cast<int64_t>(totalNum == 0 ? 0 : totalNum);
    tilingData->ubFactor = static_cast<int64_t>(totalNum >= 256 ? 256 : 64);
    tilingData->useLocking = 0;
    tilingData->reserved = 0;

    AscendC::SetKernelMode(KernelMode::AIV_MODE);
    ICPU_SET_TILING_KEY(static_cast<uint64_t>(BUFFER_MODE));
    uint32_t blockDim = 1;
    auto kernel = [](GM_ADDR a, GM_ADDR b, GM_ADDR c, GM_ADDR d, GM_ADDR e, GM_ADDR f, GM_ADDR g, GM_ADDR h, GM_ADDR i,
                     GM_ADDR j, GM_ADDR ws,
                     GM_ADDR td) { ::inplace_apply_adadelta<T, BUFFER_MODE>(a, b, c, d, e, f, g, h, i, j, ws, td); };
    ICPU_RUN_KF(kernel, blockDim, var, accum, accumUpdate, lr, rho, epsilon, grad, varOut, accumOut, accumUpdateOut,
                workspace, tiling);

    KernelOutputs outputs;
    outputs.var.assign(varOut, varOut + mainBytes);
    outputs.accum.assign(accumOut, accumOut + mainBytes);
    outputs.accumUpdate.assign(accumUpdateOut, accumUpdateOut + mainBytes);

    AscendC::GmFree(var);
    AscendC::GmFree(accum);
    AscendC::GmFree(accumUpdate);
    AscendC::GmFree(lr);
    AscendC::GmFree(rho);
    AscendC::GmFree(epsilon);
    AscendC::GmFree(grad);
    AscendC::GmFree(workspace);
    AscendC::GmFree(tiling);
    return outputs;
}

class InplaceApplyAdadeltaKernelTest : public testing::Test {
protected:
    static void SetUpTestCase() { cout << "InplaceApplyAdadeltaKernelTest SetUp" << endl; }

    static void TearDownTestCase() { cout << "InplaceApplyAdadeltaKernelTest TearDown" << endl; }
};

TEST_F(InplaceApplyAdadeltaKernelTest, fp32_single_buffer)
{
    constexpr size_t kTotalNum = 256;
    const auto outputs = RunKernel<float, 0>(kTotalNum);
    // TIK CPU mode does not execute the FTZ Compare/Select sequence or
    // guarantee DataCopyPad GM write-back. This UT therefore owns dispatch,
    // scalar-address, buffer-mode and no-crash coverage. Golden + TTK on real
    // hardware own numerical correctness.
    ExpectOutputSizes<float>(outputs, kTotalNum);
}

TEST_F(InplaceApplyAdadeltaKernelTest, fp32_double_buffer)
{
    constexpr size_t kTotalNum = 2048;
    const auto outputs = RunKernel<float, 1>(kTotalNum);
    ExpectOutputSizes<float>(outputs, kTotalNum);
}

TEST_F(InplaceApplyAdadeltaKernelTest, fp16_scalar_gm_load)
{
    constexpr size_t kTotalNum = 256;
    const auto outputs = RunKernel<half, 0>(kTotalNum);
    ExpectOutputSizes<half>(outputs, kTotalNum);
}

TEST_F(InplaceApplyAdadeltaKernelTest, empty_tensor_is_no_op)
{
    const auto outputs = RunKernel<float, 0>(0);
    ASSERT_EQ(outputs.var.size(), sizeof(float));
    ASSERT_EQ(outputs.accum.size(), sizeof(float));
    ASSERT_EQ(outputs.accumUpdate.size(), sizeof(float));
    EXPECT_FLOAT_EQ(*reinterpret_cast<const float*>(outputs.var.data()), 7.0f);
    EXPECT_FLOAT_EQ(*reinterpret_cast<const float*>(outputs.accum.data()), 11.0f);
    EXPECT_FLOAT_EQ(*reinterpret_cast<const float*>(outputs.accumUpdate.data()), 13.0f);
}
