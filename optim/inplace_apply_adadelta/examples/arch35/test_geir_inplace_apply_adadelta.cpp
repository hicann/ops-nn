uint32_t GetDataTypeSize(DataType dt)
{
    uint32_t dilation = 1;
    uint32_t oneByte = 1;
    uint32_t twoByte = 2;
    uint32_t fourByte = 4;
    uint32_t eightByte = 8;

    if (dt == ge::DT_FLOAT) {
        dilation = fourByte;
    } else if (dt == ge::DT_FLOAT16) {
        dilation = twoByte;
    } else if (dt == ge::DT_BF16) {
        dilation = twoByte;
    } else if (dt == ge::DT_INT16) {
        dilation = twoByte;
    } else if (dt == ge::DT_UINT16) {
        dilation = twoByte;
    } else if (dt == ge::DT_INT32) {
        dilation = fourByte;
    } else if (dt == ge::DT_UINT32) {
        dilation = fourByte;
    } else if (dt == ge::DT_INT64) {
        dilation = eightByte;
    } else if (dt == ge::DT_UINT64) {
        dilation = eightByte;
    } else if (dt == ge::DT_INT8) {
        dilation = oneByte;
    }
    return dilation;
}

static uint16_t FloatToHalfBits(float value)
{
    uint32_t bits = 0;
    std::memcpy(&bits, &value, sizeof(bits));
    const uint32_t sign = (bits >> 16) & 0x8000U;
    int32_t exponent = static_cast<int32_t>((bits >> 23) & 0xFFU) - 127 + 15;
    uint32_t mantissa = bits & 0x7FFFFFU;

    if (exponent <= 0) {
        if (exponent < -10) {
            return static_cast<uint16_t>(sign);
        }
        mantissa = (mantissa | 0x800000U) >> (1 - exponent);
        if ((mantissa & 0x1000U) != 0) {
            mantissa += 0x2000U;
        }
        return static_cast<uint16_t>(sign | (mantissa >> 13));
    }
    if (exponent >= 31) {
        return static_cast<uint16_t>(sign | 0x7C00U | (mantissa != 0 ? 0x0200U : 0U));
    }
    if ((mantissa & 0x1000U) != 0) {
        mantissa += 0x2000U;
        if ((mantissa & 0x800000U) != 0) {
            mantissa = 0;
            ++exponent;
            if (exponent >= 31) {
                return static_cast<uint16_t>(sign | 0x7C00U);
            }
        }
    }
    return static_cast<uint16_t>(sign | (static_cast<uint32_t>(exponent) << 10) | (mantissa >> 13));
}

int32_t GenFloatData(const vector<int64_t>& shapes, Tensor& input_tensor, TensorDesc& input_tensor_desc,
                     DataType data_type, float value)
{
    input_tensor_desc.SetRealDimCnt(shapes.size());
    size_t size = 1;
    for (uint32_t i = 0; i < shapes.size(); i++) {
        size *= shapes[i];
    }
    if (data_type != ge::DT_FLOAT && data_type != ge::DT_FLOAT16) {
        printf("GenFloatData: unsupported dtype=%d\n", static_cast<int>(data_type));
        return FAILED;
    }

    const uint32_t element_size = GetDataTypeSize(data_type);
    const uint32_t data_len = static_cast<uint32_t>(size * element_size);
    std::vector<uint8_t> data(data_len);
    for (size_t i = 0; i < size; ++i) {
        if (data_type == ge::DT_FLOAT) {
            std::memcpy(data.data() + i * element_size, &value, sizeof(value));
        } else {
            const uint16_t halfValue = FloatToHalfBits(value);
            std::memcpy(data.data() + i * element_size, &halfValue, sizeof(halfValue));
        }
    }
    input_tensor = Tensor(input_tensor_desc, data.data(), data_len);
    return SUCCESS;
}

int32_t WriteDataToFile(string bin_file, uint64_t data_size, uint8_t* inputData)
{
    FILE* fp = fopen(bin_file.c_str(), "wb");
    if (fp == nullptr) {
        printf("WriteDataToFile: fopen failed for %s\n", bin_file.c_str());
        return FAILED;
    }
    size_t written = fwrite(inputData, sizeof(uint8_t), data_size, fp);
    fclose(fp);
    if (written != data_size) {
        printf("WriteDataToFile: short write %zu/%lu\n", written, data_size);
        return FAILED;
    }
    return SUCCESS;
}

static bool SameShape(const vector<int64_t>& expected, const ge::Shape& actual)
{
    if (expected.size() != actual.GetDimNum()) {
        return false;
    }
    for (size_t i = 0; i < expected.size(); ++i) {
        if (expected[i] != actual.GetDim(i)) {
            return false;
        }
    }
    return true;
}

static bool VerifyConstantOutput(const ge::Tensor& output, const vector<int64_t>& expectedShape, DataType expectedDtype,
                                 float expectedValue, const char* name)
{
    const auto& desc = output.GetTensorDesc();
    if (!SameShape(expectedShape, desc.GetShape()) || desc.GetDataType() != expectedDtype) {
        printf("[FAIL] %s metadata mismatch\n", name);
        return false;
    }
    const float* data = reinterpret_cast<const float*>(output.GetData());
    if (data == nullptr) {
        printf("[FAIL] %s output data is null\n", name);
        return false;
    }
    const size_t count = static_cast<size_t>(desc.GetShape().GetShapeSize());
    constexpr float rtol = 1.22e-4F;
    constexpr float atol = 1.22e-4F;
    for (size_t i = 0; i < count; ++i) {
        const float tolerance = atol + rtol * std::fabs(expectedValue);
        if (std::fabs(data[i] - expectedValue) > tolerance) {
            printf("[FAIL] %s[%zu]: expected=%.8g actual=%.8g tolerance=%.4e\n", name, i, expectedValue, data[i],
                   tolerance);
            return false;
        }
    }
    return true;
}

// 构造一个 GE Data 输入（host 占位，device 填充 tensor），并绑定到 op 的指定输入端口
//   placeholderIndex : 占位索引（用于生成独立变量名）
//   portSetter       : op.set_input_<name>(data) 的函数
//   dtype            : 数据类型
//   shape            : shape
//   fillValue        : 填充的常数值
//   graph / input / inputs : 图、device tensor 列表、graph 输入端口列表
template <typename SetterFn>
int32_t AddDataInput(int placeholderIndex, SetterFn portSetter, DataType dtype, const vector<int64_t>& shape,
                     float fillValue, Graph& graph, std::vector<ge::Tensor>& input, std::vector<Operator>& inputs)
{
    std::string name = "placeholder" + std::to_string(placeholderIndex);
    auto data = op::Data(name.c_str()).set_attr_index(placeholderIndex);
    TensorDesc desc = TensorDesc(ge::Shape(shape), FORMAT_ND, dtype);
    desc.SetPlacement(ge::kPlacementHost);
    desc.SetFormat(FORMAT_ND);
    Tensor tensor;
    Status ret = GenFloatData(shape, tensor, desc, dtype, fillValue);
    if (ret != SUCCESS) {
        printf("%s - ERROR - [XIR]: Generate input data failed for %s\n", GetTime().c_str(), name.c_str());
        return FAILED;
    }
    data.update_input_desc_x(desc);
    input.push_back(tensor);
    graph.AddOp(data);
    portSetter(data);
    inputs.push_back(data);
    return SUCCESS;
}

int CreateOppInGraph(DataType inDtype, std::vector<ge::Tensor>& input, std::vector<Operator>& inputs,
                     std::vector<Operator>& outputs, Graph& graph)
{
    // 自定义代码：添加 InplaceApplyAdadelta 单算子定义到图中
    auto adadelta = op::InplaceApplyAdadelta("inplace_apply_adadelta_1");

    // shape 约定
    std::vector<int64_t> tensorShape = {2, 4, 4, 4}; // var / accum / accum_update / grad 的 shape（共 128 元素）
    std::vector<int64_t> scalarShape = {1};          // lr / rho / epsilon 的 shape

    int idx = 0;
    // 7 个输入 —— 顺序须与 REG_OP(InplaceApplyAdadelta) 的 .INPUT 顺序一致
    if (AddDataInput(
            idx++, [&](Operator& d) { adadelta.set_input_var(d); }, inDtype, tensorShape, 1.0f, graph, input, inputs) !=
        SUCCESS)
        return FAILED;
    if (AddDataInput(
            idx++, [&](Operator& d) { adadelta.set_input_accum(d); }, inDtype, tensorShape, 0.1f, graph, input,
            inputs) != SUCCESS)
        return FAILED;
    if (AddDataInput(
            idx++, [&](Operator& d) { adadelta.set_input_accum_update(d); }, inDtype, tensorShape, 0.05f, graph, input,
            inputs) != SUCCESS)
        return FAILED;
    if (AddDataInput(
            idx++, [&](Operator& d) { adadelta.set_input_lr(d); }, inDtype, scalarShape, 0.01f, graph, input, inputs) !=
        SUCCESS)
        return FAILED;
    if (AddDataInput(
            idx++, [&](Operator& d) { adadelta.set_input_rho(d); }, inDtype, scalarShape, 0.9f, graph, input, inputs) !=
        SUCCESS)
        return FAILED;
    if (AddDataInput(
            idx++, [&](Operator& d) { adadelta.set_input_epsilon(d); }, inDtype, scalarShape, 1e-6f, graph, input,
            inputs) != SUCCESS)
        return FAILED;
    if (AddDataInput(
            idx++, [&](Operator& d) { adadelta.set_input_grad(d); }, inDtype, tensorShape, 0.2f, graph, input,
            inputs) != SUCCESS)
        return FAILED;

    // bool 属性
    adadelta.set_attr_use_locking(false);

    // V2 三输出端口的 TensorDesc（var / accum / accum_update），shape/dtype 与对应输入一致
    // 三输出均 inplace alias 对应 INPUT，故 shape 全部等于 tensorShape。
    TensorDesc varOutDesc = TensorDesc(ge::Shape(tensorShape), FORMAT_ND, inDtype);
    adadelta.update_output_desc_var(varOutDesc);
    TensorDesc accumOutDesc = TensorDesc(ge::Shape(tensorShape), FORMAT_ND, inDtype);
    adadelta.update_output_desc_accum(accumOutDesc);
    TensorDesc accumUpdateOutDesc = TensorDesc(ge::Shape(tensorShape), FORMAT_ND, inDtype);
    adadelta.update_output_desc_accum_update(accumUpdateOutDesc);

    // V2 三输出全部接入 graph 输出端口
    outputs.push_back(adadelta);
    return SUCCESS;
}

