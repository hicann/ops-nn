// 生成填充指定值的 float Tensor（ND tensor 输入用）
static Tensor MakeNdTensor(const vector<int64_t>& shape, float fillValue, TensorDesc& desc)
{
    desc = TensorDesc(ge::Shape(shape), FORMAT_ND, DT_FLOAT);
    desc.SetPlacement(ge::kPlacementHost);
    desc.SetFormat(FORMAT_ND);
    desc.SetRealDimCnt(shape.size());
    size_t n = 1;
    for (auto d : shape) {
        n *= static_cast<size_t>(d);
    }
    std::vector<float> buf(n, fillValue);
    return Tensor(desc, reinterpret_cast<uint8_t*>(buf.data()), n * sizeof(float));
}

// 生成标量 float Tensor（lr/rho/momentum/epsilon 用，shape={1}）
static Tensor MakeScalarTensor(float value, TensorDesc& desc)
{
    vector<int64_t> shape = {1};
    desc = TensorDesc(ge::Shape(shape), FORMAT_ND, DT_FLOAT);
    desc.SetPlacement(ge::kPlacementHost);
    desc.SetFormat(FORMAT_ND);
    desc.SetRealDimCnt(shape.size());
    std::vector<float> buf = {value};
    return Tensor(desc, reinterpret_cast<uint8_t*>(buf.data()), buf.size() * sizeof(float));
}

// 添加一个 Data 输入节点（动态 shape 声明）
template <typename SetterFn, typename DescSetterFn>
static int AddDataInput(int index, const string& name, const vector<int64_t>& shape, DataType dtype,
                        SetterFn portSetter, DescSetterFn descSetter, Graph& graph, vector<Operator>& inputs)
{
    auto data = op::Data(name.c_str()).set_attr_index(index);
    TensorDesc desc = TensorDesc(ge::Shape(shape), FORMAT_ND, dtype);
    desc.SetFormat(FORMAT_ND);
    desc.SetRealDimCnt(shape.size());
    data.update_input_desc_x(desc);
    data.update_output_desc_y(desc);
    graph.AddOp(data);
    portSetter(data);
    descSetter(desc);
    inputs.push_back(data);
    return SUCCESS;
}

// 构建单算子图（动态 shape）
// tensorShape: ND tensor 的动态 shape 声明（-1 或 -2）
static int CreateOppInGraph(const vector<int64_t>& tensorShape, vector<Operator>& inputs, vector<Operator>& outputs,
                            Graph& graph)
{
    auto op1 = op::InplaceApplyCenteredRMSProp("inplace_apply_centered_rms_prop_dyn");
    op1.SetAttr("use_locking", false);

    DataType dtype = DT_FLOAT;
    vector<int64_t> scalarShape = {1};

    // 9 inputs — order must match REG_OP .INPUT order
    // var(0), mg(1), ms(2), mom(3), lr(4), rho(5), momentum(6), epsilon(7), grad(8)
    AddDataInput(
        0, "var", tensorShape, dtype, [&](Operator& d) { op1.set_input_var(d); },
        [&](const TensorDesc& d) { op1.update_input_desc_var(d); }, graph, inputs);
    AddDataInput(
        1, "mg", tensorShape, dtype, [&](Operator& d) { op1.set_input_mg(d); },
        [&](const TensorDesc& d) { op1.update_input_desc_mg(d); }, graph, inputs);
    AddDataInput(
        2, "ms", tensorShape, dtype, [&](Operator& d) { op1.set_input_ms(d); },
        [&](const TensorDesc& d) { op1.update_input_desc_ms(d); }, graph, inputs);
    AddDataInput(
        3, "mom", tensorShape, dtype, [&](Operator& d) { op1.set_input_mom(d); },
        [&](const TensorDesc& d) { op1.update_input_desc_mom(d); }, graph, inputs);
    AddDataInput(
        4, "lr", scalarShape, dtype, [&](Operator& d) { op1.set_input_lr(d); },
        [&](const TensorDesc& d) { op1.update_input_desc_lr(d); }, graph, inputs);
    AddDataInput(
        5, "rho", scalarShape, dtype, [&](Operator& d) { op1.set_input_rho(d); },
        [&](const TensorDesc& d) { op1.update_input_desc_rho(d); }, graph, inputs);
    AddDataInput(
        6, "momentum", scalarShape, dtype, [&](Operator& d) { op1.set_input_momentum(d); },
        [&](const TensorDesc& d) { op1.update_input_desc_momentum(d); }, graph, inputs);
    AddDataInput(
        7, "epsilon", scalarShape, dtype, [&](Operator& d) { op1.set_input_epsilon(d); },
        [&](const TensorDesc& d) { op1.update_input_desc_epsilon(d); }, graph, inputs);
    AddDataInput(
        8, "grad", tensorShape, dtype, [&](Operator& d) { op1.set_input_grad(d); },
        [&](const TensorDesc& d) { op1.update_input_desc_grad(d); }, graph, inputs);

    // 4 outputs (in-place alias, dynamic shape same as ND inputs)
    TensorDesc outDesc = TensorDesc(ge::Shape(tensorShape), FORMAT_ND, dtype);
    outDesc.SetFormat(FORMAT_ND);
    outDesc.SetRealDimCnt(tensorShape.size());
    op1.update_output_desc_var(outDesc);
    op1.update_output_desc_mg(outDesc);
    op1.update_output_desc_ms(outDesc);
    op1.update_output_desc_mom(outDesc);

    outputs.push_back(op1);
    return SUCCESS;
}

// 准备 9 个输入 Tensor（5 ND + 4 scalar），顺序匹配 Data index
static vector<ge::Tensor> MakeFeeds(const vector<int64_t>& actualShape)
{
    vector<ge::Tensor> feeds;
    TensorDesc desc;

    // 5 ND tensors: var, mg, ms, mom, grad
    feeds.push_back(MakeNdTensor(actualShape, 1.0f, desc));
    feeds.push_back(MakeNdTensor(actualShape, 0.05f, desc));
    feeds.push_back(MakeNdTensor(actualShape, 0.1f, desc));
    feeds.push_back(MakeNdTensor(actualShape, 0.0f, desc));

    // 4 scalar tensors: lr, rho, momentum, epsilon
    feeds.push_back(MakeScalarTensor(0.01f, desc));
    feeds.push_back(MakeScalarTensor(0.9f, desc));
    feeds.push_back(MakeScalarTensor(0.0f, desc));
    feeds.push_back(MakeScalarTensor(1e-7f, desc));

    // 5th ND tensor: grad
    feeds.push_back(MakeNdTensor(actualShape, 0.2f, desc));

    return feeds;
}

static bool VerifyOutputShape(const vector<int64_t>& expected, const ge::Shape& actual)
{
    if (expected.size() != actual.GetDimNum()) {
        return false;
    }
    for (size_t i = 0; i < expected.size(); ++i) {
        if (expected[i] != actual.GetDim(i)) {
            return false;
        }
    }
    return true;
}

static string ShapeToStr(const vector<int64_t>& shape)
{
    string s = "[";
    for (size_t i = 0; i < shape.size(); ++i) {
        s += std::to_string(shape[i]);
        if (i + 1 < shape.size())
            s += ",";
    }
    s += "]";
    return s;
}

// 运行一个动态 shape 场景：用 graphShape 构图，用 testShapes 逐个喂图
static int RunDynamicScenario(const string& scenarioName, const vector<int64_t>& graphShape,
                              const vector<vector<int64_t>>& testShapes)
{
    printf("\n%s\n", "============================================================");
    printf("%s - INFO - [XIR]: Scenario: %s, graph shape = %s\n", GetTime().c_str(), scenarioName.c_str(),
           ShapeToStr(graphShape).c_str());
    printf("%s\n", "============================================================");

    const char* graph_name = "inplace_apply_centered_rms_prop_geir_dynamic";
    Graph graph(graph_name);
    vector<Operator> inputs{};
    vector<Operator> outputs{};

    if (CreateOppInGraph(graphShape, inputs, outputs, graph) != SUCCESS) {
        printf("%s - ERROR - [XIR]: Create graph failed for %s\n", GetTime().c_str(), scenarioName.c_str());
        return FAILED;
    }
    graph.SetInputs(inputs).SetOutputs(outputs);

    std::map<AscendString, AscendString> build_options = {};
    ge::Session* session = new Session(build_options);
    if (session == nullptr) {
        printf("%s - ERROR - [XIR]: Create session failed\n", GetTime().c_str());
        return FAILED;
    }

    std::map<AscendString, AscendString> graph_options = {};
    uint32_t graph_id = 0;
    Status ret = session->AddGraph(graph_id, graph, graph_options);
    if (ret != SUCCESS) {
        printf("%s - ERROR - [XIR]: AddGraph failed for %s\n", GetTime().c_str(), scenarioName.c_str());
        ge::AscendString error_msg = ge::GEGetErrorMsgV2();
        std::cout << "Error message: " << error_msg.GetString() << std::endl;
        delete session;
        return FAILED;
    }
    printf("%s - INFO - [XIR]: AddGraph success (%s, shape=%s)\n", GetTime().c_str(), scenarioName.c_str(),
           ShapeToStr(graphShape).c_str());

    int passCount = 0;
    int failCount = 0;

    for (size_t t = 0; t < testShapes.size(); ++t) {
        const auto& shape = testShapes[t];
        printf("\n%s - INFO - [XIR]: [%s] Testing actual shape %s\n", GetTime().c_str(), scenarioName.c_str(),
               ShapeToStr(shape).c_str());

        vector<ge::Tensor> feeds = MakeFeeds(shape);
        vector<ge::Tensor> output;
        ret = session->RunGraph(graph_id, feeds, output);
        if (ret != SUCCESS) {
            printf("%s - ERROR - [XIR]: [%s] RunGraph failed for shape %s\n", GetTime().c_str(), scenarioName.c_str(),
                   ShapeToStr(shape).c_str());
            ge::AscendString error_msg = ge::GEGetErrorMsgV2();
            std::cout << "Error message: " << error_msg.GetString() << std::endl;
            failCount++;
            continue;
        }

        if (output.size() != 4) {
            printf("%s - ERROR - [XIR]: [%s] Expected 4 outputs, got %d\n", GetTime().c_str(), scenarioName.c_str(),
                   static_cast<int>(output.size()));
            failCount++;
            continue;
        }

        bool allMatch = true;
        const char* outNames[] = {"var", "mg", "ms", "mom"};
        for (int i = 0; i < 4; ++i) {
            auto outShape = output[i].GetTensorDesc().GetShape();
            bool match = VerifyOutputShape(shape, outShape);
            if (!match)
                allMatch = false;
            std::cout << "  output[" << i << "] (" << outNames[i] << ") shape = [";
            for (size_t k = 0; k < outShape.GetDimNum(); ++k) {
                std::cout << outShape.GetDim(k) << (k + 1 < outShape.GetDimNum() ? "," : "");
            }
            std::cout << "], dtype = " << output[i].GetTensorDesc().GetDataType() << (match ? " ✓" : " ✗") << std::endl;
        }

        if (allMatch) {
            printf("%s - INFO - [XIR]: [%s] shape %s PASSED\n", GetTime().c_str(), scenarioName.c_str(),
                   ShapeToStr(shape).c_str());
            passCount++;
        } else {
            printf("%s - ERROR - [XIR]: [%s] shape %s FAILED (shape mismatch)\n", GetTime().c_str(),
                   scenarioName.c_str(), ShapeToStr(shape).c_str());
            failCount++;
        }
    }

    printf("\n%s - INFO - [XIR]: [%s] summary: %d/%d passed\n", GetTime().c_str(), scenarioName.c_str(), passCount,
           static_cast<int>(testShapes.size()));

    delete session;
    return (failCount > 0) ? FAILED : SUCCESS;
}

int main(int argc, char* argv[])
{
    (void)argc;
    (void)argv;

    printf("%s - INFO - [XIR]: Start to initialize ge\n", GetTime().c_str());
    std::map<AscendString, AscendString> global_options = {{"ge.exec.deviceId", "0"}, {"ge.graphRunMode", "1"}};
    Status ret = ge::GEInitialize(global_options);
    if (ret != SUCCESS) {
        printf("%s - ERROR - [XIR]: Initialize ge failed\n", GetTime().c_str());
        return FAILED;
    }
    printf("%s - INFO - [XIR]: Initialize ge success\n", GetTime().c_str());

    int totalFail = 0;

    // ====================================================================
    // 场景一：-1（动态 shape，维度已知、每维大小未知）
    // graph 声明 shape = {-1, -1}，表示 2D 但每维大小未知
    // ====================================================================
    {
        vector<int64_t> graphShape = {-1, -1};
        vector<vector<int64_t>> testShapes = {{2, 4}, {8, 16}, {1, 128}, {4, 4}, {16, 32}};
        if (RunDynamicScenario("DynamicShape(-1)", graphShape, testShapes) != SUCCESS) {
            totalFail++;
        }
    }

    // ====================================================================
    // 场景二：-2（动态 rank，维度和大小均未知）
    // graph 声明 shape = {-2}，表示 rank 和每维大小均未知
    // ====================================================================
    {
        vector<int64_t> graphShape = {-2};
        vector<vector<int64_t>> testShapes = {{128}, {2, 64}, {4, 4, 8}, {2, 4, 4, 4}, {1, 1}};
        if (RunDynamicScenario("DynamicRank(-2)", graphShape, testShapes) != SUCCESS) {
            totalFail++;
        }
    }

    ret = ge::GEFinalize();
    if (ret != SUCCESS) {
        printf("%s - ERROR - [XIR]: Finalize failed\n", GetTime().c_str());
        return FAILED;
    }
    printf("%s - INFO - [XIR]: Finalize success\n", GetTime().c_str());

    if (totalFail > 0) {
        printf("\n%s - ERROR - [XIR]: Dynamic shape verification FAILED (%d scenario(s) failed)\n", GetTime().c_str(),
               totalFail);
        return FAILED;
    }

    printf("\n%s - INFO - [XIR]: Dynamic shape verification PASSED (all scenarios)\n", GetTime().c_str());
    return SUCCESS;
}
