// LoadScalarFromGm: 从 GM 装载 1 个标量到 UB 暂存区并转为 FP32
//   （直接对 1 元素 GM Tensor 使用 GetValue 在 arch35 真机会触发 MTE 越界，
//     必须先经 DataCopyPad 落 UB —— 与兄弟算子 inplace_apply_power_sign 一致）
