struct ExpectedTiling {
    uint32_t totalElements;
    uint32_t blockDim;
    uint32_t blockFormer;
    uint32_t blockNum;
    uint32_t ubFormer;
    uint32_t ubLoopOfFormerBlock;
    uint32_t ubTailOfFormerBlock;
    uint32_t ubLoopOfTailBlock;
    uint32_t ubTailOfTailBlock;
    uint32_t dtypeSize;
    uint32_t ctxBlockDim;
};

static int64_t UtCeilDiv(int64_t a, int64_t b) { return (a + b - 1) / b; }

static int64_t UtCeilAlign(int64_t a, int64_t b) { return UtCeilDiv(a, b) * b; }

static ExpectedTiling OracleComputeTiling(ge::DataType varDtype, const vector<int64_t>& varDims)
{
    ExpectedTiling exp{};
    uint32_t dtypeSize = (varDtype == ge::DT_FLOAT) ? 4U : 2U;
    uint32_t minDtypeBits = dtypeSize * 8;
    uint32_t bufferDivisor = (varDtype == ge::DT_FLOAT) ? UT_FP32_UB_BYTES_PER_ELEM : UT_HALF_UB_BYTES_PER_ELEM;

    int64_t totalElements = 1;
    for (int64_t d : varDims) {
        totalElements *= d;
    }
    if (totalElements == 0) {
        // 空 tensor 短路：字段全 0（含 dtypeSize），SetBlockDim(1)
        exp.ctxBlockDim = 1;
        return exp;
    }
    exp.dtypeSize = dtypeSize;

    // CalcUbTiling
    uint32_t maxElemNum = static_cast<uint32_t>(UT_UB_SIZE / bufferDivisor);
    maxElemNum = maxElemNum * UT_UB_USAGE_PERCENT / UT_PERCENTAGE_BASE;
    uint32_t alignFactor = UT_UB_ALIGN_BITS / minDtypeBits;
    exp.ubFormer = (maxElemNum / alignFactor) * alignFactor;
    if (exp.ubFormer == 0) {
        exp.ubFormer = alignFactor;
    }

    // CalcBlockTiling
    uint32_t calcCoreNum = static_cast<uint32_t>((totalElements * minDtypeBits + UT_MIN_TILING_BITS - 1) /
                                                 UT_MIN_TILING_BITS);
    calcCoreNum = std::min(calcCoreNum, static_cast<uint32_t>(UT_CORE_NUM));
    if (calcCoreNum == 0) {
        calcCoreNum = 1;
    }
    exp.blockFormer = static_cast<uint32_t>(UtCeilAlign(UtCeilDiv(totalElements, calcCoreNum), UT_ELEM_ALIGN_FACTOR));
    if (exp.blockFormer > exp.ubFormer) {
        exp.blockFormer = (exp.ubFormer / UT_ELEM_ALIGN_FACTOR) * UT_ELEM_ALIGN_FACTOR;
        if (exp.blockFormer == 0) {
            exp.blockFormer = UT_ELEM_ALIGN_FACTOR;
        }
    }
    exp.blockNum = static_cast<uint32_t>(UtCeilDiv(totalElements, exp.blockFormer));
    exp.blockDim = exp.blockNum;

    // CalcUbLoopInfo
    exp.ubLoopOfFormerBlock = static_cast<uint32_t>(UtCeilDiv(exp.blockFormer, exp.ubFormer));
    exp.ubTailOfFormerBlock = exp.blockFormer - (exp.ubLoopOfFormerBlock - 1) * exp.ubFormer;
    int64_t blockTail = totalElements - static_cast<int64_t>(exp.blockNum - 1) * exp.blockFormer;
    exp.ubLoopOfTailBlock = static_cast<uint32_t>(UtCeilDiv(blockTail, exp.ubFormer));
    exp.ubTailOfTailBlock = static_cast<uint32_t>(blockTail - (exp.ubLoopOfTailBlock - 1) * exp.ubFormer);

    exp.totalElements = static_cast<uint32_t>(totalElements);
    exp.ctxBlockDim = exp.blockDim;
    return exp;
}

