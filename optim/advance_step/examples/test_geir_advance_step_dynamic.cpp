GoldenOutputs ComputeV2Golden(const V2Feeds& feeds)
{
    const int64_t numSeqs = feeds.numSeqs;
    const int64_t blockSize = feeds.blockSize;
    const int64_t specNum = feeds.specNum;
    const int64_t ter = feeds.tokenEachReqs;
    const int64_t stride = feeds.btStride;

    GoldenOutputs out;
    out.tokens = feeds.inputTokens;
    out.positions = feeds.inputPositions;
    out.seqLens = feeds.seqLens;
    out.slotMapping = feeds.slotMapping;

    for (int64_t s = 0; s < numSeqs; ++s) {
        for (int64_t j = 0; j < ter; ++j) {
            const int64_t idx = s * ter + j;
            const int64_t pos = feeds.inputPositions[static_cast<size_t>(idx)] +
                                feeds.acceptedNum[static_cast<size_t>(s)] + 1;
            out.positions[static_cast<size_t>(idx)] = pos;
            out.seqLens[static_cast<size_t>(idx)] = pos + 1;
            const int64_t blockIndex = pos / blockSize;
            const int64_t blockOffset = pos % blockSize;
            out.slotMapping[static_cast<size_t>(
                idx)] = feeds.blockTables[static_cast<size_t>(s * stride + blockIndex)] * blockSize + blockOffset;
        }
        int64_t minIndex = ter; // sentinel appended after the row
        for (int64_t j = 0; j < ter; ++j) {
            if (feeds.sampledTokenIds[static_cast<size_t>(s * ter + j)] == -1) {
                minIndex = j;
                break;
            }
        }
        const int64_t lastToken = (minIndex == 0) ? -1 :
                                                    feeds.sampledTokenIds[static_cast<size_t>(s * ter + minIndex - 1)];
        out.tokens[static_cast<size_t>(s * ter)] = lastToken;
        for (int64_t j = 1; j < ter; ++j) {
            out.tokens[static_cast<size_t>(s * ter + j)] = feeds.specToken[static_cast<size_t>(s * specNum + (j - 1))];
        }
    }
    return out;
}

