// Helper: launch the kernel with the given dtype and BUFFER_MODE on the
// supplied shape. Allocates GM, sets up tiling, fills input data, runs
// the kernel and returns the (var, ms, mom) outputs by-reference for the
// caller to validate.
//
// The kernel reads main tensors var/ms/mom/grad and writes new var to
// var_out (which the caller aliases to var GM for inplace semantics).
