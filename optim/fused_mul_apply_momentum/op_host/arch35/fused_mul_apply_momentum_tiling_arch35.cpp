bool ShapeProductsFitInt64(const std::vector<int64_t>& dims)
{
    for (bool reverse : {false, true}) {
        int64_t product = 1;
        for (size_t i = 0; i < dims.size(); ++i) {
            int64_t dim = dims[reverse ? dims.size() - 1 - i : i];
            if (dim < 0) {
                return false;
            }
            if (dim == 0) {
                product = 1;
                continue;
            }
            if (product > std::numeric_limits<int64_t>::max() / dim) {
                return false;
            }
            product *= dim;
        }
    }
    return true;
}

