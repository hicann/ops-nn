bool FindSplitAxis(const std::vector<int64_t>& max_bro_shape, int64_t comp_dtype_size, int64_t copy_dtype_size,
                   int64_t ub_per_core, int64_t phys_nodes, SplitResult& out)
{
    int64_t per_buf_bytes = ((ub_per_core - kScalarBufBytes) / phys_nodes) & ~(kUBAlignBytes - 1);
    int64_t per_buf_elems = per_buf_bytes / comp_dtype_size;
    constexpr int64_t MAX_COUNT = 4096;
    if (per_buf_elems > MAX_COUNT) {
        per_buf_elems = MAX_COUNT;
    }
    if (per_buf_elems < 1) {
        per_buf_elems = 1;
    }
    int64_t rank = static_cast<int64_t>(max_bro_shape.size());
    int64_t inner = 1;
    for (int64_t k = rank - 1; k >= 0; k--) {
        if (max_bro_shape[k] * inner > per_buf_elems) {
            out.a_i = per_buf_elems / inner;
            if (inner == 1) {
                int64_t elem_align = kUBAlignBytes / copy_dtype_size;
                if (elem_align < 1) {
                    elem_align = 1;
                }
                out.a_i = (out.a_i / elem_align) * elem_align;
                if (out.a_i < 1) {
                    out.a_i = 1;
                }
            }
            out.a_o = max_bro_shape[k] / out.a_i + (max_bro_shape[k] % out.a_i != 0);
            int64_t rem = max_bro_shape[k] % out.a_i;
            out.a_i_tail = (rem == 0) ? out.a_i : rem;
            out.axis = k;
            return true;
        }
        if (k == 0) {
            out.axis = 0;
            out.a_i = max_bro_shape[0];
            out.a_o = 1;
            out.a_i_tail = max_bro_shape[0];
            return true;
        }
        inner *= max_bro_shape[k];
    }
    return true;
}

bool MultiCoreSplit(const std::vector<int64_t>& max_bro_shape, const SplitResult& ub_split, int64_t max_cores,
                    MultiCoreResult& out)
{
    int64_t k = ub_split.axis;
    int64_t outer_prod = 1;
    for (int64_t j = 0; j < k; j++)
        outer_prod *= max_bro_shape[j];
    out.total_tiles = outer_prod * ub_split.a_o;
    out.num_cores = (out.total_tiles < max_cores) ? out.total_tiles : max_cores;
    if (out.num_cores <= 0) {
        return false;
    }
    out.tiles_main = out.total_tiles / out.num_cores;
    out.cores_tail = out.total_tiles % out.num_cores;
    return true;
}

bool PrecomputeStrides(const std::vector<int64_t>& s, std::vector<int64_t>& strides)
{
    int64_t rank = static_cast<int64_t>(s.size());
    strides.assign(rank, 0);
    for (int64_t d = rank - 1; d >= 0; d--) {
        if (s[d] == 1) {
            strides[d] = 0;
            continue;
        }
        int64_t prod = 1;
        for (int64_t j = d + 1; j < rank; j++)
            prod *= s[j];
        strides[d] = prod;
    }
    return true;
}

