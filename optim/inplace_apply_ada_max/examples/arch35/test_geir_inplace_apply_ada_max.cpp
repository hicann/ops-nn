ge::Tensor MakeFp32Tensor(const std::vector<float>& data, const std::vector<int64_t>& shape)
{
    TensorDesc desc(ge::Shape(shape), FORMAT_ND, DT_FLOAT);
    desc.SetRealDimCnt(static_cast<int32_t>(shape.size()));
    return ge::Tensor(desc, reinterpret_cast<const uint8_t*>(data.data()), data.size() * sizeof(float));
}

ge::Tensor MakeFp32ScalarTensor(float value)
{
    std::vector<int64_t> scalar_shape = {1};
    TensorDesc desc(ge::Shape(scalar_shape), FORMAT_ND, DT_FLOAT);
    desc.SetRealDimCnt(1);
    return ge::Tensor(desc, reinterpret_cast<const uint8_t*>(&value), sizeof(float));
}

std::vector<float> GeTensorToFp32(const ge::Tensor& t)
{
    auto* data = t.GetData();
    auto size = t.GetSize();
    if (data == nullptr || size == 0) {
        auto desc = t.GetTensorDesc();
        auto shape = desc.GetShape();
        int64_t dims = 1;
        bool hasUnknown = false;
        for (size_t i = 0; i < shape.GetDimNum(); i++) {
            if (shape.GetDim(i) < 0) {
                hasUnknown = true;
                break;
            }
            dims *= shape.GetDim(i);
        }
        if (!hasUnknown && dims > 0) {
            size = static_cast<size_t>(dims) * sizeof(float);
        } else {
            return {};
        }
    }
    size_t n = size / sizeof(float);
    std::vector<float> out(n);
    std::memcpy(out.data(), data, size);
    return out;
}

void GoldenApplyAdaMax(const std::vector<double>& var, const std::vector<double>& m, const std::vector<double>& v,
                       double beta1_power, double lr, double beta1, double beta2, double epsilon,
                       const std::vector<double>& grad, std::vector<double>& var_new, std::vector<double>& m_new,
                       std::vector<double>& v_new)
{
    size_t n = var.size();
    var_new.resize(n);
    m_new.resize(n);
    v_new.resize(n);
    double lr_adj = lr / (1.0 - beta1_power);
    for (size_t i = 0; i < n; ++i) {
        m_new[i] = beta1 * m[i] + (1.0 - beta1) * grad[i];
        v_new[i] = std::max(beta2 * v[i], std::fabs(grad[i]));
        var_new[i] = var[i] - lr_adj * m_new[i] / (v_new[i] + epsilon);
    }
}

struct CompareResult {
    bool pass;
    size_t mismatch_count;
    double max_abs_err;
    double max_rel_err;
};

CompareResult CompareFp32(const std::vector<float>& golden, const std::vector<float>& actual, double rtol = 1e-5,
                          double atol = 1e-5)
{
    CompareResult r{true, 0, 0.0, 0.0};
    if (golden.size() != actual.size()) {
        r.pass = false;
        r.mismatch_count = std::max(golden.size(), actual.size());
        return r;
    }
    for (size_t i = 0; i < golden.size(); ++i) {
        double g = golden[i];
        double a = actual[i];
        if (std::isnan(g) || std::isnan(a)) {
            if (std::isnan(g) != std::isnan(a)) {
                r.pass = false;
                r.mismatch_count++;
            }
            continue;
        }
        if (std::isinf(g) || std::isinf(a)) {
            if (g != a) {
                r.pass = false;
                r.mismatch_count++;
            }
            continue;
        }
        double abs_err = std::fabs(a - g);
        double rel_err = (g != 0.0) ? abs_err / std::fabs(g) : 0.0;
        double threshold = atol + rtol * std::fabs(g);
        if (abs_err > threshold) {
            r.pass = false;
            r.mismatch_count++;
            if (r.mismatch_count <= 3) {
                LOG_PRINT("    mismatch[%zu]: golden=%.6f actual=%.6f abs_err=%.2e threshold=%.2e", i, g, a, abs_err,
                          threshold);
            }
        }
        r.max_abs_err = std::max(r.max_abs_err, abs_err);
        if (g != 0.0)
            r.max_rel_err = std::max(r.max_rel_err, rel_err);
    }
    return r;
}

struct TestInput {
    std::vector<float> var;
    std::vector<float> m;
    std::vector<float> v;
    std::vector<float> grad;
    float beta1_power;
    float lr;
    float beta1;
    float beta2;
    float epsilon;
    std::vector<int64_t> shape;
};

TestInput GenTestInput(uint32_t seed)
{
    TestInput ti;
    ti.shape = {4, 4};
    size_t n = 16;
    ti.var.resize(n);
    ti.m.resize(n);
    ti.v.resize(n);
    ti.grad.resize(n);
    std::mt19937 rng(seed);
    std::uniform_real_distribution<float> d1(-1.0f, 1.0f);
    std::uniform_real_distribution<float> d2(-0.1f, 0.1f);
    for (size_t i = 0; i < n; ++i) {
        ti.var[i] = d1(rng);
        ti.m[i] = d2(rng);
        ti.v[i] = d2(rng);
        ti.grad[i] = d2(rng);
    }
    ti.beta1_power = 0.1f;
    ti.lr = 0.01f;
    ti.beta1 = 0.9f;
    ti.beta2 = 0.999f;
    ti.epsilon = 1e-6f;
    return ti;
}

struct GeirOutput {
    std::vector<float> var_out;
    std::vector<float> m_out;
    std::vector<float> v_out;
    bool ok;
    std::string err_msg;
};

GeirOutput RunGeir(const TestInput& ti)
{
    GeirOutput out;
    out.ok = false;

    Graph graph("geir_inplace_apply_ada_max_example");
    auto op_inst = op::InplaceApplyAdaMax("inplace_apply_ada_max_op");

    ge::Tensor var_tensor = MakeFp32Tensor(ti.var, ti.shape);
    ge::Tensor m_tensor = MakeFp32Tensor(ti.m, ti.shape);
    ge::Tensor v_tensor = MakeFp32Tensor(ti.v, ti.shape);
    ge::Tensor beta1_power_tensor = MakeFp32ScalarTensor(ti.beta1_power);
    ge::Tensor lr_tensor = MakeFp32ScalarTensor(ti.lr);
    ge::Tensor beta1_tensor = MakeFp32ScalarTensor(ti.beta1);
    ge::Tensor beta2_tensor = MakeFp32ScalarTensor(ti.beta2);
    ge::Tensor epsilon_tensor = MakeFp32ScalarTensor(ti.epsilon);
    ge::Tensor grad_tensor = MakeFp32Tensor(ti.grad, ti.shape);

    auto make_data_op = [&](const std::string& data_name, const std::vector<int64_t>& shape) -> op::Data {
        TensorDesc desc(ge::Shape(shape), FORMAT_ND, DT_FLOAT);
        desc.SetRealDimCnt(static_cast<int32_t>(shape.size()));
        auto data_op = op::Data(data_name.c_str()).set_attr_index(0);
        data_op.update_input_desc_x(desc);
        data_op.update_output_desc_y(desc);
        graph.AddOp(data_op);
        return data_op;
    };

    auto var_op = make_data_op("data_var", ti.shape);
    auto m_op = make_data_op("data_m", ti.shape);
    auto v_op = make_data_op("data_v", ti.shape);
    auto b1p_op = make_data_op("data_beta1_power", {1});
    auto lr_op = make_data_op("data_lr", {1});
    auto b1_op = make_data_op("data_beta1", {1});
    auto b2_op = make_data_op("data_beta2", {1});
    auto eps_op = make_data_op("data_epsilon", {1});
    auto grad_op = make_data_op("data_grad", ti.shape);

    op_inst.set_input_var(var_op);
    op_inst.set_input_m(m_op);
    op_inst.set_input_v(v_op);
    op_inst.set_input_beta1_power(b1p_op);
    op_inst.set_input_lr(lr_op);
    op_inst.set_input_beta1(b1_op);
    op_inst.set_input_beta2(b2_op);
    op_inst.set_input_epsilon(eps_op);
    op_inst.set_input_grad(grad_op);

    TensorDesc var_out_desc(ge::Shape(ti.shape), FORMAT_ND, DT_FLOAT);
    var_out_desc.SetRealDimCnt(static_cast<int32_t>(ti.shape.size()));
    op_inst.update_output_desc_var(var_out_desc);
    op_inst.update_output_desc_m(var_out_desc);
    op_inst.update_output_desc_v(var_out_desc);

    op_inst.set_attr_use_locking(false);

    std::vector<Operator> inputs = {var_op, m_op, v_op, b1p_op, lr_op, b1_op, b2_op, eps_op, grad_op};
    std::vector<Operator> outputs = {op_inst};
    graph.SetInputs(inputs).SetOutputs(outputs);

    std::map<AscendString, AscendString> build_options;
    Session* session = new Session(build_options);
    if (session == nullptr) {
        out.err_msg = "Session creation failed";
        return out;
    }

    uint32_t graph_id = 0;
    std::map<AscendString, AscendString> graph_options;
    auto ret = session->AddGraph(graph_id, graph, graph_options);
    if (ret != SUCCESS) {
        out.err_msg = "AddGraph failed: " + std::to_string(ret);
        delete session;
        return out;
    }

    std::vector<ge::Tensor> input_tensors = {var_tensor,   m_tensor,     v_tensor,       beta1_power_tensor, lr_tensor,
                                             beta1_tensor, beta2_tensor, epsilon_tensor, grad_tensor};
    std::vector<ge::Tensor> output_tensors;
    ret = session->RunGraph(graph_id, input_tensors, output_tensors);
    if (ret != SUCCESS) {
        out.err_msg = "RunGraph failed: " + std::to_string(ret);
        delete session;
        return out;
    }
    delete session;

    if (output_tensors.size() < 3) {
        out.err_msg = "output tensor count insufficient: " + std::to_string(output_tensors.size()) + " (expected 3)";
        return out;
    }

    out.var_out = GeTensorToFp32(output_tensors[0]);
    out.m_out = GeTensorToFp32(output_tensors[1]);
    out.v_out = GeTensorToFp32(output_tensors[2]);
    out.ok = true;
    return out;
}

bool RunOneCase(const std::string& case_name, const TestInput& ti)
{
    LOG_PRINT("\n----------------------------------------");
    LOG_PRINT("[%s] shape=[4,4], n=%zu", case_name.c_str(), ti.var.size());
    LOG_PRINT("----------------------------------------");

    LOG_PRINT("[INFO] Running GE IR on NPU...");
    GeirOutput geir_out = RunGeir(ti);
    if (!geir_out.ok) {
        LOG_PRINT("[FAIL] GEIR failed: %s", geir_out.err_msg.c_str());
        return false;
    }
    LOG_PRINT("[INFO] GEIR ok, var_out.size=%zu m_out.size=%zu v_out.size=%zu", geir_out.var_out.size(),
              geir_out.m_out.size(), geir_out.v_out.size());

    std::vector<double> var_d(ti.var.begin(), ti.var.end());
    std::vector<double> m_d(ti.m.begin(), ti.m.end());
    std::vector<double> v_d(ti.v.begin(), ti.v.end());
    std::vector<double> grad_d(ti.grad.begin(), ti.grad.end());
    std::vector<double> var_g, m_g, v_g;
    GoldenApplyAdaMax(var_d, m_d, v_d, ti.beta1_power, ti.lr, ti.beta1, ti.beta2, ti.epsilon, grad_d, var_g, m_g, v_g);
    std::vector<float> var_golden(var_g.begin(), var_g.end());
    std::vector<float> m_golden(m_g.begin(), m_g.end());
    std::vector<float> v_golden(v_g.begin(), v_g.end());

    auto vr = CompareFp32(var_golden, geir_out.var_out);
    auto mr = CompareFp32(m_golden, geir_out.m_out);
    auto vrr = CompareFp32(v_golden, geir_out.v_out);

    LOG_PRINT("[%s] var_out: mismatch=%zu/%zu max_abs=%.2e max_rel=%.2e", vr.pass ? "PASS" : "FAIL", vr.mismatch_count,
              var_golden.size(), vr.max_abs_err, vr.max_rel_err);
    LOG_PRINT("[%s] m_out:   mismatch=%zu/%zu max_abs=%.2e max_rel=%.2e", mr.pass ? "PASS" : "FAIL", mr.mismatch_count,
              m_golden.size(), mr.max_abs_err, mr.max_rel_err);
    LOG_PRINT("[%s] v_out:   mismatch=%zu/%zu max_abs=%.2e max_rel=%.2e", vrr.pass ? "PASS" : "FAIL",
              vrr.mismatch_count, v_golden.size(), vrr.max_abs_err, vrr.max_rel_err);

    return vr.pass && mr.pass && vrr.pass;
}

int main(int argc, char** argv)
{
    LOG_PRINT("========================================");
    LOG_PRINT("InplaceApplyAdaMax GE IR example");
    LOG_PRINT("========================================");

    const char* dev_id_env = std::getenv("ASCEND_DEVICE_ID");
    std::string dev_id_str = (dev_id_env != nullptr) ? std::string(dev_id_env) : "1";
    std::map<AscendString, AscendString> global_options = {{"ge.exec.deviceId", dev_id_str.c_str()},
                                                           {"ge.graphRunMode", "1"}};
    LOG_PRINT("[INFO] GE init, deviceId=%s", dev_id_str.c_str());
    auto initRet = ge::GEInitialize(global_options);
    if (initRet != ge::SUCCESS) {
        LOG_PRINT("[FATAL] GEInitialize failed: %u", initRet);
        return 1;
    }

    int pass_count = 0;
    int total = 0;

    {
        TestInput ti = GenTestInput(42);
        total++;
        if (RunOneCase("Case1_FP32", ti)) {
            pass_count++;
        }
    }

    ge::GEFinalize();

    LOG_PRINT("");
    LOG_PRINT("========================================");
    LOG_PRINT("Summary: %d/%d passed", pass_count, total);
    if (pass_count == total) {
        LOG_PRINT("Result: PASS");
        LOG_PRINT("========================================");
        return 0;
    } else {
        LOG_PRINT("Result: FAIL");
        LOG_PRINT("========================================");
        return 1;
    }
}
