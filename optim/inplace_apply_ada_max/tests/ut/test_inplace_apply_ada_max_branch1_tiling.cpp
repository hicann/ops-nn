TEST_P(Branch1TilingTest, Formula)
{
    const auto& p = GetParam();
    int64_t rank = static_cast<int64_t>(p.shape.size());

    OracleBranch1 exp = Branch1TilingOracle(p.shape.data(), rank, p.N, PER_BUF_ELEMS, p.coreNumAiv, ALIGN_ELEM_FP32);

    optiling::BranchInputs in{};
    in.maxBroShape = p.shape.data();
    in.rank = rank;
    in.N = p.N;
    in.perBufElems = PER_BUF_ELEMS;
    in.coreNumAiv = p.coreNumAiv;
    in.alignElem = ALIGN_ELEM_FP32;

    SplitResult split{};
    MultiCoreResult multicore{};
    std::memset(&split, 0, sizeof(split));
    std::memset(&multicore, 0, sizeof(multicore));
    optiling::ComputeBranchTiling(1, in, split, multicore);

    // §2 UB切分 (split) — 逐字段比较.
    EXPECT_EQ(split.axis, exp.splitAxis);
    EXPECT_EQ(split.aI, exp.splitAI);
    EXPECT_EQ(split.aO, exp.splitAO);
    EXPECT_EQ(split.aITail, exp.splitAITail);
    // §2 多核切分 (multicore) — 逐字段比较.
    EXPECT_EQ(multicore.numCores, exp.mcNumCores);
    EXPECT_EQ(multicore.totalTiles, exp.mcTotalTiles);
    EXPECT_EQ(multicore.tilesMain, exp.mcTilesMain);
    EXPECT_EQ(multicore.coresTail, exp.mcCoresTail);
}

