constexpr int64_t UB_BYTES_DAV3510 = 253952; // 248 KiB (DAV_3510)
constexpr int64_t P_PHYS_NODES = 5;          // 4 inputs + 1 tmp (§5.3)
constexpr int64_t COMPUTE_DTYPE_SZ = 4;      // FP32 compute domain
constexpr int64_t ALIGN_ELEM_FP32 = 8;       // FP32: 32B / 4B

// perBufElems = ((ubBytes / P) & ~31) / 4 = (50784) / 4 = 12696
constexpr int64_t AlignDown32(int64_t v) { return v & ~static_cast<int64_t>(31); }
constexpr int64_t PER_BUF_ELEMS = AlignDown32(UB_BYTES_DAV3510 / P_PHYS_NODES) / COMPUTE_DTYPE_SZ; // 12696

// ===========================================================================
// Independent oracle — hand-written DESIGN-BRANCH-1.md §2 formulas.
// Does NOT call any optiling:: function (skill §五.5: oracle independence).
//
// §2 UB切分 (Branch-1: fp32-unalign, key difference in k==0 path):
//   inner = 1
//   for k = rank-1 downto 0:
//       if maxBroShape[k] * inner > perBufElems:    # split needed
//           aIRaw  = perBufElems / inner
//           aI      = (aIRaw // alignElem) * alignElem   # align down to 8
//           aO      = ceil(maxBroShape[k] / aI)
//           aITail = maxBroShape[k] - aI * (aO - 1)   # non-aligned (N%8!=0)
//           axis = k; break
//       if k == 0:                                       # whole tensor fits
//           axis = 0
//           aI = (perBufElems // alignElem) * alignElem # = 12696 (aligned buf upper bound)
//           aO = 1
//           aITail = maxBroShape[0]                   # non-aligned (N%8!=0)
//       inner *= maxBroShape[k]
//
// §2 多核切分 (MultiCoreSplit):
//   outerProd  = Π_{j=0}^{axis-1} maxBroShape[j]
//   totalTiles = outerProd * aO
//   numCores   = min(totalTiles, coreNumAiv); if <1 → 1
//   tilesMain  = totalTiles // numCores
//   coresTail  = totalTiles %  numCores
// ===========================================================================
struct OracleBranch1 {
    int64_t splitAxis;
    int64_t splitAI;
    int64_t splitAO;
    int64_t splitAITail;
    int64_t mcNumCores;
    int64_t mcTotalTiles;
    int64_t mcTilesMain;
    int64_t mcCoresTail;
};

// Note: function name intentionally avoids the 'OracleCompute' prefix to keep
// the skill's oracle-independence grep (gate 5) precise (same convention as
// Branch-0's Branch0TilingOracle).
OracleBranch1 Branch1TilingOracle(const int64_t* maxBroShape, int64_t rank, int64_t N, int64_t perBufElems,
                                  int64_t coreNumAiv, int64_t alignElem)
{
    OracleBranch1 t{}; // zero-init

    // Branch-1 covers N%8!=0 (N=0 is align → Branch-0); guard anyway.
    if (N == 0) {
        t.splitAxis = 0;
        return t;
    }

    // ---- §2 UB切分 (Branch-1: k==0 path differs from Branch-0) ----
    int64_t inner = 1;
    int64_t axis = 0, aI = 0, aO = 0, aITail = 0;
    for (int64_t k = rank - 1; k >= 0; --k) {
        if (maxBroShape[k] * inner > perBufElems) {
            // Split path: align aI down to alignElem (same as Branch-0 split).
            int64_t aIRaw = perBufElems / inner;
            aI = (aIRaw / alignElem) * alignElem; // align down to 8
            if (aI < 1)
                aI = alignElem;                  // guard against 0
            aO = (maxBroShape[k] + aI - 1) / aI; // ceil
            aITail = maxBroShape[k] - aI * (aO - 1);
            axis = k;
            break;
        }
        if (k == 0) {
            // Branch-1 KEY DIFFERENCE: aI = aligned buffer upper bound
            // (NOT maxBroShape[0] as in Branch-0). aO=1, single tile.
            axis = 0;
            aI = (perBufElems / alignElem) * alignElem; // = 12696
            aO = 1;
            aITail = maxBroShape[0]; // non-aligned (N%8!=0)
            break;
        }
        inner *= maxBroShape[k];
    }

    t.splitAxis = axis;
    t.splitAI = aI;
    t.splitAO = aO;
    t.splitAITail = aITail;

    // ---- §2 多核切分 (MultiCoreSplit) ----
    int64_t outerProd = 1;
    for (int64_t j = 0; j < axis; ++j) {
        outerProd *= maxBroShape[j];
    }
    int64_t totalTiles = outerProd * aO;
    int64_t numCores = std::min(totalTiles, coreNumAiv);
    if (numCores < 1)
        numCores = 1;
    int64_t tilesMain = totalTiles / numCores;
    int64_t coresTail = totalTiles % numCores;

    t.mcNumCores = numCores;
    t.mcTotalTiles = totalTiles;
    t.mcTilesMain = tilesMain;
    t.mcCoresTail = coresTail;

    return t;
}

