TEST(ChooseTilingKeyTest, Section55FourBranchMutex)
{
    using optiling::ChooseTilingKey;
    // align-only: 0=align, 1=non-align (dtype driven by def, not encoded in key).
    EXPECT_EQ(ChooseTilingKey(ge::DT_FLOAT, 8), 0);     // fp32-align
    EXPECT_EQ(ChooseTilingKey(ge::DT_FLOAT, 100), 1);   // fp32-unalign (100%8=4)
    EXPECT_EQ(ChooseTilingKey(ge::DT_FLOAT16, 16), 0);  // fp16-align
    EXPECT_EQ(ChooseTilingKey(ge::DT_FLOAT16, 100), 1); // fp16-unalign (100%16=4)
    // Empty tensor N=0: 0%alignElem==0 → align branch.
    EXPECT_EQ(ChooseTilingKey(ge::DT_FLOAT, 0), 0);   // empty fp32 → align
    EXPECT_EQ(ChooseTilingKey(ge::DT_FLOAT16, 0), 0); // empty fp16 → align
    // Unsupported dtypes → -1.
    EXPECT_EQ(ChooseTilingKey(ge::DT_BF16, 8), -1);
    EXPECT_EQ(ChooseTilingKey(ge::DT_INT32, 8), -1);
    EXPECT_EQ(ChooseTilingKey(ge::DT_DOUBLE, 8), -1);
}

