// ===========================================================================
// §5.2 公共量常量 (手抄自 DESIGN §5.2 / §5.3, NOT from impl)
// ===========================================================================
constexpr int64_t UB_BYTES_DAV3510 = 253952; // 248 KiB (DAV_3510)
constexpr int64_t P_PHYS_NODES = 5;          // 4 inputs + 1 tmp (§5.3)
constexpr int64_t COMPUTE_DTYPE_SZ = 4;      // FP32 compute domain (§1.4)

// 32B alignment helpers (independent of impl).
inline int64_t AlignDown32(int64_t v) { return v & ~static_cast<int64_t>(31); }

// ===========================================================================
// Independent oracle — hand-written §5.2/§5.5 formulas.
// Does NOT call any optiling:: function (skill §五.5: oracle independence).
// ===========================================================================
struct OracleCommon {
    int64_t perBufBytes;
    int64_t perBufElems;
    int64_t P;
    int64_t ubUsedBytes;
    int32_t tilingKey;
    int64_t alignElem;
    bool isAlign;
    int64_t totalTiles;
};

OracleCommon OracleCompute(ge::DataType dtype, int64_t N, int64_t ubBytes, int64_t coreNumAiv)
{
    (void)coreNumAiv; // coreNumAiv feeds MultiCoreSplit (Task 20), not common.
    OracleCommon t{};

    // ---- §5.2 公共量 (platform-derived, independent of N/dtype) ----
    t.P = P_PHYS_NODES;
    int64_t raw = ubBytes / t.P;                      // integer division: 253952/5 = 50790
    t.perBufBytes = AlignDown32(raw);                 // 50790 & ~31 = 50784
    t.perBufElems = t.perBufBytes / COMPUTE_DTYPE_SZ; // 50784 / 4 = 12696
    t.ubUsedBytes = t.P * t.perBufBytes;              // 5 * 50784 = 253920

    // ---- §5.5 分支判定 (align-only → tilingKey 0/1, dtype 由 def 驱动) ----
    bool isFp32 = (dtype == ge::DT_FLOAT);
    bool isFp16 = (dtype == ge::DT_FLOAT16);
    if (isFp32) {
        t.alignElem = 8;
    } else if (isFp16) {
        t.alignElem = 16;
    } else {
        t.alignElem = 0; // unsupported dtype
    }
    t.isAlign = (t.alignElem > 0) ? (N % t.alignElem == 0) : false;

    // align-only: 0=align, 1=non-align, -1=unsupported dtype.
    if (!isFp32 && !isFp16) {
        t.tilingKey = -1;
    } else {
        t.tilingKey = t.isAlign ? 0 : 1;
    }

    // ---- 空 Tensor N=0 → align branch direct return, totalTiles=0 ----
    // For N>0, totalTiles is deferred to branch impl (Tasks 21+); oracle uses
    // INT64_MIN sentinel to signal "pending branch computation".
    t.totalTiles = (N == 0) ? 0 : INT64_MIN;

    return t;
}

