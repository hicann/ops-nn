class CommonTilingTest : public testing::TestWithParam<TilingCase> {};

TEST_P(CommonTilingTest, Formula)
{
    const auto& p = GetParam();
    OracleCommon exp = OracleCompute(p.dtype, p.N, UB_BYTES_DAV3510, p.coreNumAiv);

    optiling::CommonTilingInputs in{};
    in.dtype = p.dtype;
    in.N = p.N;
    in.coreNumAiv = p.coreNumAiv;
    in.ubBytes = UB_BYTES_DAV3510;

    optiling::CommonTilingOutputs act{}; // zero-init
    optiling::ComputeCommonTiling(in, act);

    // §5.2 公共量 (always asserted — independent of N/dtype).
    EXPECT_EQ(act.perBufBytes, exp.perBufBytes);
    EXPECT_EQ(act.perBufElems, exp.perBufElems);
    EXPECT_EQ(act.P, exp.P);
    EXPECT_EQ(act.ubUsedBytes, exp.ubUsedBytes);
    // §5.5 分支判定 (always asserted).
    EXPECT_EQ(act.tilingKey, exp.tilingKey);
    EXPECT_EQ(act.alignElem, exp.alignElem);
    EXPECT_EQ(act.isAlign, exp.isAlign);
    // 空 Tensor totalTiles=0 (only asserted when N==0; for N>0 it is
    // deferred to branch impl and not part of common tiling scope).
    if (p.N == 0) {
        EXPECT_EQ(act.totalTiles, 0);
    }
}

