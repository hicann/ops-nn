constexpr int64_t UB_BYTES_DAV3510 = 253952; // 248 KiB (DAV_3510)
constexpr int64_t P_PHYS_NODES = 5;          // 4 inputs + 1 tmp (§5.3)
constexpr int64_t COMPUTE_DTYPE_SZ = 4;      // FP32 compute domain (§5.7)
constexpr int64_t ALIGN_ELEM_FP16 = 16;      // FP16: 32B / 2B
constexpr int64_t FP32_VEC_ALIGN = 8;        // FP32 Vector: 32B / 4B (§2 tailAlignElems)

// perBufElems = ((ubBytes / P) & ~31) / 4 = (50784) / 4 = 12696
// (same as Branch-0/1/2: UB budget is in FP32 compute domain, §5.2)
constexpr int64_t AlignDown32(int64_t v) { return v & ~static_cast<int64_t>(31); }
constexpr int64_t PER_BUF_ELEMS = AlignDown32(UB_BYTES_DAV3510 / P_PHYS_NODES) / COMPUTE_DTYPE_SZ; // 12696

// ===========================================================================
// Independent oracle — hand-written DESIGN-BRANCH-3.md §2 formulas.
// Does NOT call any optiling:: function (skill §五.5: oracle independence).
//
// §2 UB切分 (Branch-3: fp16-unalign, alignElem=16; k==0 path differs from
//             Branch-2 — uses Branch-1's "aligned buffer upper bound" pattern):
//   inner = 1
//   for k = rank-1 downto 0:
//       if maxBroShape[k] * inner > perBufElems:    # split needed
//           aIRaw  = perBufElems / inner
//           aI      = (aIRaw // alignElem) * alignElem   # align down to 16
//                                                            # = (12696//16)*16 = 12688
//           aO      = ceil(maxBroShape[k] / aI)
//           aITail = maxBroShape[k] - aI * (aO - 1)   # NON-16-aligned (N%16!=0)
//           axis = k; break
//       if k == 0:                                       # whole tensor fits
//           axis = 0
//           aI = (perBufElems // alignElem) * alignElem # = 12688 (aligned buf upper bound,
//                                                           #          NOT maxBroShape[0])
//           aO = 1
//           aITail = maxBroShape[0]                   # NON-16-aligned (N%16!=0)
//       inner *= maxBroShape[k]
//   tile_elems = aI * inner    # ≤ 12688 (FP32 compute domain, 16-aligned)
//   tailElems = aITail * inner
//   tailAlignElems = ((tailElems + 7) // 8) * 8        # FP32 Vector align (8 elems = 32B)
//
// §2 多核切分 (MultiCoreSplit):
//   outerProd  = Π_{j=0}^{axis-1} maxBroShape[j]
//   totalTiles = outerProd * aO
//   numCores   = min(totalTiles, coreNumAiv); if <1 → 1
//   tilesMain  = totalTiles // numCores
//   coresTail  = totalTiles %  numCores
//
// §2 兜底: N==0 → totalTiles=0, numCores=0, all fields 0 (kernel no-op).
//   (Branch-3 covers N%16!=0; N==0 is align → Branch-2. Guard anyway.)
// ===========================================================================
struct OracleBranch3 {
    int64_t splitAxis;
    int64_t splitAI;
    int64_t splitAO;
    int64_t splitAITail;
    int64_t tailElems;      // = aITail * inner (§2)
    int64_t tailAlignElems; // = ceil(tailElems, 8) (§2, FP32 Vector align)
    int64_t mcNumCores;
    int64_t mcTotalTiles;
    int64_t mcTilesMain;
    int64_t mcCoresTail;
};

// Note: function name intentionally avoids the 'OracleCompute' prefix to keep
// the skill's oracle-independence grep (gate 5) precise (same convention as
// Branch-0/1/2's BranchNTilingOracle).
OracleBranch3 Branch3TilingOracle(const int64_t* maxBroShape, int64_t rank, int64_t N, int64_t perBufElems,
                                  int64_t coreNumAiv, int64_t alignElem)
{
    OracleBranch3 t{}; // zero-init

    // §2 兜底: empty tensor → all fields 0.
    if (N == 0) {
        // splitAxis=0, all other fields already 0 from {} init.
        t.splitAxis = 0;
        return t;
    }

    // ---- §2 UB切分 (Branch-3: fp16-unalign, alignElem=16) ----
    int64_t inner = 1;
    int64_t axis = 0, aI = 0, aO = 0, aITail = 0;
    for (int64_t k = rank - 1; k >= 0; --k) {
        if (maxBroShape[k] * inner > perBufElems) {
            // Split path: align aI DOWN to alignElem=16 (FP16 hard-aligned GM
            // access for main tiles). aI = (12696//16)*16 = 12688.
            int64_t aIRaw = perBufElems / inner;
            aI = (aIRaw / alignElem) * alignElem; // align down to 16
            if (aI < 1)
                aI = alignElem;                  // guard against 0
            aO = (maxBroShape[k] + aI - 1) / aI; // ceil
            aITail = maxBroShape[k] - aI * (aO - 1);
            // Branch-3 unalign: aITail is NON-16-aligned (N%16!=0).
            axis = k;
            break;
        }
        if (k == 0) {
            // Branch-3 single-tile KEY DIFFERENCE (same as Branch-1):
            // aI = aligned buffer upper bound (NOT maxBroShape[0] as in
            // Branch-0/2). aO=1; aITail = maxBroShape[0] (non-aligned,
            // kernel treats whole tensor as "tail tile" needing Cast + Pad).
            axis = 0;
            aI = (perBufElems / alignElem) * alignElem; // = 12688
            aO = 1;
            aITail = maxBroShape[0]; // non-aligned (N%16!=0)
            break;
        }
        inner *= maxBroShape[k];
    }

    t.splitAxis = axis;
    t.splitAI = aI;
    t.splitAO = aO;
    t.splitAITail = aITail;

    // §2 tailElems / tailAlignElems (FP32 Vector alignment, 8 elems = 32B).
    // tailAlignElems = ceil(tailElems, 8) — kernel S4.5 Pad-to-align target.
    int64_t tailElems = aITail * inner;
    int64_t tailAlignElems = ((tailElems + FP32_VEC_ALIGN - 1) / FP32_VEC_ALIGN) * FP32_VEC_ALIGN;
    t.tailElems = tailElems;
    t.tailAlignElems = tailAlignElems;

    // ---- §2 多核切分 (MultiCoreSplit) ----
    int64_t outerProd = 1;
    for (int64_t j = 0; j < axis; ++j) {
        outerProd *= maxBroShape[j];
    }
    int64_t totalTiles = outerProd * aO;
    int64_t numCores = std::min(totalTiles, coreNumAiv);
    if (numCores < 1)
        numCores = 1;
    int64_t tilesMain = totalTiles / numCores;
    int64_t coresTail = totalTiles % numCores;

    t.mcNumCores = numCores;
    t.mcTotalTiles = totalTiles;
    t.mcTilesMain = tilesMain;
    t.mcCoresTail = coresTail;

    return t;
}

