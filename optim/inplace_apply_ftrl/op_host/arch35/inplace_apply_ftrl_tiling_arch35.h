inline int64_t CalcUbFactor(uint64_t ubSize, int64_t blockFactor)
{
    int64_t usableUb = static_cast<int64_t>(ubSize) - SELECT_TMP_BYTES;
    if (usableUb <= 0) {
        return -1;
    }
    int64_t ubCapacityElem = FloorAlign(FloorDiv(usableUb / TYPE_SIZE_FP32, UB_FP32_SLOTS), CMP_ALIGN_ELEM);
    int64_t ubFactor = (TILE_ELEM_NUM_TARGET < ubCapacityElem) ? TILE_ELEM_NUM_TARGET : ubCapacityElem;
    if (ubFactor > blockFactor) {
        ubFactor = blockFactor;
    }
    ubFactor = FloorAlign(ubFactor, CMP_ALIGN_ELEM);
    if (ubFactor < CMP_ALIGN_ELEM) {
        ubFactor = CMP_ALIGN_ELEM;
    }
    return ubFactor;
}

