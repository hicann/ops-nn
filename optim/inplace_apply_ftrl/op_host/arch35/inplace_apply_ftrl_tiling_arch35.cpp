    int64_t ubBlockSize = GetDtypeUbBlockSize(dataType);
    int64_t blockFactor = CalcBlockFactor(totalElements, coreNum, ubBlockSize);
    int64_t ubFactor = CalcUbFactor(ubSize, blockFactor);
