static bool VerifyOutputShape(const vector<int64_t>& expected, const ge::Shape& actual)
{
    if (expected.size() != actual.GetDimNum()) {
        return false;
    }
    for (size_t i = 0; i < expected.size(); ++i) {
        if (expected[i] != actual.GetDim(i)) {
            return false;
        }
    }
    return true;
}

static int RunStaticScenario(const vector<int64_t>& shape, DataType dtype)
{
    printf("\nStatic shape = %s, dtype = %d\n", ShapeToStr(shape).c_str(), static_cast<int>(dtype));

    const char* graph_name = "inplace_apply_ftrl_geir_static";
    Graph graph(graph_name);
    vector<Operator> inputs{};
    vector<Operator> outputs{};

    if (CreateStaticGraph(shape, dtype, inputs, outputs, graph) != SUCCESS) {
        printf("ERROR: Create graph failed for shape %s\n", ShapeToStr(shape).c_str());
        return FAILED;
    }
    graph.SetInputs(inputs).SetOutputs(outputs);

    std::map<AscendString, AscendString> build_options = {};
    ge::Session* session = new Session(build_options);
    if (session == nullptr) {
        printf("ERROR: Create session failed\n");
        return FAILED;
    }

    std::map<AscendString, AscendString> graph_options = {};
    uint32_t graph_id = 0;
    Status ret = session->AddGraph(graph_id, graph, graph_options);
    if (ret != SUCCESS) {
        printf("ERROR: AddGraph failed for shape %s\n", ShapeToStr(shape).c_str());
        ge::AscendString error_msg = ge::GEGetErrorMsgV2();
        std::cout << "Error message: " << error_msg.GetString() << std::endl;
        delete session;
        return FAILED;
    }

    vector<ge::Tensor> feeds;
    feeds.push_back(MakeNdTensor(shape, dtype, 0.5f));
    feeds.push_back(MakeNdTensor(shape, dtype, 0.1f));
    feeds.push_back(MakeNdTensor(shape, dtype, 0.0f));
    feeds.push_back(MakeNdTensor(shape, dtype, 0.3f));
    feeds.push_back(MakeScalarTensor(0.01f, dtype));
    feeds.push_back(MakeScalarTensor(0.01f, dtype));
    feeds.push_back(MakeScalarTensor(0.0f, dtype));
    feeds.push_back(MakeScalarTensor(-0.5f, dtype));

    vector<ge::Tensor> output;
    ret = session->RunGraph(graph_id, feeds, output);
    if (ret != SUCCESS) {
        printf("ERROR: RunGraph failed for shape %s\n", ShapeToStr(shape).c_str());
        ge::AscendString error_msg = ge::GEGetErrorMsgV2();
        std::cout << "Error message: " << error_msg.GetString() << std::endl;
        delete session;
        return FAILED;
    }

    if (output.size() != 3) {
        printf("ERROR: Expected 3 outputs, got %d\n", static_cast<int>(output.size()));
        delete session;
        return FAILED;
    }

    bool allMatch = true;
    const char* outNames[] = {"var", "accum", "linear"};
    for (int i = 0; i < 3; ++i) {
        auto outShape = output[i].GetTensorDesc().GetShape();
        bool match = VerifyOutputShape(shape, outShape);
        if (!match)
            allMatch = false;
        std::cout << "  output[" << i << "] (" << outNames[i] << ") shape = [";
        for (size_t k = 0; k < outShape.GetDimNum(); ++k) {
            std::cout << outShape.GetDim(k) << (k + 1 < outShape.GetDimNum() ? "," : "");
        }
        std::cout << "], dtype = " << output[i].GetTensorDesc().GetDataType() << (match ? " OK" : " MISMATCH")
                  << std::endl;
    }

    delete session;

    if (allMatch) {
        printf("Shape, dtype and values PASSED for %s\n", ShapeToStr(shape).c_str());
        return SUCCESS;
    } else {
        printf("FAILED: shape mismatch for %s\n", ShapeToStr(shape).c_str());
        return FAILED;
    }
}

