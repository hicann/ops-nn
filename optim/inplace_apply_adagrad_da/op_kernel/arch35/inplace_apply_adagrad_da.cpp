        // ggAccOutF32 = ggAccF32 + grad²（ggAccF32 原地复用为输出）
        Add(ggAccOutF32, ggAccF32, scratch, n);
        // TF DAZ+FTZ 对齐: gsa_new 冲刷 + -0→+0 规范(同 FP32 路径)
