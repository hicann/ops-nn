def _ref_full(var, accum, linear, grad, lr, l1, l2, lr_power):
    """Independent fp64 reference returning (var, accum_new, linear_new).

    Valid-domain reference (accum >= 0), using the standard power function
    np.power — the same std::pow / TF ApplyFtrl semantics used on device.
    """
    var = var.astype(np.float64)
    accum = accum.astype(np.float64)
    linear = linear.astype(np.float64)
    grad = grad.astype(np.float64)
    neg_p = -lr_power
    accum_new = accum + grad * grad
    pow_old = np.power(accum, neg_p)
    pow_new = np.power(accum_new, neg_p)
    sigma = (pow_new - pow_old) / lr
    linear_new = linear + grad - sigma * var
    quad = pow_new / lr + 2 * l2
    x = np.sign(linear_new) * l1 - linear_new
    var_out = np.where(np.abs(linear_new) > l1, x / quad, 0.0)
    return var_out, accum_new, linear_new


