// CPU Golden 实现（C++ double, FP64 等价，独立于 kernel）
//   Keras 公式：
//     accum_new = momentum * accum - lr * grad
//     标准模式:    var_new = var + accum_new
//     Nesterov:    var_new = var + momentum * accum_new - lr * grad
// ============================================================================
void GoldenApplyKerasMomentum(const std::vector<double>& var, const std::vector<double>& accum, double lr,
                              const std::vector<double>& grad, double momentum, bool use_nesterov,
                              std::vector<double>& var_new, std::vector<double>& accum_new)
{
    size_t n = var.size();
    var_new.resize(n);
    accum_new.resize(n);
    for (size_t i = 0; i < n; ++i) {
        // Keras 公式: accum_new = momentum * accum - lr * grad
        double an = momentum * accum[i] - lr * grad[i];
        accum_new[i] = an;
        if (use_nesterov) {
            // Nesterov: var_new = var + momentum * accum_new - lr * grad
            var_new[i] = var[i] + momentum * an - lr * grad[i];
        } else {
            // 标准模式: var_new = var + accum_new
            var_new[i] = var[i] + an;
        }
    }
}

