            LocalTensor<float> accumF32 = accumF32Buf_.template Get<float>();
            LocalTensor<float> gradF32 = gradF32Buf_.template Get<float>();

            Cast(varF32, varLocal, RoundMode::CAST_NONE, currentChunk);
            Cast(accumF32, accumLocal, RoundMode::CAST_NONE, currentChunk);
            Cast(gradF32, gradLocal, RoundMode::CAST_NONE, currentChunk);

