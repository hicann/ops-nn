        pipe_.InitBuffer(inAccumQue_, BUFFER_NUM, chunkSize_ * sizeof(T));
        pipe_.InitBuffer(inGradQue_, BUFFER_NUM, chunkSize_ * sizeof(T));
        // 输出 Queue（VECOUT，存原始 dtype T）
        pipe_.InitBuffer(outVarQue_, BUFFER_NUM, chunkSize_ * sizeof(T));
        pipe_.InitBuffer(outAccumQue_, BUFFER_NUM, chunkSize_ * sizeof(T));
        // FP32 nesterov scratch（复用为 negLrGrad buffer）
        pipe_.InitBuffer(nesterovBuf_, chunkSize_ * sizeof(float));
        // momentum 标量广播为 tensor（Fma 要求 src 为 LocalTensor）
