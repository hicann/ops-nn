/*!
 * \file inplace_apply_keras_momentum.h
 * \brief InplaceApplyKerasMomentum Kernel（arch35 / DAV_3510）
 *
 * 采用与 inplace_apply_adagrad_da 一致的 inplace 设计模式：
 *   - DUAL-WRITE: CopyOut 同时写输出 GM_ADDR 和输入 GM_ADDR，保证 inplace 语义
 *   - 三级流水: CopyIn(EnQue) → Compute(DeQue/Cast/计算/Cast/EnQue) → CopyOut(DeQue/DataCopyPad/FreeTensor)
 *   - TQue 存原始 dtype T，FP16/BF16 路径用 TBuf 做 FP32 中间计算
 *   - if constexpr 区分 FP32/FP16，无 SCH_MODE 模板参数
 *
 * Keras 公式（严禁与 ApplyMomentum 标准公式混淆）：
 *   accum_new = momentum * accum - lr * grad
 *   标准模式 (use_nesterov=0):  var_new = var + accum_new
 *   Nesterov 模式 (use_nesterov=1): var_new = var + momentum * accum_new - lr * grad
 *   accum = accum_new  (inplace 写回)
 *
 * Nesterov 计算顺序须与 golden(TF) 一致：var + (mom*accum_new - lr*grad)
 */

