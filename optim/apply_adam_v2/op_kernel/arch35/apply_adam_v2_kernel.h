        int64_t start, end;
        GetCoreRange(AscendC::GetBlockIdx(), td_->multicore.tilesMain, td_->multicore.coresTail, start, end);

        constexpr int IN_LR = 3, IN_BETA1 = 4, IN_BETA2 = 5, IN_EPSILON = 6;
        constexpr int IN_MAX_GRAD_NORM = 8, IN_GLOBAL_GRAD_NORM = 9;
        constexpr int IN_WEIGHT_DECAY = 10, IN_STEP_SIZE = 11;

        int64_t inner_count = 1;
        for (int64_t d = td_->split.axis + 1; d < RANK; d++)
            inner_count *= td_->maxBroShape[d];

        float lr = static_cast<float>(*(gmInPtr_[IN_LR]));
        float beta1 = static_cast<float>(*(gmInPtr_[IN_BETA1]));
        float beta2 = static_cast<float>(*(gmInPtr_[IN_BETA2]));
        float epsilon = static_cast<float>(*(gmInPtr_[IN_EPSILON]));
        float weightDecay = static_cast<float>(*(gmInPtr_[IN_WEIGHT_DECAY]));

