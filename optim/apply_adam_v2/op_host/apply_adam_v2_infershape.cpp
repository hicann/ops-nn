bool ValidShape(const gert::Shape& shape, bool scalar)
{
    if (shape.GetDimNum() == 1 && shape.GetDim(0) == -2) {
        return true; // Unknown rank; validate the resolved shape in tiling.
    }
    if (shape.GetDimNum() > MAX_RANK || (scalar && shape.GetDimNum() > 1)) {
        return false;
    }
    for (size_t d = 0; d < shape.GetDimNum(); ++d) {
        const auto dim = shape.GetDim(d);
        if (dim != -1 && (dim < 0 || (scalar && dim != 1))) {
            return false;
        }
    }
    return true;
}

bool CompatibleShape(const gert::Shape& lhs, const gert::Shape& rhs)
{
    if ((lhs.GetDimNum() == 1 && lhs.GetDim(0) == -2) || (rhs.GetDimNum() == 1 && rhs.GetDim(0) == -2)) {
        return true;
    }
    if (lhs.GetDimNum() != rhs.GetDimNum()) {
        return false;
    }
    for (size_t d = 0; d < lhs.GetDimNum(); ++d) {
        if (lhs.GetDim(d) != -1 && rhs.GetDim(d) != -1 && lhs.GetDim(d) != rhs.GetDim(d)) {
            return false;
        }
    }
    return true;
}
