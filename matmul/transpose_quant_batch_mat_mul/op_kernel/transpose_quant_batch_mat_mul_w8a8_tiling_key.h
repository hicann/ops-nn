//   要求 AIV 侧有真实的 fixpipe/Vector 代码才能生成 .o 并链接；当前 Process 为空
//   导致 ld.lld 报 `cannot open ..._mix_aic_4128.o`。
// - **结论**：mix 二进制生成和 Vector epilogue 实现必须同期进行。Step C compute 时
//   重新接入 QUANT_MODE 维度和 MIX_AIC_1_1 变体。本阶段保留 QUANT_MODE 枚举常量但
//   不进 ASCENDC_TPL_SEL；kernel 入口通过 is_same_v<DTYPE_X1, int8_t> 二次分发到
//   W8A8 class（骨架 Process 空）。
