float StableSigmoid(float value)
{
    if (value >= 0.0F) {
        return 1.0F / (1.0F + std::exp(-value));
    }
    const float expValue = std::exp(value);
    return expValue / (1.0F + expValue);
}

std::vector<float> ComputeGolden(const Feeds& feeds)
{
    const float reduceMeanCoef = 1.0F / static_cast<float>(feeds.pred.size());
    std::vector<float> golden(feeds.pred.size());
    for (size_t index = 0; index < feeds.pred.size(); ++index) {
        const float p = StableSigmoid(feeds.pred[index]);
        const float q = 1.0F - p;
        const float pFloor = std::max(p, kLogEps);
        const float qFloor = std::max(q, kLogEps);
        const float dpos = kAlpha * kGamma * p * std::pow(qFloor, kGamma) * std::log(pFloor) -
                           kAlpha * std::pow(qFloor, kGamma + 1.0F);
        const float dneg = kGamma * (kAlpha - 1.0F) * std::pow(pFloor, kGamma) * q * std::log(qFloor) +
                           (1.0F - kAlpha) * std::pow(pFloor, kGamma + 1.0F);
        const float raw = dpos * (1.0F - static_cast<float>(feeds.target[index])) +
                          dneg * static_cast<float>(feeds.target[index]);
        golden[index] = raw * feeds.weight[index] * feeds.dout[index] * reduceMeanCoef;
    }
    return golden;
}

