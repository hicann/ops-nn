template <typename T>
ge::Tensor MakeHostTensor(ge::DataType dataType, const std::array<T, kElementCount>& values)
{
    ge::TensorDesc desc(ge::Shape(kShape), ge::FORMAT_ND, dataType);
    desc.SetOriginFormat(ge::FORMAT_ND);
    desc.SetOriginShape(ge::Shape(kShape));
    desc.SetPlacement(ge::kPlacementHost);
    desc.SetRealDimCnt(kShape.size());
    ge::Tensor tensor(desc);
    tensor.SetData(reinterpret_cast<const uint8_t*>(values.data()), values.size() * sizeof(T));
    return tensor;
}

