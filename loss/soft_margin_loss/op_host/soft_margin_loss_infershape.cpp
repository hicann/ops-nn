constexpr int64_t UNKNOWN_DIM_VALUE = -1;
constexpr size_t MAX_SUPPORTED_RANK = 8;

bool IsUnknownDim(int64_t dim) { return dim < 0; }

bool ExceedsMaxRank(const gert::Shape& shape)
{
    return !Ops::Base::IsUnknownRank(shape) && shape.GetDimNum() > MAX_SUPPORTED_RANK;
}

// Merge self/target shapes for graph mode. -2 denotes unknown rank and -1 denotes
// an unknown dimension; either side may carry them independently for a dynamic
// graph input. Known dimensions still have to match because the kernel consumes
// same-shaped operands.
ge::graphStatus MergeSelfTargetShape(const gert::Shape& selfShape, const gert::Shape& targetShape,
                                     gert::Shape& mergedShape)
{
    const bool selfUnknownRank = Ops::Base::IsUnknownRank(selfShape);
    const bool targetUnknownRank = Ops::Base::IsUnknownRank(targetShape);
    if (selfUnknownRank && targetUnknownRank) {
        Ops::Base::SetUnknownRank(mergedShape);
        return GRAPH_SUCCESS;
    }
    if (selfUnknownRank) {
        mergedShape = targetShape;
        return GRAPH_SUCCESS;
    }
    if (targetUnknownRank) {
        mergedShape = selfShape;
        return GRAPH_SUCCESS;
    }
    if (selfShape.GetDimNum() != targetShape.GetDimNum()) {
        return GRAPH_FAILED;
    }

    mergedShape.SetDimNum(selfShape.GetDimNum());
    for (size_t i = 0; i < selfShape.GetDimNum(); ++i) {
        const int64_t selfDim = selfShape.GetDim(i);
        const int64_t targetDim = targetShape.GetDim(i);
        if (IsUnknownDim(selfDim)) {
            mergedShape.SetDim(i, IsUnknownDim(targetDim) ? UNKNOWN_DIM_VALUE : targetDim);
        } else if (IsUnknownDim(targetDim)) {
            mergedShape.SetDim(i, selfDim);
        } else if (selfDim != targetDim) {
            return GRAPH_FAILED;
        } else {
            mergedShape.SetDim(i, selfDim);
        }
    }
    return GRAPH_SUCCESS;
}
