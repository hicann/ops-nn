static ge::graphStatus TilingFuncSigmoidFocalLoss(gert::TilingContext* context)
{
    SigmoidFocalLossCompileInfo info{};
    if (GetPlatformInfo(context, info) != ge::GRAPH_SUCCESS) {
        return ge::GRAPH_FAILED;
    }
    SemanticInfo semanticInfo{};
    if (ValidateInputs(context, semanticInfo) != ge::GRAPH_SUCCESS) {
        return ge::GRAPH_FAILED;
    }

    SigmoidFocalLossTilingData tilingData{};
    tilingData.totalElements = semanticInfo.totalElements;
    tilingData.reductionMode = semanticInfo.reductionMode;
    tilingData.hasWeight = semanticInfo.hasWeight ? 1 : 0;
    tilingData.gamma = semanticInfo.gamma;
    tilingData.alpha = semanticInfo.alpha;
    tilingData.invRTotal = ComputeReductionScale(semanticInfo.totalElements, semanticInfo.reductionMode);

    bool isGroup = false;
    uint64_t key = TILING_KEY_ELEWISE;
    uint32_t blockDim = 0;
    if (semanticInfo.reductionMode == REDUCTION_NONE) {
        if (semanticInfo.totalElements == 0) {
            uint64_t userWorkspaceBytes = std::numeric_limits<uint64_t>::max();
            ComputeBranch1Tiling({semanticInfo.totalElements, semanticInfo.reductionMode,
                                  semanticInfo.hasWeight ? 1 : 0, semanticInfo.gamma, semanticInfo.alpha},
                                 tilingData, key, blockDim, userWorkspaceBytes);
            if (key != GET_TPL_TILING_KEY(1, SIGMOID_FOCAL_LOSS_ELEWISE) || blockDim != 1 || userWorkspaceBytes != 0) {
                OP_LOGE(context->GetNodeName(), "invalid empty EleWise tiling result");
                return ge::GRAPH_FAILED;
            }
        } else {
            if (FillElewise(semanticInfo, info, tilingData) != ge::GRAPH_SUCCESS) {
                return ge::GRAPH_FAILED;
            }
            key = GET_TPL_TILING_KEY(0, SIGMOID_FOCAL_LOSS_ELEWISE);
            blockDim = static_cast<uint32_t>(tilingData.usedCoreNum);
        }
    } else {
        if (semanticInfo.totalElements == 0) {
            uint64_t userWorkspaceBytes = std::numeric_limits<uint64_t>::max();
            ComputeBranch3Tiling(
                {semanticInfo.totalElements, semanticInfo.reductionMode, semanticInfo.hasWeight ? 1 : 0,
                 semanticInfo.gamma, semanticInfo.alpha, info.blockSize, semanticInfo.dtypeBytes},
                tilingData, key, blockDim, userWorkspaceBytes);
            if (key != GET_TPL_TILING_KEY(1, SIGMOID_FOCAL_LOSS_REDUCE_NORMAL) || blockDim != 1 ||
                userWorkspaceBytes != 0) {
                OP_LOGE(context->GetNodeName(), "invalid EMPTY_R tiling result");
                return ge::GRAPH_FAILED;
            }
        } else {
            if (FillReduction(semanticInfo, info, isGroup, tilingData) != ge::GRAPH_SUCCESS) {
                return ge::GRAPH_FAILED;
            }
            if (isGroup) {
                key = GET_TPL_TILING_KEY(0, SIGMOID_FOCAL_LOSS_REDUCE_GROUP);
            } else {
                key = GET_TPL_TILING_KEY(0, SIGMOID_FOCAL_LOSS_REDUCE_NORMAL);
            }
            blockDim = static_cast<uint32_t>(std::max<int32_t>(1, tilingData.usedCoreNum));
        }
    }

    if (ValidateFinalTiling(semanticInfo, info, key, tilingData) != ge::GRAPH_SUCCESS ||
        Serialize(tilingData, context) != ge::GRAPH_SUCCESS) {
        return ge::GRAPH_FAILED;
    }
    if (context->SetTilingKey(key) != ge::GRAPH_SUCCESS || context->SetBlockDim(blockDim) != ge::GRAPH_SUCCESS) {
        OP_LOGE(context->GetNodeName(), "failed to set key=%lu or blockDim=%u", key, blockDim);
        return ge::GRAPH_FAILED;
    }
    if (isGroup && context->SetScheduleMode(SCHEDULE_MODE_GROUP) != ge::GRAPH_SUCCESS) {
        OP_LOGE(context->GetNodeName(), "failed to set Group schedule mode for key=%lu", key);
        return ge::GRAPH_FAILED;
    }
    if (SetWorkspaceSize(context, isGroup, tilingData.rGroupCnt, info.systemWorkspaceSize) != ge::GRAPH_SUCCESS) {
        return ge::GRAPH_FAILED;
    }
    LogTilingData(context->GetNodeName(), key, tilingData);
    return ge::GRAPH_SUCCESS;
}

static ge::graphStatus TilingPrepareForSigmoidFocalLoss(gert::TilingParseContext* context)
{
    if (context == nullptr) {
        OP_LOGE("SigmoidFocalLoss", "tiling parse context is null");
        return ge::GRAPH_FAILED;
    }
    auto* compileInfo = context->GetCompiledInfo<SigmoidFocalLossCompileInfo>();
    auto* platformInfo = context->GetPlatformInfo();
    if (compileInfo == nullptr || platformInfo == nullptr) {
        OP_LOGE(context->GetNodeName(), "compile info or platform info is null");
        return ge::GRAPH_FAILED;
    }
    platform_ascendc::PlatformAscendC platform(platformInfo);
    compileInfo->coreNum = platform.GetCoreNumAiv();
    platform.GetCoreMemSize(platform_ascendc::CoreMemType::UB, compileInfo->ubSize);
    compileInfo->systemWorkspaceSize = platform.GetLibApiWorkSpaceSize();
    compileInfo->blockSize = Ops::Base::GetUbBlockSize(context);
    compileInfo->cacheLineSize = Ops::Base::GetCacheLineSize(context);
    compileInfo->vectorSize = Ops::Base::GetVRegSize(context);
    if (compileInfo->coreNum == 0 || compileInfo->ubSize == 0 || compileInfo->blockSize == 0 ||
        compileInfo->cacheLineSize == 0 || compileInfo->vectorSize == 0) {
        OP_LOGE(context->GetNodeName(), "invalid parsed platform info: cores=%u ub=%lu block=%lu cache=%lu vector=%lu",
                compileInfo->coreNum, compileInfo->ubSize, compileInfo->blockSize, compileInfo->cacheLineSize,
                compileInfo->vectorSize);
        return ge::GRAPH_FAILED;
    }
    return ge::GRAPH_SUCCESS;
}

