def _focal_loss(pred, target, weight, gamma, alpha, reduction):
    fp32_min = torch.finfo(torch.float32).tiny
    positive_target = torch.ne(target, 0)
    log_term = torch.log1p(torch.exp(torch.neg(torch.abs(pred))))
    positive_bce = torch.add(torch.clamp_min(torch.neg(pred), 0.0), log_term)
    negative_bce = torch.add(torch.clamp_min(pred, 0.0), log_term)
    bce = torch.where(positive_target, positive_bce, negative_bce)

    probability = torch.sigmoid(pred)
    pt = torch.where(
        positive_target,
        torch.sub(1.0, probability),
        probability,
    )
    alpha_factor = torch.where(
        positive_target,
        torch.full_like(probability, alpha),
        torch.full_like(probability, 1.0 - alpha),
    )
    loss = torch.mul(
        torch.mul(bce, alpha_factor),
        torch.pow(torch.clamp_min(pt, fp32_min), gamma),
    )
    if weight is not None:
        loss = torch.mul(loss, weight)

    if reduction == "mean":
        return torch.mean(loss)
    if reduction == "sum":
        return torch.sum(loss)
    if reduction == "none":
        return loss
    raise ValueError(f"unsupported reduction: {reduction}")


