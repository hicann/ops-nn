import pathlib
import unittest

KERNEL = (
    pathlib.Path(__file__).resolve().parents[2]
    / "op_kernel"
    / "arch35"
    / "sigmoid_focal_loss_kernel.h"
)


class GroupReductionSourceTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.source = KERNEL.read_text(encoding="utf-8")

    def test_group_reduction_has_one_multicore_route(self):
        process_group = self.source.split("__aicore__ inline void ProcessGroup()", 1)[
            1
        ].split("private:", 1)[0]
        self.assertIn("Phase1Process();", process_group)
        self.assertIn("SyncAll();", process_group)
        self.assertIn("Phase2Process();", process_group)

        phase2 = self.source.split("__aicore__ inline void Phase2Process()", 1)[
            1
        ].split("__aicore__ inline void PostElewiseAndCopyOut()", 1)[0]
        self.assertIn("Pattern::Reduce::RA", phase2)
        self.assertNotIn("totalElements", phase2)
        self.assertNotIn("GetValue", phase2)
        self.assertNotIn("Recompute", self.source)


if __name__ == "__main__":
    unittest.main()
