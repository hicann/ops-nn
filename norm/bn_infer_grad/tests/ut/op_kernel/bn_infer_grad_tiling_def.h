// BNInferGrad 的 Kernel UT tiling-definition shim。
//
// op_kernel 入口用 REGISTER_NONE_TILING，构建系统的 tiling-header 生成器不识别该宏
// （它只处理 REGISTER_TILING_DEFAULT / BroadcastSch），因此不会自动生成
// GET_TILING_DATA_WITH_STRUCT。当此 <op>_tiling_def.h 存在时，ut.cmake（cmake/ut.cmake:574-575）
// 会用 `-include` 强制注入本头文件并跳过自动生成，故在此定义该宏。
//
// BNInferGradTilingData<R> 为 POD（全 int64_t/float + 定长数组），
// 从原始 tiling GM buffer 按字节拷贝即等价于生成器行为
// （省去仅内部使用、UT 不需要的 REGISTER_TILINGDATA_SIZE 记账）。

#ifndef BN_INFER_GRAD_TILING_DEF_H_
#define BN_INFER_GRAD_TILING_DEF_H_

#include <cstring>

#ifndef GET_TILING_DATA_WITH_STRUCT
#define GET_TILING_DATA_WITH_STRUCT(tiling_struct, tiling_data, tiling_arg) \
    tiling_struct tiling_data;                                              \
    std::memcpy(reinterpret_cast<void*>(&tiling_data), reinterpret_cast<const void*>(tiling_arg), sizeof(tiling_struct))
#endif

#endif // BN_INFER_GRAD_TILING_DEF_H_
