// 整块单 tile + 单核的 TilingData 填充（split.axis=dim0, a_o=1, num_cores=1）。
// eff 为有效（去 size-1 后）shape，要求 eff[0]>=2、eff[1](=C)>=2、其余>=2。
template <int64_t R>
static void FillSingleTileTiling(BNInferGradTilingData<R>* td, const std::vector<int64_t>& eff, float eps)
{
    int64_t rank = static_cast<int64_t>(eff.size());
    int64_t delta = R - rank;

    td->split.axis = 0 + delta; // dim0 作切分轴，右移 delta
    td->split.a_i = eff[0];
    td->split.a_o = 1;
    td->split.a_i_tail = eff[0];

    td->multicore.num_cores = 1;
    td->multicore.total_tiles = 1;
    td->multicore.tiles_main = 1;
    td->multicore.cores_tail = 0;

    td->rank = rank;
    td->per_buf_bytes = 32768; // 32KB/slot，5 槽 <UB；单 tile 元素数远小于此
    td->num_inputs = 3;
    td->num_outputs = 1;

    for (int64_t d = 0; d < delta; d++)
        td->max_bro_shape[d] = 1;
    for (int64_t d = 0; d < rank; d++)
        td->max_bro_shape[d + delta] = eff[d];

    // grads(slot0) / output: 完整 shape + 行主序 stride（size-1 轴 stride=0）
    auto fillFull = [&](int64_t* shape, int64_t* strides) {
        for (int64_t d = 0; d < delta; d++) {
            shape[d] = 1;
            strides[d] = 0;
        }
        for (int64_t d = 0; d < rank; d++)
            shape[d + delta] = eff[d];
        int64_t prod = 1;
        for (int64_t d = rank - 1; d >= 0; d--) {
            strides[d + delta] = (eff[d] == 1) ? 0 : prod;
            prod *= eff[d];
        }
    };
    fillFull(td->input_shapes[0], td->input_strides[0]);
    fillFull(td->output_shapes[0], td->output_strides[0]);

    // scale(slot1) / variance(slot2): reshape 为 [1,C,1,...]，仅 C 轴 stride=1，其余广播(=0)
    for (int i = 1; i <= 2; i++) {
        for (int64_t d = 0; d < R; d++) {
            td->input_shapes[i][d] = 1;
            td->input_strides[i][d] = 0;
        }
        td->input_shapes[i][1 + delta] = eff[1]; // C 落在 axis1（右移后 1+delta）
        td->input_strides[i][1 + delta] = 1;
    }

    td->epsilon_value = eps;
}

// 独立 golden + 逐元素比对：x_backprop[i] = grads[i]*scale[c]/sqrt(var[c]+eps)
static void CheckGolden(const std::vector<int64_t>& eff, const float* grads, const float* scale, const float* var,
                        const float* out, float eps)
{
    int64_t total = 1;
    for (auto d : eff)
        total *= d;
    int64_t C = eff[1];
    int64_t innerAfterC = 1;
    for (size_t d = 2; d < eff.size(); d++)
        innerAfterC *= eff[d];

    for (int64_t i = 0; i < total; i++) {
        int64_t c = (i / innerAfterC) % C;
        float golden = grads[i] * scale[c] / std::sqrt(var[c] + eps);
        EXPECT_NEAR(out[i], golden, 1e-3f) << "mismatch at flat index " << i << " (c=" << c << ")";
    }
}

