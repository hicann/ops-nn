bool Close(float actual, float expected)
{
    return std::isfinite(actual) && std::fabs(actual - expected) <= kAtol + kRtol * std::fabs(expected);
}

bool ValidateTensor(const ge::Tensor& actual, const std::vector<float>& expected,
                    const std::vector<int64_t>& expectedShape, const char* outputName)
{
    const ge::TensorDesc desc = actual.GetTensorDesc();
    if (desc.GetShape().GetDims() != expectedShape || desc.GetDataType() != ge::DT_FLOAT ||
        actual.GetSize() != expected.size() * sizeof(float)) {
        std::printf("  output %s metadata check not passed\n", outputName);
        return false;
    }
    const float* values = reinterpret_cast<const float*>(actual.GetData());
    for (size_t i = 0; i < expected.size(); ++i) {
        if (!Close(values[i], expected[i])) {
            std::printf("  output %s[%zu] got %.8g, expected %.8g\n", outputName, i, values[i], expected[i]);
            return false;
        }
    }
    return true;
}

