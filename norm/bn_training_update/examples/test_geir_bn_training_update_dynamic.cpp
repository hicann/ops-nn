int RunScenario(ge::Session& session, uint32_t graphId, const std::string& scenario,
                const std::vector<int64_t>& xDeclared, const std::vector<int64_t>& channelDeclared, int64_t xRealDimCnt,
                const std::vector<std::vector<int64_t>>& concreteShapes)
{
    const std::string nodeName = "bn_training_update_" + scenario;
    ge::Graph graph = BuildScenarioGraph(nodeName, xDeclared, channelDeclared, xRealDimCnt);
    std::printf("Scenario %s, declared shape %s\n", scenario.c_str(), ShapeText(xDeclared).c_str());

    const ge::Status addStatus = session.AddGraph(graphId, graph, std::map<ge::AscendString, ge::AscendString>{});
    if (addStatus != ge::SUCCESS) {
        std::printf("AddGraph status=%u error=%s\n", addStatus, CurrentError().c_str());
        return 1;
    }

    int passed = 0;
    for (const auto& shape : concreteShapes) {
        std::printf("Run concrete shape %s\n", ShapeText(shape).c_str());
        const Inputs inputs = MakeInputs(shape);
        const Expected expected = ComputeExpected(shape, inputs);
        std::vector<ge::Tensor> feeds = {
            MakeTensor(shape, ge::FORMAT_NCHW, inputs.x),
            MakeTensor(kChannelShape, ge::FORMAT_ND, inputs.sum),
            MakeTensor(kChannelShape, ge::FORMAT_ND, inputs.squareSum),
            MakeTensor(kChannelShape, ge::FORMAT_ND, inputs.scale),
            MakeTensor(kChannelShape, ge::FORMAT_ND, inputs.offset),
            MakeTensor(kChannelShape, ge::FORMAT_ND, inputs.meanRef),
            MakeTensor(kChannelShape, ge::FORMAT_ND, inputs.varianceRef),
        };
        std::vector<ge::Tensor> outputs;
        const ge::Status runStatus = session.RunGraph(graphId, feeds, outputs);
        if (runStatus != ge::SUCCESS) {
            std::printf("RunGraph status=%u error=%s\n", runStatus, CurrentError().c_str());
            continue;
        }
        if (outputs.size() != 5U) {
            std::printf("expected 5 outputs, got %zu\n", outputs.size());
            continue;
        }
        if (ValidateTensor(outputs[0], expected.y, shape, "y") &&
            ValidateTensor(outputs[1], expected.meanOut, kChannelShape, "mean") &&
            ValidateTensor(outputs[2], expected.varianceOut, kChannelShape, "variance") &&
            ValidateTensor(outputs[3], expected.batchMean, kChannelShape, "batch_mean") &&
            ValidateTensor(outputs[4], expected.batchVariance, kChannelShape, "batch_variance")) {
            std::printf("Shape, dtype and values PASSED for %s\n", ShapeText(shape).c_str());
            ++passed;
        }
    }
    std::printf("Scenario %s summary: %d/%zu passed\n", scenario.c_str(), passed, concreteShapes.size());
    return passed == static_cast<int>(concreteShapes.size()) ? 0 : 1;
}

