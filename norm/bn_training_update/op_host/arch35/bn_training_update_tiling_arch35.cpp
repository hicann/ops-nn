template <int64_t kRank>
bool FindSplitAxis(const std::array<int64_t, kRank>& shape, int64_t ubPerCore, int64_t blockSize, SplitResult& split,
                   int64_t& perBufBytes)
{
    if (ubPerCore <= 0 || blockSize <= 0) {
        return false;
    }

    perBufBytes = (ubPerCore / kPhysNodes / blockSize) * blockSize;
    const int64_t perBufElems = perBufBytes / kComputeTypeBytes;
    if (perBufElems <= 0 || perBufBytes * kPhysNodes > ubPerCore) {
        return false;
    }

    int64_t inner = 1;
    for (int64_t axis = kRank - 1; axis >= 0; --axis) {
        const int64_t dim = shape[axis];
        if (dim > perBufElems / inner) {
            split.axis = axis;
            split.aI = perBufElems / inner;
            if (split.aI <= 0) {
                return false;
            }
            const int64_t remainder = dim % split.aI;
            split.aO = dim / split.aI + (remainder == 0 ? 0 : 1);
            split.aITail = remainder == 0 ? split.aI : remainder;
            return true;
        }
        if (axis == 0) {
            split.axis = 0;
            split.aI = dim;
            split.aO = 1;
            split.aITail = dim;
            return true;
        }
        inner *= dim;
    }
    return false;
}

template <int64_t kRank>
bool MultiCoreSplit(const std::array<int64_t, kRank>& shape, const SplitResult& split, int64_t platformCoreNum,
                    MultiCoreResult& multicore)
{
    if (platformCoreNum <= 0 || split.axis < 0 || split.axis >= kRank || split.aO <= 0) {
        return false;
    }

    int64_t outerProduct = 1;
    for (int64_t axis = 0; axis < split.axis; ++axis) {
        if (shape[axis] > std::numeric_limits<int64_t>::max() / outerProduct) {
            return false;
        }
        outerProduct *= shape[axis];
    }
    if (split.aO > std::numeric_limits<int64_t>::max() / outerProduct) {
        return false;
    }

    multicore.totalTiles = outerProduct * split.aO;
    multicore.numCores = std::min(multicore.totalTiles, platformCoreNum);
    if (multicore.numCores <= 0) {
        return false;
    }
    multicore.tilesMain = multicore.totalTiles / multicore.numCores;
    multicore.coresTail = multicore.totalTiles % multicore.numCores;
    return true;
}

