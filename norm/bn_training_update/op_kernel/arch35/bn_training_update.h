        AscendC::Reg::LoadAlign(addReg, addPtr);
        AscendC::Reg::Adds(idxReg, baseIdxReg, coefOffset, idxMask);
        AscendC::Reg::Gather<float>(multBReg, multReg, (AscendC::Reg::RegTensor<uint32_t>&)idxReg);
