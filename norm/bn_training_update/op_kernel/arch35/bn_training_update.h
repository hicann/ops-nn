    AscendC::Reg::Arange<int32_t, AscendC::Reg::IndexOrder::INCREASE_ORDER>(baseIdxReg, 0);
    AscendC::Reg::Muls(baseIdxReg, baseIdxReg, gatherScale, idxMask);
    AscendC::Reg::ShiftRights(baseIdxReg, baseIdxReg, kGatherFixedPointBits, idxMask);
