enum class StatMode {
    // Channel values contiguous in the broadcast tile (inner stride == 1).
    BROADCAST,
    // Channel is the split axis: compact chain plus in-register Gather
    // broadcast of the coefficient vectors.
    GATHER,
    // Rare layouts: broadcast tile plus the legacy strided scalar gather.
    LEGACY_GATHER,
};

