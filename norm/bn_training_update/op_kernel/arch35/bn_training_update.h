// Unified gather-based normalize. The tile is processed in blocks; within a
// block, element lane l belongs to channel floor(l / innerStride) of the
// block's channel range, so a register Gather with idx = coefOffset +
// lane / innerStride broadcasts the compact coefficient vectors. Works for
// innerStride <= oneRepeatSize (multi-channel blocks) and innerStride >
// oneRepeatSize (single-channel blocks iterated in repeats).
// 定点除法小数位数（Gather 索引 = (lane × ceil(2^kGatherFixedPointBits/stride)) >> kGatherFixedPointBits）
constexpr int16_t kGatherFixedPointBits = 24;

